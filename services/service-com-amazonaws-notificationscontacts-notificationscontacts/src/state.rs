/// The activation token outstanding for one email contact: the code the last
/// `SendActivationCode` minted, the instant it was minted, and how much of its
/// attempt budget the activations since have spent.
///
/// The three travel together because both documented bounds on a code
/// ([`ACTIVATION_CODE_LIFETIME_MILLIS`] and [`MAX_ACTIVATION_ATTEMPTS`]) are bounds on
/// the ONE code a send issued: superseding the code restarts both.
#[derive(Debug, Clone)]
pub struct ActivationToken {
    /// The `^[a-z0-9]{7}$` code an activation is compared against.
    pub code: String,
    /// When this code was issued, in milliseconds since the Unix epoch.
    pub issued_at_millis: i64,
    /// How many activation attempts have already been made against this code.
    pub attempts: u32,
}

impl ActivationToken {
    /// A freshly issued token: a full attempt budget, and a lifetime running from
    /// `issued_at_millis`.
    pub fn issued(code: String, issued_at_millis: i64) -> Self {
        Self {
            code,
            issued_at_millis,
            attempts: 0,
        }
    }

    /// Whether this code's [`ACTIVATION_CODE_LIFETIME_MILLIS`] lifetime has run out by
    /// `now_millis`. The lifetime is the span the code is usable FOR, so a code whose
    /// whole lifetime has elapsed is past it.
    pub fn has_expired(&self, now_millis: i64) -> bool {
        now_millis.saturating_sub(self.issued_at_millis) >= ACTIVATION_CODE_LIFETIME_MILLIS
    }

    /// Whether this code's [`MAX_ACTIVATION_ATTEMPTS`] attempt budget is spent.
    pub fn budget_is_spent(&self) -> bool {
        self.attempts >= MAX_ACTIVATION_ATTEMPTS
    }

    /// Whether this token is still the one an activation is compared against at
    /// `now_millis`: inside both of the bounds its code documents.
    pub fn is_outstanding(&self, now_millis: i64) -> bool {
        !self.has_expired(now_millis) && !self.budget_is_spent()
    }

    /// Spend one of this code's [`MAX_ACTIVATION_ATTEMPTS`] attempts.
    pub fn record_attempt(&mut self) {
        self.attempts = self.attempts.saturating_add(1);
    }
}

/// One stored email contact: every member `EmailContact` reports, plus the tags the
/// tagging operations will key off its ARN and the activation code
/// `SendActivationCode` issued for it.
#[derive(Debug, Clone, Default)]
pub struct EmailContactRecord {
    /// The contact's ARN: this record's store key and the label every other
    /// operation addresses it by.
    pub arn: String,
    pub name: String,
    /// The email address the create supplied as `emailAddress`; the wire shape
    /// reports it as `address`.
    pub address: String,
    /// One of [`EMAIL_CONTACT_STATUS_VALUES`].
    pub status: String,
    /// Creation time, in milliseconds since the Unix epoch.
    pub creation_time_millis: i64,
    /// Last-update time, in milliseconds since the Unix epoch.
    pub update_time_millis: i64,
    /// Tags attached to this contact, keyed by tag key. Bounded by
    /// [`MAX_TAGS_PER_CONTACT`].
    pub tags: BTreeMap<String, String>,
    /// The activation token the last `SendActivationCode` stored, present only once
    /// one was issued. Kept after a successful activation so re-activating with the
    /// same code is idempotent.
    pub activation_token: Option<ActivationToken>,
}

impl EmailContactRecord {
    /// This record as the modelled `EmailContact` wire shape.
    pub fn to_wire(&self) -> EmailContact {
        EmailContact {
            arn: self.arn.clone(),
            name: self.name.clone(),
            address: self.address.clone(),
            status: self.status.clone(),
            creation_time: wire_timestamp(self.creation_time_millis),
            update_time: wire_timestamp(self.update_time_millis),
        }
    }

    /// Whether this contact has been activated.
    pub fn is_active(&self) -> bool {
        self.status == STATUS_ACTIVE
    }
}

