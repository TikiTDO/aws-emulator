/// The modelled `TagKey` pattern, verbatim
/// (`smithy_query(query="shape",shape="TagKey")`).
///
/// Stated here because it has to be applied by hand: see
/// [`satisfies_tag_key_pattern`].
pub const TAG_KEY_PATTERN: &str = r"^(?!aws:).{1,128}$";

/// The tag-key prefix [`TAG_KEY_PATTERN`]'s leading negative lookahead excludes: the
/// namespace AWS reserves for its own tags.
pub const RESERVED_TAG_KEY_PREFIX: &str = "aws:";

/// The fewest characters [`TAG_KEY_PATTERN`]'s `.{1,128}` admits — an empty key is not
/// a `TagKey`. `TagKey` carries no separate `@length`, so this bound lives only inside
/// the pattern.
pub const MIN_TAG_KEY_LEN: usize = 1;

/// The most characters [`TAG_KEY_PATTERN`]'s `.{1,128}` admits, from the same pattern.
pub const MAX_TAG_KEY_LEN: usize = 128;

/// The characters a modelled `@pattern`'s `.` does NOT match.
///
/// A Smithy `@pattern` is an ECMA-262 regular expression, and there `.` matches every
/// character except a LINE TERMINATOR: line feed, carriage return, line separator and
/// paragraph separator. A value carrying any of them therefore cannot be matched by a
/// `.` of such an expression, however many characters it has — so a key carrying one is
/// not `.{1,128}` ([`TAG_KEY_PATTERN`]) and an address carrying one is not `(.+)@(.+)`
/// ([`EMAIL_CONTACT_ADDRESS_PATTERN`]).
///
/// Stated once for every pattern this service applies by hand, because the engine the
/// framework's centralized constraint walk compiles a `@pattern` with — the `regex`
/// crate — reads `.` as every character except a line FEED alone, so the other three are
/// admitted there whatever the modelled expression says.
pub const PATTERN_DOT_EXCLUDED_CHARS: [char; 4] = ['\n', '\r', '\u{2028}', '\u{2029}'];

/// Whether `key` satisfies the modelled `TagKey` `@pattern` ([`TAG_KEY_PATTERN`]).
///
/// This one modelled constraint cannot be left to the framework's centralized
/// constraint walk, for two independent reasons, both in
/// `vendor/smithy-schema-server/src/constraints.rs`: the walk does not capture a map
/// KEY's constraints at all ("Map *keys* are not covered"), and the pattern opens with
/// the negative lookahead `(?!aws:)`, which the `regex` crate cannot compile — and a
/// `@pattern` that fails to compile is treated there as matching EVERY value. So the
/// pattern is applied here instead, by every operation that accepts a tag key
/// (`CreateEmailContact` and `TagResource` through `tags`, `UntagResource` through
/// `tagKeys`), and the 1..128 character bound travels with it because `TagKey` carries
/// no separate `@length`.
///
/// It is applied as the pattern's independent parts rather than by pulling in a
/// look-around regex engine, because the pattern's ONLY look-around is that leading
/// `(?!aws:)`, which states exactly "the key does not begin with
/// [`RESERVED_TAG_KEY_PREFIX`]" — a prefix test, case-SENSITIVE because the pattern is
/// (`AWS:` is admitted by it). What remains is `.{1,128}` anchored at both ends: 1 to
/// 128 characters, counted as the Unicode scalar values `.` matches, none of them one of
/// the [`PATTERN_DOT_EXCLUDED_CHARS`] it does not.
///
/// WHICH of those parts a key broke is deliberately not reported: the model declares ONE
/// expression for this member, so a key outside it is refused with that expression —
/// see [`pattern_validation_failure`] — exactly as a `@pattern` the walk could apply is.
pub fn satisfies_tag_key_pattern(key: &str) -> bool {
    !key.starts_with(RESERVED_TAG_KEY_PREFIX)
        && (MIN_TAG_KEY_LEN..=MAX_TAG_KEY_LEN).contains(&key.chars().count())
        && !carries_excluded_char(key)
}

/// `Ok` when every KEY of a `TagMap` member in `keys` satisfies [`TAG_KEY_PATTERN`],
/// else the modelled 400 blaming that member.
///
/// `member` is the map member the keys arrived through (`tags`), and that member is the
/// path the refusal blames: the centralized walk visits no map key at all, so there is
/// no element position of its spelling to name. A request carrying several bad keys is
/// refused for the lexicographically first of them, so one request always reads the same
/// way however the map happened to hand its keys over.
pub fn check_tag_map_keys<'a, I>(member: &str, keys: I) -> Result<(), ValidationException>
where
    I: IntoIterator<Item = &'a str>,
{
    let refused = keys
        .into_iter()
        .filter(|key| !satisfies_tag_key_pattern(key))
        .min();
    refuse_outside_pattern(TAG_KEY_PATTERN, refused.map(|_| member.to_string()))
}

/// `Ok` when every ELEMENT of a `TagKeys` member in `keys` satisfies
/// [`TAG_KEY_PATTERN`], else the modelled 400 for the first offending one.
///
/// A list arrives in the order the caller wrote it, and the centralized walk names a list
/// element by the member, its 1-based position and the step into the collection
/// (`names.2.member`), so the refusal blames the position the request wrote the key at —
/// the same position the walk would have named had it been able to apply this pattern.
pub fn check_tag_key_list<'a, I>(member: &str, keys: I) -> Result<(), ValidationException>
where
    I: IntoIterator<Item = &'a str>,
{
    let refused = keys
        .into_iter()
        .enumerate()
        .find(|(_, key)| !satisfies_tag_key_pattern(key));
    refuse_outside_pattern(
        TAG_KEY_PATTERN,
        refused.map(|(index, _)| element_path(member, index + 1)),
    )
}

/// The path the framework's own path spelling gives the `position`-th (1-based) element
/// of the list member `member`.
fn element_path(member: &str, position: usize) -> String {
    ::aws_smithy_schema_server::constraints::path::join(&[
        member.to_string(),
        ::aws_smithy_schema_server::constraints::path::element(position),
    ])
}

/// `Ok` when `offender` is `None`, else the modelled 400 that
/// [`pattern_validation_failure`] words for the member path it carries.
///
/// The ONE refusal path for a `@pattern` this service has to apply by hand, so no caller
/// of it can word such a refusal its own way. It carries the path and not the offending
/// value, because the refusal states the member and the constraint and never the value.
fn refuse_outside_pattern(
    pattern: &str,
    offender: Option<String>,
) -> Result<(), ValidationException> {
    match offender {
        Some(path) => Err(pattern_validation_failure(&path, pattern)),
        None => Ok(()),
    }
}

/// The modelled `EmailContactName` pattern, verbatim
/// (`smithy_query(query="shape",shape="EmailContactName")`).
///
/// Stated here because this one, too, has to be applied by hand: see
/// [`satisfies_email_contact_name_pattern`].
pub const EMAIL_CONTACT_NAME_PATTERN: &str = r"[\w-.~]+";

/// The characters [`EMAIL_CONTACT_NAME_PATTERN`]'s class admits BESIDE `\w`.
///
/// A Smithy `@pattern` is an ECMA-262 regular expression, and there a `-` between two
/// class items that are not both single characters is a LITERAL `-` rather than a range
/// operator — so `[\w-.~]` is the union of `\w`, `-`, `.` and `~`, the unreserved
/// characters of a URI. The `regex` crate reads the same text as the range `\w`-`.`,
/// whose start is not a single codepoint, so it refuses to compile it at all.
pub const EMAIL_CONTACT_NAME_LITERAL_CHARS: [char; 3] = ['-', '.', '~'];

/// Whether `character` is one [`EMAIL_CONTACT_NAME_PATTERN`]'s class admits: an ECMA-262
/// `\w` — an ASCII letter, an ASCII digit or an underscore, that class being ASCII-only
/// there, so a letter of another script is not one — or one of
/// [`EMAIL_CONTACT_NAME_LITERAL_CHARS`].
fn is_email_contact_name_char(character: char) -> bool {
    character.is_ascii_alphanumeric()
        || character == '_'
        || EMAIL_CONTACT_NAME_LITERAL_CHARS.contains(&character)
}

/// Whether `name` satisfies the modelled `EmailContactName` `@pattern`
/// ([`EMAIL_CONTACT_NAME_PATTERN`]).
///
/// This modelled constraint cannot be left to the framework's centralized constraint
/// walk either: the walk compiles a `@pattern` with the `regex` crate, which rejects this
/// expression's character class outright (see [`EMAIL_CONTACT_NAME_LITERAL_CHARS`]), and
/// a `@pattern` that fails to compile is treated there as matching EVERY value. So the
/// expression is applied here instead, by the one operation that accepts a name
/// (`CreateEmailContact`), as the class it is: every character of the value is one
/// [`is_email_contact_name_char`] admits, and the `+` quantifier wants at least one of
/// them (the member's own `@length` 1..64 refuses an empty value at the boundary too).
///
/// It holds over the WHOLE value, which is what the service enforces: a value merely
/// CARRYING a run of admitted characters — `oncall primary`, say — is refused, the way
/// the modelled expression's own anchored siblings are.
pub fn satisfies_email_contact_name_pattern(name: &str) -> bool {
    !name.is_empty() && name.chars().all(is_email_contact_name_char)
}

/// `Ok` when `name` satisfies the modelled `EmailContactName` `@pattern`, else the
/// modelled 400 for the input member it arrived through.
///
/// `member` is the member the caller named, so the refusal blames what the request wrote
/// rather than the shape behind it.
pub fn check_email_contact_name(member: &str, name: &str) -> Result<(), ValidationException> {
    refuse_outside_pattern(
        EMAIL_CONTACT_NAME_PATTERN,
        (!satisfies_email_contact_name_pattern(name)).then(|| member.to_string()),
    )
}

/// The modelled `EmailContactAddress` pattern, verbatim
/// (`smithy_query(query="shape",shape="EmailContactAddress")`).
///
/// Stated here because this one, too, has to be applied by hand: see
/// [`satisfies_email_contact_address_pattern`].
pub const EMAIL_CONTACT_ADDRESS_PATTERN: &str = r"^(.+)@(.+)$";

/// The character [`EMAIL_CONTACT_ADDRESS_PATTERN`] requires between its two `.+` runs.
pub const EMAIL_CONTACT_ADDRESS_SEPARATOR: char = '@';

/// Whether `address` satisfies the modelled `EmailContactAddress` `@pattern`
/// ([`EMAIL_CONTACT_ADDRESS_PATTERN`]).
///
/// The framework's centralized constraint walk compiles this expression and applies it,
/// but it compiles it with the `regex` crate, whose `.` excludes a line FEED alone —
/// where the modelled ECMA-262 expression's `.` excludes every one of the
/// [`PATTERN_DOT_EXCLUDED_CHARS`]. So a value carrying a carriage return, a line
/// separator or a paragraph separator satisfies the compiled expression while the
/// modelled one excludes it, and the member that reports the stored value back
/// (`EmailContact$address`) declares that same modelled expression. The expression is
/// therefore applied here as the parts it is, by the one operation that accepts an
/// address (`CreateEmailContact`): no character of the value is one `.` does not match,
/// and `(.+)@(.+)` anchored at both ends wants a [`EMAIL_CONTACT_ADDRESS_SEPARATOR`]
/// with at least one such character on each side of it.
///
/// WHICH part a value broke is deliberately not reported, for the reason
/// [`satisfies_tag_key_pattern`] gives: the model declares ONE expression for this
/// member, so a value outside it is refused with that expression.
pub fn satisfies_email_contact_address_pattern(address: &str) -> bool {
    if carries_excluded_char(address) {
        return false;
    }
    let characters = address.chars().count();
    address
        .chars()
        .enumerate()
        .any(|(position, character)| {
            character == EMAIL_CONTACT_ADDRESS_SEPARATOR
                && position > 0
                && position + 1 < characters
        })
}

/// `Ok` when `address` satisfies the modelled `EmailContactAddress` `@pattern`, else the
/// modelled 400 for the input member it arrived through.
///
/// `member` is the member the caller named, so the refusal blames what the request wrote
/// rather than the shape behind it.
pub fn check_email_contact_address(
    member: &str,
    address: &str,
) -> Result<(), ValidationException> {
    refuse_outside_pattern(
        EMAIL_CONTACT_ADDRESS_PATTERN,
        (!satisfies_email_contact_address_pattern(address)).then(|| member.to_string()),
    )
}

/// Whether `value` carries a character a modelled `@pattern`'s `.` does not match (one of
/// the [`PATTERN_DOT_EXCLUDED_CHARS`]) — the one test every pattern applied here shares.
fn carries_excluded_char(value: &str) -> bool {
    value
        .chars()
        .any(|character| PATTERN_DOT_EXCLUDED_CHARS.contains(&character))
}

