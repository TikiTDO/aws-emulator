        // names has to be one a stream has: a table action in it could never be decided
        // by the resource it is attached to.
        if resource.target == crate::state::PolicyTarget::Stream {
            crate::state::check_stream_policy_actions(&policy).map_err(lift_policy_fault)?;
        }
        // "Set this parameter to true to confirm that you want to remove your
        // permissions to change the policy of this resource in the future"
        // (`ConfirmRemoveSelfResourceAccess`): a document that denies the caller the
        // policy-management actions does exactly that, so without the confirmation it
        // is refused rather than attached — once attached, no later call could take it
        // off again. Only a deny that applies to EVERY request counts: a statement
        // whose deny is gated on a `Condition` leaves the caller able to change the
        // policy from a request the condition does not select, so it is not a
        // lock-out (see [`crate::state::locks_the_caller_out`]).
        if !input.confirm_remove_self_resource_access
            && crate::state::locks_the_caller_out(&policy, &resource.arn)
        {
            return Err(crate::scaffolded::Scaffolded::access_denied(
                "The new resource policy will not allow you to update the resource policy in the \
                 future.",
            ));
        }

        let mut store = state.lock();
        store.apply_due_transitions(now);
        let table = store.table_for_policy_mut(&resource).map_err(lift)?;
        // No status requirement: `CreateTable$ResourcePolicy` attaches a policy to a
        // table that is still `CREATING`, so a policy is not something only an ACTIVE
        // table can carry. A table whose deletion is already due is gone by the time
        // this lookup runs, and answers `ResourceNotFoundException` above.
        // "When you provide an expected revision ID, if the revision ID of the existing
        // policy on the resource doesn't match or if there's no policy attached to the
        // resource, your request will be rejected with a PolicyNotFoundException. To
        // conditionally attach a policy when no policy exists for the resource, specify
        // NO_POLICY for the revision ID" (`PutResourcePolicy$ExpectedRevisionId`).
        let attached_revision_id = table
            .attached_policy(&resource)
            .map_err(lift)?
            .map(crate::state::AttachedPolicy::revision_id);
        let attached_revision_id = attached_revision_id.as_deref();
