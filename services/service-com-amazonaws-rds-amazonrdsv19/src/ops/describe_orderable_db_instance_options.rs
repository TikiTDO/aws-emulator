/// The DB instance families a CLUSTER-engine DB instance can be ordered in: the
/// burstable `medium` classes and the memory-optimised families, as the Aurora section of
/// the same instance-class list publishes them. A DocumentDB or Neptune instance is a
/// cluster member ordered in those same families. `db.serverless`, the serverless
/// capacity class, is not a family-by-size class and is added by [`instance_classes`].
const CLUSTER_FAMILIES: &[InstanceFamily] = &[
    family("t3", CLUSTER_BURSTABLE_SIZES, true, false),
    family("t4g", CLUSTER_BURSTABLE_SIZES, true, true),
    family("r5", STANDARD_SIZES, false, false),
    family("r6i", STANDARD_SIZES, false, false),
    family("r6g", STANDARD_SIZES, false, true),
    family("r7g", STANDARD_SIZES, false, true),
];

/// The serverless capacity class (Aurora Serverless v2, and the serverless capacity a
/// DocumentDB or Neptune cluster member is ordered with), which has no family-and-size
/// form.
const SERVERLESS_CLASS: &str = "db.serverless";

/// The threads each configurable (Intel) core runs, which is also why a class's
/// `coreCount` is half its vCPU count: the published `threadsPerCore` processor feature
/// allows `1,2`.
const THREADS_PER_CORE: i32 = 2;

/// One DB instance class this service offers, as an option reports it.
pub struct InstanceClass {
    /// `DBInstanceClass`.
    pub name: String,
    /// Whether the class is burstable (see [`InstanceFamily::burstable`]).
    pub burstable: bool,
    /// The CPU CORES whose count a caller can configure on this class, or `None` for a
    /// class whose processor features are not configurable (a burstable or Graviton
    /// class, or a size whose vCPU count the published naming does not state).
    pub cores: Option<i32>,
    /// Whether `SupportsPerformanceInsights`.
    pub supports_performance_insights: bool,
}

/// The profile of the class NAMED `name` for `engine`.
///
/// A class this service's family table publishes carries that row's profile. A class
/// outside it is still a real class — `crate::state::check_db_instance_class` admits every
/// value of the published `db.<family>.<size>` form, because which classes exist is AWS's
/// moving per-region matrix and this table is an explicitly partial subset of it — so one
/// is profiled from its NAME: burstable exactly for the burstable (`t`) generations, and
/// with no configurable processor cores, since the vCPU count of a family this table does
/// not publish is not known here.
pub fn instance_class_profile(engine: &str, name: &str) -> InstanceClass {
    if let Some(published) = instance_classes(engine)
        .into_iter()
        .find(|class| class.name.eq_ignore_ascii_case(name))
    {
        return published;
    }
    let family = name
        .strip_prefix("db.")
        .and_then(|rest| rest.split('.').next())
        .unwrap_or_default();
    InstanceClass {
        name: name.to_string(),
        burstable: family.starts_with('t'),
        cores: None,
        supports_performance_insights: true,
    }
}

/// The vCPU count the published instance-size naming gives `size`: a `large` is 2 vCPUs
/// and each `<n>xlarge` is `4 * n`, with `xlarge` as `n = 1`. `None` for the burstable
/// sizes (`micro`, `small`, `medium`), whose vCPUs are shared and whose count is
/// therefore not a configurable processor feature.
fn vcpus(size: &str) -> Option<i32> {
    /// `(size, vCPUs)` for the sizes whose name states the count.
    const SIZE_VCPUS: &[(&str, i32)] = &[
        ("large", 2),
        ("xlarge", 4),
        ("2xlarge", 8),
        ("4xlarge", 16),
        ("8xlarge", 32),
        ("12xlarge", 48),
        ("16xlarge", 64),
        ("24xlarge", 96),
        ("32xlarge", 128),
    ];

    SIZE_VCPUS
        .iter()
        .find(|(name, _)| *name == size)
        .map(|(_, vcpus)| *vcpus)
}

/// The classes `engine` can be ordered in, built from the family tables above.
///
/// `pub` because this catalogue is the service's one published answer to "what can a DB
/// instance be": `DescribeValidDBInstanceModifications` reports the bounds of the class a
/// stored instance already runs, and reads them from here so the two reports cannot
/// disagree about a class.
pub fn instance_classes(engine: &str) -> Vec<InstanceClass> {
    let cluster = is_cluster_engine(engine);
    let mut classes: Vec<InstanceClass> = instance_families(engine)
        .iter()
        .flat_map(|family| {
            family.sizes.iter().map(move |size| InstanceClass {
                name: format!("db.{}.{size}", family.family),
                burstable: family.burstable,
                cores: if family.burstable || family.graviton {
                    None
                } else {
                    vcpus(size).map(|vcpus| vcpus / THREADS_PER_CORE)
                },
                // Performance Insights is not offered on the two smallest burstable
                // sizes; every other class this service offers takes it.
                supports_performance_insights: !(family.burstable
                    && matches!(*size, "micro" | "small")),
            })
        })
        .collect();
    if cluster {
        classes.push(InstanceClass {
            name: SERVERLESS_CLASS.to_string(),
            burstable: false,
            cores: None,
            supports_performance_insights: true,
        });
    }
    classes
}

/// The DB instance FAMILIES `engine` can be ordered in: the family rows this report is
/// built from, which is the part of AWS's per-region, per-engine matrix this service
/// publishes.
fn instance_families(engine: &str) -> &'static [InstanceFamily] {
    if is_cluster_engine(engine) {
        CLUSTER_FAMILIES
    } else {
        PROVISIONED_FAMILIES
    }
}

/// Whether this report publishes any option at all in the instance GENERATION
/// `db_instance_class` names — the family part of `db.<family>.<size>`.
///
/// The published matrix is families crossed with sizes, and it is an explicitly PARTIAL
/// subset of AWS's own, which moves with every instance-type launch, in both directions:
/// a SIZE outside the rows is still a size AWS may offer in a family that is in them
/// (`db.m5.24xlarge`), and which of its families each ENGINE offers is the part of the
/// matrix this service does not hold. What the report does publish about a class is
/// therefore its generation: the families any DB instance can be ordered in. A class whose
/// family appears in no row of either table names a generation this service offers no
/// option in — a previous-generation family no engine version it publishes can be created
/// with — which is what the real service refuses a create of.
pub fn publishes_instance_family(db_instance_class: &str) -> bool {
    // The serverless capacity class has no family-and-size form at all; it is published as
    // an option of its own, so the class itself is the generation.
    if db_instance_class.eq_ignore_ascii_case(SERVERLESS_CLASS) {
        return true;
    }
    let Some(family) = db_instance_class
        .strip_prefix("db.")
        .and_then(|rest| rest.split('.').next())
    else {
        return false;
    };
    PROVISIONED_FAMILIES
        .iter()
        .chain(CLUSTER_FAMILIES)
        .any(|row| row.family.eq_ignore_ascii_case(family))
}

/// Whether this report offers `engine` under `license_model` ([`license_models`]).
pub fn offers_license_model(engine: &str, license_model: &str) -> bool {
    license_models(engine)
        .iter()
        .any(|offered| offered.eq_ignore_ascii_case(license_model))
}

/// The license models `engine` can be ordered under, as `CreateDBInstance`'s
/// `LicenseModel` member documents them per engine ("`license-included`",
/// "`bring-your-own-license`", "`general-public-license`", "`postgresql-license`",
/// "`marketplace-license`").
///
/// An engine of another control plane this one front door serves is licensed by that
/// control plane rather than by a database vendor, so its licence is the one THAT engine
/// publishes and not a value from the list above.
///
/// `pub` for the same reason as [`instance_classes`]: a create that names a licence
/// resolves it against the licences published here.
pub fn license_models(engine: &str) -> &'static [&'static str] {
    match engine {
        "postgres" | "aurora-postgresql" => &["postgresql-license"],
        "mysql" | "mariadb" | "aurora-mysql" => &["general-public-license"],
        // An engine AWS licenses itself is ordered under its own licence: the graph
        // engine of the Amazon Neptune control plane this door serves reports
        // `amazon-license`, the one licence a Neptune instance runs under.
        "neptune" => &["amazon-license"],
        // The licence setting "doesn't apply to" the Amazon DocumentDB engine, whose
        // orderable options carry `na`.
        "docdb" => &["na"],
        // Oracle Enterprise Edition is BYOL only; Standard Edition Two is offered both
        // ways.
        "oracle-ee" | "oracle-ee-cdb" => &["bring-your-own-license"],
        "oracle-se2" | "oracle-se2-cdb" => &["license-included", "bring-your-own-license"],
        // Db2 is ordered through a Marketplace subscription or BYOL.
        "db2-ae" | "db2-ce" | "db2-se" => &["bring-your-own-license", "marketplace-license"],
        // Every SQL Server edition RDS offers includes its licence.
        _ => &["license-included"],
    }
}

/// The provisioned IOPS a storage type takes, as the published storage table states them.
pub struct ProvisionedIops {
    /// `MinIopsPerDbInstance`.
    pub min_per_instance: i32,
    /// `MaxIopsPerDbInstance`.
    pub max_per_instance: i32,
    /// `MinIopsPerGib` — the lowest IOPS-to-GiB ratio.
    pub min_per_gib: f64,
    /// `MaxIopsPerGib` — the highest IOPS-to-GiB ratio.
    pub max_per_gib: f64,
}

/// The provisioned storage throughput a storage type takes, in MiB/s.
pub struct ProvisionedThroughput {
    /// `MinStorageThroughputPerDbInstance`.
    pub min_per_instance: i32,
    /// `MaxStorageThroughputPerDbInstance`.
    pub max_per_instance: i32,
    /// `MinStorageThroughputPerIops`.
    pub min_per_iops: f64,
    /// `MaxStorageThroughputPerIops`.
    pub max_per_iops: f64,
}

/// One storage type a DB instance can be ordered with, and everything an option reports
/// ABOUT that type.
///
/// Source: the "Amazon RDS DB instance storage" section of the Amazon RDS User Guide —
/// General Purpose SSD (`gp2`, `gp3`) and Provisioned IOPS SSD (`io1`, `io2`), with the
/// sizes, IOPS and throughput each publishes.
pub struct StorageProfile {
    /// `StorageType`.
    pub name: &'static str,
    /// `MinStorageSize` and the largest `MaxStorageSize` this type reaches, in GiB,
    /// before the engine's own cap ([`max_allocated_storage`]) is applied. `None` for
    /// storage that is managed by a cluster rather than ordered per instance (Aurora),
    /// which reports no storage bounds and no autoscaling.
    pub size_range: Option<(i32, i32)>,
    /// The provisioned IOPS this type takes, which is also `SupportsIops`.
    pub iops: Option<ProvisionedIops>,
    /// The provisioned throughput this type takes, which is also
    /// `SupportsStorageThroughput`.
    pub throughput: Option<ProvisionedThroughput>,
}

/// General Purpose SSD `gp2`: 20 GiB upwards, with IOPS and throughput derived from the
/// volume size rather than provisioned, so it takes neither.
const GP2: StorageProfile = StorageProfile {
    name: "gp2",
    size_range: Some((20, 65_536)),
    iops: None,
    throughput: None,
};

/// General Purpose SSD `gp3`: 20 GiB upwards, with a 3,000 IOPS / 125 MiB/s baseline that
/// can be provisioned up to 64,000 IOPS and 4,000 MiB/s, at up to 0.25 MiB/s per
/// provisioned IOPS.
const GP3: StorageProfile = StorageProfile {
    name: "gp3",
    size_range: Some((20, 65_536)),
    iops: Some(ProvisionedIops {
        min_per_instance: 3_000,
        max_per_instance: 64_000,
        min_per_gib: 0.5,
        max_per_gib: 500.0,
    }),
    throughput: Some(ProvisionedThroughput {
        min_per_instance: 125,
        max_per_instance: 4_000,
        min_per_iops: 0.0,
        max_per_iops: 0.25,
    }),
};

/// Provisioned IOPS SSD `io1`: from 100 GiB, 1,000 to 256,000 provisioned IOPS, at a
/// ratio of up to 50 IOPS per GiB. Throughput follows the provisioned IOPS and is not
/// ordered separately.
const IO1: StorageProfile = StorageProfile {
    name: "io1",
    size_range: Some((100, 65_536)),
    iops: Some(ProvisionedIops {
        min_per_instance: 1_000,
        max_per_instance: 256_000,
        min_per_gib: 0.5,
        max_per_gib: 50.0,
    }),
    throughput: None,
};

/// Provisioned IOPS SSD `io2` Block Express: the same sizes and IOPS as `io1` at a ratio
/// of up to 1,000 IOPS per GiB.
const IO2: StorageProfile = StorageProfile {
    name: "io2",
    size_range: Some((100, 65_536)),
    iops: Some(ProvisionedIops {
        min_per_instance: 1_000,
        max_per_instance: 256_000,
        min_per_gib: 0.5,
        max_per_gib: 1_000.0,
    }),
    throughput: None,
};

/// Aurora storage, which the CLUSTER manages: it is not ordered per instance, so the
/// option reports the type and no bounds.
const AURORA: StorageProfile = StorageProfile {
    name: "aurora",
    size_range: None,
    iops: None,
    throughput: None,
};

/// The storage an Amazon DocumentDB or Amazon Neptune cluster member reports.
///
/// `CreateDBClusterMessage$StorageType` in the DocumentDB and Neptune models: "Valid
/// values for storage type - standard | iopt1 … Default value is standard" — and the
/// CLUSTER carries it, so the instance orders neither size nor IOPS of its own.
const CLUSTER_STANDARD: StorageProfile = StorageProfile {
    name: "standard",
    size_range: None,
    iops: None,
    throughput: None,
};

/// The storage types an Aurora DB instance is offered with.
const AURORA_STORAGE: &[StorageProfile] = &[AURORA];

/// The storage types a DocumentDB or Neptune cluster member is offered with.
const CLUSTER_STANDARD_STORAGE: &[StorageProfile] = &[CLUSTER_STANDARD];

/// The storage types a provisioned-storage (non-cluster) class is offered with, in the
/// order the published storage table lists them.
///
/// A BURSTABLE class is offered the same four, and two sources say so. The model: the
/// storage members are bound by SIZE and RATIO and never by DB instance class —
/// `CreateDBInstanceMessage$StorageType` publishes one value list for every DB instance
/// ("Valid Values: `gp2 | gp3 | io1 | io2 | standard`") and carves out only Aurora ("This
/// setting doesn't apply to Amazon Aurora DB instances. Storage is managed by the DB
/// cluster."), and `CreateDBInstanceMessage$Iops`'s constraints are a multiple of the
/// storage amount, not a list of classes; the only constraint Provisioned IOPS SSD adds is
/// its own 100 GiB minimum size ([`IO1`]/[`IO2`]'s `size_range`), which `MinStorageSize`
/// reports. And the RECORDING: the behavioural unit
/// `rds.valid-db-instance-modifications-bound-what-modify-accepts` runs on a
/// `db.t4g.micro` — a burstable class — and requires its reported `StorageSize` to carry a
/// range starting ABOVE the 20 GiB it runs, which only the Provisioned IOPS SSD minimum
/// provides; while this table withheld `io1`/`io2` from burstable classes that unit failed
/// with "must report at least one StorageSize range enlarging beyond the current
/// allocation 20; it reported only [(20, 65536, 1)]".
const ALL_PROVISIONED_STORAGE: &[StorageProfile] = &[GP2, GP3, IO1, IO2];

/// Legacy MAGNETIC storage: still published by `StorageType` ("Valid Values: gp2 | gp3 |
/// io1 | io2 | standard") and ordered with no option here, since
/// `DescribeOrderableDBInstanceOptions` offers the four current types — but a modification
/// can still convert to it, so its bounds live beside theirs and [`storage_bounds`] hands
/// them out.
///
/// Source: the "Magnetic storage (not recommended)" section of the Amazon RDS User Guide —
/// 20 GiB to 3,072 GiB (3 TiB), with neither provisioned IOPS nor provisioned throughput:
/// a magnetic volume's performance is not configurable.
const MAGNETIC: StorageProfile = StorageProfile {
    name: LEGACY_MAGNETIC_STORAGE,
    size_range: Some((20, 3_072)),
    iops: None,
    throughput: None,
};

/// The storage types a DB instance of `engine` can be ordered with.
///
/// It is a property of the ENGINE alone: an engine whose storage its cluster manages
/// carries that one type, and every other engine is offered the four per-instance types,
/// whatever class it runs on.
///
/// `pub` because a MODIFICATION is bounded by the same table an order is:
/// `DescribeValidDBInstanceModifications` reports one `ValidStorageOptions` per type this
/// returns for the stored instance's engine.
pub fn storage_profiles(engine: &str) -> &'static [StorageProfile] {
    if crate::state::is_aurora(engine) {
        return AURORA_STORAGE;
    }
    if matches!(engine, "docdb" | "neptune") {
        return CLUSTER_STANDARD_STORAGE;
    }
    ALL_PROVISIONED_STORAGE
}

/// The bounds `storage_type` carries for a DB instance of `engine`, or `None` when the
/// engine publishes no such type at all.
///
/// Every type an option is ordered with ([`storage_profiles`]), plus the legacy
/// [`MAGNETIC`] type `StorageType` publishes for an engine whose storage is its own. This
/// is what `ModifyDBInstance` judges a storage modification against, so a type the member
/// admits is bounded rather than unbounded.
pub fn storage_bounds(engine: &str, storage_type: &str) -> Option<&'static StorageProfile> {
    let profiles = storage_profiles(engine);
    if let Some(profile) = profiles
        .iter()
        .find(|profile| profile.name.eq_ignore_ascii_case(storage_type))
    {
        return Some(profile);
    }
    // An engine whose storage is its own also takes the legacy magnetic type.
    (profiles.iter().any(|profile| profile.size_range.is_some())
        && storage_type.eq_ignore_ascii_case(LEGACY_MAGNETIC_STORAGE))
    .then_some(&MAGNETIC)
}

/// Whether `StorageType` publishes `storage_type` for a DB instance of `engine`.
///
/// `CreateDBInstanceMessage$StorageType` publishes one value list for a DB instance whose
/// storage is its own ("Valid Values: `gp2 | gp3 | io1 | io2 | standard`") and carves out
/// the engines whose "Storage is managed by the DB cluster", which carry their cluster's
/// type instead. `standard` — legacy magnetic storage — is in that list and is ordered
/// with no option here, so it is published with [`MAGNETIC`]'s bounds rather than refused.
pub fn publishes_storage_type(engine: &str, storage_type: &str) -> bool {
    storage_bounds(engine, storage_type).is_some()
}

/// The legacy magnetic storage type `StorageType` still publishes.
pub const LEGACY_MAGNETIC_STORAGE: &str = "standard";

/// The largest `AllocatedStorage` `engine` accepts, in GiB.
///
/// The published per-engine caps: 65,536 GiB for the MySQL, MariaDB, PostgreSQL and
/// Oracle engines, 16,384 GiB for Microsoft SQL Server and 64,000 GiB for Db2. A storage
/// type's own maximum ([`StorageProfile::size_range`]) is capped at this; a cluster
/// engine's storage carries no bounds at all, so this is not consulted for one.
///
/// `pub` for the same reason as [`storage_profiles`]: the storage a modification can grow
/// to is capped by the engine exactly as the storage an order can ask for is.
pub fn max_allocated_storage(engine: &str) -> i32 {
    if engine.starts_with("sqlserver") {
        return 16_384;
    }
    if engine.starts_with("db2") {
        return 64_000;
    }
    65_536
}

/// Whether `engine` supports IAM database authentication
/// (`SupportsIAMDatabaseAuthentication`): the MySQL, MariaDB and PostgreSQL engines do;
/// the Oracle, SQL Server and Db2 engines do not.
///
/// The GRAPH engine of the Amazon Neptune control plane this door serves does too, and at
/// the cluster level: its own
/// `CreateDBClusterMessage$EnableIAMDatabaseAuthentication` "enables Amazon Identity and
/// Access Management (IAM) authentication for the entire DB cluster (this cannot be set at
/// an instance level)"
/// (`smithy_query(query="doc",shape="CreateDBClusterMessage",member="EnableIAMDatabaseAuthentication",model_path="services/service-com-amazonaws-neptune-amazonrdsv19/smithy-model/com-amazonaws-neptune-amazonrdsv19.json")`),
/// so every option of it is offered with that auth mode. The DOCUMENT engine's control
/// plane models no such member on either create
/// (`com.amazonaws.docdb#CreateDBClusterMessage`,
/// `com.amazonaws.docdb#CreateDBInstanceMessage`), so an option of it reports none: the
/// capability is read per engine from the control plane that owns it rather than defaulted
/// for this one front door.
fn supports_iam_database_authentication(engine: &str) -> bool {
    matches!(
        engine,
        "mysql" | "mariadb" | "postgres" | "aurora-mysql" | "aurora-postgresql" | "neptune"
    )
}

/// Whether a DB instance of `engine` can be ordered as a MULTI-AZ deployment
/// (`MultiAZCapable`, "whether a DB instance is Multi-AZ capable").
///
/// A Multi-AZ deployment is a standby DB INSTANCE the service keeps in another zone of the
/// region for an instance that owns its own storage. For a cluster engine the zones are
/// not the instance's at all: `CreateDBInstanceMessage$MultiAZ` states it — "This setting
/// doesn't apply to Amazon Aurora because the DB instance Availability Zones (AZs) are
/// managed by the DB cluster" — and the two sibling control planes served by this one door
/// document their instance members the same way ("Not applicable … managed by the DB
/// cluster" on the Amazon Neptune and Amazon DocumentDB `CreateDBInstance` members). An
/// option of a cluster engine therefore reports no instance-level Multi-AZ capability; the
/// zones its members are placed in come from the CLUSTER's own `AvailabilityZones`.
fn multi_az_capable(engine: &str) -> bool {
    !is_cluster_engine(engine)
}

/// Whether an option of `engine` reports Enhanced Monitoring
/// (`SupportsEnhancedMonitoring`, "Enhanced Monitoring at intervals from 1 to 60
/// seconds").
///
/// Enhanced Monitoring is the OS-metric stream Amazon RDS collects from a DB instance's
/// host under a monitoring role, which this control plane's own engines publish. An engine
/// of ANOTHER control plane served by this one door
/// ([`serves_another_control_plane`]) publishes its own capability set and neither of them
/// offers it: the document engine's control plane models no monitoring member to enable it
/// with at all (`com.amazonaws.docdb#CreateDBInstanceMessage` carries neither
/// `MonitoringInterval` nor `MonitoringRoleArn`), and the graph engine's own front-door
/// option report publishes the member unsupported for every class. So it is read per
/// engine rather than claimed for every option.
fn supports_enhanced_monitoring(engine: &str) -> bool {
    !serves_another_control_plane(engine)
}

/// Whether `engine` offers Performance Insights at all, before the CLASS is consulted.
///
/// The graph engine does not: its own control plane documents both the option member and
/// the create flag that would enable it as "(Not supported by Neptune)"
/// (`smithy_query(query="shape",shape="OrderableDBInstanceOption",model_path="services/service-com-amazonaws-neptune-amazonrdsv19/smithy-model/com-amazonaws-neptune-amazonrdsv19.json")`
/// on `SupportsPerformanceInsights`, and the same note on that model's
/// `CreateDBInstanceMessage$EnablePerformanceInsights`), so no option of it claims the
/// capability whatever class it runs on. The document engine's control plane DOES model
/// `EnablePerformanceInsights`, so its options report the capability its classes carry —
/// the question is the engine's, not this front door's.
fn engine_offers_performance_insights(engine: &str) -> bool {
    engine != crate::state::NEPTUNE_ENGINE
}

/// The Database Activity Streams modes an option reports, exactly as
/// `OrderableDBInstanceOption$SupportedActivityStreamModes` documents them: "Aurora
/// PostgreSQL returns the value `[sync, async]`. Aurora MySQL and RDS for Oracle return
/// `[async]` only. If Database Activity Streams isn't supported, the return value is an
/// empty list."
fn activity_stream_modes(engine: &str) -> Vec<String> {
    let modes: &[&str] = match engine {
        "aurora-postgresql" => &["sync", "async"],
        "aurora-mysql" => &["async"],
        engine if engine.starts_with("oracle") => &["async"],
        _ => &[],
    };
    modes.iter().map(|mode| (*mode).to_string()).collect()
}

/// The processor features a caller can configure on `class` for `engine`.
///
/// Configuring the CPU cores and threads per core of a DB instance is published for the
/// core-licensed engines — RDS for Oracle and RDS for Microsoft SQL Server — on the Intel
/// classes that expose multithreaded cores. Every other combination reports no
/// configurable feature, so the list is empty and the member is left absent.
///
/// The two features are the published ones: `coreCount`, whose default is the class's
/// full core count and whose allowed values are the EVEN counts up to it (cores are
/// disabled in pairs), and `threadsPerCore`, which allows one thread or
/// [`THREADS_PER_CORE`].
///
/// `pub` because the processor features a stored instance's class can be MODIFIED to are
/// the same ones it can be ordered with: `DescribeValidDBInstanceModifications` reports
/// this list as its `ValidProcessorFeatures`.
pub fn available_processor_features(
    engine: &str,
    class: &InstanceClass,
) -> Vec<AvailableProcessorFeature> {
    if !(engine.starts_with("oracle") || engine.starts_with("sqlserver")) {
        return Vec::new();
    }
    let Some(cores) = class.cores.filter(|cores| *cores > 1) else {
        return Vec::new();
    };
    let allowed_core_counts: Vec<String> = (1..=cores)
        .filter(|count| count % 2 == 0)
        .map(|count| count.to_string())
        .collect();
    vec![
        AvailableProcessorFeature {
            name: Some("coreCount".to_string()),
            default_value: Some(cores.to_string()),
            allowed_values: Some(allowed_core_counts.join(",")),
        },
        AvailableProcessorFeature {
            name: Some("threadsPerCore".to_string()),
            default_value: Some(THREADS_PER_CORE.to_string()),
            allowed_values: Some(
                (1..=THREADS_PER_CORE)
                    .map(|threads| threads.to_string())
                    .collect::<Vec<_>>()
                    .join(","),
            ),
        },
    ]
}

/// The Availability Zones of `region` an option is offered in.
///
/// Every AWS Region has at least three zones, named `<region><letter>`, and
/// `CreateDBInstance` in this emulator places an instance that names no zone in the
/// region's FIRST zone, so the zones reported here are the ones an instance can land in.
fn availability_zones(region: &str) -> Vec<AvailabilityZone> {
    ["a", "b", "c"]
        .into_iter()
        .map(|letter| AvailabilityZone {
            name: Some(format!("{region}{letter}")),
        })
        .collect()
}

/// Project one (engine version, DB instance class, license model, storage type) onto the
/// modelled `OrderableDBInstanceOption` wire shape.
fn to_wire(
    version: &crate::ops::describe_db_engine_versions::CatalogVersion,
    class: &InstanceClass,
    license_model: &str,
    storage: &StorageProfile,
    region: &str,
) -> OrderableDBInstanceOption {
    let engine = version.engine;
    // A storage type's published maximum, capped by what the ENGINE accepts.
    let storage_size = storage
        .size_range
        .map(|(min, max)| (min, max.min(max_allocated_storage(engine))));
    let processor_features = available_processor_features(engine, class);
    OrderableDBInstanceOption {
        engine: Some(engine.to_string()),
        engine_version: Some(version.engine_version.to_string()),
        db_instance_class: Some(class.name.clone()),
        license_model: Some(license_model.to_string()),
        availability_zones: Some(availability_zones(region)),
        // Multi-AZ, a read replica and Enhanced Monitoring are INSTANCE-level
        // capabilities, so each is the engine's own rather than this front door's default:
        // a cluster engine's deployment and replication belong to its cluster, and the
        // read-replica answer is read from the engine catalogue so this report and
        // `DescribeDBEngineVersions` cannot disagree about the version.
        multi_az_capable: Some(multi_az_capable(engine)),
        read_replica_capable: Some(version.profile.supports_read_replica),
        vpc: Some(true),
        supports_storage_encryption: Some(true),
        // Everything below comes from the option's OWN storage type.
        storage_type: Some(storage.name.to_string()),
        supports_iops: Some(storage.iops.is_some()),
        min_iops_per_db_instance: storage.iops.as_ref().map(|iops| iops.min_per_instance),
        max_iops_per_db_instance: storage.iops.as_ref().map(|iops| iops.max_per_instance),
        min_iops_per_gib: storage.iops.as_ref().map(|iops| iops.min_per_gib),
        max_iops_per_gib: storage.iops.as_ref().map(|iops| iops.max_per_gib),
        supports_storage_throughput: Some(storage.throughput.is_some()),
        min_storage_throughput_per_db_instance: storage
            .throughput
            .as_ref()
            .map(|throughput| throughput.min_per_instance),
        max_storage_throughput_per_db_instance: storage
            .throughput
            .as_ref()
            .map(|throughput| throughput.max_per_instance),
        min_storage_throughput_per_iops: storage
            .throughput
            .as_ref()
            .map(|throughput| throughput.min_per_iops),
        max_storage_throughput_per_iops: storage
            .throughput
            .as_ref()
            .map(|throughput| throughput.max_per_iops),
        // Storage autoscaling raises `AllocatedStorage`, so it applies exactly where
        // storage is ordered per instance rather than managed by a cluster.
        supports_storage_autoscaling: Some(storage.size_range.is_some()),
        min_storage_size: storage_size.map(|(min, _)| min),
        max_storage_size: storage_size.map(|(_, max)| max),
        supports_enhanced_monitoring: Some(supports_enhanced_monitoring(engine)),
        // Performance Insights is the ENGINE's first and the class's second: an engine
        // that does not offer it claims it on no class.
        supports_performance_insights: Some(
            engine_offers_performance_insights(engine) && class.supports_performance_insights,
        ),
        supports_iam_database_authentication: Some(supports_iam_database_authentication(engine)),
        // The engine modes and the global-database capability are the VERSION's, read
        // from the engine catalogue, so this report and `DescribeDBEngineVersions` cannot
        // disagree about the version an option is offered for.
        supported_engine_modes: Some(
            version
                .profile
                .engine_modes
                .iter()
                .map(|mode| (*mode).to_string())
                .collect(),
        ),
        supports_global_databases: Some(version.profile.supports_global_databases),
        // "Whether DB instances can be configured as a Multi-AZ DB cluster": the Multi-AZ
        // DB cluster deployment is offered on the MySQL and PostgreSQL engines and never on
        // a burstable class. An engine of ANOTHER control plane served by this door reports
        // it too — an Amazon DocumentDB or Amazon Neptune instance is only ever a member of
        // its cluster, and recorded behaviour for the DocumentDB engine reports this member
        // true for every option.
        supports_clusters: Some(
            serves_another_control_plane(engine)
                || (!class.burstable && matches!(engine, "mysql" | "postgres")),
        ),
        // A dedicated log volume is offered on the RDS engines, whose log volume is
        // ordered with the instance; a cluster engine's storage is cluster-managed.
        supports_dedicated_log_volume: Some(!is_cluster_engine(engine)),
        supported_activity_stream_modes: Some(activity_stream_modes(engine)),
        // Absent rather than empty when the class has no configurable feature.
        available_processor_features: (!processor_features.is_empty()).then_some(processor_features),
        // This emulator's subnets are IPv4, so an option is offered for IPv4 only rather
        // than reporting a dual-stack network it does not provide.
        supported_network_types: Some(vec!["IPV4".to_string()]),
        // `AvailabilityZoneGroup` names a Local Zone group and `OutpostCapable` an AWS
        // Outpost; this service offers neither, so no option claims one.
        outpost_capable: Some(false),
        // The members that describe capacity this emulator does not model — Kerberos
        // authentication, additional storage volumes, the Data API HTTP endpoint — are
        // left absent rather than invented.
        ..Default::default()
    }
}
