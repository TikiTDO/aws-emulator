impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for SendMessageBatch<Eng>
{
    type Input = SendMessageBatchInput;
    type Output = SendMessageBatchOutput;
    type Error = SendMessageBatchError;

    const NAME: &'static str = "SendMessageBatch";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SEND_MESSAGE_BATCH_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::SEND_MESSAGE_BATCH_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let store = sqs::service_state(&*self.engine).ok_or_else(|| {
            SendMessageBatchErrorModeled::UnsupportedOperation(sqs::store_unavailable())
        })?;

        // The whole-request refusals, before anything is enqueued: a batch that is not
        // one AWS would act on stores nothing at all.
        if input.entries.is_empty() {
            return Err(SendMessageBatchErrorModeled::EmptyBatchRequest(
                EmptyBatchRequest {
                    message: Some(sqs::empty_batch_message("SendMessageBatch")),
                },
            )
            .into());
        }
        if input.entries.len() > sqs::MAX_BATCH_ENTRIES {
            return Err(
                SendMessageBatchErrorModeled::TooManyEntriesInBatchRequest(
                    TooManyEntriesInBatchRequest {
                        message: Some(format!(
                            "Maximum number of entries per request are {}. You have sent {}.",
                            sqs::MAX_BATCH_ENTRIES,
                            input.entries.len()
                        )),
                    },
                )
                .into(),
            );
        }
        let mut seen: BTreeSet<&str> = BTreeSet::new();
        for entry in &input.entries {
            if !sqs::is_valid_batch_entry_id(&entry.id) {
                return Err(SendMessageBatchErrorModeled::InvalidBatchEntryId(
                    InvalidBatchEntryId {
                        message: Some(format!(
                            "A batch entry id can only contain alphanumeric characters, hyphens \
                             and underscores. It can be at most {} letters long.",
                            sqs::MAX_BATCH_ENTRY_ID_LEN
                        )),
                    },
                )
                .into());
            }
            if !seen.insert(entry.id.as_str()) {
                return Err(SendMessageBatchErrorModeled::BatchEntryIdsNotDistinct(
                    BatchEntryIdsNotDistinct {
                        message: Some(format!("Id {} repeated.", entry.id)),
                    },
                )
                .into());
            }
        }

        // The request is one AWS would act on, so now the queue's encryption key is asked
        // about — once, because every entry goes to ONE queue: a queue encrypted with a
        // customer managed key needs KMS to generate the data key its messages are sealed
        // under, as this caller, and a caller the key does not permit has the whole batch
        // refused with nothing enqueued. Asked AFTER the refusals about the request's own
        // shape, which AWS answers without reaching the key at all.
        sqs::encryption::authorize_queue_key(
            &*self.engine,
            ctx,
            &input.queue_url,
            sqs::encryption::GENERATE_DATA_KEY_ACTION,
        )
        .map_err(kms_refusal)?;

        let mut state = store.lock();
        let now = SystemTime::now();
        // A queue url resolves in the region the request addressed: this region's queue of
        // that name, and nothing another region holds.
        let region = sqs::request_region(ctx.parts());
        // Retention and visibility are owed by the clock, not by this call. Applied
        // across the whole store, so the store-wide byte budget below is measured
        // against what the store actually still holds.
        state.materialise_due(now);
        let store_bytes = state.retained_message_bytes();
        let Some(queue) = state.queue_by_url_mut(&region, &input.queue_url) else {
            return Err(SendMessageBatchErrorModeled::QueueDoesNotExist(
                sqs::queue_does_not_exist(),
            )
            .into());
        };
        let fifo = queue.is_fifo();

        // Whether this caller may send to this queue is decided against the queue's own
        // policy and the caller's identity-based policies, before anything is enqueued:
        // the batch is refused as a whole, so nothing is sent.
        let (queue_arn, policy) = (queue.arn.clone(), queue.policy().map(str::to_string));
        if let Some(denied) = sqs::authorization::denied(
            &*self.engine,
            ctx,
            Self::NAME,
            &queue_arn,
            policy.as_deref(),
        ) {
            return Err(denied);
        }

        // `MessageSystemAttributes` is honoured per entry, exactly as `SendMessage`
        // honours it, by `prepare` below.
        //
        // A parameter the queue's TYPE does not take cannot be satisfied by ANY entry of
        // this batch — every entry addresses the one queue — so it is the whole request
        // that is refused, before anything is enqueued, exactly as `SendMessage` refuses
        // the same parameter. This is RECORDED behaviour and not a choice: a batch one of
        // whose entries carries a per-message delay on a FIFO queue is refused whole,
        // with nothing enqueued, rather than answered 200 with that entry alone under
        // `Failed`. A fault in an entry's own content (its body, a value outside a range,
        // an absent required member) is still that entry's alone. A per-message delay of
        // zero asks for nothing a FIFO queue does not already do, so only a positive one
        // is a parameter the queue type does not take.
        for entry in &input.entries {
            let misused = if fifo {
                entry
                    .delay_seconds
                    .filter(|delay| *delay > 0)
                    .map(|delay| (delay.to_string(), sqs::DELAY_SECONDS))
            } else {
                entry
                    .message_deduplication_id
                    .clone()
                    .map(|token| (token, "MessageDeduplicationId"))
            };
            if let Some((value, parameter)) = misused {
                return Err(Scaffolded::invalid_parameter_value(sqs::invalid_parameter_message(
                    &value,
                    parameter,
                    sqs::QUEUE_TYPE_PARAMETER_REASON,
                )));
            }
        }

        // Everything each message carries counts toward the batch's payload, attributes
        // included: "all parts of the message attribute, including Name, Type, and Value,
        // are part of the message size restriction". The system attributes do not count
        // toward it — "the size of a message system attribute doesn't count towards the
        // total size of a message" — but they are part of what the store retains, so each
        // entry is measured both ways.
        let mut sized: Vec<MeasuredEntry> = Vec::with_capacity(input.entries.len());
        let mut total_bytes = 0usize;
        for entry in &input.entries {
            let attributes: BTreeMap<String, MessageAttributeValue> = entry
                .message_attributes
                .clone()
                .unwrap_or_default()
                .into_iter()
                .collect();
            let system_attributes: BTreeMap<String, MessageSystemAttributeValue> = entry
                .message_system_attributes
                .clone()
                .unwrap_or_default()
                .into_iter()
                .collect();
            let bytes = entry
                .message_body
                .len()
                .saturating_add(sqs::message_attribute_bytes(&attributes));
            let retained = bytes
                .saturating_add(sqs::message_system_attribute_bytes(&system_attributes));
            total_bytes = total_bytes.saturating_add(bytes);
            sized.push(MeasuredEntry {
                attributes,
                system_attributes,
                bytes,
                retained,
            });
        }
        // What `BatchRequestTooLong` refuses is "the length of all the messages put
        // together" against the service's own FIXED ceiling — "the maximum allowed
        // individual message size and the maximum total payload size (the sum of the
        // individual lengths of all of the batched messages)". The queue's configured
        // `MaximumMessageSize` is NOT that ceiling: it bounds ONE message, so it is
        // applied to each entry on its own by `prepare` below, and a batch whose entries
        // each fit is acceptable however many of them there are.
        let ceiling = sqs::maximum_batch_payload_bytes();
        if i64::try_from(total_bytes).unwrap_or(i64::MAX) > ceiling {
            return Err(SendMessageBatchErrorModeled::BatchRequestTooLong(
                BatchRequestTooLong {
                    message: Some(format!(
                        "Batch requests cannot be longer than {ceiling} bytes. \
                         You have sent {total_bytes} bytes."
                    )),
                },
            )
            .into());
        }

        // Each entry judged on its own against the queue, nothing stored yet: an entry
        // the queue will not take fails ALONE.
        let outcomes: Vec<Result<Prepared, EntryRefusal>> = input
            .entries
            .iter()
            .zip(sized)
            .enumerate()
            .map(|(index, (entry, sized))| prepare(queue, entry, Self::NAME, index + 1, sized))
            .collect();

        // On a FIFO queue the batch is all or nothing: an entry the queue will not take
        // refuses the whole REQUEST, before anything is enqueued, because enqueuing its
        // siblings would place the caller's retry of that one entry AFTER them and
        // reorder the message group — the guarantee a FIFO queue exists to provide. A
        // standard queue promises no order, so there the same fault fails that entry
        // alone. Reported for the first entry the request order reaches, so a batch with
        // two faults is always refused for the same one.
        if fifo {
            if let Some(refusal) = outcomes.iter().find_map(|outcome| outcome.as_ref().err()) {
                return Err(refusal.whole_request());
            }
        }

        // What this in-memory store can be made to hold is bounded, and the batch is
        // judged against those bounds as a whole: it is enqueued entirely or refused
        // entirely, never half-applied.
        let accepted = outcomes.iter().filter(|outcome| outcome.is_ok()).count();
        let accepted_bytes: usize = outcomes
            .iter()
            .filter_map(|outcome| outcome.as_ref().ok())
            .map(|prepared| prepared.bytes)
            .sum();
        if accepted > 0 {
            if let Some(reason) = queue.batch_rejection(accepted, accepted_bytes, store_bytes) {
                return Err(SendMessageBatchErrorModeled::OverLimit(OverLimit {
                    message: Some(reason),
                })
                .into());
            }
        }

        let mut successful = Vec::with_capacity(accepted);
        let mut failed = Vec::new();
        // Who these messages are FROM, read once from the credential that signed this
        // request: every entry of one batch arrived on the same send.
        let sender_id = sqs::authorization::sender_id(&*self.engine, ctx);
        for outcome in outcomes {
            let prepared = match outcome {
                Ok(prepared) => prepared,
                Err(refusal) => {
                    failed.push(refusal.reported());
                    continue;
                }
            };

            // "If a message with a particular MessageDeduplicationId is sent
            // successfully, subsequent messages with the same MessageDeduplicationId are
            // accepted successfully but aren't delivered": the resend stores nothing and
            // answers for the message the token already admitted — including a resend of
            // an entry earlier in this same batch.
            let deduplication_key = prepared.deduplication_id.as_ref().map(|token| {
                queue.deduplication_key(prepared.group_id.as_deref().unwrap_or_default(), token)
            });
            if let Some(admitted) = deduplication_key
                .as_ref()
                .and_then(|key| queue.deduplication.get(key))
            {
                successful.push(SendMessageBatchResultEntry {
                    id: prepared.id,
                    message_id: admitted.message_id.clone(),
                    md5_of_message_body: prepared.md5_of_body,
                    md5_of_message_attributes: prepared.md5_of_attributes,
                    md5_of_message_system_attributes: prepared.md5_of_system_attributes,
                    sequence_number: Some(admitted.sequence_number.clone()),
                });
                continue;
            }

            let message_id = sqs::new_identifier();
            // Only a FIFO queue sequences its messages; `SequenceNumber` "applies only
            // to FIFO (first-in-first-out) queues".
            let sequence_number = fifo.then(|| queue.next_sequence_number());
            queue.messages.push_back(sqs::StoredMessage {
                message_id: message_id.clone(),
                body: prepared.body,
                md5_of_body: prepared.md5_of_body.clone(),
                message_attributes: prepared.attributes,
                message_system_attributes: prepared.system_attributes,
                message_group_id: prepared.group_id,
                message_deduplication_id: prepared.deduplication_id,
                sequence_number: sequence_number.clone(),
                sent_at: now,
                // The queue this send enqueues the entry in is the one it was sent to, so
                // its retention runs from the same instant.
                retention_from: now,
                sender_id: sender_id.clone(),
                available_at: sqs::after(now, prepared.delay),
                invisible_until: None,
                receive_count: 0,
                queue_receive_count: 0,
                first_received_at: None,
                last_received_at: None,
                // A send puts the message in this queue directly: no redrive moved it
                // here, so it names no dead-letter source.
                dead_letter_source_arn: None,
            });
            if let (Some(key), Some(sequence_number)) =
                (deduplication_key, sequence_number.clone())
            {
                queue.record_deduplication(
                    key,
                    sqs::Deduplication {
                        message_id: message_id.clone(),
                        sequence_number,
                        accepted_at: now,
                    },
                );
            }
            // One more message added to this queue, of the size Amazon SQS measures a
            // message at: what the `AWS/SQS` sent counters count (`sqs::QueueTraffic`). An
            // entry the batch refused added none, and a resend the deduplication token
            // suppressed added none either — both left this loop before here.
            queue.count_sent(prepared.size, now);

            successful.push(SendMessageBatchResultEntry {
                id: prepared.id,
                message_id,
                md5_of_message_body: prepared.md5_of_body,
                md5_of_message_attributes: prepared.md5_of_attributes,
                md5_of_message_system_attributes: prepared.md5_of_system_attributes,
                sequence_number,
            });
        }

        Ok(SendMessageBatchOutput { successful, failed })
    }
}

