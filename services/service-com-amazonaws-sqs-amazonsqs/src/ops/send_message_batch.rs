/// `KMS.AccessDeniedException`) — carrying the message KMS words that refusal in. The
/// key belongs to the QUEUE, not to an entry, so it refuses the whole request rather
/// than filling a `failed` entry per message.
fn kms_refusal(refusal: sqs::encryption::KeyRefusal) -> SendMessageBatchError {
    use sqs::encryption::KeyRefusal;
    match refusal {
        KeyRefusal::NotFound(message) => SendMessageBatchErrorModeled::KmsNotFound(KmsNotFound {
            message: Some(message),
        }),
        KeyRefusal::Disabled(message) => SendMessageBatchErrorModeled::KmsDisabled(KmsDisabled {
            message: Some(message),
        }),
        KeyRefusal::InvalidState(message) => {
            SendMessageBatchErrorModeled::KmsInvalidState(KmsInvalidState {
                message: Some(message),
            })
        }
        KeyRefusal::InvalidKeyUsage(message) => {
            SendMessageBatchErrorModeled::KmsInvalidKeyUsage(KmsInvalidKeyUsage {
                message: Some(message),
            })
        }
        KeyRefusal::AccessDenied(message) => {
            SendMessageBatchErrorModeled::KmsAccessDenied(KmsAccessDenied {
                message: Some(message),
            })
        }
    }
    .into()
}

/// One batch entry's attribute maps and the bytes it carries, measured once for the
/// request's payload bound and reused by [`prepare`].
struct MeasuredEntry {
    attributes: BTreeMap<String, MessageAttributeValue>,
    system_attributes: BTreeMap<String, MessageSystemAttributeValue>,
    /// What this entry's message weighs against the queue's `MaximumMessageSize`: its
    /// body and its message attributes, the system attributes excluded.
    bytes: usize,
    retained: usize,
}

/// Why one entry cannot be taken: the code Amazon SQS reports the condition under, and
/// the sentence the caller has to repair that entry from.
///
/// The same refusal is reported two ways, because the queue type decides whether it is
/// about the entry or about the request: [`reported`](Self::reported) on a standard
/// queue, [`whole_request`](Self::whole_request) on a FIFO one.
struct EntryRefusal {
    id: String,
    code: &'static str,
    message: String,
}

impl EntryRefusal {
    /// This refusal as the result entry reporting it: the caller supplied what the queue
    /// refused, so the fault is the sender's.
    fn reported(self) -> BatchResultErrorEntry {
        BatchResultErrorEntry {
            id: self.id,
            sender_fault: true,
            code: self.code.to_string(),
            message: Some(self.message),
        }
    }

    /// This refusal as the refusal of the whole request, which is how a FIFO queue
    /// answers it. The sentence is the same one; only the channel differs, so the code is
    /// the request-level spelling of the same condition: the service's two documented
    /// parameter codes, or the modelled error for a body outside the allowed character
    /// set. A value that is there but holds nothing is a value the service does not
    /// accept, which is `InvalidParameterValue`.
    fn whole_request(&self) -> SendMessageBatchError {
        match self.code {
            MISSING_PARAMETER => Scaffolded::MissingParameter(crate::scaffolded::MissingParameter {
                message: self.message.clone(),
            }),
            INVALID_MESSAGE_CONTENTS => SendMessageBatchErrorModeled::InvalidMessageContents(
                InvalidMessageContents {
                    message: Some(self.message.clone()),
                },
            )
            .into(),
            _ => Scaffolded::invalid_parameter_value(self.message.clone()),
        }
    }
}

/// A batch entry the queue will take, with everything the store and the result entry
/// need: the entry's own `Id`, its body and attributes, their digests, the FIFO members
/// it resolved to and the delay that applies to it.
struct Prepared {
    id: String,
    body: String,
    attributes: BTreeMap<String, MessageAttributeValue>,
    system_attributes: BTreeMap<String, MessageSystemAttributeValue>,
    md5_of_body: String,
    md5_of_attributes: Option<String>,
    md5_of_system_attributes: Option<String>,
    group_id: Option<String>,
    deduplication_id: Option<String>,
    delay: i64,
    bytes: usize,
    /// What this entry's message weighs as Amazon SQS measures a message — its body and its
    /// message attributes — which is what the `AWS/SQS` sent-size counter reports.
    size: usize,
}

/// Judge one entry against `queue` by the rules `SendMessage` applies to one message,
/// answering either what the store needs or why this entry alone was not taken.
///
/// `sized` carries the entry's attribute maps and the bytes it weighs, already measured
/// for the request's payload bound. `operation` and `position` are what a refusal names
/// an absent value by: the entry's one-based place in the request's `Entries` list.
fn prepare(
    queue: &sqs::Queue,
    entry: &SendMessageBatchRequestEntry,
    operation: &str,
    position: usize,
    sized: MeasuredEntry,
) -> Result<Prepared, EntryRefusal> {
    let MeasuredEntry {
        mut attributes,
        system_attributes,
        bytes,
        retained,
    } = sized;
    let fifo = queue.is_fifo();

    // An entry whose `MessageBody` holds no character carries a member it had to carry
    // with nothing in it — "the minimum size is one character" for the body of a message
    // (`SendMessageRequest$MessageBody`) — so the value is EMPTY rather than absent, and
    // the refusal names the member by its place in the request.
    if entry.message_body.is_empty() {
        return Err(refused(
            entry,
            sqs::EMPTY_VALUE,
            sqs::empty_batch_entry_value_message(operation, position, "MessageBody"),
        ));
    }

    // "A message can include only XML, JSON, and unformatted text. The following Unicode
    // characters are allowed ... If a message contains characters outside the allowed
    // set, Amazon SQS rejects the message".
    if let Some(character) = sqs::invalid_body_character(&entry.message_body) {
        return Err(refused(
            entry,
            INVALID_MESSAGE_CONTENTS,
            sqs::invalid_body_character_message(character),
        ));
    }

    // "In FIFO queues, MessageGroupId organizes messages into distinct groups ... If you
    // do not provide a MessageGroupId when sending a message to a FIFO queue, the action
    // fails." A standard queue may carry one too ("in standard queues, using
    // MessageGroupId enables fair queues"), where it identifies a tenant and orders
    // nothing.
    let group_id = entry.message_group_id.clone();
    match &group_id {
        Some(given) => {
            if let Some(reason) = sqs::message_token_refusal("MessageGroupId", given) {
                return Err(refused(entry, INVALID_PARAMETER_VALUE, reason));
            }
        }
        None if fifo => {
            return Err(refused(
                entry,
                MISSING_PARAMETER,
                sqs::missing_parameter_message("MessageGroupId"),
            ));
        }
        None => {}
    }

    // The token this message is deduplicated under, on a FIFO queue: the one the entry
    // supplied, or — "if you aren't able to provide a MessageDeduplicationId and you
    // enable ContentBasedDeduplication for your queue" — a SHA-256 hash of the body. "If
    // you don't provide a MessageDeduplicationId and the queue doesn't have
    // ContentBasedDeduplication set, the action fails with an error."
    let deduplication_id = match entry.message_deduplication_id.clone() {
        Some(given) => {
            // A standard queue never reaches here: the handler refuses the whole batch
            // for a parameter the queue type does not take, before any entry is judged.
            if let Some(reason) = sqs::message_token_refusal("MessageDeduplicationId", &given) {
                return Err(refused(entry, INVALID_PARAMETER_VALUE, reason));
            }
            Some(given)
        }
        None if fifo && queue.content_based_deduplication() => {
            Some(sqs::content_deduplication_token(&entry.message_body))
        }
        None if fifo => {
            return Err(refused(
                entry,
                INVALID_PARAMETER_VALUE,
                sqs::NO_DEDUPLICATION_ID.to_string(),
            ));
        }
        None => None,
    };

    // "When you set FifoQueue, you can't set DelaySeconds per message. You can set this
    // parameter only on a queue level." A FIFO queue never reaches here carrying one:
    // the handler refuses the whole batch for it. The queue's own value applies when the
    // entry names none; either way the value must be inside the range the model
    // documents for the attribute.
    let (min_delay, max_delay) = sqs::integer_bounds(sqs::DELAY_SECONDS);
    let delay = match entry.delay_seconds {
        Some(requested) => i64::from(requested),
        None => queue.integer(sqs::DELAY_SECONDS),
    };
    if delay < min_delay || delay > max_delay {
        return Err(refused(
            entry,
            INVALID_PARAMETER_VALUE,
            sqs::invalid_parameter_message(
                &delay.to_string(),
                sqs::DELAY_SECONDS,
                &format!(
                    "{} must be >= {min_delay} and <= {max_delay}.",
                    sqs::DELAY_SECONDS
                ),
            ),
        ));
    }

    if attributes.len() > sqs::MAX_MESSAGE_ATTRIBUTES {
        return Err(refused(
            entry,
            INVALID_PARAMETER_VALUE,
            format!(
                "Number of message attributes [{}] exceeds the allowed maximum [{}].",
                attributes.len(),
                sqs::MAX_MESSAGE_ATTRIBUTES,
            ),
        ));
    }
    // Name-ordered, so an entry with two bad attributes is always refused for the same
    // one.
    if let Some(reason) = attributes
        .iter()
        .find_map(|(name, value)| sqs::message_attribute_refusal(name, value))
    {
        return Err(refused(entry, INVALID_PARAMETER_VALUE, reason));
    }
    // "Currently, the only supported message system attribute is AWSTraceHeader", judged
    // by the same rule `SendMessage` applies to the member.
    if let Some(reason) = system_attributes
        .iter()
        .find_map(|(name, value)| sqs::message_system_attribute_refusal(name, value))
    {
        return Err(refused(entry, INVALID_PARAMETER_VALUE, reason));
    }
    // `MD5OfMessageAttributes` is the digest a sender compares against its OWN digest of
    // the attributes it sent, so it covers what this ENTRY carried — taken before the
    // queue puts any value of it into the form it keeps, exactly as `SendMessage` takes it.
    let md5_of_attributes = sqs::md5_of_message_attributes(&attributes);
    // A `Number` attribute carries a number, and the queue holds the number rather than
    // the text the entry wrote it as — exactly as `SendMessage` holds it.
    sqs::store_message_attributes_canonically(&mut attributes);

    // The queue's `MaximumMessageSize` bounds ONE message, so it is this ENTRY that is
    // judged against it, exactly as `SendMessage` judges the message it carries:
    // "everything the message carries counts toward it" — "all parts of the message
    // attribute, including Name, Type, and Value, are part of the message size
    // restriction" — while the system attributes do not. An entry over the queue's bound
    // fails on its own; its siblings that fit are still taken.
    let maximum = queue.integer(sqs::MAXIMUM_MESSAGE_SIZE);
    if i64::try_from(bytes).unwrap_or(i64::MAX) > maximum {
        return Err(refused(
            entry,
            INVALID_PARAMETER_VALUE,
            sqs::unvalidated_parameters_message(&sqs::message_too_long_reason(maximum)),
        ));
    }

    Ok(Prepared {
        id: entry.id.clone(),
        md5_of_body: sqs::md5_hex(entry.message_body.as_bytes()),
        md5_of_attributes,
        md5_of_system_attributes: sqs::md5_of_message_system_attributes(&system_attributes),
        body: entry.message_body.clone(),
        attributes,
        system_attributes,
        group_id,
        deduplication_id,
        delay,
        bytes: retained,
        size: bytes,
    })
}

/// Report `entry` as not taken, under its own `Id`.
fn refused(
    entry: &SendMessageBatchRequestEntry,
    code: &'static str,
    message: String,
) -> EntryRefusal {
    EntryRefusal {
        id: entry.id.clone(),
        code,
        message,
    }
}

/// The per-entry error code for a body holding a character outside the allowed set: the
/// name of the modelled error `SendMessage` answers for the same condition
/// (`com.amazonaws.sqs#InvalidMessageContents`), which is what AWS reports in a batch
/// result entry's `Code`.
///
/// The two parameter-level codes an entry can carry are NOT restated here: a batch entry
/// reports the same codes a single send does, so it reads them from
/// [`crate::scaffolded::INVALID_PARAMETER_VALUE`] and
/// [`crate::scaffolded::MISSING_PARAMETER`] — one spelling of each for the whole crate.
const INVALID_MESSAGE_CONTENTS: &str = "InvalidMessageContents";
