impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetLatestConfiguration<Eng>
{
    type Input = GetLatestConfigurationInput;
    type Output = GetLatestConfigurationOutput;
    type Error = GetLatestConfigurationError;

    const NAME: &'static str = "GetLatestConfiguration";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_LATEST_CONFIGURATION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_LATEST_CONFIGURATION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(session_store_unavailable());
        };

        let now = std::time::SystemTime::now();
        let token = input.configuration_token;

        // STEP 0 — a request that supplies no usable value for the token member supplied
        // no token, and is refused as the validation failure it is BEFORE any lookup: the
        // verdict path below answers for a token the caller actually presented. A blank
        // value cannot be one — the member targets `Token`, whose modelled pattern is
        // `^\S{1,8192}$` (smithy_query query="shape" shape="Token"), which no run of
        // whitespace satisfies.
        if token.trim().is_empty() {
            return Err(configuration_token_required());
        }

        // STEP 0b — whether the CALLER may poll at all, decided against its own
        // identity-based IAM policies before any verdict about the token's state: AWS
        // decides authorization at the IAM layer, ahead of the service's own reading of
        // the request ([`crate::state::identity_authorization`]).
        //
        // A poll's own input names only the token, so the configuration the action is
        // judged against is the one the session that token resolves to is over — the
        // identifiers it was started with — and a token resolving to no session at all
        // addresses no configuration this service can name, so the decision is taken on
        // the action alone. The identifiers are read out and the guard released before
        // anything else is asked, so no other store is read with this one held.
        let addressed = {
            let store = state.lock();
            store.session(&token).map(|session| {
                crate::state::identity_authorization::configuration_addressed(
                    ctx.parts(),
                    &session.application_identifier,
                    &session.environment_identifier,
                    &session.configuration_profile_identifier,
                )
            })
        };
        if let Some(denial) = crate::state::identity_authorization::refusal(
            &*self.engine,
            ctx,
            <Self as smithy_server_runtime::Operation>::NAME,
            addressed
                .as_deref()
                .unwrap_or(crate::state::identity_authorization::ANY_RESOURCE),
        ) {
            tracing::debug!(
                operation = "GetLatestConfiguration",
                outcome = "AccessDeniedException",
                "refused a poll the caller's identity policies do not allow"
            );
            return Err(crate::scaffolded::Scaffolded::access_denied(denial));
        }

        // STEP 1 — resolve the token and check it may be used, under this service's
        // own lock, which is RELEASED before the control plane is read: the two stores
        // are taken one at a time, never nested. The same guard hands out the name
        // bindings STEP 2 resolves the session's identifiers through, so the control
        // plane is read with no guard of this store held.
        let (session, bindings) = {
            let state = state.lock();

            // The token is opaque, so one this store never minted carries no session
            // and cannot be understood: `Corrupted`.
            let Some(session) = state.session(&token).cloned() else {
                return Err(bad_configuration_token("Corrupted"));
            };

            // A token is usable for at most `TOKEN_LIFETIME` after it was minted; past
            // that it can no longer be used: `Expired`.
            if let Some(expired) = expiry_refusal(&session, now) {
                return Err(expired);
            }

            // Honour the floor the session asked for: a session that set
            // `RequiredMinimumPollIntervalInSeconds` may not poll faster than that, and
            // the refusal serves nothing and rotates nothing, so the same token answers
            // once the interval has passed.
            //
            // ONE value feeds both the floor enforced here and the interval reported
            // below, so the response never advertises a cadence other than the one
            // enforced. A non-positive stored value is no floor at all (the modelled
            // 15..86400 range refuses one at the boundary, before this handler runs).
            if let (Some(minimum), Some(last_polled_at)) =
                (required_minimum(&session), session.last_polled_at)
            {
                let minimum = std::time::Duration::from_secs(u64::from(minimum.unsigned_abs()));
                let since_last_poll = now
                    .duration_since(last_polled_at)
                    .unwrap_or(std::time::Duration::ZERO);
                if since_last_poll < minimum {
                    return Err(bad_configuration_token("PollIntervalNotSatisfied"));
                }
            }
            (session, state.name_bindings())
        };

        // STEP 2 — the configuration this poll serves. The session is already BOUND to
        // one (`crate::state::Session::bound_configuration`, recorded when the session
        // was started and carried forward by every poll): the AppConfig CONTROL PLANE is
        // re-read here only to pick up a configuration deployed since, so a triple that
        // no longer resolves there leaves the session serving what it is bound to rather
        // than refusing a token that is live.
        //
        // Resolving the application, environment and configuration profile is what
        // STARTING a session does — that is where a level the control plane does not hold
        // is `ResourceNotFoundException` — and the model bounds a token by TIME and
        // nothing else, so a control-plane edit made after the session was bound cannot
        // retroactively unmake it. Only a session bound to no configuration at all has
        // nothing to serve, and that is what this operation reports as not found.
        //
        // A name is resolved through the bindings the session's own mint recorded, not
        // against whatever the control plane says carries that name now, so renaming a
        // record does not redirect or break a session already polling it. The poll binds
        // nothing itself: a read must not change what a later caller sees.
        let Some(deployed) = crate::state::served_configuration(
            &*self.engine,
            &bindings,
            &session.application_identifier,
            &session.environment_identifier,
            &session.configuration_profile_identifier,
            now,
        ) else {
            return Err(control_plane_unavailable());
        };
        let deployed: std::sync::Arc<crate::state::ServedConfiguration> = match deployed {
            // The control plane answered, so the session is re-bound to what it reports.
            // A configuration VERSION is immutable once written — it is what a deployment
            // names, and no operation rewrites its bytes, its content type or its label —
            // so a live answer naming the version this session is already bound to IS that
            // configuration, and the existing binding is kept rather than a second copy of
            // the same bytes held for every token in the poll chain.
            Ok(live) => match &session.bound_configuration {
                Some(bound) if bound.version == live.version => std::sync::Arc::clone(bound),
                _ => std::sync::Arc::new(live),
            },
            Err(unresolved) => match &session.bound_configuration {
                Some(bound) => std::sync::Arc::clone(bound),
                None => {
                    return Err(GetLatestConfigurationErrorModeled::ResourceNotFoundException(
                        ResourceNotFoundException {
                            message: Some(unresolved.message.clone()),
                            resource_type: Some(unresolved.resource_type.to_string()),
                            referenced_by: unresolved.referenced_by(),
                        },
                    )
                    .into());
                }
            },
        };

        // STEP 3 — content is returned ONLY when the deployed version differs from
        // the one this session was last served. Both values are read out of state,
        // so "unchanged" is a comparison, never an assumption.
        let already_has_latest = session.last_served_version.as_deref() == Some(&deployed.version);

        // STEP 4 — rotate the token. The model's own doc for this operation says "the
        // GetLatestConfiguration response includes a NextPollConfigurationToken that
        // should always replace the token used for the just-completed call", so minting
        // the successor is what this call is defined to do. The successor carries the
        // version just served, so the next poll's comparison is against what the client
        // now holds.
        //
        // The token is re-checked under the lock the poll is recorded under: the control
        // plane was read with no guard held, so the entry could have reached its expiry in
        // between.
        let next_poll_configuration_token = {
            let mut state = state.lock();
            match state.session(&token) {
                None => return Err(bad_configuration_token("Corrupted")),
                Some(current) => {
                    if let Some(expired) = expiry_refusal(current, now) {
                        return Err(expired);
                    }
                }
            }
            state.record_token_use(&token, now);
            let mut next_session = session.clone();
            next_session.last_served_version = Some(deployed.version.clone());
            // The successor is bound to what this poll served, so a poll after the
            // control plane stops resolving the triple still has a configuration to be
            // served from.
            next_session.bound_configuration = Some(std::sync::Arc::clone(&deployed));
            next_session.last_polled_at = Some(now);
            state.store_session(next_session, now)
        };

        // An access record for the poll: which configuration was read and whether
        // content was served. The token values are never recorded.
        tracing::debug!(
            operation = "GetLatestConfiguration",
            outcome = if already_has_latest {
                "unchanged"
            } else {
                "configuration served"
            },
            application = session.application_identifier.as_str(),
            environment = session.environment_identifier.as_str(),
            configuration_profile = session.configuration_profile_identifier.as_str(),
            version = deployed.version.as_str(),
            "served a configuration poll"
        );

        Ok(GetLatestConfigurationOutput {
            next_poll_configuration_token: Some(next_poll_configuration_token),
            // The interval the session asked for, else the service's default: never
            // the modelled `0` default, which would tell a client to poll in a loop.
            next_poll_interval_in_seconds: required_minimum(&session)
                .unwrap_or(crate::state::DEFAULT_POLL_INTERVAL_IN_SECONDS),
            // An empty payload when the client already has the latest version. The
            // version label is documented to be empty in that case ("If the client
            // already has the latest version of the configuration data, this value is
            // empty"); the content type is not — it describes the format of the
            // session's configuration, which is known either way — so it is always
            // reported.
            configuration: Some(if already_has_latest {
                Vec::new()
            } else {
                deployed.content.clone()
            }),
            content_type: Some(deployed.content_type.clone()),
            version_label: if already_has_latest {
                None
            } else {
                deployed.version_label.clone()
            },
        })
    }
}

/// The poll floor this session asked for, when it asked for a usable one.
fn required_minimum(session: &crate::state::Session) -> Option<i32> {
    session
        .required_minimum_poll_interval_in_seconds
        .filter(|seconds| *seconds > 0)
}

/// Why `session`'s token can no longer be used, if it cannot: its lifetime has passed.
///
/// A token is bounded by TIME and by nothing else. The model's own doc for both
/// `ConfigurationToken` and `NextPollConfigurationToken` says "To support long poll use
/// cases, the token is valid for up to 24 hours. If a `GetLatestConfiguration` call uses
/// an expired token, the system returns `BadRequestException`" — so the one thing that
/// makes a token `Expired` is its mint instant against [`crate::state::TOKEN_LIFETIME`].
/// "This token should only be used once" is guidance to the CLIENT about which token to
/// present next, not a second expiry: a client that re-presents a token it still holds —
/// the documented recovery after a poll whose response it failed to persist — is inside
/// that token's lifetime and is served.
fn expiry_refusal(
    session: &crate::state::Session,
    now: std::time::SystemTime,
) -> Option<GetLatestConfigurationError> {
    (now >= session.expires_at).then(|| bad_configuration_token("Expired"))
}

