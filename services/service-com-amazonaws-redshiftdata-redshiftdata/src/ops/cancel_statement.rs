impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CancelStatement<Eng>
{
    type Input = CancelStatementInput;
    type Output = CancelStatementOutput;
    type Error = CancelStatementError;

    const NAME: &'static str = "CancelStatement";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CANCEL_STATEMENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CANCEL_STATEMENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(CancelStatementErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the Redshift Data API state store is unavailable".to_string(),
                },
            )
            .into());
        };

        let mut store = state.lock();
        // A statement whose execution has already reported is no longer running,
        // so those outcomes are materialised before this call decides.
        store.materialise_due_transitions();
        // ONE lookup decides the outcome and carries the status it observed.
        match store.cancel(&input.id) {
            Cancellation::Cancelled => Ok(CancelStatementOutput { status: Some(true) }),
            // Already stopped: not a cancellation, and reporting one would tell
            // the caller it stopped a query it did not stop. The service names
            // the state the query is already in and the query it asked about.
            Cancellation::AlreadyStopped(status) => {
                Err(CancelStatementErrorModeled::ValidationException(ValidationException {
                    message: Some(format!(
                        "Could not cancel a query that is already in {} state with ID: {}",
                        status.as_str(),
                        input.id,
                    )),
                })
                .into())
            }
            // One statement of a batch is not a query that runs on its own, so
            // there is no such query to stop: the batch is what a caller
            // cancels, and it is named here so the caller can.
            Cancellation::BatchMember(batch_id) => {
                Err(CancelStatementErrorModeled::ValidationException(ValidationException {
                    message: Some(format!(
                        "Query {} is one SQL statement of the batch query {batch_id}, which is \
                         what can be cancelled",
                        input.id,
                    )),
                })
                .into())
            }
            // An `Id` this service holds no query for gets the same refusal, in
            // the same fixed words and at the same status, as every other reader
            // of a statement gives (see `describe_statement::no_such_query`).
            Cancellation::Unknown => Err(crate::scaffolded::Scaffolded::modeled_with_status(
                CancelStatementErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
                    message: UNKNOWN_QUERY_MESSAGE.to_string(),
                    resource_id: input.id.clone(),
                }),
                UNKNOWN_QUERY_STATUS,
            )),
        }
    }
}
