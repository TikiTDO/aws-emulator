/// What this service's own store says about a `CreateConnection` request.
enum StoreVerdict {
    /// The request's `clientToken` already created this connection, so it is replayed.
    Replay(Connection),
    /// Nothing the store holds refuses the request: this is the Environment the
    /// connection would be created across.
    Create(Environment),
}

/// Judge everything the REQUEST ITSELF carries, before anything the request NAMES is
/// resolved.
///
/// A tag set outside what this service stores, and a value outside the constraints the
/// model puts on the union member that carries it — `AttachPoint`'s and
/// `RemoteAccountIdentifier`'s alike, neither of which the boundary validator reaches,
/// because both constraints sit on a member one level down — are faults in the INPUT
/// whatever the `environmentId` names, so they are judged here and no verdict about a
/// resource (an `environmentId` this endpoint's catalog does not hold, a `clientToken`
/// that already created a different connection) can mask them. The same ordering, and
/// the same rules, the acceptance that writes the other half of these members applies.
///
/// Whether `remoteAccount` is NEEDED at all is the Environment's to say, so that half of
/// its rule stays with the Environment below; what an identifier may CARRY is the
/// member's own and is judged here.
fn judge_request(input: &CreateConnectionInput) -> Result<(), CreateConnectionError> {
    // The entries the request carries, each inside the lengths the model gives `TagKey`
    // and `TagValue` and none of them in the namespace AWS reserves for its own system
    // tags. (The boundary validator holds a LIST's members to their target's constraints
    // but not a MAP's keys, so a tag map is checked here.) The entry-count bound on the
    // merged set is judged where the resource is known.
    if let Some(message) = input
        .tags
        .as_ref()
        .and_then(|tags| crate::state::tag_write_violation(None, tags))
    {
        return Err(CreateConnectionErrorModeled::InterconnectValidationException(
            InterconnectValidationException { message },
        )
        .into());
    }

    // What the `remoteAccount` union CARRIES, against the member's own modelled length
    // and pattern (`crate::state::remote_identifier_violation`).
    if let Some(message) = crate::state::remote_identifier_violation(input.remote_account.as_ref())
    {
        return Err(CreateConnectionErrorModeled::InterconnectValidationException(
            InterconnectValidationException { message },
        )
        .into());
    }

    // What the `attachPoint` union carries, against its own member's modelled length and
    // pattern, by the one rule every reader of an `AttachPoint` applies
    // (`crate::state::judge_attach_point_value`).
    crate::state::judge_attach_point_value::<CreateConnectionError>(&input.attach_point)
}

/// Judge a request against everything this service's OWN store answers: the idempotent
/// replay, the Environment, its state, the bandwidth it offers, whether it asks for
/// identifying information, and the `arn` attach point. What the request itself carries
/// is [`judge_request`]'s, judged before any of this.
///
/// `region` is the Region the request addressed, which is the scope every connection
/// this judgement resolves is looked up in: a connection belongs to the Region it was
/// created in, so neither a `clientToken` nor an attach-point ARN of another Region
/// resolves here.
///
/// Called under the lock BOTH before the cross-service resolution and again at the
/// instant the connection is minted, so a verdict is never acted on from a store that
/// has since moved: check and insert happen under one lock. Running the whole
/// judgement twice is deliberate — it is all map lookups over a few hundred records,
/// and the alternative, a phase-A subset, would be two rules to keep in step.
fn judge_against_store(
    store: &crate::state::ComAmazonawsInterconnectInterconnectState,
    input: &CreateConnectionInput,
    region: &str,
) -> Result<StoreVerdict, CreateConnectionError> {
    // @idempotencyToken: a retry carrying a client token that already created a
    // connection replays THAT connection instead of allocating a second one —
    // but only when it is the SAME request. A token reused with different
    // parameters names a different connection than the one it created, so it is
    // refused, naming the token, rather than answered with an unrelated record.
    // "The same" is judged on EVERY member of the create the caller owns, absence
    // included, so no member of a retried request can be swapped silently.
    //
    // The token is held under the Region the request addressed: the connection it
    // created belongs to that Region, so the same token sent to another Region's
    // endpoint is one that endpoint has never seen.
    if let Some(token) = input.client_token.as_deref() {
        if let Some(created) = store
            .idempotency_tokens
            .get(&crate::state::idempotency_key(region, token))
        {
            if !created.matches(input) {
                return Err(CreateConnectionErrorModeled::InterconnectValidationException(
                    InterconnectValidationException {
                        message: crate::state::client_token_reused_message(
                            token,
                            &created.connection_id,
                        ),
                    },
                )
                .into());
            }
            if let Some(stored) = store.connection_in(region, &created.connection_id) {
                return Ok(StoreVerdict::Replay(stored.connection.clone()));
            }
        }
    }

    // The Environment dictates the partner, the location and the product type,
    // none of which the request carries. It is resolved in the catalog of the Region
    // this create was signed for, because an Environment produces connections that
    // land in that Region alone: an id this endpoint's catalog does not hold — one of
    // another Region's catalog included — has nothing to create a connection across,
    // and naming one is this service's own client fault: the 400
    // `InterconnectClientException` every environment-resolving operation gives, with
    // the message built from the requested id.
    let Some(environment) = crate::state::environment_in_region(region, &input.environment_id)
    else {
        return Err(CreateConnectionErrorModeled::InterconnectClientException(
            InterconnectClientException {
                message: crate::state::environment_not_found_message(&input.environment_id),
            },
        )
        .into());
    };

    // `EnvironmentState`: only an environment that is not `unavailable` can take
    // new connections ("available: the environment is available and new
    // Connection objects can be requested" / "unavailable: the environment is
    // currently unavailable").
    if environment.state == crate::state::UNAVAILABLE_ENVIRONMENT_STATE {
        return Err(CreateConnectionErrorModeled::InterconnectClientException(
            InterconnectClientException {
                message: crate::state::environment_unavailable_message(
                    &environment.environment_id,
                    &environment.state,
                ),
            },
        )
        .into());
    }

    // The bandwidth the connection would be allocated at, judged by the one rule
    // every writer of a connection's bandwidth uses: it has to be one the
    // Environment it is allocated on currently offers. The create that allocates
    // the first bandwidth is therefore bounded exactly as the update that
    // re-allocates one is, so neither path can store a value the other would refuse.
    if let Some(message) = crate::state::bandwidth_availability_violation(
        Some(&environment),
        &environment.environment_id,
        &input.bandwidth,
    ) {
        return Err(CreateConnectionErrorModeled::InterconnectValidationException(
            InterconnectValidationException { message },
        )
        .into());
    }

    // `Environment$remoteIdentifierType` names the kind of identifying information
    // the partner of THIS Environment will verify the remote side by, so an
    // Environment that declares one needs a `remoteAccount` on every create against
    // it and one that declares none needs nothing. That PRESENCE is this Environment's
    // to say, which is why it is judged here; what an identifier the request did carry
    // may hold is the member's own rule and was judged on the request alone
    // ([`judge_request`]) — the identity itself is verified later, at the partner
    // portal.
    if let Some(message) =
        crate::state::remote_account_violation(&environment, input.remote_account.as_ref())
    {
        return Err(CreateConnectionErrorModeled::InterconnectValidationException(
            InterconnectValidationException { message },
        )
        .into());
    }

    // The tag set the new connection would carry is judged on the REQUEST alone
    // ([`judge_request`]): a create allocates a fresh resource, so the set it would be
    // left holding IS the set the request carries — there is no held set to merge with
    // — and the one rule every writer of a connection's tags uses
    // (`crate::state::tag_write_violation`) is applied there, ahead of every lookup.

    // The attach point the request selected, judged by the one rule both writers of a
    // connection's attach point apply to it
    // (`crate::state::judge_attach_point_in_store`): first the value against the
    // union member's OWN modelled length and pattern, which nothing before the
    // handler holds it to, so a value that is not an identifier of its kind is
    // refused as invalid INPUT rather than resolved and then reported as a resource
    // the account does not hold; then, for `AttachPoint$arn` — which "identifies an
    // attach point by full ARN", and whose pattern is an Interconnect CONNECTION ARN
    // — the connection it names, resolved in full, so one whose Region or account is
    // not the stored one names no resource this account holds, inside the scope the
    // request addressed, so a connection created through another Region's endpoint is
    // one this endpoint holds nothing for, and with the connectivity behind it actually
    // there, so a connection that is not fully provisioned — one still being brought up
    // as much as one whose teardown has been called — is not an attach
    // point. An ARN that resolves to nothing has no attach point behind it, so
    // there is nothing to provision the connection onto — the same answer, and the
    // same wording, an identifier the account does not hold at all gets, so what
    // refuses the request never reports whether another scope holds the resource.
    crate::state::judge_attach_point_in_store::<CreateConnectionError>(
        store,
        region,
        &input.attach_point,
        &environment.environment_id,
    )?;

    Ok(StoreVerdict::Create(environment))
}

