const API_KEY_AUTHORIZATION: &str = "API_KEY";
const BASIC_AUTHORIZATION: &str = "BASIC";
const OAUTH_AUTHORIZATION: &str = "OAUTH_CLIENT_CREDENTIALS";

/// The submitted authorization parameters as a READ reports them.
///
/// The projection `CreateConnection` makes, over the update request's shapes: the
/// response shape carries exactly the non-secret half of each request shape, so no
/// password, key value or client secret an update carried is ever stored on the
/// record a read serializes.
fn reported_auth_parameters(
    parameters: &UpdateConnectionAuthRequestParameters,
) -> ConnectionAuthResponseParameters {
    ConnectionAuthResponseParameters {
        basic_auth_parameters: parameters.basic_auth_parameters.as_ref().map(|basic| {
            ConnectionBasicAuthResponseParameters {
                username: basic.username.clone(),
            }
        }),
        o_auth_parameters: parameters
            .o_auth_parameters
            .as_ref()
            .map(reported_oauth_parameters),
        api_key_auth_parameters: parameters.api_key_auth_parameters.as_ref().map(|key| {
            ConnectionApiKeyAuthResponseParameters {
                api_key_name: key.api_key_name.clone(),
            }
        }),
        // Every parameter value the request flagged secret is withheld, for the
        // reason `crate::state::reported_http_parameters` records.
        invocation_http_parameters: parameters
            .invocation_http_parameters
            .as_ref()
            .map(crate::state::reported_http_parameters),
        // See `CreateConnection`: this emulator makes no resource association, so
        // there is none to name and none is reported.
        connectivity_parameters: None,
    }
}

/// The submitted OAuth parameters as a READ reports them: the client id without
/// its secret, and the HTTP parameters of the exchange with every value the
/// request flagged secret withheld.
///
/// Named on its own because the authorization parameters a read reports are the
/// non-secret half of exactly the block the exchange is made from
/// ([`connection_secret`] keeps the other half), so the two are one projection of
