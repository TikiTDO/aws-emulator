//! @op StartReplay
//! Starts a replay: re-publishes the events one archive holds, in a window of
//! event time, onto an event bus.
//!
//! "Starts the specified replay ... A replay processes events to replay based on
//! the time in the event" (this operation's documentation): the archive the
//! `EventSourceArn` names is read for the events whose OWN time lies in
//! `[EventStartTime, EventEndTime]` ([`crate::state::ReplayRecord::replays`]), and
//! each of them is re-published onto `Destination.Arn` — "the ARN of the event bus
//! to replay event to. You can replay events only to the event bus specified to
//! create the archive", so a destination that is not the archive's source bus is
//! refused. An `EventSourceArn` that resolves to no archive this account holds is
//! refused as the PARAMETER it is — a `ValidationException` naming the member and
//! the archive the ARN named — and a `ReplayName` already held is
//! `ResourceAlreadyExistsException`: the name is the replay's identity, which is
//! what `DescribeReplay` reads it back under.
//!
//! A re-published event is the event the archive holds, carrying the
//! [`crate::state::REPLAY_NAME_FIELD`] of the replay that re-published it
//! ([`crate::state::replayed_envelope`]) — which is what a rule can tell a
//! redelivered event by, and what keeps the archive's own managed rule from
//! archiving it again ([`crate::state::archive_rule_pattern`]). Routing and
//! delivery are the bus's, not this operation's: each event is matched against
//! the rules of the destination bus and handed to their targets by the SAME code
//! a published event is ([`crate::ops::put_events::route`] and
//! [`crate::ops::put_events::deliver`]), so a replayed event reaches a target
//! exactly as a live one does. "A list of ARNs for rules to replay events to"
//! (`ReplayDestination$FilterArns`) CONFINES that routing: when the destination
//! carries filters, only the rules they name are matched at all, and a filter
//! naming no rule of that bus is refused.
//!
//! The replay is answered in [`crate::state::REPLAY_STATE_STARTING`] and reaches
//! [`crate::state::REPLAY_STATE_COMPLETED`]
//! [`crate::state::REPLAY_TRANSITION`] later
//! ([`crate::state::ComAmazonawsEventbridgeAwseventsState::settle_replays`]), so a
//! caller polling `DescribeReplay` straight after the call still observes the
//! non-terminal state; its `EventLastReplayedTime` is the event time of the last
//! event this call replayed, because "a replay processes events to replay based on
//! the time in the event" and the events are therefore replayed in event-time
//! order. A `CancelReplay` in that window stops it instead
//! ([`crate::ops::cancel_replay`]), so the replay settles
//! [`crate::state::REPLAY_STATE_CANCELLED`] rather than completed.
//!
