const BASIC_AUTHORIZATION: &str = "BASIC";
const OAUTH_AUTHORIZATION: &str = "OAUTH_CLIENT_CREDENTIALS";

/// The authorization parameters as a READ reports them.
///
/// The response shape carries exactly the non-secret half of each request shape:
/// `ConnectionBasicAuthResponseParameters` has a `Username` and no password,
/// `ConnectionApiKeyAuthResponseParameters` an `ApiKeyName` and no value, and
/// `ConnectionOAuthClientResponseParameters` a `ClientID` and no secret — and
/// the header, query-string and body parameters a connection sends keep their
/// keys and lose every value flagged secret
/// ([`crate::state::reported_http_parameters`]). The projection happens ONCE,
/// here, so no secret the request carried is ever stored on the record a read
/// serializes.
fn reported_auth_parameters(
    parameters: &CreateConnectionAuthRequestParameters,
) -> ConnectionAuthResponseParameters {
    ConnectionAuthResponseParameters {
        basic_auth_parameters: parameters.basic_auth_parameters.as_ref().map(|basic| {
            ConnectionBasicAuthResponseParameters {
                username: Some(basic.username.clone()),
            }
        }),
        o_auth_parameters: parameters.o_auth_parameters.as_ref().map(|oauth| {
            ConnectionOAuthResponseParameters {
                client_parameters: Some(ConnectionOAuthClientResponseParameters {
                    client_id: Some(oauth.client_parameters.client_id.clone()),
                }),
                authorization_endpoint: Some(oauth.authorization_endpoint.clone()),
                http_method: Some(oauth.http_method.clone()),
                // The HTTP parameters of the OAuth exchange are reported back
                // with every value the request flagged secret withheld, like the
                // invocation parameters below.
                o_auth_http_parameters: oauth
                    .o_auth_http_parameters
                    .as_ref()
                    .map(crate::state::reported_http_parameters),
            }
        }),
        api_key_auth_parameters: parameters.api_key_auth_parameters.as_ref().map(|key| {
            ConnectionApiKeyAuthResponseParameters {
                api_key_name: Some(key.api_key_name.clone()),
            }
        }),
        // Every parameter value the request flagged secret is withheld, for the
        // reason `crate::state::reported_http_parameters` records: a secret value
        // lives in the connection's secret, which `SecretArn` names, and is not
        // part of what a read may report.
        invocation_http_parameters: parameters
            .invocation_http_parameters
            .as_ref()
            .map(crate::state::reported_http_parameters),
        // The connectivity parameters a read reports carry the ARN of the
        // resource ASSOCIATION EventBridge made with the resource configuration,
        // beside the configuration's own ARN. This emulator makes no such
        // association, so there is none to name and none is reported — the
        // configuration the request named is kept on the record
        // (`ConnectionRecord::invocation_resource_configuration_arn`) for when
        // the private-connectivity path is implemented.
        connectivity_parameters: None,
    }
}

/// The credential half of the submitted parameters — the half the response
/// shapes above withhold.
///
/// It is what the secret `SecretArn` names holds, and what every invocation
/// through this connection carries
/// ([`crate::state::invocation::ConnectionSecret`]): the api key under the
/// header name the request chose, the basic credentials the `Authorization`
/// header is built from, the client credentials an OAuth connection's token
/// request is made with ([`crate::state::oauth`]), and the
/// `InvocationHttpParameters` with the values the request flagged secret still in
/// them, because the endpoint is sent those values and not their keys alone. An
/// `OAUTH_CLIENT_CREDENTIALS` connection's client credentials are NOT an
/// authorization the invocation can carry — they are exchanged for a token first,
/// and the TOKEN is what the invocation carries
/// ([`crate::state::record_authorization`] is what records it).
fn connection_secret(
    parameters: &CreateConnectionAuthRequestParameters,
) -> crate::state::invocation::ConnectionSecret {
    crate::state::invocation::ConnectionSecret {
        api_key: parameters.api_key_auth_parameters.as_ref().map(|key| {
            crate::state::invocation::ApiKeyCredential {
                name: key.api_key_name.clone(),
                value: key.api_key_value.clone(),
            }
        }),
        basic: parameters.basic_auth_parameters.as_ref().map(|basic| {
            crate::state::invocation::BasicCredential {
                username: basic.username.clone(),
                password: basic.password.clone(),
            }
        }),
        oauth: parameters
            .o_auth_parameters
            .as_ref()
            .map(|oauth| crate::state::oauth::OAuthCredential {
                client_id: oauth.client_parameters.client_id.clone(),
                client_secret: oauth.client_parameters.client_secret.clone(),
                authorization_endpoint: oauth.authorization_endpoint.clone(),
                http_method: oauth.http_method.clone(),
                http_parameters: oauth.o_auth_http_parameters.clone(),
            }),
        // A connection holds a token only once an exchange has issued one.
        oauth_token: None,
        invocation_http_parameters: parameters.invocation_http_parameters.clone(),
    }
}
