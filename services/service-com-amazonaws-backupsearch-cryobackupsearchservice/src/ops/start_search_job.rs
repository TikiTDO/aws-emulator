//! @op StartSearchJob
//! Mints a search job and PERSISTS it in [`crate::state`]: a UUID
//! `SearchJobIdentifier`, the `search-job/<id>` ARN built from it, the server clock's
//! `CreationTime`, the submitted `SearchScope`/`ItemFilters`/`Name`/`EncryptionKeyArn`/
//! `Tags`, the recovery points that scope resolves to, and `Status = CREATING`. The
//! members it answers with are read back out of that record, so `GetSearchJob` reports
//! the same values.
//!
//! A scope resolves in TWO layers, both counted from the stores: the recovery points it
//! selects (`TotalRecoveryPointsToScanCount`) and the items their backup indexes hold
//! (`TotalItemsToScanCount`, [`crate::state::scanned_items`]). The backups it selects
//! from are the ones AWS Backup holds for this account, read from THAT component's store
//! ([`crate::state::indexed_recovery_points`]) because that is where a backup exists, so
//! a recovery point a client created through `backup:StartBackupJob` is in scope on the
//! next call and one Backup no longer holds is in scope for nothing. The submitted `ItemFilters`
//! select the scan's matches from that item layer
//! ([`crate::state::item_matches_filters`]), and the record keeps them until the clock
//! makes the scan's completion due — which is when `ListSearchJobResults` can page them
//! and `ItemsMatchedCount` counts them.
//!
//! Both counts are over the covered recovery points the scan can READ: a backup whose
//! index was in no state to be read ([`crate::state::index_searchable`]) takes no part in
//! the search, so neither it nor any of its items is scanned, counted, matched or paged —
//! it is displayed, with the status saying why, by `ListSearchJobBackups`, and the job's
//! own `StatusMessage` says that the scope held such backups at all.
//!
//! The clock then owes the job `RUNNING` one set-up span after this call
//! ([`crate::state::CREATING_DELAY`]) and a terminal status once the scan has run for its
//! own, longer span ([`crate::state::SCAN_DELAY`]), so each phase lasts a whole span and a
//! client that cancels or polls after its own intervening work still finds the job in one
//! of them — a running scan is the window `StopSearchJob` acts in. WHICH
//! terminal one — with the `StatusMessage` it comes with — follows from the resolved scope
//! ([`crate::state::scan_outcome`]): a scan that got through every recovery point in scope
//! runs to `COMPLETED` and explains nothing, a scope that resolved to none ends `FAILED`
//! with the `StatusMessage` the service explains an empty scope with, and a scan that
//! covered recovery points it could not read runs to `COMPLETED` carrying the
//! `StatusMessage` that says how much of the scope was left unscanned.
//!
