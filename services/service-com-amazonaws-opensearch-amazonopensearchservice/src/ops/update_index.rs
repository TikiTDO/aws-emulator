        // settings, and semantic enrichment configuration": what the request names
        // is written onto the stored schema, and what it does not name the index
        // keeps, so `GetIndex` reports the index as this call left it.
        let merged = crate::state::merged_index_schema(&index.schema, &input.index_schema);

        // Because an update MERGES, the stored document grows across calls even
        // though each request is bounded on its own: past the per-index quota the
        // update is refused rather than growing the store further. This operation
        // models no limit error, so the refusal is its `ValidationException`.
