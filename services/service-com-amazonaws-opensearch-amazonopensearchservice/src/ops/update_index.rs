        // may add to that field's mapping but not re-type it. Checked against the
        // STORED schema and before anything is written, so a refused update leaves
        // the index exactly as it was, and so of two updates mapping one field with
        // different types the one that arrives first settles the type while the
        // other is refused.
        if let Some(conflict) =
            crate::state::mapping_type_conflict(&index.schema, &input.index_schema)
        {
            return Err(UpdateIndexErrorModeled::ValidationException(
                crate::state::mapping_type_immutable(&conflict),
            )
            .into());
        }

