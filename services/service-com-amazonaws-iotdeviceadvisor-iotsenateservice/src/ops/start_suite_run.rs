//! @op StartSuiteRun
//!
//! Creates and PERSISTS a suite run of one definition version: a new UUID id, the ARN, the
//! endpoint the run's primary device connects to, and the `PENDING` status the run starts
//! in.
//!
//! ## The run itself cannot execute here
//!
//! Device Advisor drives real MQTT test cases against a physical device over the IoT data
//! plane, which this emulator has no runner for. The control plane is real — the run is
//! minted, tracked, readable and stoppable — and the execution it cannot perform ends in
//! the service's own modelled failure status (`ERROR`, with
//! [`crate::state::NO_TEST_RUNNER_REASON`] as `errorReason`) rather than in a fabricated
//! `PASS`/`FAIL` with test results nothing produced.
//!
//! ## `parallelRun` decides whether a concurrent run is refused
//!
//! `SuiteRunConfiguration$parallelRun` is the input the model documents as governing
//! exactly this — "TRUE if multiple test suites run in parallel" — so a second run of one
//! definition is accepted while an earlier one is still in progress only when this request
//! and that earlier run BOTH ask for a parallel run; otherwise the earlier run holds the
//! definition and the start is refused with the modelled `ConflictException`. Runs that do
//! share a definition are capped by
//! [`crate::state::MAX_PARALLEL_RUNS_PER_DEFINITION`].
//!
//! ## The run is minted in its DEFINITION's scope
//!
//! A suite run is a child of the definition it runs — its ARN's resource portion is
//! `suiterun/<suiteDefinitionId>/<suiteRunId>`, so a run is not addressable apart from
//! that definition. The scope it is minted in therefore comes from the parent definition's
//! STORED ARN ([`crate::state::ArnScope`]), not from whichever request started it: the
//! run's ARN and the endpoint it reports name the same partition, region and account the
//! definition's own ARN names, so one scope addresses parent and child alike. The
//! request's region still stamps the audit record, which is about the CALL rather than
//! about the resource.
//!
//! ## An unknown definition is a `ValidationException`, not a `ResourceNotFoundException`
//!
//! `smithy_query(query="operation",operation="StartSuiteRun")` declares exactly three
//! errors for this operation — `ConflictException` (400), `InternalServerException` (500)
//! and `ValidationException` (400) — and no `ResourceNotFoundException`, so a request
//! naming a `suiteDefinitionId` (or a `suiteDefinitionVersion`) the store does not hold is
//! refused with the modelled client-input error this operation actually declares.
//!
