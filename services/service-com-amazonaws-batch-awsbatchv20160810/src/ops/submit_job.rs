//! @op SubmitJob
//! Submits a job and persists it in [`crate::state`].
//!
//! `jobQueue` resolves by name or ARN and `jobDefinition` by name, `name:revision` or
//! ARN, both against persisted state: an unknown queue, a queue whose `JQState` is
//! `DISABLED` ("new jobs can't be added to the queue"), a definition reference that names
//! no ACTIVE revision or an unknown `dependsOn` job id is a `ClientException`, never a 200
//! carrying an id nothing stored. The `jobDefinition` is resolved FIRST, so a submit that
//! names neither a stored definition nor a stored queue is refused on the DEFINITION, and
//! a reference naming nothing and one naming a revision that is not `ACTIVE` are the same
//! refusal ("does not exist or is not in ACTIVE status."). The job id is a fresh UUID, and
//! the record keeps the queue ARN, the resolved
//! revision's ARN, `createdAt` in epoch milliseconds, the parameters (the definition's
//! defaults with the request's applied over them), the effective container
//! (`containerProperties` with `containerOverrides` applied) and the submit request's own
//! members, so `DescribeJobs` reports exactly what was submitted.
//!
//! The job is returned in the non-terminal `SUBMITTED` status; the clock owns every move
//! out of it (see [`crate::state`]). A job state change event reports a job MOVING, so no
//! `Batch Job State Change` event is published for the status this call stores: the job's
//! event stream begins at its first move out of it. This call still drains and publishes
//! any transition the clock had already made due
//! (`state::publish_job_state_changes`).
//!
//! A submit carrying `arrayProperties` "becomes an array job": the id answered is the
//! array's PARENT and `size` children are created under it, each with its own
//! `ArrayPropertiesDetail.index` and the per-index `dependsOn` the array dependency forms
//! document (`state::array_child_dependencies`). The documented bound on the size
//! ("between 2 and 10,000") is enforced here, and room for the whole array is made before
//! any of it is stored.
//!
//! Parts of the surface this slice does NOT implement answer 501 rather than accept a
//! request they would then answer wrongly: `nodeOverrides` (a multi-node parent whose
//! children nothing would create), and
//! `ecsPropertiesOverride`/`eksPropertiesOverride` or a job definition whose body is
//! `ecsProperties`/`eksProperties` (their detail projection is not built here).
//!
//! This is the ONLY file to touch for this operation.
//!
