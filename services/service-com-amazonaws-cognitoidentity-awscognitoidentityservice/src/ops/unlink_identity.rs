impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> UnlinkIdentity<Eng> {
    /// The unlink itself: forget the named logins of the identity.
    async fn unlink(
        &self,
        input: UnlinkIdentityInput,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<UnlinkIdentityOutput, UnlinkIdentityError> {
        // This operation reads and writes the identity store only; `ctx` carries nothing it
        // needs.
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UnlinkIdentityErrorModeled::InternalErrorException(
                InternalErrorException {
                    message: Some("the identity-pool store is unavailable".to_string()),
                },
            )
            .into());
        };

        let now = ::std::time::SystemTime::now();
        // Which issuers the pool trusts is partly IAM's record — an
        // `OpenIdConnectProviderARNs` entry names an IAM OpenID Connect provider — so the
        // account's providers are read BEFORE this service's own store is locked.
        let registered = crate::state::registered_oidc_providers(&*self.engine);
        // What an integrated user pool says about a user-pool token this call presents is
        // that service's record, so it too is read before this service's store is locked
        // ([`crate::state::user_pool_logins`]).
        let integrated = crate::state::user_pool_logins(&*self.engine, &input.logins);
        let mut store = state.lock();

        // The identity named is what this call unlinks logins FROM, so it has to be one
        // this service holds.
        let Some(identity) = store.identities.get(&input.identity_id) else {
            return Err(UnlinkIdentityErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::state::identity_not_found_message(
                        &input.identity_id,
                    )),
                },
            )
            .into());
        };
        let identity_pool_id = identity.identity_pool_id.clone();

        // An identity is an identity OF a pool, so resolving it is not done until the pool
        // it belongs to is resolved too: the record of an identity outlives the delete of
        // its pool, and a call made once the pool has gone reports the resource that is
        // actually missing — the pool — before anything about the identity or the logins
        // presented for it is decided.
        let Some(pool) = store.identity_pools.get(&identity_pool_id) else {
            return Err(UnlinkIdentityErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(format!("IdentityPool '{identity_pool_id}' not found.")),
                },
            )
            .into());
        };

        // This operation takes LINKED LOGINS off an identity, and an UNAUTHENTICATED (guest)
        // identity — the one `GetId` mints for a call presenting no login at all — has never
        // had one: there is nothing of it to unlink, whatever the call presents.
        if !identity.has_been_linked() {
            return Err(UnlinkIdentityErrorModeled::NotAuthorizedException(
                NotAuthorizedException {
                    message: Some(
                        crate::state::CANNOT_UNLINK_UNAUTHENTICATED_MESSAGE.to_string(),
                    ),
                },
            )
            .into());
        }

        // A `Logins` entry is decided by the pool the identity belongs to, exactly as it is
        // wherever else this service is handed one: the TOKEN it presents first — a value
        // that is not the kind of token its provider issues, and one issued by someone other
        // than the provider it is presented under, authorize nothing — and then the trust
        // that pool states for the token's issuer, with the audience that trust accepts, and
        // last what the user pool an entry asking for server-side token validation names
        // says about the user its token stands for.
        if let Some(refusal) = pool.refuse_logins(&registered, &integrated, &input.logins) {
            return Err(UnlinkIdentityErrorModeled::NotAuthorizedException(
                NotAuthorizedException {
                    message: Some(refusal.message(&pool.identity_pool_id).into_owned()),
                },
            )
            .into());
        }

        // A token presented under this service's OWN provider name names an issuance this
        // service recorded, so its validity is readable here exactly as it is at the
        // credential exchange: one outside the window its issuance recorded, one this
        // service never issued, and one minted for ANOTHER identity authorize nothing
        // either.
        if let Some(refusal) =
            store.refuse_presented_login_tokens(&input.identity_id, &input.logins, now)
        {
            return Err(UnlinkIdentityErrorModeled::NotAuthorizedException(
                NotAuthorizedException {
                    message: Some(refusal.message().to_string()),
                },
            )
            .into());
        }

        // Being an unsigned public API, the call carries no credential of this service: a
        // LOGIN of the identity it names is the whole authorization for it, so a call
        // presenting none at all — and one presenting only logins of some other user — is
        // refused before any index or record is touched.
        if let Some(refusal) = store.refuse_identity_access(identity, &input.logins, now) {
            return Err(UnlinkIdentityErrorModeled::NotAuthorizedException(
                NotAuthorizedException {
                    message: Some(refusal.message(&input.identity_id)),
                },
            )
            .into());
        }

        // This operation detaches PUBLIC-provider logins: a developer login is detached
        // through `UnlinkDeveloperIdentity`, which is the operation that takes a
        // `DeveloperProviderName`. A `Logins` map naming no public provider at all —
        // carrying only the pool's own developer provider — therefore presents nothing this
        // operation can act for, which is a bad input parameter.
        if !pool.logins_name_a_public_provider(&input.logins) {
            return Err(UnlinkIdentityErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(crate::state::NO_PUBLIC_PROVIDER_MESSAGE.to_string()),
                },
            )
            .into());
        }

        // A presented login this pool has linked to a DIFFERENT identity belongs to that
        // other account, so the call is not one this identity may make — which is exactly
        // what the modelled `ResourceConflictException` states ("a login which is already
        // linked to another account").
        let presents_another_account = input.logins.iter().any(|(provider, login)| {
            store
                .linked_identity(&identity_pool_id, provider, login)
                .is_some_and(|linked| *linked != input.identity_id)
        });
        if presents_another_account {
            return Err(UnlinkIdentityErrorModeled::ResourceConflictException(
                ResourceConflictException {
                    message: Some(format!(
                        "A login presented for identity '{}' is already linked to another \
                         identity.",
                        input.identity_id
                    )),
                },
            )
            .into());
        }

        // `LoginsToRemove` carries PROVIDER NAMES, and unlinking a provider from an identity
        // means no login of that provider reaches the identity any more — so every login
        // value this pool indexed for it against this identity goes, not just a value the
        // request happened to present. The index is swept ONCE, whatever the length of the
        // list (`LoginsList` states no bound of its own), so the work is the size of the
        // store rather than the product of the two.
        let unlinked: ::std::collections::HashSet<&str> =
            input.logins_to_remove.iter().map(String::as_str).collect();
        let indexed_before = store.login_index.len();
        store.login_index.retain(|(pool_id, provider, _), linked| {
            !(*pool_id == identity_pool_id
                && *linked == input.identity_id
                && unlinked.contains(provider.as_str()))
        });
        let mut unlinked_anything = store.login_index.len() != indexed_before;

        // The identity keeps the providers the call did not name. It is NOT deleted when the
        // last one goes: "removing the last linked login will make this identity
        // inaccessible", which is what an identity no login resolves to already is — and an
        // identity an unlink left linked to nothing is a DISABLED one, which is what makes
        // every later read of it project the disabled sentinel in place of the providers
        // that were removed rather than the empty list of an identity never linked at all.
        if let Some(identity) = store.identities.get_mut(&input.identity_id) {
            let linked_before = identity.logins.len();
            identity
                .logins
                .retain(|provider| !unlinked.contains(provider.as_str()));
            let took_a_provider_off = identity.logins.len() != linked_before;
            unlinked_anything |= took_a_provider_off;
            // A link the call actually removed is a change to the identity, recorded with
            // the instant it happened; a call that removed none leaves the record alone.
            if unlinked_anything {
                identity.last_modified_date = now;
            }
            if took_a_provider_off && identity.logins.is_empty() {
                identity.disabled = true;
            }
        }

        Ok(UnlinkIdentityOutput)
    }
}
