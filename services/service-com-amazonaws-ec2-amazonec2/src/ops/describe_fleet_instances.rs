        // (`smithy_query(query="operation",operation="DescribeFleetInstances")` targets a
        // plain `Integer`), so the only bound on the page size is the largest page this
        // operation serves: a value above it is not refused, it is served as that page with
        // a `NextToken` for the rest (the clamp below). A page of NONE is not a page, so
        // zero and below is still refused.
