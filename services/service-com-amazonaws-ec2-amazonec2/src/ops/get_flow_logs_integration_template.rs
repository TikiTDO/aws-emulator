/// The Amazon S3 location an ARN names: the partition it is in, the bucket, and the key
/// prefix under that bucket (empty for an ARN naming the bucket alone).
#[derive(Debug, Clone)]
struct S3Location {
    /// The partition segment of the ARN the request carried, so every ARN this template
    /// renders stays in the partition the caller named.
    partition: String,
    bucket: String,
    /// The key prefix, with no leading or trailing `/`.
    prefix: String,
}

impl S3Location {
    /// `s3://bucket/prefix/` — the URI form an Athena table location and an Athena query
    /// result location take, with exactly one trailing `/`.
    fn uri(&self) -> String {
        if self.prefix.is_empty() {
            format!("s3://{bucket}/", bucket = self.bucket)
        } else {
            format!(
                "s3://{bucket}/{prefix}/",
                bucket = self.bucket,
                prefix = self.prefix
            )
        }
    }

    /// The ARN of the bucket itself, which is what an `s3:ListBucket` statement names.
    fn bucket_arn(&self) -> String {
        format!(
            "arn:{partition}:s3:::{bucket}",
            partition = self.partition,
            bucket = self.bucket
        )
    }

    /// The ARN of every object under this location, which is what an object-level statement
    /// names.
    fn object_arn(&self) -> String {
        if self.prefix.is_empty() {
            format!("{bucket}/*", bucket = self.bucket_arn())
        } else {
            format!(
                "{bucket}/{prefix}/*",
                bucket = self.bucket_arn(),
                prefix = self.prefix
            )
        }
    }
}

/// The characters a key prefix this operation renders may carry: the Amazon S3 User Guide's
/// "Safe characters" for object key names (alphanumerics and ``!-_.*()``) and the `/` that
/// separates one prefix segment from the next.
///
/// The guide lists the single quote among those safe characters, and this does NOT: the
/// prefix is rendered into the single-quoted `LOCATION` literal of an Athena statement, so a
/// prefix carrying one would end that literal rather than name a location.
const S3_KEY_PREFIX_SAFE_PUNCTUATION: [char; 7] = ['!', '-', '_', '.', '*', '(', ')'];

/// The [`S3Location`] `value` names, or `None` when it is not the ARN of an Amazon S3
/// location this operation can render.
///
/// An S3 ARN is `arn:<partition>:s3:::<bucket>[/<key prefix>]` — Amazon S3 is a global
/// service, so the Region and account id segments of its ARNs are empty. The bucket is held
/// to the Amazon S3 general purpose bucket naming rules
/// ([`crate::state::s3_bucket_name_is_well_formed`]) and the prefix to
/// [`S3_KEY_PREFIX_SAFE_PUNCTUATION`].
fn parse_s3_location(value: &str) -> Option<S3Location> {
    // Six parts: the `arn` literal, the partition, the service, the empty Region, the empty
    // account, and the resource — which is the only part that may itself contain a `:`.
    let mut segments = value.splitn(6, ':');
    (segments.next()? == "arn").then_some(())?;
    let partition = segments.next()?;
    (segments.next()? == "s3").then_some(())?;
    segments.next()?.is_empty().then_some(())?;
    segments.next()?.is_empty().then_some(())?;
    let resource = segments.next()?;

    let partition_is_well_formed = !partition.is_empty()
        && partition
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-');
    if !partition_is_well_formed {
        return None;
    }
    let (bucket, prefix) = resource.split_once('/').unwrap_or((resource, ""));
    if !crate::state::s3_bucket_name_is_well_formed(bucket) {
        return None;
    }
    let prefix = prefix.trim_matches('/');
    let prefix_is_well_formed = prefix.chars().all(|character| {
        character.is_ascii_alphanumeric()
            || character == '/'
            || S3_KEY_PREFIX_SAFE_PUNCTUATION.contains(&character)
    });
    if !prefix_is_well_formed || prefix.contains("//") {
        return None;
    }
    Some(S3Location {
        partition: partition.to_string(),
        bucket: bucket.to_string(),
        prefix: prefix.to_string(),
    })
}

/// [`parse_s3_location`], with the "not an S3 location" case turned into the refusal the
/// member it came from carries: HTTP 400 `InvalidParameterValue`, naming the member and the
/// value the request gave it.
fn require_s3_location<E>(value: &str, member: &str) -> Result<S3Location, Scaffolded<E>> {
    parse_s3_location(value).ok_or_else(|| {
        crate::state::invalid_parameter_value(format!(
            "Invalid value '{value}' for {member}. It must be the ARN of an Amazon S3 \
             location, for example arn:aws:s3:::my-bucket/my-prefix."
        ))
    })
}

