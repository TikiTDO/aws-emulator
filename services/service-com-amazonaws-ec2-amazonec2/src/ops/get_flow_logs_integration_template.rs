/// The Athena type of the column that carries the record field `field`.
fn column_type(field: &str) -> &'static str {
    if INT_RECORD_FIELDS.contains(&field) {
        "int"
    } else if BIGINT_RECORD_FIELDS.contains(&field) {
        "bigint"
    } else {
        "string"
    }
}

/// The column name the record field `field` is read under: its field id with every character
/// that cannot appear in a column name replaced by `_`, which is how AWS's published table
/// names them (`account-id` becomes `account_id`).
fn column_name(field: &str) -> String {
    field
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect()
}

/// One column of the generated Athena table.
#[derive(Debug, Clone)]
struct TableColumn {
    name: String,
    /// The record field the column carries, as the `LogFormat` spelled it.
    field: String,
    data_type: &'static str,
}

/// The columns the table of a flow log whose record format is `log_format` has: one per
/// `${field-id}` token of that format, in the order the format lays them out, each named and
/// typed the way AWS's published flow-log table names and types it.
///
/// "Create a table in Athena that maps fields to a custom log format": the format IS the
/// column list, so a flow log created with a narrower or reordered format gets a narrower or
/// reordered table. A token the format repeats is one column, because a table cannot carry
/// the same column twice.
fn table_columns(log_format: &str) -> Vec<TableColumn> {
    let mut columns: Vec<TableColumn> = Vec::new();
    for field in crate::state::flow_log_format_fields(log_format) {
        let name = column_name(field);
        if name.is_empty() || columns.iter().any(|column| column.name == name) {
            continue;
        }
        columns.push(TableColumn {
            name,
            field: field.to_string(),
            data_type: column_type(field),
        });
    }
    columns
}

