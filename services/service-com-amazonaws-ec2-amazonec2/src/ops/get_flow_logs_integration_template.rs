/// `at` as epoch seconds, and 0 for an instant before the epoch — which no stored flow log
/// carries, since every one of them was created by a call this process served.
fn unix_seconds(at: ::std::time::SystemTime) -> i64 {
    at.duration_since(::std::time::UNIX_EPOCH)
        .map(|since| i64::try_from(since.as_secs()).unwrap_or(i64::MAX))
        .unwrap_or_default()
}

