/// The `PartitionLoadFrequency` member that asks for no scheduled partition loader at all:
/// the `none` member of the enum
/// (`crate::ops::types::PARTITION_LOAD_FREQUENCY_VALUES` is the generated catalog).
const PARTITION_LOAD_FREQUENCY_NONE: &str = "none";

/// The `daily` member, and the EventBridge schedule it loads new partitions on: every day at
/// midnight UTC.
const PARTITION_LOAD_FREQUENCY_DAILY: (&str, &str) = ("daily", "cron(0 0 * * ? *)");

/// The `weekly` member: every Sunday at midnight UTC.
const PARTITION_LOAD_FREQUENCY_WEEKLY: (&str, &str) = ("weekly", "cron(0 0 ? * 1 *)");

/// The `monthly` member: the first day of every month at midnight UTC.
const PARTITION_LOAD_FREQUENCY_MONTHLY: (&str, &str) = ("monthly", "cron(0 0 1 * ? *)");

/// The schedule the partition loader of an integration asking for `frequency` runs on, and
/// `None` for the frequency that asks for no loader.
///
/// "Create a Lambda function that updates the table with new partitions on a daily, weekly,
/// or monthly basis" — the three frequencies that schedule a loader, each as the cron
/// expression that states it. The fourth member of the enum, `none`, asks for no loader, so
/// the template carries none of its resources at all.
fn partition_load_schedule<E>(frequency: &str) -> Result<Option<&'static str>, Scaffolded<E>> {
    match frequency {
        PARTITION_LOAD_FREQUENCY_NONE => Ok(None),
        value if value == PARTITION_LOAD_FREQUENCY_DAILY.0 => {
            Ok(Some(PARTITION_LOAD_FREQUENCY_DAILY.1))
        }
        value if value == PARTITION_LOAD_FREQUENCY_WEEKLY.0 => {
            Ok(Some(PARTITION_LOAD_FREQUENCY_WEEKLY.1))
        }
        value if value == PARTITION_LOAD_FREQUENCY_MONTHLY.0 => {
            Ok(Some(PARTITION_LOAD_FREQUENCY_MONTHLY.1))
        }
        // Unreachable through the wire: `PartitionLoadFrequency` is a modelled enum, so the
        // boundary validator has already refused a value outside it. Answered as the value
        // refusal it is rather than left to a fallback schedule nobody asked for.
        other => Err(crate::state::invalid_parameter_value(format!(
            "Invalid value '{other}' for PartitionLoadFrequency. Valid values are: {values}.",
            values = PARTITION_LOAD_FREQUENCY_VALUES.join(", "),
        ))),
    }
}

