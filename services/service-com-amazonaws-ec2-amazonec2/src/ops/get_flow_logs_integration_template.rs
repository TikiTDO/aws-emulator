/// The most daily partitions one generated template loads, over every integration it carries.
///
/// A CHOSEN bound, not a published quota: `PartitionStartDate` and `PartitionEndDate` are
/// caller-chosen instants and the model bounds neither, so the number of `PARTITION` clauses
/// one small request renders into the response is bounded here — the product over the
/// integrations, not per integration, since the list itself holds up to ten of them. Three
/// years of daily partitions, well above any range a flow log of this emulator could have
/// delivered records for.
const MAX_LOADED_PARTITIONS: usize = 1096;

/// The UTC calendar day of the epoch second `secs`, or `None` when it names no day at all.
///
/// The whole calendar conversion is `chrono`'s: leap years and month lengths are the
/// calendar's rules, not this crate's.
fn utc_day(secs: i64) -> Option<::chrono::NaiveDate> {
    ::chrono::DateTime::from_timestamp(secs, 0).map(|at| at.date_naive())
}

/// The days `integration` asks the template to load partitions for, in order, or the refusal
/// a range this operation cannot render carries.
///
/// "Create a table partitioned between two timestamps in the past": the partitions are the
/// days from `PartitionStartDate` to `PartitionEndDate` inclusive, exactly as the request
/// named them. A request that names no start begins at the flow log's own creation — no
/// record exists before it — and one that names no end runs to the day the template was
/// generated, so a range the request left open is a span of days the flow log could have
/// delivered records for. `remaining` is how many partitions the template may still load,
/// counting down from [`MAX_LOADED_PARTITIONS`] over the integrations already rendered.
fn partition_days<E>(
    plan: &TemplatePlan<'_>,
    integration: &AthenaIntegrationPlan,
    remaining: usize,
) -> Result<Vec<::chrono::NaiveDate>, Scaffolded<E>> {
    let start_secs = integration
        .partition_start
        .or(plan.created_at_secs)
        .unwrap_or(plan.generated_at_secs);
    let end_secs = integration.partition_end.unwrap_or(plan.generated_at_secs);
    let position = integration.position;
    let start = utc_day(start_secs).ok_or_else(|| {
        crate::state::invalid_parameter_value(format!(
            "Invalid value '{start_secs}' for IntegrateServices.AthenaIntegrations.\
             {position}.PartitionStartDate. It must be a date."
        ))
    })?;
    let end = utc_day(end_secs).ok_or_else(|| {
        crate::state::invalid_parameter_value(format!(
            "Invalid value '{end_secs}' for IntegrateServices.AthenaIntegrations.\
             {position}.PartitionEndDate. It must be a date."
        ))
    })?;
    if end < start {
        return Err(crate::state::invalid_parameter_combination(format!(
            "IntegrateServices.AthenaIntegrations.{position}.PartitionEndDate {end} is \
             before IntegrateServices.AthenaIntegrations.{position}.PartitionStartDate \
             {start}."
        )));
    }
    let span = (end - start).num_days().saturating_add(1);
    let span = usize::try_from(span).unwrap_or(usize::MAX);
    if span > remaining {
        return Err(crate::state::invalid_parameter_value(format!(
            "The partition range of IntegrateServices.AthenaIntegrations.{position} covers \
             {span} daily partitions, and this emulator renders {remaining} more of the \
             {MAX_LOADED_PARTITIONS} it loads in one template."
        )));
    }
    let mut days: Vec<::chrono::NaiveDate> = Vec::with_capacity(span.min(MAX_LOADED_PARTITIONS));
    let mut day = start;
    while day <= end {
        days.push(day);
        match day.succ_opt() {
            Some(next) => day = next,
            // The calendar ends before the range does, so there is no next day to load.
            None => break,
        }
    }
    Ok(days)
}

/// Where the flow log records of one day live, and how the table's partitions are keyed.
#[derive(Debug, Clone)]
struct PartitionLayout {
    /// The S3 URI the table itself points at.
    root: String,
    /// Whether the day prefixes carry `key=value` segments.
    hive_compatible: bool,
}

impl PartitionLayout {
    /// The layout a flow log publishing to `logs` in `region` writes under.
    ///
    /// "Indicates whether to use Hive-compatible prefixes for flow logs stored in Amazon S3"
    /// (`DestinationOptionsResponse$HiveCompatiblePartitions`): without them a flow log's
    /// objects are at `AWSLogs/<account>/vpcflowlogs/<region>/<yyyy>/<mm>/<dd>/`, and with
    /// them at `AWSLogs/aws-account-id=<account>/aws-service=vpcflowlogs/aws-region=<region>/
    /// year=<yyyy>/month=<mm>/day=<dd>/` (Amazon VPC User Guide, "Flow log files").
    fn new(logs: &S3Location, region: &str, hive_compatible: bool) -> Self {
        let account = ::engine::emulator_account_id();
        let root = if hive_compatible {
            format!(
                "{uri}AWSLogs/aws-account-id={account}/aws-service=vpcflowlogs/\
                 aws-region={region}/",
                uri = logs.uri(),
            )
        } else {
            format!(
                "{uri}AWSLogs/{account}/vpcflowlogs/{region}/",
                uri = logs.uri(),
            )
        };
        Self {
            root,
            hive_compatible,
        }
    }

    /// The S3 URI the records of `day` are under. A day's prefix holds every object of that
    /// day, including the per-hour prefixes a flow log asked for them under, so a day is the
    /// finest partition the table needs.
    fn day_uri(&self, day: ::chrono::NaiveDate) -> String {
        use ::chrono::Datelike;
        if self.hive_compatible {
            format!(
                "{root}year={year:04}/month={month:02}/day={day_of_month:02}/",
                root = self.root,
                year = day.year(),
                month = day.month(),
                day_of_month = day.day(),
            )
        } else {
            format!(
                "{root}{year:04}/{month:02}/{day_of_month:02}/",
                root = self.root,
                year = day.year(),
                month = day.month(),
                day_of_month = day.day(),
            )
        }
    }

    /// The `PARTITION (…)` key list of `day`, as an `ALTER TABLE` clause spells it.
    fn day_keys(day: ::chrono::NaiveDate) -> String {
        use ::chrono::Datelike;
        format!(
            "year='{year:04}', month='{month:02}', day='{day_of_month:02}'",
            year = day.year(),
            month = day.month(),
            day_of_month = day.day(),
        )
    }

    /// The Python `%`-format template the scheduled loader builds the URI of the day it is
    /// adding from, so the loader points at the same layout the table does.
    fn day_uri_template(&self) -> String {
        if self.hive_compatible {
            format!("{root}year=%04d/month=%02d/day=%02d/", root = self.root)
        } else {
            format!("{root}%04d/%02d/%02d/", root = self.root)
        }
    }
}

