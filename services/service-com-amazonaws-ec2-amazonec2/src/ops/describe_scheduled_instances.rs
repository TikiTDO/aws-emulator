            if values.len() > state::MAX_FILTER_VALUES {
                return Err(state::invalid_parameter_value(format!(
                    "The filter '{name}' carries {supplied} values, above the maximum of \
                     {maximum}",
                    supplied = values.len(),
                    maximum = state::MAX_FILTER_VALUES,
                )));
            }
