/// The filter names this operation answers.
///
/// "One or more filters. The possible values are: description: The Traffic Mirror target
/// description. network-interface-id: The ID of the Traffic Mirror session network interface.
/// network-load-balancer-arn: The Amazon Resource Name (ARN) of the Network Load Balancer
