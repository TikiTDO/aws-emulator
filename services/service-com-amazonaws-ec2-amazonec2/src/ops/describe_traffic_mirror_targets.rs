/// (`DescribeTrafficMirrorTargetsRequest$Filters`), plus `tag-key` and `tag:<key>`, the
/// resource-wide tag filters EC2 documents for every taggable resource ("List and filter
/// using the CLI and API", linked from `Filter`) — and a Traffic Mirror target is taggable:
/// `CreateTrafficMirrorTarget` assigns tags to it and `TrafficMirrorTarget$Tags` reports them.
/// Every entry must be answered by [`filter_values`].
///
/// `tag:<key>` is the one name with a variable part, so it is matched by prefix rather than
/// listed here.
const TRAFFIC_MIRROR_TARGET_FILTERS: [&str; 6] = [
    "description",
    "network-interface-id",
    "network-load-balancer-arn",
    "owner-id",
    "tag-key",
    "traffic-mirror-target-id",
];

/// The name [`filter_values`] answers for the filter the request called `name`, or `None`
/// when this operation answers no such filter.
///
/// The `tag:<key>` prefix comes from the crate's one definition of it,
/// [`crate::state::TAG_FILTER_PREFIX`], so that spelling cannot drift between the describes
/// that answer the tag filter.
///
/// "Filter names are case-sensitive" (`Filter$Name`), so every comparison is exact — and a
/// `tag:` prefix with no key names no tag, so it is as undocumented as any other misspelling.
/// The `tag:<key>` family keeps its whole name, the key being part of what it selects on.
fn canonical_filter_name(name: &str) -> Option<&str> {
    if name
        .strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
    {
        return Some(name);
    }
    TRAFFIC_MIRROR_TARGET_FILTERS
        .contains(&name)
        .then_some(name)
}

/// The values the EC2 filter `name` compares against this Traffic Mirror target.
///
/// A filter naming an attribute this record does not carry compares against NO values, so it
/// selects nothing — which is the answer for `network-load-balancer-arn` on a target that
/// mirrors to a network interface. `name` is a name [`canonical_filter_name`] resolved.
fn filter_values<'a>(
    target: &'a TrafficMirrorTarget,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return target
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "description" => text(target.description.as_deref()),
        "network-interface-id" => text(target.network_interface_id.as_deref()),
        "network-load-balancer-arn" => text(target.network_load_balancer_arn.as_deref()),
        "owner-id" => text(target.owner_id.as_deref()),
        "tag-key" => target
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "traffic-mirror-target-id" => text(target.traffic_mirror_target_id.as_deref()),
        // Unreachable: `canonical_filter_name` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}
