/// The page size a request that names no `MaxResults` gets: the largest the model publishes
/// (`PoolMaxResults`, `range 1..10`), which is also the most EC2 returns in one page.
const DEFAULT_MAX_RESULTS: usize = 10;

/// The one fixed filter name this operation documents, from `$Filters`:
///
/// ```text
/// smithy_query(query="doc",shape="DescribePublicIpv4PoolsRequest",member="Filters",model_path="services/service-com-amazonaws-ec2-amazonec2/smithy-model/com-amazonaws-ec2-amazonec2.json")
/// ```
///
/// That member documents exactly two filters — this one and the `tag:<key>` family below,
/// whose variable part is matched by prefix — and nothing else, not even the `pool-id` the
/// CoIP pools' own describe documents, so every other name is refused. Each entry here must
/// be answered by [`filter_values`].
const PUBLIC_IPV4_POOL_FILTERS: [&str; 1] = ["tag-key"];

/// The prefix of the tag filter: "Use the tag key in the filter name and the tag value as
/// the filter value" (`$Filters`).
const TAG_FILTER_PREFIX: &str = "tag:";

/// Is `name` a filter this operation documents? "Filter names are case-sensitive"
/// (`Filter$Name`), so the comparison is exact — and a `tag:` prefix with no key names no
/// tag, so it is as undocumented as any other misspelling.
fn is_documented_filter(name: &str) -> bool {
    name.strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
        || PUBLIC_IPV4_POOL_FILTERS.contains(&name)
}

/// The values the EC2 filter `name` compares against this pool.
///
/// A filter naming an attribute this pool does not carry compares against NO values, so it
/// selects nothing — the same answer AWS gives for any absent attribute. The AND/OR
/// evaluation of these values, and the budget that bounds it, live in
/// [`crate::state::matches_every_filter`], which every filtered describe of this crate
/// shares: "If you specify multiple filters, the filters are joined with an AND" (`Filter`),
/// and within one filter "if you specify multiple values for a filter, the values are joined
/// with an OR" (`Filter$Values`). So a filter carrying NO value matches nothing.
fn filter_values<'a>(record: &'a PublicIpv4PoolRecord, name: &str) -> Vec<Cow<'a, str>> {
    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return record
            .tags
            .iter()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref())
            .map(Cow::Borrowed)
            .collect();
    }
    match name {
        "tag-key" => record
            .tags
            .iter()
            .filter_map(|tag| tag.key.as_deref())
            .map(Cow::Borrowed)
            .collect(),
        // Unreachable: `is_documented_filter` has already refused every other name. An
        // undefined name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}
