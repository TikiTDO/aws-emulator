        // token only when a pool follows this page.
        let next_token = page
            .get(limit)
            .map(|record| crate::state::encode_page_token(&record.pool_id));

        // Each pool is reported through the store's own projection, so what a describe says
        // about a pool's ranges and counts is derived from the ranges the store holds rather
        // than from a copy this operation keeps.
