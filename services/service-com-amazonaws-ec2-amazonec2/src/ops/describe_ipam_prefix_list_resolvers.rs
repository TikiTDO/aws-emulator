/// The prefix of the tag filter: the tag key goes in the filter name and the tag value in the
/// filter value, for "the tags assigned to the IPAM prefix list resolver"
/// (`IpamPrefixListResolver$Tags`).
const TAG_FILTER_PREFIX: &str = "tag:";

/// Is `name` a filter this operation resolves? "Filter names are case-sensitive"
/// (`Filter$Name`), so the comparison is exact — and a `tag:` prefix with no key names no tag,
/// so it is as unresolvable as any other misspelling.
fn is_documented_filter(name: &str) -> bool {
    name.strip_prefix(TAG_FILTER_PREFIX)
        .is_some_and(|key| !key.is_empty())
        || IPAM_PREFIX_LIST_RESOLVER_FILTERS.contains(&name)
}

/// The values the EC2 filter `name` compares against this resolver.
///
/// A filter naming an attribute this resolver does not carry compares against NO values, so it
/// selects nothing — the same answer AWS gives for, say, `description` on a resolver created
/// without one, or for the version creation status of one that has created no version yet.
fn filter_values<'a>(
    resolver: &'a IpamPrefixListResolver,
    name: &str,
) -> Vec<::std::borrow::Cow<'a, str>> {
    use ::std::borrow::Cow;

    if let Some(key) = name.strip_prefix(TAG_FILTER_PREFIX) {
        return resolver
            .tags
            .iter()
            .flatten()
            .filter(|tag| tag.key.as_deref() == Some(key))
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect();
    }

    let text = |value: Option<&'a str>| -> Vec<Cow<'a, str>> {
        value.map(Cow::Borrowed).into_iter().collect()
    };
    match name {
        "address-family" => text(resolver.address_family.as_deref()),
        "description" => text(resolver.description.as_deref()),
        "ipam-arn" => text(resolver.ipam_arn.as_deref()),
        "ipam-prefix-list-resolver-arn" => {
            text(resolver.ipam_prefix_list_resolver_arn.as_deref())
        }
        "ipam-prefix-list-resolver-id" => text(resolver.ipam_prefix_list_resolver_id.as_deref()),
        "ipam-region" => text(resolver.ipam_region.as_deref()),
        "last-version-creation-status" => text(resolver.last_version_creation_status.as_deref()),
        "last-version-creation-status-message" => {
            text(resolver.last_version_creation_status_message.as_deref())
        }
        "owner-id" => text(resolver.owner_id.as_deref()),
        "state" => text(resolver.state.as_deref()),
        "tag-key" => resolver
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.key.as_deref().map(Cow::Borrowed))
            .collect(),
        "tag-value" => resolver
            .tags
            .iter()
            .flatten()
            .filter_map(|tag| tag.value.as_deref().map(Cow::Borrowed))
            .collect(),
        // Unreachable: `is_documented_filter` has already refused every other name. An
        // unresolvable name compares against nothing, so it could never widen a result even if
        // that check were bypassed.
        _ => Vec::new(),
    }
}

