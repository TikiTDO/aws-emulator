impl<Eng: Send + Sync + 'static> BatchDeleteImage<Eng> {
    /// Remove what the batch names, and answer both the response the delete gives its
    /// caller and the image actions it performed.
    ///
    /// Everything this operation writes happens here, under the store's lock; the caller
    /// publishes those actions once that lock is gone.
    async fn delete_images(
        engine: &Eng,
        state: &::engine::ServiceState<
            crate::state::ComAmazonawsEcrAmazonec2containerregistryV20150921State,
        >,
        input: &BatchDeleteImageInput,
        now: ::std::time::SystemTime,
    ) -> Result<
        (
            BatchDeleteImageOutput,
            Vec<crate::state::image_events::ImageAction>,
        ),
        BatchDeleteImageError,
    > {
        let storage_error = || BatchDeleteImageError::from(BatchDeleteImageErrorModeled::ServerException(ServerException {
            message: Some("durable image deletion unavailable".to_string()),
        }));
        let _mutation = crate::state::payloads::mutation_guard(engine).await.map_err(|_| storage_error())?;
        let payload_store = crate::state::payloads::bound_store(engine).map_err(|_| storage_error())?;
        let before = { state.lock().repository(&input.repository_name).map_err(fault_error)?.clone() };
        let mut repo = before.clone();

        let mut deleted = Vec::new();
        let mut failures = Vec::new();
        // One answer per requested identifier, in request order. The resolution is the
        // repository's own, so an identifier is read here exactly as every other
        // operation that takes one reads it.
        for id in &input.image_ids {
            let (digest, tags, identifiers) = match repo.lookup_image(id) {
                // What was deleted is reported from the STORED record: the image's own
                // digest, and the tags that come off it — for a delete by digest, the
                // `(digest, tag)` pairs the image was addressable by, so a caller learns
                // every tag it has lost.
                Ok(stored) => (
                    stored.digest.clone(),
                    stored.tags.clone(),
                    stored.identifiers(),
                ),
                Err(failure) => {
                    failures.push(ImageFailure {
                        // The identifier is echoed exactly as requested: it is what lets
                        // a caller match the failure back to its own entry.
                        image_id: Some(id.clone()),
                        failure_code: Some(failure.code().to_string()),
                        failure_reason: Some(failure.reason().to_string()),
                    });
                    continue;
                }
            };

            // "You can remove a tag from an image by specifying the image's tag in your
            // request. When you remove the last tag from an image, the image is deleted
            // from your repository. You can completely delete an image (and all of its
            // tags) by specifying the image's digest in your request."
            let removed_tag = id.image_tag.clone().filter(|_| id.image_digest.is_none());
            match removed_tag {
                Some(tag) => {
                    repo.tag_index.remove(&tag);
                    if let Some(image) = repo.images.get_mut(&digest) {
                        image.tags.remove(&tag);
                        // The last tag is gone, so the image goes with it.
                        if image.tags.is_empty() {
                            repo.images.remove(&digest);
                        }
                    }
                    deleted.push(ImageIdentifier {
                        image_digest: Some(digest),
                        image_tag: Some(tag),
                    });
                }
                None => {
                    for tag in &tags {
                        repo.tag_index.remove(tag);
                    }
                    repo.images.remove(&digest);
                    deleted.extend(identifiers);
                }
            }
        }

        // The repository's image set changed, and a manifest list's size is a statement
        // about the images stored beside it, so what every remaining image reports is
        // recomputed once the deletes are done.
        repo.refresh_image_sizes();

        // Both members are reported, empty or not: the answer to a batch is the two
        // lists it partitions into.
        let output = BatchDeleteImageOutput {
            image_ids: Some(deleted),
            failures: Some(failures),
        };
        // One action per delete this batch really performed — the identifiers the answer
        // reports — for the caller to publish once this lock is released.
        let removals: Vec<crate::state::image_events::ImageAction> = output
            .image_ids
            .iter()
            .flatten()
            .filter_map(|id| {
                Some(crate::state::image_events::ImageAction {
                    repository_name: input.repository_name.clone(),
                    action_type: crate::state::image_events::ACTION_TYPE_DELETE,
                    image_digest: id.image_digest.clone()?,
                    image_tag: id.image_tag.clone(),
                    at: now,
                })
            })
            .collect();
        crate::state::catalog::publish_images(&_mutation, &payload_store, &before, &mut repo).await.map_err(|_| storage_error())?;
        state.lock().repositories.insert(repo.name.clone(), repo);
        Ok((output, removals))
    }
}
