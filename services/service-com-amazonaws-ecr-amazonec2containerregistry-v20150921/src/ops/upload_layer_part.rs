impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UploadLayerPart<Eng>
{
    type Input = UploadLayerPartInput;
    type Output = UploadLayerPartOutput;
    type Error = UploadLayerPartError;

    const NAME: &'static str = "UploadLayerPart";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPLOAD_LAYER_PART_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPLOAD_LAYER_PART_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let capacity = emulator_server::ecr_capacity::configured().map_err(|_| {
            UploadLayerPartError::from(UploadLayerPartErrorModeled::ServerException(ServerException {
                message: Some("invalid ECR capacity configuration".to_string()),
            }))
        })?;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UploadLayerPartErrorModeled::ServerException(ServerException {
                message: Some("the ecr repository store is unavailable".to_string()),
            })
            .into());
        };

        // A private registry's layers are private: whether any policy in force lets this
        // caller reach this repository is decided before a part is kept
        // (`crate::state::authorization`).
        if let Some(denied) = crate::state::authorization::denied_on_repository(
            &*self.engine,
            ctx,
            Self::NAME,
            &input.repository_name,
        ) {
            return Err(denied);
        }

        // Request metadata is used for the audit record only: the upload is held in
        // this registry's state, not in the signing region.
        let caller_akid = ::engine::extract_akid(&ctx.parts().headers);

        // "If you do not specify a registry, the default registry is assumed" — and the
        // only registry served here is this emulator's own.
        crate::state::check_registry(input.registry_id.as_ref())
            .map_err(|fault| refusal("another registry", &caller_akid, fault_error(fault)))?;

        let storage_error = || UploadLayerPartError::from(UploadLayerPartErrorModeled::ServerException(ServerException {
            message: Some("durable layer upload unavailable".to_string()),
        }));
        let _mutation = crate::state::payloads::mutation_guard(&*self.engine).await.map_err(|_| storage_error())?;
        let payload_store = crate::state::payloads::bound_store(&*self.engine).map_err(|_| storage_error())?;
        let (owner, caller_bytes_held) = {
            let store = state.lock();
            let repo = store.repository(&input.repository_name)
                .map_err(|fault| refusal("no such repository", &caller_akid, fault_error(fault)))?;
            (crate::state::payloads::repository_owner(repo).map_err(|_| storage_error())?, store.caller_bytes_held())
        };
        let bound = crate::state::payload_upload::lookup(&payload_store, &owner, &input.upload_id)
            .await.map_err(|_| storage_error())?;
        let Some(mut bound) = bound else {
            return Err(refusal("no such upload", &caller_akid,
                UploadLayerPartErrorModeled::UploadNotFoundException(UploadNotFoundException {
                    message: Some(crate::state::upload_not_found_message(&input.upload_id, &input.repository_name)),
                })).into());
        };
        let upload = bound.index_projection();

        // The addressed upload resolved, so the part is now charged against the
        // registry-wide budget: it is refused before any byte of it is kept.
        if !capacity.store_fits(caller_bytes_held, input.layer_part_blob.len())
        {
            return Err(refusal(
                "registry byte budget reached",
                &caller_akid,
                UploadLayerPartErrorModeled::LimitExceededException(LimitExceededException {
                    message: Some(format!(
                        "this registry holds at most {} bytes of in-flight layer uploads \
                         and stored image manifests together",
                        capacity.store_bytes
                    )),
                }),
            )
            .into());
        }

        // What the upload held before this part: the last byte a client may still rely
        // on, which is what a refused part reports back as `lastValidByteReceived`, and
        // the offset the next part has to begin at — the byte after it, or byte 0 while
        // the upload has received nothing. A client resuming an interrupted upload reads
        // that offset out of the refusal, so it is stated rather than left to be derived.
        let last_valid_byte_received = upload.last_byte_received();
        let expected_part_first_byte = upload.next_part_first_byte();
        let outcome = crate::state::payload_upload::validate_part(
            &bound.snapshot.checkpoint, input.part_first_byte, input.part_last_byte,
            input.layer_part_blob.len(), capacity.layer_bytes as u64,
        ).map(|()| input.part_last_byte);
        // Everything the answer reports comes from the stored upload, not from the
        // request: the repository the upload was opened against, and the byte count it
        // now holds.
        let repository_name = upload.repository_name.clone();
        let last_byte_received = match outcome {
            Ok(last_byte_received) => last_byte_received,
            Err(rejection) => {
                let (reason, error) = match rejection {
                    crate::state::LayerPartRejection::PartSizeMismatch => (
                        "part size does not match the blob",
                        UploadLayerPartErrorModeled::InvalidLayerPartException(
                            InvalidLayerPartException {
                                registry_id: Some(crate::state::registry_id().to_string()),
                                repository_name: Some(repository_name),
                                upload_id: Some(input.upload_id.clone()),
                                last_valid_byte_received,
                                message: Some(format!(
                                    "Invalid layer part: bytes {}-{} do not describe the {} \
                                     bytes the request carried",
                                    input.part_first_byte,
                                    input.part_last_byte,
                                    input.layer_part_blob.len()
                                )),
                            },
                        ),
                    ),
                    crate::state::LayerPartRejection::NonConsecutivePart => (
                        "part is not consecutive",
                        UploadLayerPartErrorModeled::InvalidLayerPartException(
                            InvalidLayerPartException {
                                registry_id: Some(crate::state::registry_id().to_string()),
                                repository_name: Some(repository_name),
                                upload_id: Some(input.upload_id.clone()),
                                last_valid_byte_received,
                                // ECR names the byte the part DID begin at and the byte
                                // it had to begin at, which is where the upload's
                                // received bytes end — the offset a resuming client
                                // continues from.
                                message: Some(format!(
                                    "First byte of the layer part is {} instead of {}",
                                    input.part_first_byte, expected_part_first_byte
                                )),
                            },
                        ),
                    ),
                    crate::state::LayerPartRejection::UploadTooLarge => (
                        "upload byte cap reached",
                        UploadLayerPartErrorModeled::LimitExceededException(
                            LimitExceededException {
                                message: Some(format!(
                                    "this registry holds at most {} bytes per in-flight layer \
                                     upload",
                                    capacity.layer_bytes
                                )),
                            },
                        ),
                    ),
                };
                return Err(refusal(reason, &caller_akid, error).into());
            }
        };

        bound.snapshot.checkpoint = crate::state::payload_upload::append_modeled_part(
            &_mutation, &payload_store, &bound, input.layer_part_blob.as_ref(),
        ).await.map_err(|_| storage_error())?;
        state.lock().uploads.insert(input.upload_id.clone(), bound.index_projection());

        // Audit record for a state-changing operation: who asked, what changed, how it
        // ended. Only wire metadata, server-held counts and the upload's own id.
        ::tracing::info!(
            target: "emulator::audit",
            audit = true,
            operation = "UploadLayerPart",
            outcome = "received",
            caller_akid = %caller_akid,
            registry_id = %crate::state::registry_id(),
            upload_id = %input.upload_id,
            last_byte_received,
            "layer part received"
        );

        Ok(UploadLayerPartOutput {
            registry_id: Some(crate::state::registry_id().to_string()),
            repository_name: Some(repository_name),
            upload_id: Some(input.upload_id),
            last_byte_received: Some(last_byte_received),
        })
    }
}
