        // address.
        if let Some(replayed) = input
            .client_token
            .as_deref()
            .and_then(|token| store.replayed_theme(&key, token))
        {
            return Ok(CreateThemeOutput {
                entity: Some(replayed.to_theme()),
            });
        }

