impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for RefreshToken<Eng>
{
    type Input = RefreshTokenInput;
    type Output = RefreshTokenOutput;
    type Error = RefreshTokenError;

    const NAME: &'static str = "RefreshToken";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REFRESH_TOKEN_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REFRESH_TOKEN_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // An unreachable shared store is a server-side condition, not a refusal
            // of a request that satisfied every constraint the model declares.
            return Err(RefreshTokenErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("the amplifyuibuilder token store is unavailable".to_string()),
                },
            )
            .into());
        };

        // `token` is `@required` but carries no `@length`, so the model admits a blank
        // one: a refresh token of no characters names no session to refresh, which is
        // the invalid input parameter this operation models. The refusal quotes nothing
        // — the member is `@sensitive`.
        if input.refresh_token_body.token.trim().is_empty() {
            return Err(RefreshTokenErrorModeled::InvalidParameterException(
                crate::state::blank_refresh_token(),
            )
            .into());
        }

        let now = ::std::time::SystemTime::now();
        // The session this refresh addresses. `provider` is an `@httpLabel` targeting
        // the `TokenProviders` enum, so the only values that reach here are the ones the
        // model declares.
        let key = (
            input.provider,
            input.refresh_token_body.client_id,
            input.refresh_token_body.token,
        );
        let mut store = state.lock();
        // The expiry the clock already owes, materialised before the bound below is
        // read, so a caller is never refused over access tokens that have run out.
        store.expire_provider_token_sessions(now);

        // The bound FIRST and the mint only after it, both settled by the store (see
        // `mint_within_token_session_bound`): a refresh this bound refuses does no work
        // on the shared credential store, exactly as a refused exchange does none. The
        // access token is drawn BY the emulator's credential store — a service never
        // constructs secret material itself.
        let credentials = ctx.credential_store();
        let access_token = match store
            .mint_within_token_session_bound(Some(&key), || {
                crate::state::mint_provider_token(credentials)
            }) {
            Ok(access_token) => access_token,
            Err(crate::state::ProviderTokenRefusal::OverQuota) => {
                // The bound is the emulator's own and this operation's model declares
                // no quota error, so the refusal is the modelled
                // `InvalidParameterException` (400): the session the request names is
                // outside the range the store can hold, which is the condition that
                // shape documents.
                return Err(RefreshTokenErrorModeled::InvalidParameterException(
                    crate::state::store_bound_reached(
                        "live token sessions",
                        crate::state::PROVIDER_TOKEN_SESSION_QUOTA,
                    ),
                )
                .into());
            }
            Err(crate::state::ProviderTokenRefusal::NothingMinted) => {
                return Err(RefreshTokenErrorModeled::InternalServerException(
                    InternalServerException {
                        message: Some(
                            "no access token could be minted for this request".to_string(),
                        ),
                    },
                )
                .into());
            }
        };

        // The response is read off the STORED session, so what the caller is handed and
        // what the store holds for that session cannot differ.
        let session = store.refresh_provider_token_session(key, access_token, now);
        Ok(RefreshTokenOutput {
            access_token: session.access_token.clone(),
            expires_in: session.expires_in(now),
        })
    }
}
