impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateComponent<Eng>
{
    type Input = UpdateComponentInput;
    type Output = UpdateComponentOutput;
    type Error = UpdateComponentError;

    const NAME: &'static str = "UpdateComponent";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_COMPONENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_COMPONENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UpdateComponentErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some(
                        "the amplifyuibuilder component store is unavailable".to_string(),
                    ),
                },
            )
            .into());
        };

        let patch = input.updated_component;

        // `UpdateComponentData$id` is documented as "The unique ID of the
        // component to update" — it names the same component the `@httpLabel`
        // does, so a payload naming a different one is a contradictory request
        // rather than an instruction to renumber the component.
        if let Some(named) = patch.id.as_deref() {
            if named != input.id {
                return Err(UpdateComponentErrorModeled::InvalidParameterException(
                    InvalidParameterException {
                        message: Some(format!(
                            "updatedComponent.id {named:?} does not name the component being \
                             updated ({:?})",
                            input.id
                        )),
                    },
                )
                .into());
            }
        }

        // The same reserved-name rule `CreateComponent` enforces, over every map
        // the model documents it for: a component's own `properties`,
        // `overrides`, `bindingProperties` and `collectionProperties`, the
        // `properties` of each `ComponentChild` at every depth of `children`, and
        // each `ComponentVariant`'s `variantValues` and `overrides`. An update may
        // not introduce the reserved key into any of them.
        let reserved = [
            patch
                .properties
                .as_ref()
                .is_some_and(crate::state::carries_reserved_name)
                .then(|| "properties".to_string()),
            patch
                .overrides
                .as_ref()
                .is_some_and(crate::state::carries_reserved_name)
                .then(|| "overrides".to_string()),
            patch
                .binding_properties
                .as_ref()
                .is_some_and(crate::state::carries_reserved_name)
                .then(|| "bindingProperties".to_string()),
            patch
                .collection_properties
                .as_ref()
                .is_some_and(crate::state::carries_reserved_name)
                .then(|| "collectionProperties".to_string()),
            crate::state::reserved_name_in_children(
                patch.children.as_deref().unwrap_or_default(),
            ),
            crate::state::reserved_name_in_variants(
                patch.variants.as_deref().unwrap_or_default(),
            ),
        ]
        .into_iter()
        .flatten()
        .next();
        if let Some(member) = reserved {
            return Err(UpdateComponentErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(format!(
                        "updatedComponent.{member} cannot carry the reserved property name {:?}",
                        crate::state::RESERVED_PROPERTY_NAME
                    )),
                },
            )
            .into());
        }

        let mut store = state.lock();
        // The clock is read with the store HELD, never before taking it: the
        // instant this call stamps into the record is then the instant it
        // observed while it owned the store, so two concurrent updates stamp in
        // the order they commit and the `modifiedAt` the record keeps is the one
        // the update that committed LAST observed. Sampling before the lock lets
        // the caller that observed the EARLIER instant commit last and write a
        // `modifiedAt` older than the one already stored.
        let now = ::std::time::SystemTime::now();

        // The target is resolved before anything is merged, and the two ways it
        // can fail to resolve are the two `GetComponent` and `DeleteComponent`
        // tell apart: an id a DIFFERENT app environment owns is a wrong-scope
        // request (the modelled `InvalidParameterException`, 400) and an id that
        // names no component anywhere is absent (`ResourceNotFoundException`,
        // 404 — widened in above). Nothing is created either way: an update is
        // not an upsert.
        if store
            .component(&input.app_id, &input.environment_name, &input.id)
            .is_none()
        {
            if store.component_in_other_scope(&input.app_id, &input.environment_name, &input.id) {
                return Err(UpdateComponentErrorModeled::InvalidParameterException(
                    crate::state::item_wrong_scope(),
                )
                .into());
            }
            return Err(UpdateComponentErrorModeled::ResourceNotFoundException(
                crate::state::item_not_found(),
            )
            .into());
        }

        // A component name identifies a component within its app environment, so
        // a rename onto a name ANOTHER live component there holds is refused with
        // the same `ResourceConflictException` a duplicate create is: the
        // constraint is on the stored set, not on which call would introduce the
        // duplicate. Renaming a component to the name it already has changes
        // nothing and is not a conflict.
        if let Some(name) = patch.name.as_deref() {
            if store
                .component_named(&input.app_id, &input.environment_name, name)
                .is_some_and(|holder| holder.id != input.id)
            {
                return Err(UpdateComponentErrorModeled::ResourceConflictException(
                    crate::state::duplicate_item_name(),
                )
                .into());
            }
        }

        let Some(component) =
            store.component_mut(&input.app_id, &input.environment_name, &input.id)
        else {
            // Unreachable: the lookup above found this id under the same lock.
            return Err(UpdateComponentErrorModeled::ResourceNotFoundException(
                crate::state::item_not_found(),
            )
            .into());
        };

        // Every `UpdateComponentData` member is optional: one the request carries
        // replaces what was stored, one it leaves out keeps it. `appId`,
        // `environmentName`, `id` and `createdAt` identify the record and are not
        // `UpdateComponentData` members at all, so they never move.
        if let Some(name) = patch.name {
            component.name = name;
        }
        if let Some(component_type) = patch.component_type {
            component.component_type = component_type;
        }
        if let Some(properties) = patch.properties {
            component.properties = properties;
        }
        if let Some(variants) = patch.variants {
            component.variants = variants;
        }
        if let Some(overrides) = patch.overrides {
            component.overrides = overrides;
        }
        if let Some(binding_properties) = patch.binding_properties {
            component.binding_properties = binding_properties;
        }
        if patch.children.is_some() {
            component.children = patch.children;
        }
        if patch.collection_properties.is_some() {
            component.collection_properties = patch.collection_properties;
        }
        if patch.events.is_some() {
            component.events = patch.events;
        }
        if patch.source_id.is_some() {
            component.source_id = patch.source_id;
        }
        if patch.schema_version.is_some() {
            component.schema_version = patch.schema_version;
        }
        component.modified_at = now;

        Ok(UpdateComponentOutput {
            entity: Some(component.to_component()),
        })
    }
}
