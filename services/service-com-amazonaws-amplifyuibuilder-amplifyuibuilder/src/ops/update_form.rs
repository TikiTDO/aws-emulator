impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateForm<Eng>
{
    type Input = UpdateFormInput;
    type Output = UpdateFormOutput;
    type Error = UpdateFormError;

    const NAME: &'static str = "UpdateForm";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_FORM_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_FORM_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UpdateFormErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("the amplifyuibuilder form store is unavailable".to_string()),
                },
            )
            .into());
        };

        let patch = input.updated_form;

        // The same documented-value-set rule `CreateForm` enforces, over the one
        // map an update can replace: `SectionalElement$type`, `$level` and
        // `$orientation` target plain `String`/`Integer` shapes while the model
        // spells out the values they admit, so a patch carrying anything else is
        // refused with the modelled `InvalidParameterException` rather than
        // merged. Checked before the target is resolved, exactly as
        // `UpdateComponent` checks its payload rule first.
        if let Some(refusal) = patch.sectional_elements.as_ref().and_then(|elements| {
            crate::state::invalid_sectional_element_value("updatedForm", elements)
        }) {
            return Err(UpdateFormErrorModeled::InvalidParameterException(refusal).into());
        }

        let mut store = state.lock();

        // The target is resolved before anything is merged, and the two ways it
        // can fail to resolve are the two `GetForm` and `DeleteForm` tell apart
        // (and `GetComponent`/`DeleteComponent` before them): an id a DIFFERENT
        // app environment owns is a wrong-scope request (the modelled
        // `InvalidParameterException`, 400) and an id that names no form anywhere
        // is absent (`ResourceNotFoundException`, 404 — widened in above, and the
        // same refusal `GetForm` answers for that id). Nothing is created either
        // way: an update is not an upsert.
        //
        // `clientToken` is an `@idempotencyToken`, but a merge of the same patch
        // into the same form leaves the same form behind however often it is
        // applied, so no token bookkeeping is needed to make a retry idempotent.
        let addressed = store
            .form(&input.app_id, &input.environment_name, &input.id)
            .is_some();
        if !addressed {
            if store.form_in_other_scope(&input.app_id, &input.environment_name, &input.id) {
                return Err(UpdateFormErrorModeled::InvalidParameterException(
                    crate::state::item_wrong_scope(),
                )
                .into());
            }
            return Err(UpdateFormErrorModeled::ResourceNotFoundException(
                crate::state::item_not_found(),
            )
            .into());
        }

        // A form name identifies a form within its app environment, so a rename
        // onto a name ANOTHER live form there holds is refused with the same
        // `ResourceConflictException` a duplicate create is: the constraint is on
        // the stored set, not on which call would introduce the duplicate.
        // Renaming a form to the name it already has changes nothing and is not a
        // conflict. `UpdateComponent` applies the same rule to a component.
        if let Some(name) = patch.name.as_deref() {
            if store
                .form_named(&input.app_id, &input.environment_name, name)
                .is_some_and(|holder| holder.id != input.id)
            {
                return Err(UpdateFormErrorModeled::ResourceConflictException(
                    crate::state::duplicate_item_name(),
                )
                .into());
            }
        }

        let Some(form) = store.form_mut(&input.app_id, &input.environment_name, &input.id) else {
            // Unreachable: the lookup above found this id under the same lock.
            return Err(UpdateFormErrorModeled::ResourceNotFoundException(
                crate::state::item_not_found(),
            )
            .into());
        };

        // Every `UpdateFormData` member is optional: one the request carries
        // replaces what was stored, one it leaves out keeps it. `appId`,
        // `environmentName` and `id` identify the record and are not
        // `UpdateFormData` members at all, so they never move; neither do `tags`,
        // which `UpdateFormData` does not carry either.
        if let Some(name) = patch.name {
            form.name = name;
        }
        if let Some(form_action_type) = patch.form_action_type {
            form.form_action_type = form_action_type;
        }
        if let Some(style) = patch.style {
            form.style = style;
        }
        if let Some(data_type) = patch.data_type {
            form.data_type = data_type;
        }
        if let Some(fields) = patch.fields {
            form.fields = fields;
        }
        if let Some(sectional_elements) = patch.sectional_elements {
            form.sectional_elements = sectional_elements;
        }
        if let Some(schema_version) = patch.schema_version {
            form.schema_version = schema_version;
        }
        if patch.cta.is_some() {
            form.cta = patch.cta;
        }
        if patch.label_decorator.is_some() {
            form.label_decorator = patch.label_decorator;
        }

        Ok(UpdateFormOutput {
            entity: Some(form.to_form()),
        })
    }
}
