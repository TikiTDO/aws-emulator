impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateTheme<Eng>
{
    type Input = UpdateThemeInput;
    type Output = UpdateThemeOutput;
    type Error = UpdateThemeError;

    const NAME: &'static str = "UpdateTheme";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_THEME_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_THEME_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UpdateThemeErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("the amplifyuibuilder theme store is unavailable".to_string()),
                },
            )
            .into());
        };

        let patch = input.updated_theme;

        // `UpdateThemeData$id` is documented as "The unique ID of the theme to
        // update" — it names the same theme the `@httpLabel` does, so a payload
        // naming a different one is a contradictory request rather than an
        // instruction to renumber the theme. The same rule `UpdateComponent`
        // applies to `UpdateComponentData$id`.
        if let Some(named) = patch.id.as_deref() {
            if named != input.id {
                return Err(UpdateThemeErrorModeled::InvalidParameterException(
                    InvalidParameterException {
                        message: Some(format!(
                            "updatedTheme.id {named:?} does not name the theme being updated \
                             ({:?})",
                            input.id
                        )),
                    },
                )
                .into());
            }
        }

        let mut store = state.lock();
        // The clock is read with the store HELD (as `UpdateComponent` and every
        // other write of this crate reads it): the instant this call stamps into
        // the record is the one it observed while it owned the store, so two
        // concurrent updates stamp in the order they commit and `modifiedAt`
        // reports the last call that changed the theme.
        let now = ::std::time::SystemTime::now();

        // The target is resolved before anything is merged, and the two ways it can
        // fail to resolve are the two `GetTheme` and `DeleteTheme` tell apart (and
        // the component and form operations before them): a theme is addressed by
        // (appId, environmentName, id), so an id another app environment owns is a
        // wrong-scope request (the modelled `InvalidParameterException`, 400) and an
        // id that names no theme anywhere is absent (the widened-in
        // `ResourceNotFoundException`, 404). Nothing is created either way — an
        // update is not an upsert.
        if store
            .theme(&input.app_id, &input.environment_name, &input.id)
            .is_none()
        {
            if store.theme_in_other_scope(&input.app_id, &input.environment_name, &input.id) {
                return Err(UpdateThemeErrorModeled::InvalidParameterException(
                    crate::state::item_wrong_scope(),
                )
                .into());
            }
            return Err(UpdateThemeErrorModeled::ResourceNotFoundException(
                crate::state::item_not_found(),
            )
            .into());
        }

        // A theme name identifies a theme within its app environment, so a rename
        // onto a name ANOTHER live theme there holds is refused with the same
        // `ResourceConflictException` a duplicate create is: the constraint is on
        // the stored set, not on which call would introduce the duplicate.
        // Renaming a theme to the name it already has changes nothing and is not a
        // conflict. `UpdateComponent` and `UpdateForm` apply the same rule.
        if let Some(name) = patch.name.as_deref() {
            if store
                .theme_named(&input.app_id, &input.environment_name, name)
                .is_some_and(|holder| holder.id != input.id)
            {
                return Err(UpdateThemeErrorModeled::ResourceConflictException(
                    crate::state::duplicate_item_name(),
                )
                .into());
            }
        }

        let Some(theme) = store.theme_mut(&input.app_id, &input.environment_name, &input.id) else {
            // Unreachable: the lookup above found this id under the same lock.
            return Err(UpdateThemeErrorModeled::ResourceNotFoundException(
                crate::state::item_not_found(),
            )
            .into());
        };

        // `UpdateThemeData$values` is `@required`, so every update carries the list
        // the theme is to hold and it replaces what was stored. `name` and
        // `overrides` are optional: one the request carries replaces what was
        // stored, one it leaves out keeps it. `appId`, `environmentName`, `id`,
        // `tags` and `createdAt` are not `UpdateThemeData` members at all, so they
        // never move.
        theme.values = patch.values;
        if let Some(name) = patch.name {
            theme.name = name;
        }
        if let Some(overrides) = patch.overrides {
            theme.overrides = Some(overrides);
        }
        theme.modified_at = now;

        Ok(UpdateThemeOutput {
            entity: Some(theme.to_theme()),
        })
    }
}
