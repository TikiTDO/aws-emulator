//! @op ExecuteChangeSet
//! IMPLEMENTED: applies the change set's stored template, parameters, tags, capabilities
//! and the rest of its configuration to the stack it belongs to, and opens the stack's
//! transition — `CREATE_IN_PROGRESS` → `CREATE_COMPLETE` for a `CREATE` change set (the one
//! that created the stack in `REVIEW_IN_PROGRESS`), `UPDATE_IN_PROGRESS` →
//! `UPDATE_COMPLETE` for an `UPDATE` one — so `DescribeStacks` reports the stack settling
//! just as it does after `CreateStack`/`UpdateStack`. Executing it also DEPLOYS that
//! template, which creates the resources it declares in the services that own them
//! (`crate::state::provisioning`) and settles the stack in the FAILED status of the
//! operation it opened when one of them refuses. A failed CREATE is rolled back the way
//! `CreateStack`'s is — what it had made is removed again — and a failed UPDATE is rolled
//! back to the previous stack configuration the way `UpdateStack`'s is, however far the
//! execution got, unless rollback is disabled for it.
//!
//! Executing a change set DEPLOYS its template, so the resources this emulator really
//! CREATES (rather than only records) are created here through their own service, exactly
//! as `CreateStack` creates them: the stack's `Ref` values are the ids those services
//! minted, and a resource one of them refuses makes the STACK operation fail. The deployed
//! template is RECONCILED with what the stack already had, the way `UpdateStack` reconciles
//! it — what the template declares again is kept, what it declares anew is created, and
//! what it no longer declares is deleted in the owning service.
//!
//! The change set itself moves to `EXECUTE_IN_PROGRESS` and reaches `EXECUTE_COMPLETE`
//! with the stack, and "CloudFormation deletes all other change sets associated with the
//! stack because they aren't valid for the updated stack". A change set whose creation has
//! not completed, or that has already been executed, is refused with the modelled
//! `InvalidChangeSetStatusException`, and a request whose `ClientRequestToken` an operation
//! on the stack already claimed with the modelled `TokenAlreadyExistsException` — whichever
//! operation claimed it, as in `UpdateStack`: this execution changes the stack, and a
//! change set that has already been executed is refused on its own status anyway.
//!
//! An UPDATE change set's execution is held to the STACK POLICY in force, exactly as
//! `UpdateStack` is ([`crate::state::stack_policy`]): where the policy refuses one of the
//! actions the stored plan would take on one of the stack's resources, the plan is not
//! carried out — the change set's configuration never reaches the stack, the protected
//! resource reports the refusal, the update is rolled back and the change set is left in
//! the modelled `EXECUTE_FAILED`.
