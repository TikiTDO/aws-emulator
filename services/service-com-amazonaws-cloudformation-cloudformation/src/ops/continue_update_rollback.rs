impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ContinueUpdateRollback<Eng>
{
    type Input = ContinueUpdateRollbackInput;
    type Output = ContinueUpdateRollbackOutput;
    type Error = ContinueUpdateRollbackError;

    const NAME: &'static str = "ContinueUpdateRollback";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CONTINUE_UPDATE_ROLLBACK_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CONTINUE_UPDATE_ROLLBACK_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // Not the shared in-memory engine: there is no stack to continue rolling back,
            // and nothing was written.
            return Err(crate::scaffolded::Scaffolded::not_implemented(
                "ContinueUpdateRollback",
            ));
        };
        // "ForceRollback and ResourcesToSkip are mutually exclusive. Specifying both in the
        // same request returns a validation error." The refusal is that documented sentence
        // about the two members, with no part of the request in it.
        let force_rollback = input.force_rollback.unwrap_or(false);
        let named_to_skip = input
            .resources_to_skip
            .as_deref()
            .is_some_and(|resources| !resources.is_empty());
        if force_rollback && named_to_skip {
            return Err(crate::scaffolded::Scaffolded::validation_error(
                "ForceRollback and ResourcesToSkip are mutually exclusive",
            ));
        }
        // The rollback runs as the `RoleARN` it names, so a role CloudFormation cannot
        // assume is refused before the stack is touched — the same check `UpdateStack`
        // makes.
        crate::state::refuse_unassumable_role(&*self.engine, input.role_arn.as_deref())?;
        let now = ::std::time::SystemTime::now();
        let request_region = crate::state::request_region(ctx.parts());
        // A rollback can be continued only from UPDATE_ROLLBACK_FAILED, so a rollback the
        // failure of the update already made due is carried out first — including the one
        // that LANDS the stack in that status: it was owed at the instant that update
        // failed, whether or not anybody called (`crate::state::settle_due_rollbacks`).
        crate::state::settle_due_rollbacks(ctx, &*self.engine).await;

        // The store lock is taken for the write and RELEASED at the end of this block: the
        // calls that put the resources back run after it, and each of those reaches another
        // service's own handler.
        let (stack_id, region, declared, against, outstanding, provenance, role_arn, policies) = {
            let mut store = state.lock();
            store.settle(now);

            let Some(previous) = store
                .resolve(&request_region, &input.stack_name)
                .filter(|stack| stack.is_live())
            else {
                return Err(crate::scaffolded::Scaffolded::validation_error(
                    crate::state::labelled_stack_does_not_exist(&input.stack_name),
                ));
            };
            // "A stack goes into the UPDATE_ROLLBACK_FAILED state when CloudFormation can't
            // roll back all changes after a failed stack update": that is the one state a
            // rollback can be continued from, so a stack in any other one is refused and
            // left exactly where it is. The refusal names the call that cannot be made and
            // the status the stack is in.
            if previous.status != status::UPDATE_ROLLBACK_FAILED {
                return Err(crate::scaffolded::Scaffolded::validation_error(
                    crate::state::cannot_continue_update_rollback(&previous.status),
                ));
            }
            // "A client request token already exists": the token identifies ONE request, so
            // one this stack has already run an operation under is the modelled refusal
            // rather than a second rollback.
            if let Some(token) = &input.client_request_token {
                if previous
                    .events
                    .iter()
                    .any(|event| event.client_request_token.as_deref() == Some(token.as_str()))
                {
                    return Err(
                        ContinueUpdateRollbackErrorModeled::TokenAlreadyExistsException(
                            TokenAlreadyExistsException {
                                message: Some(format!(
                                    "Token {token} already exists for stack {}",
                                    previous.stack_id
                                )),
                            },
                        )
                        .into(),
                    );
                }
            }
            // "You can specify only resources that are in the UPDATE_FAILED state because a
            // rollback failed", and `ForceRollback` is "this instead of listing each
            // resource individually in ResourcesToSkip. Only resources that entered the
            // UPDATE_FAILED state because a rollback failed are skipped" — so both spellings
            // select from the SAME set, and a logical id outside it is refused rather than
            // silently skipped.
            let failed: Vec<String> = previous
                .resources
                .iter()
                .filter(|deployed| deployed.status == resource_status::UPDATE_FAILED)
                .map(|deployed| deployed.resource.logical_id.clone())
                .collect();
            let skipped: Vec<String> = if force_rollback {
                failed.clone()
            } else {
                input.resources_to_skip.clone().unwrap_or_default()
            };
            if let Some(unexpected) = skipped
                .iter()
                .find(|logical_id| !failed.contains(logical_id))
            {
                return Err(crate::scaffolded::Scaffolded::validation_error(format!(
                    "ResourcesToSkip can only name resources in the {} state; [{unexpected}] \
                     is not one of them",
                    resource_status::UPDATE_FAILED
                )));
            }

            let Some(stack) = store.resolve_mut(&request_region, &input.stack_name) else {
                return Err(crate::scaffolded::Scaffolded::validation_error(
                    crate::state::labelled_stack_does_not_exist(&input.stack_name),
                ));
            };
            if let Some(role_arn) = &input.role_arn {
                // "CloudFormation always uses this role for all future operations on the
                // stack."
                stack.role_arn = Some(role_arn.clone());
            }
            stack.continue_update_rollback(
                now,
                &skipped,
                input.client_request_token.clone(),
            );
            // What the rollback still owes the owning services, and what they are still
            // HOLDING: both sides of the rollback that failed
            // ([`crate::state::StoredStack::unreverted_rollback`]). The previous
            // configuration is what this resumption declares again, and what the failed
            // update left there is what it declares that against — the stack's own records
            // report what those services hold, so resuming from them alone would ask for no
            // change at all. A stack whose outstanding rollback this service does not hold
            // is resumed over the resources in force, declared against themselves.
            //
            // The resources `ResourcesToSkip` names are left out of BOTH sides: they are
            // "left exactly as the failed update made them", so they are neither reverted
            // nor removed.
            let outstanding = stack.unreverted_rollback.clone();
            let in_force: Vec<crate::state::StoredResource> = stack
                .resources
                .iter()
                .map(|deployed| deployed.resource.clone())
                .collect();
            let not_skipped = |resources: Vec<crate::state::StoredResource>| {
                resources
                    .into_iter()
                    .filter(|resource| !skipped.contains(&resource.logical_id))
                    .collect::<Vec<crate::state::StoredResource>>()
            };
            let declared = not_skipped(match &outstanding {
                Some(rollback) => rollback.previous.clone(),
                None => in_force.clone(),
            });
            let against = not_skipped(match &outstanding {
                Some(rollback) => rollback.applied.clone(),
                None => declared.clone(),
            });
            (
                stack.stack_id.clone(),
                stack.region.clone(),
                declared,
                against,
                outstanding,
                stack.provenance(),
                // The role the resumed rollback's own calls are made under: the one in
                // force on the stack, which this request may have just replaced.
                stack.role_arn.clone(),
                // What this rollback does with the `DeletionPolicy` of a resource the failed
                // update had created, which it is still resuming the removal of.
                stack.rolled_back_resource_policies(),
            )
        };

        // The rollback is re-attempted over the resources it did not skip, in the Region the
        // stack lives in: each is declared again in the service that owns it, against what
        // that service is still holding, so a change the failed rollback could not put back
        // is asked for again and nothing the rollback is not resuming is created or deleted.
        let role = crate::state::service_role::ServiceRole::of(&*self.engine, role_arn.as_deref());
        let reverted = crate::state::service_role::acting_as(
            role,
            crate::state::provisioning::reconcile(
                ctx,
                &region,
                &provenance,
                declared,
                &against,
                // A resumed rollback puts back a configuration this stack already
                // deployed, so there is nothing for CloudFormation to refuse about it.
                None,
                policies,
            ),
        )
        .await;

        let mut store = state.lock();
        if let Some(stack) = store.resolve_mut(&request_region, &stack_id) {
            stack.schedule_resource_events(&reverted.transitions);
            stack.record_materialised_resources(reverted.resources);
            // What the resumed rollback left each resource in, which is what a client reads
            // back — and what says which resource a further resumption may skip.
            stack.record_rollback_resource_statuses(
                &reverted.transitions,
                ::std::time::SystemTime::now(),
            );
            if let Some(failure) = reverted.failure {
                // The rollback could not be carried out even now: the stack stays in
                // UPDATE_ROLLBACK_FAILED with the owning service's own refusal as the
                // reason, rather than reporting a rollback that did not happen, and what
                // the owning services hold is still what the failed update put there.
                stack.fail_transition(
                    ::std::time::SystemTime::now(),
                    status::UPDATE_ROLLBACK_FAILED,
                    failure,
                );
                stack.unreverted_rollback = outstanding;
            }
        }

        Ok(ContinueUpdateRollbackOutput {})
    }
}
