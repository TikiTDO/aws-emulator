            // deleting the stack that publishes it would break the cross-stack reference
            // the importing stack resolved. The model declares no error for it, so the CALL
            // is not refused — the deletion workflow below is what FAILS, which is read off
            // this store's own index (`ListImports` reports the same relation) and so lets
            // the identical call through as soon as the last importer is gone.
