//! @op DeleteStack
//! IMPLEMENTED: starts the stored stack's deletion — `DELETE_IN_PROGRESS` now, then
//! `DELETE_COMPLETE` with a `DeletionTime` once the clock makes it due, which takes the
//! stack out of the live set and deletes the resources it provisioned, each with its own
//! events. A stack with termination protection enabled is refused, and so is a request
//! whose `ClientRequestToken` an operation on that stack already claimed (the modelled
//! `TokenAlreadyExistsException`) — including a delete's own token, as in `UpdateStack`,
//! and whatever the stack is doing; the one token answered rather than refused is the
//! DELETION IN FLIGHT's own, which is the caller who really is repeating the request and
//! gets the no-op success a delete already under way has always answered.
//!
//! A deletion the service cannot carry out because the stack publishes an export another
//! live stack still imports is TAKEN and then CANCELLED: the model declares no error for
//! it, so the stack reports `DELETE_IN_PROGRESS` and then goes back to the healthy status
//! it held, carrying the reason naming the export and the importing stack, with nothing of
//! it disposed of — so a caller waiting on the deletion reads a stack that is still there
//! and intact rather than one whose resources are stranded.
//!
//! Deleting a stack also DELETES THE RESOURCES it created, newest first, through the
//! services that own them ([`crate::state::provisioning`]); a resource one of those
//! services refuses to delete leaves the stack in `DELETE_FAILED` with that refusal as
//! the reason, rather than reporting a deletion that did not happen — unless the request
//! names `DeletionMode` `FORCE_DELETE_STACK`, under which such a resource is ABANDONED (it
//! stays exactly as it is, reported `DELETE_SKIPPED`) and the deletion carries on to
//! `DELETE_COMPLETE`, which is the documented way out of a stack stuck in `DELETE_FAILED`.
//!
//! `RetainResources` is the other way out of that status, and the only member whose
//! resources this deletion does not remove: for a stack in `DELETE_FAILED` ("retaining
//! resources is useful when you can't delete a resource, such as a non-empty S3 bucket, but
//! you want to delete the stack"), every logical id it names is RELEASED rather than
//! removed — nothing is asked of the service that owns it, so the resource stays exactly as
//! it is and goes on serving its own clients, the stack records its deletion as
//! `DELETE_SKIPPED`, and the stack's own deletion completes around it. It is refused for a
//! stack in any other status, as CloudFormation refuses it, and so is a list naming a
//! resource that is not there to be retained: a resource is retained by being LEFT where it
//! is, so one whose own deletion already completed — which is every resource of a stack
//! whose deletion completed — cannot be
//! ([`RETAINED_RESOURCES_MUST_EXIST`]).
//!
//! A deletion is refused outright while an UPDATE of the stack is in flight
//! ([`crate::state::status_takes_a_delete`]): CloudFormation runs one operation at a time
//! against a stack, and that update is changing the very resources this deletion would
//! dispose of.
//!
