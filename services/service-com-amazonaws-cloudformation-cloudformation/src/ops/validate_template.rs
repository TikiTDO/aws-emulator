impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ValidateTemplate<Eng>
{
    type Input = ValidateTemplateInput;
    type Output = ValidateTemplateOutput;
    type Error = ValidateTemplateError;

    const NAME: &'static str = "ValidateTemplate";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::VALIDATE_TEMPLATE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::VALIDATE_TEMPLATE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // A verdict on the REQUEST's template body: this operation reads no stored
        // resource and writes none.
        let _ = &self.engine;
        // "Conditional: You must pass TemplateURL or TemplateBody" — and one of them, not
        // both: a request carrying a body AND a reference states two templates, so there is
        // no one body to give a verdict on. The condition and its wording come from the one
        // place that owns them (`crate::state::validate_one_template_source`).
        crate::state::validate_one_template_source(
            input.template_body.as_deref(),
            input.template_url.as_deref(),
        )
        .map_err(crate::scaffolded::Scaffolded::validation_error)?;
        // A `TemplateURL` says WHERE the body is, not what it means: the object it
        // addresses is read from this emulator's own Amazon S3 and the verdict below is
        // given on it exactly as on an inline body (`crate::state::template_url`).
        let fetched: Option<String> = match (&input.template_body, &input.template_url) {
            (None, Some(url)) => Some(
                crate::state::template_url::fetch(
                    ctx,
                    &crate::state::request_region(ctx.parts()),
                    url,
                )
                .await
                .map_err(crate::scaffolded::Scaffolded::validation_error)?,
            ),
            _ => None,
        };
        // Borrowed, never copied: the body may be 51,200 bytes and nothing below needs
        // to own it.
        let (template_body, max_template_bytes) = match (&input.template_body, &fetched) {
            (Some(body), _) => (body.as_str(), crate::state::TEMPLATE_BODY_MAX_BYTES),
            (None, Some(body)) => (body.as_str(), crate::state::TEMPLATE_MAX_BYTES),
            (None, None) => {
                return Err(crate::scaffolded::Scaffolded::validation_error(
                    "Either TemplateBody or TemplateURL must be specified",
                ))
            }
        };
        // The documented `TemplateBody` maximum, which the model carries no `@length`
        // for — the same rule every operation that takes a body is held to.
        crate::state::validate_template_body_within(template_body, max_template_bytes)
            .map_err(crate::scaffolded::Scaffolded::validation_error)?;
        // The documented per-template quotas, named one by one: a body past one of them is
        // refused for the quota it is past rather than for the form it has, which is the
        // same verdict the operations that SUBMIT a template for deployment give it.
        crate::state::validate_template_quotas(template_body)
            .map_err(crate::scaffolded::Scaffolded::validation_error)?;
        // A body this service's reader will not read at all, and one it reads into something
        // that is no mapping of template sections, refused with the one wording every
        // operation that reads a body gives it — the structural fault FIRST, so a document
        // the format cannot carry is reported for its structure rather than for a section it
        // was never read to have.
        if let Err(refusal) = template::section_map(template_body) {
            return Err(crate::scaffolded::Scaffolded::validation_error(refusal));
        }
        let Some(template) = template::parse(template_body) else {
            return Err(crate::scaffolded::Scaffolded::validation_error(
                template::not_well_formed(template_body),
            ));
        };
        // "Resources (required): Specifies the stack resources and their properties" is
        // the one section a template cannot leave out, and an entry carrying no `Type`
        // ("Type: required") declares no resource — so a body whose `Resources` section
        // is missing or empty is refused rather than reported as valid, and one carrying an
        // untyped entry is refused for that entry. Both are worded in the one place that
        // owns them.
        if let Some(refusal) = template::resources_refusal(&template) {
            return Err(crate::scaffolded::Scaffolded::validation_error(refusal));
        }
        // A `Description` past its documented maximum, and a `Mappings` member that is no
        // map, are template-FORMAT errors this verdict gives in the one wording every
        // operation that reads a body gives them (`crate::state::template`) — reached below,
        // with the rest of the template-validation pass.
        // A resource type CloudFormation does not recognise is a template-FORMAT error, and
        // this verdict on the body is held to the same catalogue the operations that SUBMIT
        // a body for deployment hold it to, worded identically: a client validating a
        // template before a stack operation is told what that operation would refuse
        // (`crate::state::resource_types`). A template declaring a `Transform` is held to no
        // catalogue at all, which is the rule that one place owns.
        crate::state::validate_resource_types(template_body)
            .map_err(crate::scaffolded::Scaffolded::validation_error)?;
        // The template-VALIDATION rules are each decided from the document alone — a
        // function no template may use, an intrinsic spelled with the wrong arguments, a name
        // the template does not declare, a dependency cycle — so they are this operation's
        // verdict too, and the body is held to exactly the pass the operations that SUBMIT
        // one hold it to, worded identically
        // (`crate::state::template_validation`). The values in force are the template's own
        // `Default`s, which is every value a request carrying nothing but a body fixes. What
        // an intrinsic RESOLVES to is not part of the verdict: this operation gives it
        // without evaluating the template's expressions, so a `Mappings` lookup it makes is
        // left to the operation that deploys the body.
        let parameters: ::std::collections::BTreeMap<String, String> =
            crate::state::parameters_in_force(template_body, Vec::new())
                .into_iter()
                .map(|parameter| (parameter.key, parameter.value))
                .collect();
        let processed = template::process_with_parameters(template_body, &parameters);
        crate::state::validate_template_for_validation(
            template_body,
            &processed,
            &parameters,
            &crate::state::request_region(ctx.parts()),
        )
        .map_err(crate::scaffolded::Scaffolded::validation_error)?;
        let required = crate::state::template_summary::required_capabilities(template_body, &template);
        Ok(ValidateTemplateOutput {
            // One `TemplateParameter` per parameter the template declares, carrying what
            // the declaration says: a template declaring no `Parameters` section reports
            // the empty list rather than nothing, because "no parameters" is itself the
            // answer a client validating a template before a stack operation reads.
            // `NoEcho` is reported for every parameter, `false` being its documented
            // default.
            parameters: Some(
                template
                    .parameters
                    .iter()
                    .map(|parameter| TemplateParameter {
                        parameter_key: Some(parameter.key.clone()),
                        default_value: parameter.default.clone(),
                        no_echo: Some(parameter.no_echo),
                        description: parameter.description.clone(),
                    })
                    .collect(),
            ),
            // "The description found within the template."
            description: template.description.clone(),
            // "The capabilities found within the template": reported only where the
            // template declares something that has to be acknowledged — its IAM resources
            // and the macros it invokes — together with the resources that generated them
            // (`crate::state::template_summary`).
            capabilities: (!required.capabilities.is_empty()).then_some(required.capabilities),
            capabilities_reason: required.reason,
            // "A list of the transforms that are declared in the template."
            declared_transforms: (!template.transforms.is_empty())
                .then(|| template.transforms.clone()),
        })
    }
}
