//! What a stack's provisioning and its TEARDOWN leave of the AWS Step Functions state
//! machine it declares, end to end over both services' own wires, with Step Functions
//! mounted beside CloudFormation on one engine.
//!
//! Two rules are under test, each read back through the OWNING service's API rather than out
//! of CloudFormation's own record:
//!
//! 1. a resource CloudFormation provisions carries, in the service that owns it, the
//!    stack-level `Tags` the stack operation supplied PLUS the three tags CloudFormation
//!    records itself — `aws:cloudformation:stack-name`, `aws:cloudformation:stack-id` and
//!    `aws:cloudformation:logical-id` — and a key the resource's own declaration states keeps
//!    that declaration's value, except those three, which are CloudFormation's to set
//!    whatever a declaration spells;
//! 2. a stack's deletion REMOVES the resource from the service that owns it, so once the
//!    stack reports `DELETE_COMPLETE` that service holds nothing under the handle the stack
//!    published: every read of it is refused with that service's own does-not-exist error,
//!    which for a state machine is HTTP 400 `StateMachineDoesNotExist` carrying
//!    `State Machine Does Not Exist: '<stateMachineArn>'`.
//!
//! A leaked state machine would fail the second rule in a way a client sees: it still answers
//! `DescribeStateMachine` as `ACTIVE`, it still holds its name against a redeployment, and an
//! execution can still be started against a workflow the stack that owned it is reported as
//! having deleted — so a teardown could never be confirmed.
//!
//! The rows differ along what the rules generalise over: where the machine's NAME comes from
//! (spelled by the template, or generated by CloudFormation for a declaration that states
//! none), the workflow TYPE (`STANDARD` and `EXPRESS`), the FORM the definition is stated in
//! (`DefinitionString` text and a `Definition` document), and what the declaration's own
//! `Tags` ask for (none, one of its own, a key the stack also states, and a key that is
//! CloudFormation's own). Every machine is a resource of ONE stack, so the two stack-level
//! tags are the same across the rows while `aws:cloudformation:logical-id` differs per
//! resource. Every expected value is computed from what the row declares plus the stack id
//! `DescribeStacks` reports — never read back out of the answer being checked.

use std::collections::BTreeMap;

use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

use crate::stack_lifecycle::{
    call, create_stack, describe_stack, member, output_value, router, xml_text,
};
use crate::stack_owned_secret_teardown::{error_code, poll_to_terminal};
use crate::stack_tag_propagation::expected_tags;
use crate::step_functions_state_machine_replacement::sfn_json;

/// The stack every row is deployed in: one provisioning and one teardown is what the rules
/// are about, so the rows are resources of ONE stack rather than a stack each.
const STACK: &str = "sfn-stack-provenance";

/// The stack-level `Tags` the `CreateStack` call supplies, which every resource of the stack
/// must carry beside CloudFormation's own three.
const STACK_TAGS: &[(&str, &str)] = &[("team", "platform"), ("owner", "the-stack")];

/// The role every declared machine runs its executions as, which the type requires.
const ROLE_ARN: &str = "arn:aws:iam::000000000000:role/StepFunctionsRole";

/// The error code Step Functions refuses a call naming a state machine it does not hold with
/// (`StateMachineDoesNotExist`, that service's own modelled refusal).
const STATE_MACHINE_DOES_NOT_EXIST: &str = "StateMachineDoesNotExist";

/// The status `DescribeStateMachine` reports a usable state machine in
/// (`StateMachineStatus`: ACTIVE | DELETING).
const ACTIVE: &str = "ACTIVE";

/// The sentence that refusal carries: the condition the error shape names, then the ARN the
/// request asked about.
fn expected_missing_message(arn: &str) -> String {
    format!("State Machine Does Not Exist: '{arn}'")
}

/// The workflow one row declares. Different per row, so no row can pass on another's
/// document.
const PASS_DEFINITION: &str = r#"{"StartAt":"Done","States":{"Done":{"Type":"Pass","End":true}}}"#;
const RESULT_DEFINITION: &str =
    r#"{"StartAt":"Done","States":{"Done":{"Type":"Pass","Result":{"ok":true},"End":true}}}"#;
const WAITING_DEFINITION: &str = r#"{"StartAt":"Hold","States":{"Hold":{"Type":"Wait","Seconds":1,"Next":"Done"},"Done":{"Type":"Succeed"}}}"#;
const CHOICE_DEFINITION: &str = r#"{"StartAt":"Pick","States":{"Pick":{"Type":"Choice","Choices":[{"Variable":"$.go","BooleanEquals":true,"Next":"Done"}],"Default":"Done"},"Done":{"Type":"Succeed"}}}"#;

/// Which property the row states its definition in: the type states the workflow as TEXT
/// (`DefinitionString`) or as the template OBJECT (`Definition`), and both are the definition
/// itself.
#[derive(Debug, Clone, Copy)]
enum Form {
    /// `DefinitionString`: the Amazon States Language document as text.
    Text,
    /// `Definition`: that same document as a template object.
    Document,
}

/// One declared state machine of the stack.
#[derive(Debug, Clone, Copy)]
struct Row {
    case: &'static str,
    /// The logical id the template declares it under, which also names its output.
    logical_id: &'static str,
    /// The `StateMachineName` the declaration states, or `""` for the row that states none
    /// and so is created under the name CloudFormation generates.
    declared_name: &'static str,
    /// The `StateMachineType` the declaration states.
    machine_type: &'static str,
    /// The workflow the declaration states, and how it states it.
    definition: &'static str,
    form: Form,
    /// The `Tags` the declaration asks for.
    declared_tags: &'static [(&'static str, &'static str)],
    /// The declared tags that must read back under their declared value: every one whose key
    /// is the declaration's own to set, which is every one outside the three CloudFormation
    /// records itself.
    kept_tags: &'static [(&'static str, &'static str)],
}

const ROWS: &[Row] = &[
    Row {
        // The recorded shape: a named STANDARD machine that declares no tags of its own, so
        // the stack's two tags and CloudFormation's three are the whole set.
        case: "a named STANDARD machine declaring no tags of its own",
        logical_id: "Named",
        declared_name: "sfn-stack-provenance-named",
        machine_type: "STANDARD",
        definition: PASS_DEFINITION,
        form: Form::Text,
        declared_tags: &[],
        kept_tags: &[],
    },
    Row {
        // No `StateMachineName` at all, an EXPRESS workflow, and the definition stated as the
        // template OBJECT: the rules hold whichever way the resource is identified and the
        // workflow written.
        case: "an EXPRESS machine under a generated name, declaring its definition as a document",
        logical_id: "Generated",
        declared_name: "",
        machine_type: "EXPRESS",
        definition: RESULT_DEFINITION,
        form: Form::Document,
        declared_tags: &[("workload", "express")],
        kept_tags: &[("workload", "express")],
    },
    Row {
        // A key the stack ALSO states: the declaration is the more specific statement about
        // this one resource, so its value is the one the machine carries.
        case: "a declared tag whose key the stack states too",
        logical_id: "Collides",
        declared_name: "sfn-stack-provenance-collides",
        machine_type: "STANDARD",
        definition: WAITING_DEFINITION,
        form: Form::Text,
        declared_tags: &[("owner", "the-resource"), ("retention-days", "7")],
        kept_tags: &[("owner", "the-resource"), ("retention-days", "7")],
    },
    Row {
        // A declaration that spells one of CloudFormation's OWN three keys does not displace
        // it: those three are CloudFormation's to set, wherever they are written.
        case: "a declaration that spells aws:cloudformation:logical-id itself",
        logical_id: "Claimed",
        declared_name: "",
        machine_type: "STANDARD",
        definition: CHOICE_DEFINITION,
        form: Form::Text,
        declared_tags: &[
            ("aws:cloudformation:logical-id", "NotThisOne"),
            ("workload", "claimed"),
        ],
        // Only the key that is CloudFormation's own is overridden; the ordinary declared tag
        // stands.
        kept_tags: &[("workload", "claimed")],
    },
];

/// The `Properties` a row declares.
fn properties(row: &Row) -> Value {
    let mut properties = serde_json::Map::new();
    match row.form {
        Form::Text => {
            properties.insert("DefinitionString".to_string(), json!(row.definition));
        }
        Form::Document => {
            properties.insert("Definition".to_string(), declared_document(row));
        }
    }
    properties.insert("RoleArn".to_string(), json!(ROLE_ARN));
    properties.insert("StateMachineType".to_string(), json!(row.machine_type));
    if !row.declared_name.is_empty() {
        properties.insert("StateMachineName".to_string(), json!(row.declared_name));
    }
    if !row.declared_tags.is_empty() {
        properties.insert(
            "Tags".to_string(),
            Value::Array(
                row.declared_tags
                    .iter()
                    .map(|(key, value)| json!({"Key": key, "Value": value}))
                    .collect(),
            ),
        );
    }
    Value::Object(properties)
}

/// The row's workflow as the template OBJECT form carries it.
fn declared_document(row: &Row) -> Value {
    serde_json::from_str(row.definition).expect("a row's definition is a JSON document")
}

/// The document Step Functions must hold for the row: the text the declaration stated, and
/// for the document form the JSON that document serializes to — computed from the
/// declaration, so the row's own definition is what the assertion is held to.
fn expected_definition(row: &Row) -> String {
    match row.form {
        Form::Text => row.definition.to_string(),
        Form::Document => declared_document(row).to_string(),
    }
}

/// The template declaring every row, and publishing each machine's ARN as an output — "Ref
/// returns the ARN of the state machine", which is the handle every Step Functions call
/// takes.
fn template() -> String {
    let mut resources = serde_json::Map::new();
    let mut outputs = serde_json::Map::new();
    for row in ROWS {
        resources.insert(
            row.logical_id.to_string(),
            json!({
                "Type": "AWS::StepFunctions::StateMachine",
                "Properties": properties(row),
            }),
        );
        outputs.insert(arn_output(row), json!({"Value": {"Ref": row.logical_id}}));
    }
    json!({"Resources": resources, "Outputs": outputs}).to_string()
}

/// The output key a row's ARN is published under.
fn arn_output(row: &Row) -> String {
    format!("{}Arn", row.logical_id)
}

/// The `Tags.member.N.Key`/`Value` request members the stack-level tag list is.
fn stack_tag_members() -> Vec<(String, String)> {
    let mut members = Vec::new();
    for (index, (key, value)) in STACK_TAGS.iter().enumerate() {
        let position = index + 1;
        members.push(member(&format!("Tags.member.{position}.Key"), key));
        members.push(member(&format!("Tags.member.{position}.Value"), value));
    }
    members
}

/// The tags Step Functions holds for `arn`, with the status it answered.
///
/// That service's model spells a tag with the members `key` and `value`
/// (`smithy_query(query="shape",shape="Tag")`), which is how the answer is read.
async fn machine_tags(
    router: &MultiServiceRouter,
    arn: &str,
) -> (u16, BTreeMap<String, String>) {
    let (status_code, answered) = sfn_json(
        router,
        "ListTagsForResource",
        &json!({"resourceArn": arn}),
    )
    .await;
    let held = answered
        .get("tags")
        .and_then(Value::as_array)
        .map(|tags| {
            tags.iter()
                .filter_map(|tag| {
                    let key = tag.get("key").and_then(Value::as_str)?;
                    Some((
                        key.to_string(),
                        tag.get("value")
                            .and_then(Value::as_str)
                            .unwrap_or_default()
                            .to_string(),
                    ))
                })
                .collect()
        })
        .unwrap_or_default();
    (status_code, held)
}

/// A required string member of an answer.
fn text(case: &str, answered: &Value, member: &str) -> String {
    answered
        .get(member)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: no {member} in {answered}"))
        .to_string()
}

#[tokio::test]
async fn a_stacks_state_machine_carries_its_provenance_tags_and_goes_with_the_stack() {
    let router = router();
    let (status_code, body) =
        create_stack(&router, STACK, &template(), &stack_tag_members()).await;
    assert_eq!(
        status_code, 200,
        "CreateStack must answer 200, got {status_code} {body}"
    );
    let described = poll_to_terminal(&router, "the stack", STACK).await;
    assert_eq!(
        xml_text(&described, "StackStatus").as_deref(),
        Some("CREATE_COMPLETE"),
        "expected the create to complete, got {described}"
    );
    let stack_id = xml_text(&described, "StackId").unwrap_or_default();
    assert!(
        !stack_id.is_empty(),
        "expected the stack to report its id, got {described}"
    );

    // BEFORE the teardown: every machine the stack declared really exists in Step Functions,
    // carries the declared workflow, and answers that service's own tag read with the stack's
    // tags and CloudFormation's three.
    let mut published: Vec<(Row, String)> = Vec::new();
    for row in ROWS {
        let case = row.case;
        let arn = output_value(&described, &arn_output(row))
            .unwrap_or_else(|| panic!("case {case:?}: the stack published no ARN in {described}"));

        let (status_code, answered) = sfn_json(
            &router,
            "DescribeStateMachine",
            &json!({"stateMachineArn": arn}),
        )
        .await;
        assert_eq!(
            status_code, 200,
            "case {case:?}: expected Step Functions to hold the machine the stack created, got \
             {status_code} {answered}"
        );
        assert_eq!(
            text(case, &answered, "status"),
            ACTIVE,
            "case {case:?}: expected a created machine to be {ACTIVE}, got {answered}"
        );
        assert_eq!(
            text(case, &answered, "type"),
            row.machine_type,
            "case {case:?}: expected the declared type, got {answered}"
        );
        assert_eq!(
            text(case, &answered, "definition"),
            expected_definition(row),
            "case {case:?}: expected the declared workflow, got {answered}"
        );
        let name = text(case, &answered, "name");
        if row.declared_name.is_empty() {
            assert!(
                name.starts_with(STACK) && name.len() > STACK.len(),
                "case {case:?}: expected a generated name built on the stack's, got {name:?}"
            );
        } else {
            assert_eq!(
                name, row.declared_name,
                "case {case:?}: expected the machine to be created under the declared name, got \
                 {name:?}"
            );
        }

        let (status_code, held) = machine_tags(&router, &arn).await;
        assert_eq!(
            status_code, 200,
            "case {case:?}: expected ListTagsForResource({arn:?}) to answer 200, got \
             {status_code}"
        );
        let expected = expected_tags(
            STACK_TAGS,
            row.kept_tags,
            STACK,
            &stack_id,
            row.logical_id,
        );
        assert_eq!(
            held, expected,
            "case {case:?}: expected the stack's tags and CloudFormation's own on {arn:?}, got \
             {held:?}"
        );

        published.push((*row, arn));
    }

    // The teardown itself.
    let (status_code, body) = call(&router, "DeleteStack", &[member("StackName", STACK)]).await;
    assert_eq!(
        status_code, 200,
        "DeleteStack must answer 200, got {status_code} {body}"
    );
    let described = poll_to_terminal(&router, "the teardown", &stack_id).await;
    assert_eq!(
        xml_text(&described, "StackStatus").as_deref(),
        Some("DELETE_COMPLETE"),
        "expected the teardown to reach DELETE_COMPLETE, got {described}"
    );
    let (status_code, body) = describe_stack(&router, &stack_id).await;
    assert_eq!(
        status_code, 200,
        "DescribeStacks on the deleted stack's id must still answer, got {status_code} {body}"
    );

    // AFTER it: Step Functions holds no such machine, whichever operation asks — a read of it
    // and a start against it are each refused with that service's own does-not-exist error,
    // naming the ARN the request asked about.
    for (row, arn) in &published {
        let case = row.case;
        for operation in ["DescribeStateMachine", "StartExecution"] {
            let (status_code, refused) =
                sfn_json(&router, operation, &json!({"stateMachineArn": arn})).await;
            assert_eq!(
                (status_code, error_code(case, &refused).as_str()),
                (400, STATE_MACHINE_DOES_NOT_EXIST),
                "case {case:?}: expected {operation}({arn:?}) on the deleted stack's machine to \
                 be refused with {STATE_MACHINE_DOES_NOT_EXIST}, got {status_code} {refused}"
            );
            let expected = expected_missing_message(arn);
            assert_eq!(
                refused.get("message").and_then(Value::as_str),
                Some(expected.as_str()),
                "case {case:?}: expected {operation} to state {expected:?}, got {refused}"
            );
        }
    }
}
