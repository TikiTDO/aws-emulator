impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for StopJob<Eng>
{
    type Input = StopJobInput;
    type Output = StopJobOutput;
    type Error = StopJobError;

    const NAME: &'static str = "StopJob";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::STOP_JOB_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::STOP_JOB_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            StopJobErrorModeled::InternalFailureException(InternalFailureException {
                message: Some("the Amplify emulator has no state store attached".to_string()),
            })
        })?;

        let mut store = state.lock();

        // A job is addressed through its branch and its app, so neither an unknown app
        // nor a branch this app does not carry resolves to a job: the 404 names the
        // entity that is actually absent.
        let app = store
            .apps
            .get_mut(&input.app_id)
            .ok_or_else(|| absent(crate::state::APP_ENTITY, &input.app_id))?;

        let branch = app
            .branches
            .get_mut(&input.branch_name)
            .ok_or_else(|| absent(crate::state::BRANCH_ENTITY, &input.branch_name))?;
        let job = branch
            .jobs
            .get_mut(&input.job_id)
            .ok_or_else(|| absent(crate::state::JOB_ENTITY, &input.job_id))?;

        // The status change the clock has already made due is materialised BEFORE this
        // call judges the job: it was owed whether or not anybody called, so a job the
        // clock finished is a finished job here too, not one still in progress that this
        // call could stop.
        job.settle();

        // "Stops a job that is in progress": a job that has already reached a terminal
        // status has no progress left to stop, so the request is refused with the
        // modelled 400 and the job is left exactly as it ended. The message is the fixed
        // text of this error class — `BadRequestException` is the catch-all for every 400
        // on this surface, so the message is the only thing that discriminates them —
        // and it names neither the job, the branch nor the status.
        if crate::state::is_terminal_job_status(&job.job.summary.status) {
            return Err(StopJobErrorModeled::BadRequestException(BadRequestException {
                message: Some(crate::state::JOB_ALREADY_TERMINAL_MESSAGE.to_string()),
            })
            .into());
        }

        // Stopping a job whose work has BEGUN is asynchronous, like starting one: the
        // call answers with the non-terminal status Amplify spells `CANCELLING` and the
        // clock settles the job to `CANCELLED`, so a caller that reads the job straight
        // after this call still observes the cancellation in flight. A job NOTHING has
        // started — a deployment that only reserved its number — has no work to wind
        // down, so its cancellation is COMPLETE in this call's own answer: the terminal
        // `CANCELLED` (see `crate::state::BranchJob::cancel`), which leaves the branch
        // deployable again by the caller's very next call.
        job.cancel();
        // A deployment that was created and never started is cancelled as a whole: its
        // reservation is spent by this call, so the upload destinations
        // `CreateDeployment` handed out can no longer be started. A job that was already
        // running holds no reservation and this removes nothing.
        branch.deployments.remove(&input.job_id);
        let job_summary = branch
            .jobs
            .get(&input.job_id)
            .map(|stopped| stopped.job.summary.clone())
            .ok_or_else(|| absent(crate::state::JOB_ENTITY, &input.job_id))?;
        Ok(StopJobOutput { job_summary })
    }
}
