impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ListJobs<Eng>
{
    type Input = ListJobsInput;
    type Output = ListJobsOutput;
    type Error = ListJobsError;

    const NAME: &'static str = "ListJobs";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_JOBS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_JOBS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            ListJobsErrorModeled::InternalFailureException(InternalFailureException {
                message: Some("the Amplify emulator has no state store attached".to_string()),
            })
        })?;

        // Every `nextToken` this operation issues is a `jobId`, so a token that could
        // not be one was never issued by this service: refuse it instead of serving an
        // arbitrary suffix of the collection for it.
        if let Some(token) = input.next_token.as_deref() {
            if !is_job_id(token) {
                return Err(ListJobsErrorModeled::BadRequestException(
                    BadRequestException {
                        message: Some("Invalid nextToken".to_string()),
                    },
                )
                .into());
            }
        }

        // A report of ONE branch's jobs: the jobs are read out of that branch's own
        // map, which is read out of its app's own map, so neither another app's branch
        // nor another branch's job can appear in the page, and the 404 names the entity
        // that is actually absent.
        let mut store = state.lock();
        let app = store.apps.get_mut(&input.app_id).ok_or_else(|| {
            ListJobsErrorModeled::NotFoundException(NotFoundException {
                message: Some(crate::state::not_found_message(
                    crate::state::APP_ENTITY,
                    &input.app_id,
                )),
            })
        })?;
        let branch = app.branches.get_mut(&input.branch_name).ok_or_else(|| {
            ListJobsErrorModeled::NotFoundException(NotFoundException {
                message: Some(crate::state::not_found_message(
                    crate::state::BRANCH_ENTITY,
                    &input.branch_name,
                )),
            })
        })?;

        // The ONLY write this report performs, and the same one `GetJob` performs: the
        // status change the clock has ALREADY made due for each job, which was owed at
        // that instant whether or not anybody called. A job whose instant has not come
        // is left exactly as it is, so a listing taken straight after `StartJob` still
        // reports the non-terminal status, and a listed job agrees member for member
        // with a `GetJob` of the same job.
        for stored in branch.jobs.values_mut() {
            stored.settle();
        }

        // One page of this branch's job history, NEWEST JOB FIRST — a branch's jobs are
        // reported most recent first, so a client polling the deployment it just started
        // reads it at the head of the listing — with the `nextToken` being the `jobId` of
        // the first job the page did not return.
        let mut history: Vec<(String, JobSummaryProjection)> = branch
            .jobs
            .iter()
            .map(|(job_id, stored)| (job_id.clone(), stored.job.summary.clone()))
            .collect();
        history.sort_by(|(left, _), (right, _)| crate::state::newest_job_first(left, right));
        let (job_summaries, next_token) = crate::state::page_jobs(
            history,
            input.next_token.as_deref(),
            crate::state::page_size(input.max_results, MAX_RESULTS),
        );

        Ok(ListJobsOutput {
            job_summaries,
            next_token,
        })
    }
}

/// The largest page `ListJobs` serves, and the page it serves a caller that set no
/// bound: `maxResults` is modelled `range 0..50`
/// (`smithy_query(query="operation",operation="ListJobs")`).
const MAX_RESULTS: usize = 50;

/// Could `value` be a `jobId`? `JobId` is modelled `length 0..255, pattern ^[0-9]+$`
/// (`smithy_query(query="shape",shape="JobSummary")`), which admits a non-empty run of
/// decimal digits.
///
/// A token naming a job that has since been deleted, or retired out of the branch's
/// bounded history, still satisfies this and is still honoured — the scan resumes at
/// the next id — so a page boundary survives a concurrent delete, which is the
/// behaviour a paging client depends on.
fn is_job_id(value: &str) -> bool {
    !value.is_empty() && value.len() <= 255 && value.bytes().all(|byte| byte.is_ascii_digit())
}
