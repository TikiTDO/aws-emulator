        // certificate still has validation mail to send for that domain. A domain ACM
        // proves control of by another method has no approval mail at all, and the
        // sentence says so by naming the certificate, the method the resend is for and
        // the domain the request asked about — never the method in force, which
        // `DescribeCertificate` reports.
        let validation = &certificate.domain_validations[index];
        if validation.validation_method != crate::state::VALIDATION_METHOD_EMAIL {
            return Err(invalid_state(format!(
                "Certificate {} is not using {} validation for domain {}",
                input.certificate_arn,
                crate::state::VALIDATION_METHOD_EMAIL,
                input.domain
            )));
        }
        if validation.validation_status != crate::state::DOMAIN_STATUS_PENDING_VALIDATION {
            let status = validation.validation_status.clone();
            return Err(invalid_state(format!(
                "The domain {} of certificate {} has validation status {status}, so it is not awaiting an approval mail.",
                input.domain, input.certificate_arn
            )));
        }

        // ACM sends the FIRST validation mail itself, as part of the domain validation
        // it performs for the request: while no mail has gone out for this certificate
        // there is no message to RE-send yet, whether the initial dispatch is still owed
        // or the request never earned one because ACM fixed its outcome when it accepted
        // it. The sentence is ACM's own fixed text for that gate — it names nothing of
        // the request, which is what tells it apart from the refusals above that name
        // the certificate and the domain they were asked about.
