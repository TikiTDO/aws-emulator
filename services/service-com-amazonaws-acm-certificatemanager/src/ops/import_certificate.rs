impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ImportCertificate<Eng>
{
    type Input = ImportCertificateInput;
    type Output = ImportCertificateOutput;
    type Error = ImportCertificateError;

    const NAME: &'static str = "ImportCertificate";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::IMPORT_CERTIFICATE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::IMPORT_CERTIFICATE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // Unreachable in the assembled emulator (the engine is the shared store), and
        // this operation models no server fault, so the modelled validation failure is
        // the one honest answer left.
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(ImportCertificateErrorModeled::ValidationException(
                ValidationException {
                    message: Some("the acm certificate store is unavailable".into()),
                },
            )
            .into());
        };

        // ONE instant answers the whole request: it decides whether the certificate is
        // inside its own validity window, materialises what the clock already owes the
        // store, and dates the import.
        let now = ::std::time::SystemTime::now();

        // Everything the record will report comes from the bodies the request carries,
        // read before the store is touched, so a refused import changes nothing.
        let imported = imported_certificate(&input, now)?;

        let region = crate::state::request_region(ctx.parts());

        let mut store = state.lock();
        store.materialize_due_in(&*self.engine, now);

        // "To import a new certificate, omit the CertificateArn argument. Include this
        // argument only when you want to replace a previously imported certificate"
        // (`ImportCertificate` doc).
        if let Some(target) = input.certificate_arn.as_deref() {
            if crate::state::certificate_id_from_arn(target).is_none() {
                return Err(ImportCertificateErrorModeled::InvalidArnException(
                    InvalidArnException {
                        message: Some(crate::state::invalid_arn_message(target)),
                    },
                )
                .into());
            }
            // "You cannot apply tags when reimporting a certificate"
            // (`ImportCertificateRequest$Tags` doc).
            if input.tags.is_some() {
                return Err(invalid_parameter(
                    "tags cannot be applied when reimporting a certificate",
                ));
            }
            let Some(existing) = store.certificates.get_mut(target) else {
                return Err(ImportCertificateErrorModeled::ResourceNotFoundException(
                    ResourceNotFoundException {
                        message: Some(crate::state::certificate_not_found_message(target)),
                    },
                )
                .into());
            };
            // The argument names "an imported certificate to replace"
            // (`ImportCertificateRequest$CertificateArn` doc): a certificate ACM issued
            // is not one. What this argument addresses is the IMPORTED certificate at
            // that ARN, and there is none — which is what `ResourceNotFoundException`
            // reports, even though the ARN itself resolves to a certificate every read
            // operation serves. A revoked import has nothing left to replace either —
            // "revoking a certificate is permanent" (`RevokeCertificate` doc) — but it
            // IS an imported certificate, so that is a refusal of the request's own
            // parameter.
            if !existing.is_imported() {
                return Err(ImportCertificateErrorModeled::ResourceNotFoundException(
                    ResourceNotFoundException {
                        message: Some(crate::state::not_an_imported_certificate_message(target)),
                    },
                )
                .into());
            }
            if existing.is_revoked() {
                return Err(invalid_parameter(format!(
                    "the certificate {target} is revoked, and a revocation is permanent"
                )));
            }
            // A reimport replaces the CERTIFICATE, not the ACM resource it is stored
            // as: the tags it carries, the options it was created with and the instant it
            // first entered the store stay as they are, and everything the new
            // certificate itself decides is replaced. The resources using it are no part
            // of the record at all — they are keyed by this ARN in the shared
            // association directory, so they survive a reimport untouched.
            // The material the certificate is SERVED from, taken before the record
            // consumes the import: a reimport replaces what a presenting service
            // terminates a connection with, exactly as it replaces the certificate.
            let material = serving_material(&imported, &input);
            let replaced = imported.record(target.to_string(), existing.tags.clone(), now);
            *existing = crate::state::Certificate {
                options: existing.options.clone(),
                created_at: existing.created_at,
                exported: existing.exported,
                ..replaced
            };
            let target = target.to_string();
            drop(store);
            record_serving_material(&*self.engine, &target, material);
            return Ok(ImportCertificateOutput {
                certificate_arn: Some(target),
            });
        }

        let tags = crate::state::tag_map(input.tags.as_deref().unwrap_or_default()).map_err(
            |message| {
                ImportCertificateErrorModeled::InvalidTagException(InvalidTagException {
                    message: Some(message),
                })
            },
        )?;

        // The cap on the WHOLE store, checked first because it is the one bound nothing
        // in the request can partition: the Region an ARN is minted in comes off the
        // caller's own credential scope, so the per-Region quota alone would let a
        // caller that varies the Region string grow the store without limit.
        let stored = store.certificates.len();
        let tokens = store.idempotency.len();
        if stored >= crate::state::CERTIFICATE_STORE_LIMIT
            || tokens >= crate::state::CERTIFICATE_STORE_LIMIT
        {
            // Name whichever count reached the cap, so the refusal says what is full.
            let (full, held) = if stored >= crate::state::CERTIFICATE_STORE_LIMIT {
                ("ACM certificates", stored)
            } else {
                ("certificate idempotency tokens", tokens)
            };
            return Err(ImportCertificateErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(format!(
                        "this emulator already holds {held} {full}, the most it stores ({})",
                        crate::state::CERTIFICATE_STORE_LIMIT
                    )),
                },
            )
            .into());
        }

        // The per-account certificate quota: refused BEFORE the record is inserted, so
        // the store cannot grow past it however many times the call is repeated.
        if store.certificates.len() >= crate::state::CERTIFICATE_LIMIT {
            let held = store.certificates.len();
            return Err(ImportCertificateErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(format!(
                        "this account already holds {held} ACM certificates, the quota of {} for this Region",
                        crate::state::CERTIFICATE_LIMIT
                    )),
                },
            )
            .into());
        }

        let certificate_id = uuid::Uuid::new_v4().to_string();
        let arn = crate::state::certificate_arn(&region, &certificate_id);
        // The material the certificate is SERVED from, taken before the record consumes
        // the import.
        let material = serving_material(&imported, &input);
        let certificate = imported.record(arn.clone(), tags, now);
        store.certificates.insert(arn.clone(), certificate);
        drop(store);
        record_serving_material(&*self.engine, &arn, material);

        Ok(ImportCertificateOutput {
            certificate_arn: Some(arn),
        })
    }
}

/// What the certificate this import brings in is SERVED from, for the service that
/// PRESENTS it on a connection: the leaf and the chain as the request carried them, the
/// private key that matches the leaf, and the names the certificate covers.
///
/// The key is read here and nowhere else in this operation: it is held in memory for the
/// certificate's lifetime so a handshake can be run with it, and is written to no file,
/// named in no log and reported in no response.
fn serving_material(
    imported: &ImportedCertificate,
    input: &ImportCertificateInput,
) -> ::service_common::acm_certificate_key_material::CertificateKeyMaterial {
    ::service_common::acm_certificate_key_material::CertificateKeyMaterial {
        certificate_pem: imported.body.clone(),
        certificate_chain_pem: imported.chain.clone(),
        // The private key the request carried, held as it arrived apart from its line
        // endings — the same reading the certificate's own body is stored under. It has
        // already been held to "The private key must be unencrypted" and to matching the
        // certificate's public key ([`check_private_key`]), so what is recorded here is
        // material that can actually complete a handshake for this certificate.
        private_key_pem: ::std::str::from_utf8(&input.private_key)
            .map(stored_pem)
            .unwrap_or_default(),
        domain_names: imported.subject_alternative_names.clone(),
    }
}

/// Record the serving material of `certificate_arn` in the shared directory the
/// presenting service reads ([`crate::state::certificate_key_material_directory`]).
///
/// Called with this service's own store already released, which is the lock order that
/// directory documents. An engine carrying no directory leaves the material unrecorded:
/// it is an aid to the service that presents the certificate, never part of this
/// operation's answer.
fn record_serving_material<Eng: ::std::marker::Send + ::std::marker::Sync + 'static>(
    engine: &Eng,
    certificate_arn: &str,
    material: ::service_common::acm_certificate_key_material::CertificateKeyMaterial,
) {
    if let Some(directory) = crate::state::certificate_key_material_directory(engine) {
        directory.lock().record(certificate_arn, material);
    }
}

/// `InvalidParameterException` ("an input parameter was invalid"), the refusal ACM
