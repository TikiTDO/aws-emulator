impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeDocument<Eng>
{
    type Input = DescribeDocumentInput;
    type Output = DescribeDocumentOutput;
    type Error = DescribeDocumentError;

    const NAME: &'static str = "DescribeDocument";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_DOCUMENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_DOCUMENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `Name`'s and `DocumentVersion`'s patterns are MODELLED constraints, so the
        // centralized walk has already refused anything outside them: reaching here
        // means `DocumentVersion` is `$LATEST`, `$DEFAULT` or a positive integer.
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            DescribeDocumentErrorModeled::InternalServerError(InternalServerError {
                message: Some("the document store is unavailable".to_string()),
            })
        })?;

        let missing = || {
            DescribeDocumentErrorModeled::InvalidDocument(InvalidDocument {
                message: Some(crate::state::document_not_found_message(&input.name)),
            })
        };

        // The document the request names, resolved through the endpoint it was signed for
        // by the one lookup every document read uses; it also materialises the status move
        // the clock already owed. The account holds the documents a caller created here
        // AND the ones Systems Manager publishes, so a name the catalogue carries resolves
        // without any create; only a name neither holds is a miss.
        let region = crate::state::request_region(ctx.parts());
        let now = ::std::time::SystemTime::now();
        let Some(record) = state
            .lock()
            .resolve_document_for_request(&input.name, &region, now)
        else {
            return Err(missing().into());
        };

        // "The document version for which you want information. Can be a specific
        // version or the default version", and a `VersionName` is "unique across all
        // versions of a document": a read that names neither resolves to the default
        // version, and a selector or a version name no version of the document answers
        // to names nothing to report.
        let version = match record.select_requested(
            input.document_version.as_deref(),
            input.version_name.as_deref(),
        ) {
            Ok(version) => version,
            Err(crate::state::DocumentVersionRejection::Version(requested)) => {
                return Err(DescribeDocumentErrorModeled::InvalidDocumentVersion(
                    InvalidDocumentVersion {
                        message: Some(format!(
                            "Document {} has no version '{requested}'",
                            record.name
                        )),
                    },
                )
                .into());
            }
            Err(crate::state::DocumentVersionRejection::VersionName(requested)) => {
                return Err(DescribeDocumentErrorModeled::InvalidDocumentVersion(
                    InvalidDocumentVersion {
                        message: Some(format!(
                            "Document {} has no version named '{requested}'",
                            record.name
                        )),
                    },
                )
                .into());
            }
        };

        Ok(DescribeDocumentOutput {
            document: Some(record.described_version(version)),
        })
    }
}
