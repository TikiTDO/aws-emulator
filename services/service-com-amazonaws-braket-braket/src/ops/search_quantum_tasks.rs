/// One filter's values, parsed to the type its member compares as.
enum Bounds {
    /// Instants in whole nanoseconds since the epoch, for `createdAt`.
    Instants(Vec<i128>),
    /// Text, for every other member.
    Text(Vec<String>),
}

impl Bounds {
    /// How many values the filter carries.
    fn len(&self) -> usize {
        match self {
            Self::Instants(values) => values.len(),
            Self::Text(values) => values.len(),
        }
    }

    /// Whether the filter carries no value at all.
    fn is_empty(&self) -> bool {
        self.len() == 0
    }
}

/// Parse a filter's values once, before any task is read.
fn parse_bounds(filter: &SearchQuantumTasksFilter) -> Result<Bounds, SearchQuantumTasksError> {
    if filter.name != FILTER_CREATED_AT {
        return Ok(Bounds::Text(filter.values.clone()));
    }
    let mut instants = Vec::with_capacity(filter.values.len());
    for value in &filter.values {
        let parsed = ::aws_smithy_types::DateTime::from_str(
            value,
            ::aws_smithy_types::date_time::Format::DateTime,
        )
        .map_err(|_| {
            refuse(format!(
                "Filter createdAt value {value} is not an ISO-8601 date-time"
            ))
        })?;
        instants.push(crate::state::date_time_as_nanos(&parsed));
    }
    Ok(Bounds::Instants(instants))
}

/// Whether one filter holds for one task.
fn filter_holds(
    task: &crate::state::QuantumTask,
    filter: &SearchQuantumTasksFilter,
    bounds: &Bounds,
) -> bool {
    match bounds {
        Bounds::Instants(values) => {
            // Compared as the instant the response reports, so a filter bound and the
            // `createdAt` a caller read back are the same value.
            let created =
                crate::state::date_time_as_nanos(&crate::state::to_date_time(task.created_at));
            compare(&filter.operator, &created, values)
        }
        Bounds::Text(values) => match task_member(task, &filter.name) {
            Some(actual) => compare(&filter.operator, &actual.to_string(), values),
            // A member the task does not carry satisfies no comparison.
            None => false,
        },
    }
}

/// Apply one operator to a member's value and the filter's values.
///
/// Only `createdAt` reaches the ordering arms; [`OPERATOR_EQUAL`] says why.
fn compare<T: PartialOrd>(operator: &str, actual: &T, values: &[T]) -> bool {
    match operator {
        OPERATOR_EQUAL => values.iter().any(|value| actual == value),
        "GT" => values.first().is_some_and(|value| actual > value),
        "GTE" => values.first().is_some_and(|value| actual >= value),
        "LT" => values.first().is_some_and(|value| actual < value),
        "LTE" => values.first().is_some_and(|value| actual <= value),
        "BETWEEN" => match values {
            [low, high] => actual >= low && actual <= high,
            _ => false,
        },
        _ => false,
    }
}

