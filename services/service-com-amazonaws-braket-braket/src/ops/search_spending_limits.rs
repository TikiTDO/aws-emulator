/// The textual value of one filterable member of a spending limit.
fn limit_member<'l>(limit: &'l crate::state::SpendingLimit, name: &str) -> Option<&'l str> {
    match name {
        "deviceArn" => Some(&limit.device_arn),
        "spendingLimitArn" => Some(&limit.spending_limit_arn),
        _ => None,
    }
}

/// Whether one filter holds for one spending limit.
fn filter_holds(limit: &crate::state::SpendingLimit, filter: &SearchSpendingLimitsFilter) -> bool {
    match limit_member(limit, &filter.name) {
        // `EQUAL` is the only modelled operator, and the validation above refuses any
        // other before a record is read.
        Some(actual) => filter.values.iter().any(|value| value == actual),
        // A member the limit does not carry satisfies no comparison.
        None => false,
    }
}

