/// The digest that decides whether a repeated `clientToken` is a replay of the same
/// request (same ARN comes back) or a reuse of the token for a different one (refused).
/// Every member that lands in the stored record takes part.
fn request_digest(input: &CreateQuantumTaskInput) -> String {
    let shots = input.shots.to_string();
    let associations = input.associations.as_deref().map_or_else(String::new, |list| {
        list.iter()
            .map(|a| format!("{}={}", a.r#type, a.arn))
            .collect::<Vec<String>>()
            .join(",")
    });
    let tags = input.tags.as_ref().map_or_else(String::new, |tags| {
        let mut pairs: Vec<String> = tags.iter().map(|(k, v)| format!("{k}={v}")).collect();
        pairs.sort();
        pairs.join(",")
    });
    let capabilities = input
        .experimental_capabilities
        .as_ref()
        .map_or_else(String::new, |caps| format!("{caps:?}"));
    crate::state::digest(&[
        // The operation takes part, so one token presented to two different creates is
        // a reuse of the token rather than a replay of this request.
        "CreateQuantumTask",
        &input.device_arn,
        &shots,
        &input.output_s3_bucket,
        &input.output_s3_key_prefix,
        &input.action,
        input.device_parameters.as_deref().unwrap_or(""),
        input.job_token.as_deref().unwrap_or(""),
        &associations,
        &tags,
        &capabilities,
    ])
}

