/// The `position` a task that has left the queue reports: the one sentinel this
/// service reports for a resource that is no longer waiting in its queue, shared with
/// the hybrid-job queue info in `crate::state`.
use crate::state::QUEUE_POSITION_NOT_QUEUED as POSITION_NOT_QUEUED;

/// Where the task sits in its device's queue, counted from the stored tasks.
///
/// A task that has left the queue has no position: the modelled members are strings,
/// and the position reads [`POSITION_NOT_QUEUED`] with a message saying why, rather
/// than a number that would claim the task is still waiting.
fn queue_info(
    state: &crate::state::ComAmazonawsBraketBraketState,
    task: &crate::state::QuantumTask,
) -> QuantumTaskQueueInfo {
    let position = state
        .queued_tasks_on(&task.device_arn)
        .iter()
        .position(|queued| queued.quantum_task_arn == task.quantum_task_arn)
        .map(|index| (index + 1).to_string());
    QuantumTaskQueueInfo {
        queue: crate::state::QUEUE_QUANTUM_TASKS.to_string(),
        position: position
            .clone()
            .unwrap_or_else(|| POSITION_NOT_QUEUED.to_string()),
        queue_priority: Some(task.queue_priority().to_string()),
        message: match position {
            Some(_) => None,
            None => Some(format!(
                "Task is in {} status. Queue position is not applicable.",
                task.status
            )),
        },
    }
}

/// The metadata of the stored action, read back out of the action document itself.
///
/// `None` when the document names no action type: the emulator reports what the action
/// says and invents nothing for one that says nothing.
fn action_metadata(action: &str) -> Option<ActionMetadata> {
    let document: serde_json::Value = serde_json::from_str(action).ok()?;
    let action_type = document
        .get("braketSchemaHeader")
        .and_then(|header| header.get("name"))
        .or_else(|| document.get("type"))
        .and_then(serde_json::Value::as_str)?;
    let program_count = document
        .get("programs")
        .and_then(serde_json::Value::as_array)
        .map(|programs| programs.len() as i64);
    Some(ActionMetadata {
        action_type: action_type.to_string(),
        program_count,
        executable_count: None,
    })
}

