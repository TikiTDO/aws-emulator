impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for StartQueryExecution<Eng>
{
    type Input = StartQueryExecutionInput;
    type Output = StartQueryExecutionOutput;
    type Error = StartQueryExecutionError;

    const NAME: &'static str = "StartQueryExecution";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::START_QUERY_EXECUTION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::START_QUERY_EXECUTION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        _ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let query_string = input.query_string;
        // The workgroup a query belongs to. A query runs in a workgroup this account
        // has — one `CreateWorkGroup` registered, or Athena's own default workgroup,
        // which every account has and which this registry therefore holds no record of
        // (`GetWorkGroup` is what reports a registered workgroup's own settings).
        let work_group = input
            .work_group
            .unwrap_or_else(|| crate::state::DEFAULT_WORK_GROUP.to_string());
        let context = {
            let mut context = input.query_execution_context.unwrap_or_default();
            // The context a read of this execution reports: the database as the request
            // wrote it, and the data catalog FOLDED — a data catalog name is resolved
            // without regard to case, so the name Athena reports for the catalog a query
            // ran against is the folded one, which is also the spelling its own catalog
            // refusals name it by.
            context.catalog = context.catalog.map(|catalog| catalog.to_ascii_lowercase());
            context
        };
        let execution_parameters = input.execution_parameters.unwrap_or_default();

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(internal_server("Athena state is not reachable on this engine"));
        };

        // The catalog and database an unqualified name in the statement resolves
        // against: the ones its context names, or the defaults Athena resolves against.
        let query_context = catalog_sql::statement::QueryContext {
            catalog: context
                .catalog
                .clone()
                .unwrap_or_else(|| crate::state::GLUE_DATA_CATALOG_NAME.to_string()),
            database: context
                .database
                .clone()
                .unwrap_or_else(|| crate::state::DEFAULT_QUERY_DATABASE.to_string()),
        };
        // The statement is READ before any lock is taken — what it is, what it addresses
        // and how it runs; what it computes is the catalog's and the engine's own answer
        // below. Reading it is the first half of PLANNING the query, so the span is
        // measured; the other half is the resolution the run does against the catalog.
        let planning_started = ::std::time::Instant::now();
        let reading = catalog_sql::statement::read(&query_string, &query_context);
        let read_time = planning_started.elapsed();
        // A submission is PARSED before it is accepted, so text that is not a statement
        // of this language is refused here rather than accepted and failed later: no
        // execution is minted for it, and the refusal carries the parser's own diagnostic
        // for where the grammar stopped reading.
        if reading.statements.is_none() {
            return Err(StartQueryExecutionError::invalid_request(
                catalog_sql::grammar::ERROR_CODE_MALFORMED_QUERY,
                catalog_sql::grammar::malformed_statement(&query_string),
            ));
        }
        // What the statement DECLARES is judged here too: a definition Athena could never
        // perform is refused at submission rather than minted as an execution that fails.
        // It is a refusal of the STATEMENT, so it carries the statement refusal class the
        // grammar's own refusals do.
        if let Some(message) = reading.declaration_refusal() {
            return Err(StartQueryExecutionError::invalid_request(
                catalog_sql::grammar::ERROR_CODE_MALFORMED_QUERY,
                message,
            ));
        }
        let id = crate::state::new_query_execution_id();
        let submitted_at = SystemTime::now();
        // Everything that reads or writes the registry happens here, and the lock is
        // released before the engine is asked to run anything: a query running on one
        // database must not serialise every other Athena request behind it. The
        // execution and its token are RESERVED here too, before the SQL runs, so a
        // concurrent call carrying the same token answers with this id rather than
        // running the statement a second time.
        let prepared = {
            let mut store = state.lock();

            // A query cannot run in a workgroup that does not exist: its settings, its
            // results location and the history it belongs to are the workgroup's.
            if !store.holds_work_group(&work_group) {
                return Err(invalid_request(crate::state::WORK_GROUP_NOT_FOUND));
            }

            let group = store.work_groups.get(&work_group).cloned();
            // A workgroup's state is what decides whether queries may run in it: a
            // query submitted to a DISABLED workgroup is refused rather than queued, so
            // the state `UpdateWorkGroup` stored is what this submission is judged by.
            if group
                .as_ref()
                .is_some_and(|group| group.state == crate::state::WORK_GROUP_STATE_DISABLED)
            {
                return Err(invalid_request(crate::state::work_group_disabled(
                    &work_group,
                )));
            }
            // Nowhere to write the results is a refusal, not a query that runs: "If
            // none of them is set, Athena issues an error that no output location is
            // provided." A workgroup that keeps its results in Athena's own storage is
            // the other way that same sentence names of satisfying the rule, so a query
            // in such a workgroup runs with no location of its own. Resolved BEFORE the
            // idempotency check below, so that check compares the configuration the query
            // would really run under against the one the earlier call ran under.
            let managed_query_results =
                crate::state::resolved_managed_query_results(group.as_ref());
            let result_configuration = match crate::state::resolved_result_configuration(
                input.result_configuration,
                group.as_ref(),
            ) {
                Some(result_configuration) => result_configuration,
                None if managed_query_results.is_some() => ResultConfiguration::default(),
                None => return Err(invalid_request(crate::state::NO_OUTPUT_LOCATION)),
            };

            // "If another StartQueryExecution request is received, the same response is
            // returned and another query is not created." The answer comes from the
            // token the earlier call stored, so no second execution is minted and no
            // statement runs twice — and a token reused under changed parameters is
            // refused rather than answered with an id that ran different SQL, or wrote
            // its results elsewhere.
            if let Some(token) = input.client_request_token.as_deref() {
                if let Some(existing) = store.query_execution_for_token(token) {
                    if existing.query_string != query_string
                        || existing.work_group != work_group
                        || existing.context.database != context.database
                        || existing.context.catalog != context.catalog
                        || existing.execution_parameters != execution_parameters
                        || !crate::state::same_result_configuration(
                            &existing.result_configuration,
                            &result_configuration,
                        )
                        || !crate::state::same_result_reuse_configuration(
                            existing.result_reuse_configuration.as_ref(),
                            input.result_reuse_configuration.as_ref(),
                        )
                    {
                        return Err(invalid_request(
                            crate::state::IDEMPOTENT_PARAMETERS_DO_NOT_MATCH,
                        ));
                    }
                    return Ok(StartQueryExecutionOutput {
                        query_execution_id: Some(existing.id.clone()),
                    });
                }
            }

            // The engine database a query runs in is the one its context addresses: the
            // catalog and database it names, or the defaults an unqualified query
            // resolves against.
            let handle = match store
                .query_database(&query_context.catalog, &query_context.database)
            {
                Ok(handle) => handle,
                Err(message) => return Err(internal_server(&message)),
            };

            // The completion is due a span after the submit; `complete_query_execution`
            // moves it out if the engine was still running then, so a query is reported
            // complete because its work is over and not because a span elapsed.
            let record = crate::state::QueryExecutionRecord {
                id: id.clone(),
                query_string: query_string.clone(),
                statement_type: reading.statement_type.map(str::to_string),
                substatement_type: reading.substatement_type.map(str::to_string),
                work_group,
                context,
                result_configuration,
                managed_query_results,
                result_reuse_configuration: input.result_reuse_configuration,
                execution_parameters: execution_parameters.clone(),
                engine_version: crate::state::resolved_engine_version(
                    group
                        .as_ref()
                        .and_then(|group| group.configuration.engine_version.as_ref()),
                ),
                submitted_at,
                completion_due_at: submitted_at
                    .checked_add(crate::state::QUERY_EXECUTION_COMPLETION)
                    .unwrap_or(submitted_at),
                // Written by this same call, once the engine has reported.
                outcome: None,
                engine_time: Duration::ZERO,
                // The reading above is planning this call already did; the resolution the
                // run does against the catalog is added to it when the run reports.
                planning_time: read_time,
                engine_reported_at: None,
                cancelled_at: None,
            };
            store.record_query_execution(record, input.client_request_token);

            handle
        };

        let completion = match reading.statements {
            // One statement, or text this parser could not read at all — in which case
            // the engine is the one that reports why.
            Some(1) | None => {
                let sql = query_string.clone();
                let parameters = execution_parameters.clone();
                let engine = ::std::sync::Arc::clone(&self.engine);
                // The statement runs on a blocking thread: the catalog's store, the
                // object store and the SQL engine are all synchronous, and the engine is
                // CPU-bound, so none of that work belongs on an async worker. The bounds
                // one run is held to are installed by `catalog_sql::execute`.
                let run = ::tokio::task::spawn_blocking(move || {
                    catalog_sql::execute(
                        &*engine,
                        &prepared,
                        &sql,
                        reading,
                        &query_context,
                        &parameters,
                        SystemTime::now(),
                    )
                })
                .await;
                run.unwrap_or_else(|_| query_engine::Completion {
                    outcome: query_engine::Outcome::Failed {
                        message: UNREPORTED_RUN.to_string(),
                        reason: None,
                        cause: query_engine::FailureCause::Emulator,
                    },
                    engine_time: Duration::ZERO,
                    planning_time: Duration::ZERO,
                })
            }
            // A query execution runs ONE statement, so text carrying another count is a
            // query that fails rather than one that runs its first statement and drops
            // the rest.
            Some(count) => query_engine::Completion {
                outcome: query_engine::Outcome::Failed {
                    message: one_statement_only(count),
                    reason: None,
                    cause: query_engine::FailureCause::Emulator,
                },
                engine_time: Duration::ZERO,
                planning_time: Duration::ZERO,
            },
        };

        state
            .lock()
            .complete_query_execution(&id, completion, SystemTime::now());

        Ok(StartQueryExecutionOutput {
            query_execution_id: Some(id),
        })
    }
}

/// The `StateChangeReason` of a query whose run reported nothing at all, because the
