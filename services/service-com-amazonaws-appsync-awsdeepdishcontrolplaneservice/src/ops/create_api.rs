impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CreateApi<Eng>
{
    type Input = CreateApiInput;
    type Output = CreateApiOutput;
    type Error = CreateApiError;

    const NAME: &'static str = "CreateApi";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_API_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_API_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // The name has to be one `ApiName` admits. Checked FIRST, before anything else of
        // the request is read, because this is the request-form check the boundary would
        // have taken ahead of the handler — and it is taken HERE, with the framework's own
        // constraint report under the framework's `ValidationException` (400), because
        // this surface's recordings show that error for this member where the rest of the
        // service answers its own `BadRequestException`
        // (`crate::state::api_name_refusal`, shared with `UpdateApi`).
        if let Some(message) = crate::state::api_name_refusal(&input.name) {
            return Err(crate::scaffolded::Scaffolded::validation(message));
        }

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(CreateApiErrorModeled::InternalFailureException(
                InternalFailureException {
                    message: Some("the appsync store is unavailable on this engine".to_string()),
                },
            )
            .into());
        };

        // The Event API configuration has to be well formed: an authorization type
        // that is configured through a member of its own needs that member, no type
        // may be set up twice, an OIDC issuer has to be an absolute URL, and every
        // authorization mode has to name a type the API's providers set up.
        // `UpdateApi` carries the same `eventConfig` and is refused on the same
        // grounds, so the rules live in [`crate::state::event_config_refusal`].
        if let Some(message) = crate::state::event_config_refusal(&input.event_config) {
            return Err(CreateApiErrorModeled::BadRequestException(BadRequestException {
                message: Some(message),
                ..Default::default()
            })
            .into());
        }

        let region = crate::state::request_region(ctx);

        // Minting the API's id is all the store is held for here, in a block of its own,
        // so the guard is out of scope before the sockets below are opened: opening one is
        // the core's work and is awaited, and no state guard may be held across an await.
        let api_id = {
            let mut guard = state.lock();

            // The store is bounded, so a repeated create cannot grow it without limit:
            // an account holds at most `APIS_PER_REGION` APIs in a Region, and
            // `ServiceQuotaExceededException` ("The operation exceeded the service quota
            // for this resource") is the modelled refusal for a create past it. This
            // emulator serves one Region's worth of state, so the cap applies to the
            // whole store.
            if guard.event_apis.len() >= APIS_PER_REGION {
                return Err(CreateApiErrorModeled::ServiceQuotaExceededException(
                    ServiceQuotaExceededException {
                        message: Some(format!(
                            "an account may hold at most {APIS_PER_REGION} APIs in a Region"
                        )),
                    },
                )
                .into());
            }

            // Mint an id that is not already taken. The id is drawn from the state's own
            // counter, so it is new on every call even for an identical request.
            let mut api_id = guard.mint_id();
            while guard.event_apis.contains_key(&api_id) {
                api_id = guard.mint_id();
            }
            api_id
        };

        // An Event API's endpoints are DATA planes — "real-time message publishing and
        // message subscriptions over WebSockets" — and the core owns the sockets they are
        // served on ([`crate::service::event_api`]): they are opened for the id just
        // minted, and the addresses they landed on are what this API publishes as its
        // `dns` records, so the values a caller hands a publisher and a WebSocket client
        // are addresses those clients can reach. Sockets that could not be opened leave
        // the API UNCREATED rather than publishing endpoints nothing serves.
        let (http_authority, realtime_authority) =
            match crate::service::event_api::open_for_api(&*self.engine, &api_id).await {
                Ok(authorities) => authorities,
                Err(reason) => {
                    state.lock().event_data_plane.forget_api(&api_id);
                    return Err(CreateApiErrorModeled::InternalFailureException(
                        InternalFailureException {
                            message: Some(format!(
                                "this emulator could not open the sockets an Event API's \
                                 endpoints are served on, so no API was created: {reason}"
                            )),
                        },
                    )
                    .into());
                }
            };

        let mut guard = state.lock();
        // The quota is weighed AGAIN under this lock, because the one above was released
        // while the sockets were opened: two creates in flight at once must not both pass
        // a check made before either inserted, or the account would come to hold more APIs
        // than the limit the modelled refusal names. The sockets this request opened are
        // forgotten with the refusal, so nothing stays listening for an API that was not
        // created.
        if guard.event_apis.len() >= APIS_PER_REGION {
            guard.event_data_plane.forget_api(&api_id);
            return Err(CreateApiErrorModeled::ServiceQuotaExceededException(
                ServiceQuotaExceededException {
                    message: Some(format!(
                        "an account may hold at most {APIS_PER_REGION} APIs in a Region"
                    )),
                },
            )
            .into());
        }
        let seq = guard.next_seq();

        let record = crate::state::EventApiRecord {
            seq,
            api_arn: ::engine::emulator_arn(
                crate::state::ARN_SERVICE,
                &region,
                &crate::state::api_resource(&api_id),
            ),
            // The DNS records publish the two endpoints this API is SERVED on, one per
            // socket (`crate::state::event_api_dns`): an `Api` publishes its HTTP endpoint
            // under the `HTTP` key and its real-time one under `REALTIME`.
            dns: crate::state::event_api_dns(&http_authority, &realtime_authority),
            api_id: api_id.clone(),
            name: input.name,
            owner_contact: input.owner_contact,
            // Neither member is set by this call: X-Ray tracing is off until an
            // update turns it on, and an API carries a web ACL only once one is
            // associated with it.
            xray_enabled: false,
            waf_web_acl_arn: None,
            event_config: input.event_config,
            tags: input.tags.unwrap_or_default().into_iter().collect(),
            created: std::time::SystemTime::now(),
            // A fresh API holds no channel namespaces: each one is created by
            // `CreateChannelNamespace` under the API this call just minted.
            channel_namespaces: std::collections::BTreeMap::new(),
            // A fresh API holds no API keys; `CreateApiKey` mints them under this
            // API the same way it does under a GraphQL API.
            api_keys: std::collections::BTreeMap::new(),
        };

        // Answer from the STORED record, so this body is the one `GetApi` answers
        // with later: the record is projected through the entry it was inserted
        // under, so the response cannot report an API the store does not hold.
        let api = Some(guard.event_apis.entry(api_id).or_insert(record).to_api());

        Ok(CreateApiOutput { api })
    }
}

/// The AppSync service quota for APIs an account holds in one Region, which
/// `ServiceQuotaExceededException` reports. It is also what bounds this service's
/// store of `Api` records.
const APIS_PER_REGION: usize = 25;
