//! What a REGIONAL custom domain name serves on the address it publishes, end to end in one
//! process: the address itself, the TLS handshake, the certificate presented, the
//! mutual-TLS contract its truststore enforces, and the stage a base path mapping routes to.
//!
//! The rule under test: **`DomainName$regionalDomainName` is an address a client can dial —
//! "you set up this association by adding a DNS record that points the custom domain name to
//! this regional domain name" — and the front door on it terminates TLS under the
//! certificate Certificate Manager holds for the record's `regionalCertificateArn`, enforces
//! the record's `mutualTlsAuthentication` truststore ("clients must present a trusted
//! certificate to access your API": no certificate is refused at the TLS layer, an untrusted
//! one with `403` `Forbidden`, a trusted one is served), and answers from the api and stage
//! the record's base path mapping names.** Only a regional record publishes such an address:
//! an edge-optimized one publishes its CloudFront distribution's name and a private one
//! publishes neither.
//!
//! Nothing here is staged in a store: every certificate is minted by `rcgen` (something
//! other than the code under test), the serving certificate is brought in through
//! Certificate Manager's OWN `ImportCertificate`, the truststore is staged through Amazon
//! S3's OWN `PutObject`, and every api, stage, domain name and mapping is created through
//! this service's own API. The client is a real `rustls` client that dials the published
//! address in this process, so an answer not computed from those records cannot pass.
//!
//! The rows span what the rule generalises over: the mutual-TLS verdicts (a client
//! certificate the truststore trusts, one signed by another CA, and none at all), the base
//! paths a request arrives under (a mapping's own base path, a path under it, the `(none)`
//! mapping, and a path no mapping answers), the endpoint types that publish an address and
//! those that do not, and the update that migrates a record onto a regional endpoint.

