/// RULE (which records publish an address): only a REGIONAL custom domain name publishes a
/// and a private one publishes neither — so only a regional record is given an address of
/// this emulator's own.
#[tokio::test]
async fn only_a_regional_record_publishes_a_dialable_address() {
    let gateway = gateway_with_acm_and_s3();
    // The rows span the endpoint types a custom domain name is served by.
    let cases: &[(&str, Value, bool, bool)] = &[
        (
            "a regional record",
            json!({ "types": ["REGIONAL"] }),
            true,
            false,
        ),
        (
            "an edge-optimized record",
            json!({ "types": ["EDGE"] }),
            false,
            true,
        ),
        (
            "a record that names no endpoint type",
            json!({}),
            false,
            true,
        ),
        (
            "a private record",
            json!({ "types": ["PRIVATE"] }),
            false,
            false,
        ),
    ];
    for (index, (case, configuration, regional, edge)) in cases.iter().enumerate() {
        let domain_name = format!("endpoint-{index}.frontdoor.example.com");
        let created = created_domain(
            &gateway,
            &domain_name,
            json!({ "endpointConfiguration": configuration }),
        )
        .await;
        let published = created["regionalDomainName"].as_str();
        match regional {
            true => assert!(
                published.is_some_and(is_reachable_authority),
                "case {case}: expected a dialable regionalDomainName, got {published:?}"
            ),
            false => assert!(
                published.is_none(),
                "case {case}: expected no regionalDomainName, got {published:?}"
            ),
        }
        let distribution = created["distributionDomainName"].as_str();
        assert_eq!(
            distribution.is_some(),
            *edge,
            "case {case}: expected a distributionDomainName only for an edge-optimized \
             record, got {distribution:?}"
        );
    }
}

/// RULE (the update half): an update that migrates a record ONTO a regional endpoint
/// publishes an address of this emulator's own for it, exactly as a create does, and the
/// front door on that address answers.
#[tokio::test]
async fn an_update_that_migrates_a_record_to_a_regional_endpoint_publishes_a_dialable_address() {
    let gateway = gateway_with_acm_and_s3();
    let domain_name = "migrated.frontdoor.example.com";
    let created = created_domain(
        &gateway,
        domain_name,
        json!({ "endpointConfiguration": { "types": ["EDGE"] } }),
    )
    .await;
    assert!(
        created["regionalDomainName"].as_str().is_none(),
        "expected an edge-optimized record to publish no regionalDomainName, got {:?}",
        created["regionalDomainName"]
    );

    let answer = gateway
        .call(
            "PATCH",
            &format!("/domainnames/{domain_name}"),
            Some(json!({
                "patchOperations": [{
                    "op": "replace",
                    "path": "/endpointConfiguration/types/EDGE",
                    "value": "REGIONAL",
                }],
            })),
        )
        .await;
    assert_eq!(
        answer.status, 200,
        "case the migration: expected 200 from UpdateDomainName, got {} with {:?}",
        answer.status, answer.body
    );
    let published = string_member(&answer.body, "regionalDomainName", "UpdateDomainName");
    assert!(
        is_reachable_authority(&published),
        "case the migration: expected a dialable regionalDomainName, got {published:?}"
    );

    // The address ANSWERS: the record holds no base path mapping, so the front door turns
    // the request away itself rather than the connection being refused.
    let case = "a migrated record's own address";
    let refused = tls_exchange(case, &published, domain_name, None, "/pets").await;
    assert_forbidden(&refused.answered(case), case);
}
