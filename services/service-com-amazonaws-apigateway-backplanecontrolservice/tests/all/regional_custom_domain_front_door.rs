/// RULE (the whole mutual-TLS contract): the address a regional custom domain name publishes
/// is dialable, the handshake there presents the certificate Certificate Manager holds for
/// the record's `regionalCertificateArn`, a client certificate the record's truststore
/// trusts is served the stage its base path mapping names, one signed by another CA is
/// refused `403` `Forbidden`, and one that presents no certificate at all is refused at the
/// TLS layer with no HTTP answer.
#[tokio::test]
async fn a_regional_custom_domain_enforces_its_mutual_tls_truststore_on_its_published_address() {
    let gateway = gateway_with_acm_and_s3();
    let domain_name = "mtls.frontdoor.example.com";

    let serving = leaf(domain_name);
    let certificate_arn = import_certificate(&gateway, "the serving certificate", &serving).await;
    let trusted_ca = authority("trusted-ca.frontdoor.example.com");
    let other_ca = authority("other-ca.frontdoor.example.net");
    let trusted_client = client_identity(&trusted_ca, "client.frontdoor.example.com");
    let untrusted_client = client_identity(&other_ca, "client.frontdoor.example.com");
    let truststore_version = stage_truststore(&gateway, &trusted_ca.certificate.pem()).await;

    let (api, stage) = deployed_api(&gateway, "mtls-front-door").await;

    let mut authentication = json!({
        "truststoreUri": format!("s3://{TRUSTSTORE_BUCKET}/{TRUSTSTORE_KEY}"),
    });
    if let Some(version) = truststore_version.as_deref() {
        authentication["truststoreVersion"] = json!(version);
    }
    let created = created_domain(
        &gateway,
        domain_name,
        json!({
            "endpointConfiguration": { "types": ["REGIONAL"] },
            "regionalCertificateArn": certificate_arn,
            "securityPolicy": "TLS_1_2",
            "mutualTlsAuthentication": authentication,
        }),
    )
    .await;

    let published = string_member(&created, "regionalDomainName", "CreateDomainName");
    assert!(
        is_reachable_authority(&published),
        "expected the record to publish an address a client can dial, got {published:?}"
    );
    let read_back = get_domain_name(&gateway, domain_name).await;
    assert_eq!(
        read_back["regionalDomainName"].as_str(),
        Some(published.as_str()),
        "expected GetDomainName to report the same address, got {:?}",
        read_back["regionalDomainName"]
    );
    assert_eq!(
        read_back["domainNameStatus"].as_str(),
        Some("AVAILABLE"),
        "expected a regional record to be AVAILABLE, got {:?}",
        read_back["domainNameStatus"]
    );

    // Two mappings of this domain name: one under a base path, one answering every other
    // path.
    for (base_path, case) in [("shop", "a base path"), ("(none)", "the (none) mapping")] {
        let answer = create_mapping(
            &gateway,
            domain_name,
            json!({ "basePath": base_path, "restApiId": api, "stage": stage }),
        )
        .await;
        assert_eq!(
            answer.status, 201,
            "case {case}: expected 201 from CreateBasePathMapping, got {} with {:?}",
            answer.status, answer.body
        );
    }

    // The rows span the three mutual-TLS outcomes, each over a path the mappings answer.
    let trusted = tls_exchange(
        "a client certificate the truststore trusts",
        &published,
        domain_name,
        Some(&trusted_client),
        "/pets",
    )
    .await;
    let case = "a client certificate the truststore trusts";
    assert_eq!(
        trusted.leaf,
        Some(serving.der.clone()),
        "case {case}: expected the imported certificate to be presented"
    );
    let answered = trusted.answered(case);
    assert!(
        answered.starts_with("http/1.1 200") && answered.contains(&STAGE_BODY.to_lowercase()),
        "case {case}: expected the stage's own answer, got {answered:?}"
    );

    let case = "a trusted client certificate under a base path";
    let under_base_path = tls_exchange(
        case,
        &published,
        domain_name,
        Some(&trusted_client),
        "/shop/pets",
    )
    .await;
    let answered = under_base_path.answered(case);
    assert!(
        answered.starts_with("http/1.1 200") && answered.contains(&STAGE_BODY.to_lowercase()),
        "case {case}: expected the stage's own answer under the base path, got {answered:?}"
    );

    let case = "a client certificate signed by another CA";
    let untrusted = tls_exchange(
        case,
        &published,
        domain_name,
        Some(&untrusted_client),
        "/pets",
    )
    .await;
    assert_forbidden(&untrusted.answered(case), case);

    let case = "no client certificate at all";
    let anonymous = tls_exchange(case, &published, domain_name, None, "/pets").await;
    assert!(
        anonymous.answer.is_none(),
        "case {case}: expected no HTTP answer at all, got {:?}",
        anonymous.answer
    );

    // A request in the clear presents no certificate either, so the record that enforces
    // mutual TLS refuses it the way it refuses an untrusted one rather than serving the
    // stage: the other half of the address is served only where no truststore is named.
    let case = "a request in the clear on a record that enforces mutual TLS";
    let in_the_clear = clear_exchange(case, &published, domain_name, "/pets").await;
    assert_forbidden(&in_the_clear, case);
}

/// RULE (the certificate and the routing halves, without mutual TLS): a regional record that
/// enforces no mutual TLS serves every client the stage its base path mapping names, under
/// the certificate it holds material for, and refuses a path no mapping of it answers with
/// `403` `Forbidden`.
#[tokio::test]
async fn a_regional_custom_domain_routes_by_base_path_and_refuses_an_unmapped_path() {
    let gateway = gateway_with_acm_and_s3();
    let domain_name = "routing.frontdoor.example.com";
    let serving = leaf(domain_name);
    let certificate_arn = import_certificate(&gateway, "the serving certificate", &serving).await;
    let (api, stage) = deployed_api(&gateway, "routing-front-door").await;
    let created = created_domain(
        &gateway,
        domain_name,
        json!({
            "endpointConfiguration": { "types": ["REGIONAL"] },
            "regionalCertificateArn": certificate_arn,
            "securityPolicy": "TLS_1_0",
        }),
    )
    .await;
    let published = string_member(&created, "regionalDomainName", "CreateDomainName");
    assert!(
        is_reachable_authority(&published),
        "expected the record to publish an address a client can dial, got {published:?}"
    );
    let answer = create_mapping(
        &gateway,
        domain_name,
        json!({ "basePath": "shop", "restApiId": api, "stage": stage }),
    )
    .await;
    assert_eq!(
        answer.status, 201,
        "case CreateBasePathMapping(shop): expected 201, got {} with {:?}",
        answer.status, answer.body
    );

    // The rows span the paths the one mapping does and does not answer, over both halves of
    // the published address (TLS and in the clear).
    let case = "a path under the mapping's base path";
    let served = tls_exchange(case, &published, domain_name, None, "/shop/pets").await;
    assert_eq!(
        served.leaf,
        Some(serving.der.clone()),
        "case {case}: expected the imported certificate to be presented"
    );
    let answered = served.answered(case);
    assert!(
        answered.starts_with("http/1.1 200") && answered.contains(&STAGE_BODY.to_lowercase()),
        "case {case}: expected the stage's own answer, got {answered:?}"
    );

    let case = "a path no mapping of this domain name answers";
    let refused = tls_exchange(case, &published, domain_name, None, "/pets").await;
    assert_forbidden(&refused.answered(case), case);

    // A path carrying a relative segment answers to no mapping either: what a mapping
    // selects is the api and stage the path under its base path is served by, and a
    // remainder that could climb out of that reaches no api.
    for case in [
        "a dot segment under the base path",
        "a parent segment under the base path",
        "a percent-encoded parent segment",
    ] {
        let path = match case {
            "a dot segment under the base path" => "/shop/./pets",
            "a parent segment under the base path" => "/shop/../shop/pets",
            _ => "/shop/%2e%2e/shop/pets",
        };
        let refused = tls_exchange(case, &published, domain_name, None, path).await;
        assert_forbidden(&refused.answered(case), case);
    }

    let case = "a request in the clear on the same address";
    let in_the_clear = clear_exchange(case, &published, domain_name, "/shop/pets").await;
    assert!(
        in_the_clear.starts_with("http/1.1 200")
            && in_the_clear.contains(&STAGE_BODY.to_lowercase()),
        "case {case}: expected the stage's own answer, got {in_the_clear:?}"
    );
}

/// RULE (the handshake where Certificate Manager holds no material): a record that enforces
/// mutual TLS is served on its published address whether or not this emulator holds key
/// material for the certificate it names — a certificate Certificate Manager ISSUED rather
/// than one a caller imported has no private key here — and the three mutual-TLS outcomes
/// are the same ones: a trusted client certificate is served the stage, an untrusted one is
/// refused `403` `Forbidden`, and a client presenting none gets no HTTP answer at all.
#[tokio::test]
async fn mutual_tls_is_enforced_for_a_certificate_no_key_material_is_held_for() {
    let gateway = gateway_with_acm_and_s3();
    let domain_name = "issued.frontdoor.example.com";
    // The ARN of a certificate this emulator holds no serving material for, which is what a
    // certificate Certificate Manager issued (rather than one a caller imported) is here.
    let certificate_arn = format!(
        "arn:aws:acm:{REGION}:000000000000:certificate/11111111-2222-3333-4444-555555555555"
    );
    let trusted_ca = authority("issued-trusted-ca.frontdoor.example.com");
    let other_ca = authority("issued-other-ca.frontdoor.example.net");
    let trusted_client = client_identity(&trusted_ca, "client.frontdoor.example.com");
    let untrusted_client = client_identity(&other_ca, "client.frontdoor.example.com");
    let truststore_version = stage_truststore(&gateway, &trusted_ca.certificate.pem()).await;
    let (api, stage) = deployed_api(&gateway, "issued-front-door").await;

    let mut authentication = json!({
        "truststoreUri": format!("s3://{TRUSTSTORE_BUCKET}/{TRUSTSTORE_KEY}"),
    });
    if let Some(version) = truststore_version.as_deref() {
        authentication["truststoreVersion"] = json!(version);
    }
    let created = created_domain(
        &gateway,
        domain_name,
        json!({
            "endpointConfiguration": { "types": ["REGIONAL"] },
            "regionalCertificateArn": certificate_arn,
            "securityPolicy": "TLS_1_2",
            "mutualTlsAuthentication": authentication,
        }),
    )
    .await;
    let published = string_member(&created, "regionalDomainName", "CreateDomainName");
    let answer = create_mapping(
        &gateway,
        domain_name,
        json!({ "basePath": "(none)", "restApiId": api, "stage": stage }),
    )
    .await;
    assert_eq!(
        answer.status, 201,
        "case CreateBasePathMapping((none)): expected 201, got {} with {:?}",
        answer.status, answer.body
    );

    // The rows span the three outcomes, on a record whose certificate carries no material.
    let case = "a trusted client certificate";
    let trusted = tls_exchange(case, &published, domain_name, Some(&trusted_client), "/pets").await;
    assert!(
        trusted.leaf.is_some(),
        "case {case}: expected a certificate to be presented for the handshake to run at all"
    );
    let answered = trusted.answered(case);
    assert!(
        answered.starts_with("http/1.1 200") && answered.contains(&STAGE_BODY.to_lowercase()),
        "case {case}: expected the stage's own answer, got {answered:?}"
    );

    let case = "an untrusted client certificate";
    let untrusted =
        tls_exchange(case, &published, domain_name, Some(&untrusted_client), "/pets").await;
    assert_forbidden(&untrusted.answered(case), case);

    let case = "no client certificate at all";
    let anonymous = tls_exchange(case, &published, domain_name, None, "/pets").await;
    assert!(
        anonymous.answer.is_none(),
        "case {case}: expected no HTTP answer at all, got {:?}",
        anonymous.answer
    );
}

/// RULE (the truststore's version): the truststore is the object at the version the record
