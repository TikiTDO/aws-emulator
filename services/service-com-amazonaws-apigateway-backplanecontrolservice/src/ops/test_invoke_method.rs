impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TestInvokeMethod<Eng>
{
    type Input = TestInvokeMethodInput;
    type Output = TestInvokeMethodOutput;
    type Error = TestInvokeMethodError;

    const NAME: &'static str = "TestInvokeMethod";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TEST_INVOKE_METHOD_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TEST_INVOKE_METHOD_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `latency` is "the execution latency, in ms, of the test invoke request", so it is
        // MEASURED over the simulation rather than stated: the clock is started before the
        // records are read and read once the response has been computed.
        let started = ::std::time::Instant::now();
        // WHAT is simulated, read under ONE read of the store and taken off it as OWNED
        // records: the api (what a refusal is rendered from), the resource path the
        // simulated request is bound against, the verb and the method that carries the
        // integration. The store is released with that read, because an integration naming
        // another service's action is performed by CALLING that service in process and no
        // lock of this service's is held while another service answers.
        let (api, resource_path, verb, method) = {
            let state = crate::state::service_state(&*self.engine)
                .ok_or_else(crate::state::state_unavailable)?;
            let store = state.lock();
            let api = store
                .rest_apis
                .get(&input.rest_api_id)
                .ok_or_else(|| not_found(&crate::state::no_such_rest_api(&input.rest_api_id)))?;
            let resource = api
                .resources
                .get(&input.resource_id)
                .ok_or_else(|| not_found(crate::state::NO_SUCH_RESOURCE))?;
            // The verb is addressed exactly as `GetMethod` addresses it, so a method is
            // reachable by the spelling it was put under.
            let verb = super::put_method::method_key(&input.http_method);
            let method = resource
                .methods
                .get(&verb)
                .ok_or_else(|| not_found(crate::state::NO_SUCH_METHOD))?;
            (
                api.clone(),
                resource.path.clone(),
                verb,
                method.clone(),
            )
        };
        // The integration is WHAT a simulated invocation invokes. A method that carries
        // none cannot be invoked at all, so this is a precondition of the operation —
        // refused on its error channel before anything is simulated — and not a response
        // to render. An integration that exists and cannot be PERFORMED is reported
        // through the API's gateway response further down, which is the data plane's own
        // answer for it.
        if method.integration.is_none() {
            return Err(bad_request(crate::state::NO_INTEGRATION_DEFINED));
        }

        let mut log = ExecutionLog::started_at(
            crate::state::now()
                .fmt(::aws_smithy_types::date_time::Format::DateTime)
                .unwrap_or_default(),
        );
        log.line(format!("HTTP Method: {verb}, Resource Path: {resource_path}"));
        let (path, query) = split_query(input.path_with_query_string.as_deref());
        if let Some(path) = path {
            log.line(format!("Method request path: {path}"));
        }
        if let Some(query) = query {
            log.line(format!("Method request query string: {query}"));
        }
        log.line(format!(
            "Method request headers: [{}]",
            header_names(&input).join(", ")
        ));
        // The body's SIZE, not the body: it is the caller's own text, and reporting its
        // length says what the integration was handed without copying a payload into a log.
        log.line(format!(
            "Method request body before transformations: {} byte(s)",
            input.body.as_deref().unwrap_or_default().len()
        ));
        let stage_variables: Vec<&str> = input
            .stage_variables
            .iter()
            .flatten()
            .map(|(name, _)| name.as_str())
            .collect::<BTreeSet<&str>>()
            .into_iter()
            .collect();
        if !stage_variables.is_empty() {
            log.line(format!(
                "Stage variables: [{}]",
                stage_variables.join(", ")
            ));
        }
        if let Some(certificate) = input.client_certificate_id.as_deref() {
            log.line(format!(
                "Client certificate {certificate} is not presented: a simulated invocation \
                 makes no HTTPS request to a backend"
            ));
        }
        log.line(format!(
            "Integration type: {}",
            method
                .integration
                .as_ref()
                .and_then(|integration| integration.r#type.as_deref())
                .unwrap_or("none")
        ));

        // The stage variables the caller asked to simulate are what the integration's
        // configuration is read against: `stageVariables` is "a key-value map of stage
        // variables to simulate an invocation on a deployed Stage", so a configuration
        // naming one is resolved exactly as the data plane resolves it at a stage whose
        // own map carries those entries.
        let simulated_variables: BTreeMap<String, String> = input
            .stage_variables
            .iter()
            .flatten()
            .map(|(name, value)| (name.clone(), value.clone()))
            .collect();
        // What a MAPPING TEMPLATE of this simulated call renders against: the same members
        // the data plane reads off the wire, taken from the ones a caller simulates the
        // request with, so one stored template renders one way whichever side drives it.
        // The path parameters are bound against the RESOURCE's own template, because
        // `pathWithQueryString` is where a caller "specif[ies] path parameters and query
        // string parameters". A simulated call reaches no stage, so it carries no stage of
        // its own to name.
        let inputs = TemplateInputs {
            payload: Some(
                input
                    .body
                    .as_deref()
                    .unwrap_or_default()
                    .as_bytes()
                    .to_vec(),
            ),
            path: matched_path_parameters(&resource_path, path.unwrap_or("")),
            querystring: sent_query_parameters(query.unwrap_or_default()),
            header: simulated_headers(&input),
            stage_variables: simulated_variables.clone(),
            context: BTreeMap::from([
                ("apiId".to_string(), input.rest_api_id.clone()),
                ("httpMethod".to_string(), verb.clone()),
                ("resourcePath".to_string(), resource_path.clone()),
                (
                    "path".to_string(),
                    path.unwrap_or(resource_path.as_str()).to_string(),
                ),
            ]),
        };
        let call = MethodRequest::simulated(
            simulated_header(&input, CONTENT_TYPE),
            simulated_header(&input, ACCEPT),
            inputs,
            // What a PROXY integration's event names a SIMULATED call by: the resource and
            // the verb the caller named, the path it simulated, and every value its
            // `multiValueHeaders` and query string carry. The method ARN is the one AWS
            // narrows a grant for a TEST invocation by — the api's own method under
            // [`TEST_INVOKE_STAGE`] — so the function's resource policy decides a simulated
            // invocation exactly as it decides a deployed stage's, and a function that
            // admits API Gateway nothing for this method is not invoked at all.
            ProxyInputs {
                resource_id: input.resource_id.clone(),
                http_method: verb.clone(),
                request_path: path.unwrap_or(resource_path.as_str()).to_string(),
                domain_name: String::new(),
                multi_value_querystring: every_simulated_query_parameter(query),
                multi_value_header: every_simulated_header(&input),
                source_arn: Some(
                    crate::service::resource_policy::Call {
                        region: api.arn_region(),
                        api_id: &input.rest_api_id,
                        stage: TEST_INVOKE_STAGE,
                        verb: &verb,
                        resource_path: &resource_path,
                        request_path: path.unwrap_or(resource_path.as_str()),
                        source_vpce: None,
                        caller: crate::service::resource_policy::Caller::Anonymous,
                    }
                    .method_arn(),
                ),
                // What the api declares BINARY, which decides whether a base64 body the
                // function returns is reported as the bytes it names or as the base64
                // text it is — the same records the data plane reads it from.
                binary_media_types: api.binary_media_types.clone(),
                // A simulated call reached no stage, so there is no stage whose tracing
                // setting could decide a sampling decision the caller did not take.
                tracing_enabled: false,
            },
        );
        let performed = match with_stage_variables(&method, &simulated_variables) {
            // The api's own Region is the endpoint an `AWS` integration naming no Region of
            // its own is called at.
            Ok(resolved) => {
                performed_integration(ctx, api.arn_region(), Some(&resolved), &call).await
            }
            Err(unserved) => Err(unserved),
        };
        let (status, body, headers) = match performed {
            Ok(served) => {
                let mut headers = served.headers;
                headers.insert(CONTENT_TYPE_HEADER.to_string(), vec![served.content_type]);
                log.line("Successfully completed execution".to_string());
                (served.status, served.body, headers)
            }
            Err(unserved) => {
                // The same sentence the data plane logs for this call, and the same gateway
                // response it answers through — including a developer's customization of
                // that response type, which `refusal_rendering` reads off this API.
                log.line(format!(
                    "Execution failed due to configuration error: {}",
                    unserved.reason
                ));
                log.line(format!(
                    "Answered through this API's {} gateway response",
                    unserved.refusal.response_type()
                ));
                let (status, body) = refusal_rendering(Some(&api), unserved.refusal);
                let headers = BTreeMap::from([(
                    CONTENT_TYPE_HEADER.to_string(),
                    vec![JSON_CONTENT_TYPE.to_string()],
                )]);
                (status, body, headers)
            }
        };
        // The response headers with their VALUES, where the request-side line above logs
        // names only: a response header is rendered from the API's own records (a static
        // mapping a control-plane call stored), so no caller credential travels in one.
        // That asymmetry is deliberate and is not licence to log a request header's value.
        log.line(format!(
            "Method response headers: [{}]",
            headers
                .iter()
                .map(|(name, values)| format!("{name}={}", values.join(", ")))
                .collect::<Vec<String>>()
                .join(", ")
        ));
        log.line(format!(
            "Method response body after transformations: {} byte(s)",
            body.len()
        ));
        log.line(format!("Method completed with status: {status}"));

        Ok(TestInvokeMethodOutput {
            status: i32::from(status),
            // The rendered body as text: `body` is modelled a `String`, and a stored
            // response template is text a caller wrote.
            body: Some(String::from_utf8_lossy(&body).into_owned()),
            // The single-valued view: the FIRST value under each name, which is what a
            // single-valued read of a multi-valued header is.
            headers: Some(
                headers
                    .iter()
                    .filter_map(|(name, values)| {
                        values.first().map(|first| (name.clone(), first.clone()))
                    })
                    .collect::<HashMap<String, String>>(),
            ),
            // The multi-valued view of the same headers: every value each name carries.
            multi_value_headers: Some(
                headers
                    .into_iter()
                    .collect::<HashMap<String, Vec<String>>>(),
            ),
            log: Some(log.rendered()),
            latency: i64::try_from(started.elapsed().as_millis()).unwrap_or(i64::MAX),
        })
    }
}

/// The modelled 400 this operation answers for a request a precondition of the operation
/// refuses, carrying the fixed sentence the service words that condition as.
fn bad_request(message: &str) -> TestInvokeMethodError {
    TestInvokeMethodErrorModeled::BadRequestException(BadRequestException {
        message: Some(message.to_string()),
    })
    .into()
}

/// The modelled 404 this operation answers for an identifier no record of this account
/// carries, worded as every other reader of the same records words it.
fn not_found(message: &str) -> TestInvokeMethodError {
    TestInvokeMethodErrorModeled::NotFoundException(NotFoundException {
        message: Some(message.to_string()),
    })
    .into()
}
