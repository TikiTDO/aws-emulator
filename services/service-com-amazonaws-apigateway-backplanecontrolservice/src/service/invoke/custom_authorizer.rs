//! The `CUSTOM` authorizer of a method: how the Lambda function an `Authorizer` names
//! decides a request to the deployed stage, and how long that decision is held.
//!
//! `Method$authorizationType` gives `CUSTOM` "for using a custom authorizer", and an
//! `Authorizer` of type `TOKEN` or `REQUEST` IS a Lambda function: `Authorizer$authorizerUri`
//! is "the authorizer's Uniform Resource Identifier (URI) … For `TOKEN` or `REQUEST`
//! authorizers, this must be a well-formed Lambda function URI", in the same
//! `arn:aws:apigateway:{region}:lambda:path/{version}/functions/{function-arn}/invocations`
//! form an `AWS_PROXY` integration's `uri` takes. So the decision is a function's RETURN
//! VALUE, obtained the way this data plane obtains every other one: by invoking the
//! function in process, over the transport the router hands this plane
//! ([`super::lambda_proxy`] owns the client, the ARN reading and the resource-policy check,
//! called here rather than copied).
//!
//! What the function is handed is the event its own type documents:
//!
//! * a `TOKEN` authorizer gets the identity source's value as `authorizationToken`, beside
//!   the ARN of the method the call addresses — "a `TOKEN` authorizer receives the caller's
//!   identity in a bearer token" (`AuthorizerType`);
//! * a `REQUEST` authorizer gets the whole method request, the same document an `AWS_PROXY`
//!   integration's event describes it with ("a `REQUEST` authorizer receives the caller's
//!   identity in a request context"), minus the body, which that event does not carry.
//!
//! What comes back is "an IAM policy that is generated by the authorizer"
//! (`AuthorizerType`), under the two members such an output declares: `principalId`, the
//! identity the authorizer resolved the caller to, and `policyDocument`, the policy that
//! decides this call. The DECISION is then the tree's one evaluation of a policy document
//! ([`::service_common::iam_authorization`]), asked about `execute-api:Invoke` on the ARN of
//! the method the request addressed — so the document admits the methods it names and no
//! others, and an explicit `Deny` in it refuses whatever else it allows. A `context` map the
//! output carries is published to the integration, each entry under the `$context.authorizer`
//! member path a mapping template reads it by.
//!
//! # What is held, and for how long
//!
//! `Authorizer$authorizerResultTtlInSeconds` is "the TTL in seconds of cached authorizer
//! results. If it equals 0, authorization caching is disabled. If it is greater than 0, API
//! Gateway caches authorizer responses", so a result obtained for one identity is HELD on
//! the stage ([`crate::state::StageEntry::authorizer_results`]) and the function is not
//! invoked again while it is held. The entry is the authorizer's own RETURN VALUE rather
//! than the decision taken from it, because that is what the caching documentation names:
//! one held result then decides every method the same identity goes on to address, each
//! against the policy it carries.
//!
//! The key is the authorizer and the VALUE the request carried for each identity source it
//! declares — `Authorizer$identitySource` is "the identity source for which authorization is
//! requested", so two callers presenting two tokens are two entries and the same token
//! twice is one. `FlushStageAuthorizersCache` drops what the stage holds before the TTL
//! passes, through the watermark that operation writes.
//!
//! # What is never guessed
//!
//! Every outcome here is either the function's own answer or a refusal of the request. A
//! call whose function cannot be invoked at all — an `authorizerUri` that names no function,
//! a function no Lambda answers for, a function whose resource policy grants
//! `apigateway.amazonaws.com` no invocation of it for this authorizer — earns the
//! `AUTHORIZER_CONFIGURATION_ERROR` gateway response, and one whose function RAN and
//! returned something that is not an authorizer output earns `AUTHORIZER_FAILURE`: both are
//! `500` with `{"message":"Internal server error"}`, which is the envelope API Gateway
//! reserves for an authorizer that errors, times out or returns a malformed policy. Nothing
//! admits a request because it merely carried a token.

use std::collections::BTreeMap;
use std::time::{Duration, Instant};

use ::serde_json::{Map, Value};
use ::service_common::iam_authorization::{self as iam, Decision};
use ::smithy_server_runtime::OperationContext;

use crate::state::CachedAuthorizerResult;

use super::super::resource_policy::INVOKE_ACTION;

/// The member the authorizer's output names the caller by: "the principal user
/// identification associated with the token sent by the client" — what the integration reads
/// as `$context.authorizer.principalId`.
const PRINCIPAL_ID_MEMBER: &str = "principalId";

/// The member it carries the IAM policy in.
const POLICY_DOCUMENT_MEMBER: &str = "policyDocument";

/// The member it carries the key-value pairs published to the integration in.
const CONTEXT_MEMBER: &str = "context";

/// The `$context` member path the authorizer's own values are published under:
/// `$context.authorizer.{key}`, which is how a mapping template reads one.
pub(super) const AUTHORIZER_MEMBER: &str = "authorizer";

/// The error message a `TOKEN` authorizer's function raises to refuse the call outright, as
/// API Gateway's own authorizer documentation words it: a function that fails with exactly
/// this message answers the caller `401`, rather than being an authorizer that failed.
const UNAUTHORIZED_ERROR_MESSAGE: &str = "Unauthorized";

/// The member a Lambda function's error payload carries its message in.
const ERROR_MESSAGE_MEMBER: &str = "errorMessage";

/// The most bytes one authorizer output may carry.
///
/// A returned result is HELD on the stage per identity
/// ([`crate::state::CachedAuthorizerResult`]), so what the authorizer's own code answers with
/// decides how much this service keeps: the document is bounded BEFORE it is read, and an
/// answer past the bound is an authorizer that returned no policy this call can use rather
/// than one buffered and stored without limit. The size is the emulator's own — AWS
/// publishes no quota for an authorizer's return value — and is far above every policy
/// document AWS's own published policy-size quotas admit.
const MAX_AUTHORIZER_OUTPUT_BYTES: usize = 128 * 1024;

/// How long this call waits for the authorizer's answer.
///
/// `Authorizer` publishes no timeout member of its own, and API Gateway's published quota
/// for a Lambda authorizer is 29 seconds — the same bound an integration's own
/// `timeoutInMillis` is capped at ([`crate::ops::put_integration::MAX_TIMEOUT_IN_MILLIS`]) —
/// so that bound is what a request to a deployed stage waits here, and an authorizer that
/// has not answered by then has not answered the call.
fn waited_for() -> Duration {
    let millis = u64::try_from(crate::ops::put_integration::MAX_TIMEOUT_IN_MILLIS)
        .unwrap_or_default();
    Duration::from_millis(millis)
}

/// What the method's `CUSTOM` authorizer is to be asked, when the stage holds no usable
/// result for this identity: everything the invocation needs, read off the records under the
/// store lock so the call itself is made with no lock held.
#[derive(Debug)]
pub(super) struct Pending {
    /// The api whose stage this call reached, for finding the stage again to hold the result.
    pub api_id: String,
    /// The stage within it; see [`Self::api_id`].
    pub stage: String,
    /// The Region the function is invoked at when the `authorizerUri` names none.
    pub region: String,
    /// The authorizer's own name, for the log.
    pub authorizer_name: String,
    /// `Authorizer$authorizerUri`, which names the function.
    pub authorizer_uri: String,
    /// The ARN of the AUTHORIZER, which is the `aws:SourceArn` a grant to API Gateway for
    /// an authorizer's function is narrowed by.
    pub authorizer_arn: String,
    /// The event the function is handed; see the module docs.
    pub event: Value,
    /// The X-Ray trace context this invocation carries — the header the stage propagates
    /// onto every call it makes on this request's behalf ([`super::trace_context`]) — or
    /// `None` where this request names no chain.
    pub trace_header: Option<String>,
    /// Where the result is held on the stage, or `None` when the authorizer holds none at
    /// all: a TTL of zero holds nothing, which is what `authorizerResultTtlInSeconds` of 0
    /// means.
    pub cache_key: Option<String>,
    /// `authorizerResultTtlInSeconds` as a duration; zero disables caching.
    pub ttl: Duration,
}

/// What asking the authorizer produced: its own return value, or a refusal of the request.
#[derive(Debug)]
pub(super) enum Obtained {
    /// The function ran and returned an authorizer output: this is it, as the stage holds
    /// one. The DECISION is taken from its policy per method ([`decided`]).
    Returned(CachedAuthorizerResult),
    /// The call has no authorizer result: the function could not be invoked, did not answer
    /// in time, errored, or returned something that is not an authorizer output. The refusal
    /// is the caller's, and the sentence is for the log.
    Unobtained {
        /// The gateway response the request is answered through.
        refusal: super::GatewayRefusal,
        /// Why, in one sentence. States the configuration or the function's own signal,
        /// never a decision.
        reason: String,
    },
}

/// What a held authorizer result says about ONE method: the values it publishes to the
/// integration, or the sentence the request is refused with.
#[derive(Debug)]
pub(super) enum Judged {
    /// The policy allows `execute-api:Invoke` on the method: these are the `$context`
    /// members the integration sees, the principal included.
    Published(BTreeMap<String, String>),
    /// The policy does not allow it. This is the sentence API Gateway refuses such a call
    /// with, answered `403` through the `ACCESS_DENIED` gateway response.
    Refused(&'static str),
}

/// The sentence a call an authorizer's policy explicitly DENIES is refused with.
const EXPLICIT_DENY_MESSAGE: &str =
    "User is not authorized to access this resource with an explicit deny";

/// The sentence a call no statement of the authorizer's policy allows is refused with.
///
/// `pub(super)` because it is the sentence an AUTHORIZER's refusal of a call carries whichever
/// kind of authorizer took the decision: a `COGNITO_USER_POOLS` authorizer that evaluated the
/// presented token and does not accept it refuses the call with this same sentence
/// ([`super::cognito_refusal`]), rather than holding a second copy of it.
pub(super) const NOT_AUTHORIZED_MESSAGE: &str = "User is not authorized to access this resource";

/// What `held` says about the method `method_arn`.
///
/// The policy is evaluated as the identity-based document it is — an authorizer "returns an
/// IAM policy", with no `Principal` element of its own — so the same held result admits a
/// call to one method of the api and refuses a call to another exactly as the document the
/// function returned says.
pub(super) fn decided(held: &CachedAuthorizerResult, method_arn: &str) -> Judged {
    let principals = [held.principal_id.clone()];
    let request = iam::Request::new(INVOKE_ACTION, method_arn, &principals);
    let documents = [held.policy_document.clone()];
    match iam::identity_decision(&documents, &request) {
        Decision::Allowed => Judged::Published(published(held)),
        Decision::Denied => Judged::Refused(EXPLICIT_DENY_MESSAGE),
        Decision::NotStated => Judged::Refused(NOT_AUTHORIZED_MESSAGE),
    }
}

/// The `$context` members an allowed call's integration sees: the principal the authorizer
/// named and every entry of the `context` map it published, each under the
/// `authorizer.{key}` member path a mapping template reads it by.
fn published(held: &CachedAuthorizerResult) -> BTreeMap<String, String> {
    let mut members = BTreeMap::new();
    members.insert(
        format!("{AUTHORIZER_MEMBER}.{PRINCIPAL_ID_MEMBER}"),
        held.principal_id.clone(),
    );
    for (key, value) in &held.context {
        members.insert(format!("{AUTHORIZER_MEMBER}.{key}"), value.clone());
    }
    members
}

/// The event a `TOKEN` authorizer is handed: the token the identity source carried and the
/// ARN of the method the call addresses, under the `type` its own authorizer type names.
pub(super) fn token_event(token: &str, method_arn: &str) -> Value {
    let mut event = Map::new();
    event.insert("type".to_string(), Value::from("TOKEN"));
    event.insert("authorizationToken".to_string(), Value::from(token));
    event.insert("methodArn".to_string(), Value::from(method_arn));
    Value::Object(event)
}

/// Ask the authorizer, with no store lock held: invoke the function its `authorizerUri`
/// names and read what it returned.
pub(super) async fn obtained(ctx: &OperationContext<'_>, pending: &Pending) -> Obtained {
    let Some((addressed_region, function)) =
        super::lambda_proxy::invoked_function(&pending.authorizer_uri)
    else {
        return Obtained::Unobtained {
            refusal: super::AUTHORIZER_CONFIGURATION_ERROR,
            reason: "the authorizer's authorizerUri does not name a Lambda function's \
                     invocation path, so there is no function to invoke"
                .to_string(),
        };
    };
    let at = if addressed_region.is_empty() {
        pending.region.as_str()
    } else {
        addressed_region
    };
    let client = super::lambda_proxy::lambda_client(ctx, at);
    if !super::lambda_proxy::invocation_admitted(&client, function, &pending.authorizer_arn).await {
        return Obtained::Unobtained {
            refusal: super::AUTHORIZER_CONFIGURATION_ERROR,
            reason: format!(
                "the authorizer's function allows this api's authorizer {} no invocation of \
                 it, so no invocation was made",
                pending.authorizer_name
            ),
        };
    }
    let Ok(payload) = ::serde_json::to_vec(&pending.event) else {
        return Obtained::Unobtained {
            refusal: super::AUTHORIZER_CONFIGURATION_ERROR,
            reason: "the authorizer's event could not be written, so no invocation was made"
                .to_string(),
        };
    };
    let invocation = client
        .invoke()
        .function_name(function)
        .invocation_type(::aws_sdk_lambda::types::InvocationType::RequestResponse)
        .payload(::aws_sdk_lambda::primitives::Blob::new(payload))
        .customize()
        .mutate_request({
            let trace = pending.trace_header.clone();
            move |request| {
                if let Some(trace) = trace.clone() {
                    // `try_insert`, not the panicking `insert`, for the reason the sibling
                    // insertion of this same header records ([`super::lambda_proxy`]): the
                    // value may be the caller's own header text, carried on as written.
                    if let Err(refused) = request
                        .headers_mut()
                        .try_insert(super::trace_context::TRACE_HEADER, trace)
                    {
                        ::tracing::warn!(
                            error = %refused,
                            "the tracing header this request named cannot travel on the wire, \
                             so the authorizer's invocation carries none"
                        );
                    }
                }
            }
        })
        .send();
    let within = waited_for();
    let answer = match ::tokio::time::timeout(within, invocation).await {
        Ok(answer) => answer,
        Err(_elapsed) => {
            return Obtained::Unobtained {
                refusal: super::AUTHORIZER_FAILURE,
                reason: format!(
                    "the authorizer's function did not answer within {} ms, so the call has \
                     no authorizer decision",
                    within.as_millis()
                ),
            }
        }
    };
    let answered = match answer {
        Ok(answered) => answered,
        Err(error) => {
            return Obtained::Unobtained {
                refusal: super::AUTHORIZER_CONFIGURATION_ERROR,
                reason: format!(
                    "the authorizer's function did not answer the invocation: {}",
                    ::aws_smithy_types::error::display::DisplayErrorContext(&error)
                ),
            }
        }
    };
    let returned = answered
        .payload()
        .map(|payload| payload.as_ref().to_vec())
        .unwrap_or_default();
    if returned.len() > MAX_AUTHORIZER_OUTPUT_BYTES {
        return Obtained::Unobtained {
            refusal: super::AUTHORIZER_FAILURE,
            reason: format!(
                "the authorizer's function returned {} bytes, more than the \
                 {MAX_AUTHORIZER_OUTPUT_BYTES} bytes one authorizer output carries",
                returned.len()
            ),
        };
    }
    // "FunctionError: if present, indicates that an error occurred during function
    // execution" — a run that errored returned no policy. The ONE error that is not an
    // authorizer failure is the documented refusal: a function raising exactly
    // `Unauthorized` refuses the caller `401`.
    if let Some(signal) = answered.function_error() {
        let message = error_message(&returned);
        if message.as_deref() == Some(UNAUTHORIZED_ERROR_MESSAGE) {
            return Obtained::Unobtained {
                refusal: super::UNAUTHORIZED,
                reason: format!(
                    "the authorizer's function refused the call with the {UNAUTHORIZED_ERROR_MESSAGE} \
                     error it words a refusal with ({signal})"
                ),
            };
        }
        return Obtained::Unobtained {
            refusal: super::AUTHORIZER_FAILURE,
            reason: format!("the authorizer's function errored ({signal}), so it returned no policy"),
        };
    }
    match authorizer_output(&returned, pending.ttl) {
        Ok(result) => Obtained::Returned(result),
        Err(reason) => Obtained::Unobtained {
            refusal: super::AUTHORIZER_FAILURE,
            reason,
        },
    }
}

/// The error message a failed run reported, when its payload carries one.
fn error_message(payload: &[u8]) -> Option<String> {
    ::serde_json::from_slice::<Value>(payload)
        .ok()?
        .get(ERROR_MESSAGE_MEMBER)?
        .as_str()
        .map(str::to_string)
}

/// The authorizer output `returned` is, as the stage holds one, or why it is not an
/// authorizer output at all.
///
/// `ttl` is the authorizer's own `authorizerResultTtlInSeconds`, which is how long the
/// result stays usable; a result obtained under a TTL of zero expires at the instant it was
/// obtained, so nothing reads it again.
fn authorizer_output(returned: &[u8], ttl: Duration) -> Result<CachedAuthorizerResult, String> {
    let document: Value = ::serde_json::from_slice(returned)
        .map_err(|_| "the authorizer's function returned no JSON document".to_string())?;
    let principal_id = document
        .get(PRINCIPAL_ID_MEMBER)
        .and_then(Value::as_str)
        .ok_or_else(|| {
            format!("the authorizer's function returned no {PRINCIPAL_ID_MEMBER} member")
        })?
        .to_string();
    let policy = document.get(POLICY_DOCUMENT_MEMBER).ok_or_else(|| {
        format!("the authorizer's function returned no {POLICY_DOCUMENT_MEMBER} member")
    })?;
    if !policy.is_object() {
        return Err(format!(
            "the authorizer's function returned a {POLICY_DOCUMENT_MEMBER} that is not a \
             policy document"
        ));
    }
    let obtained = Instant::now();
    Ok(CachedAuthorizerResult {
        principal_id,
        policy_document: policy.to_string(),
        context: context_of(document.get(CONTEXT_MEMBER)),
        cached_at: obtained,
        expires_at: obtained + ttl,
    })
}

/// The `context` map the output published, as the string values a mapping template reads.
///
/// "You cannot set a JSON object or array as a valid value of any key in the `context` map",
/// so an entry carrying one is not a value the integration can read and is left out; every
/// scalar is published as the text it renders to, which is what a template substitutes.
fn context_of(published: Option<&Value>) -> BTreeMap<String, String> {
    let Some(Value::Object(entries)) = published else {
        return BTreeMap::new();
    };
    entries
        .iter()
        .filter_map(|(key, value)| {
            let text = match value {
                Value::String(text) => text.clone(),
                Value::Number(number) => number.to_string(),
                Value::Bool(flag) => flag.to_string(),
                _ => return None,
            };
            Some((key.clone(), text))
        })
        .collect()
}

#[cfg(test)]
mod tests {
    //! The pure rules this module owns: what a held result says about a method, and what an
    //! authorizer output is read as. What a deployed stage SERVES for a `CUSTOM` method is
    //! pinned end to end in `tests/all/stage_custom_authorizer.rs`.

    use super::*;

    /// One held result carrying `policy`.
    fn held(policy: &str) -> CachedAuthorizerResult {
        let now = Instant::now();
        CachedAuthorizerResult {
            principal_id: "sim-user".to_string(),
            policy_document: policy.to_string(),
            context: BTreeMap::new(),
            cached_at: now,
            expires_at: now + Duration::from_secs(300),
        }
    }

    /// RULE: the decision is the authorizer's own policy applied to the METHOD the request
    /// addressed — it admits the methods the document names and no others, and an explicit
    /// deny refuses whatever else it allows.
    #[test]
    fn the_returned_policy_decides_each_method_it_names() {
        let arn = "arn:aws:execute-api:us-east-1:000000000000:abc1230000/live/GET/secure";
        let statement = |effect: &str, resource: &str| {
            format!(
                "{{\"Version\":\"2012-10-17\",\"Statement\":[{{\"Effect\":\"{effect}\",\
                 \"Action\":\"execute-api:Invoke\",\"Resource\":\"{resource}\"}}]}}"
            )
        };
        // Rows differ along what the returned document states about this method.
        let rows: &[(&str, String, Option<&str>)] = &[
            ("the method itself", statement("Allow", arn), None),
            ("every method", statement("Allow", "*"), None),
            (
                "the api's own wildcard",
                statement(
                    "Allow",
                    "arn:aws:execute-api:us-east-1:000000000000:abc1230000/live/*/*",
                ),
                None,
            ),
            (
                "another method",
                statement(
                    "Allow",
                    "arn:aws:execute-api:us-east-1:000000000000:abc1230000/live/GET/other",
                ),
                Some(NOT_AUTHORIZED_MESSAGE),
            ),
            (
                "an explicit deny",
                statement("Deny", "*"),
                Some(EXPLICIT_DENY_MESSAGE),
            ),
            (
                "a document stating nothing",
                "{\"Statement\":[]}".to_string(),
                Some(NOT_AUTHORIZED_MESSAGE),
            ),
        ];
        for (case, policy, refused) in rows {
            let judged = decided(&held(policy), arn);
            match (&judged, refused) {
                (Judged::Published(members), None) => assert_eq!(
                    members.get("authorizer.principalId").map(String::as_str),
                    Some("sim-user"),
                    "case {case:?}: expected the principal published, got {members:?}"
                ),
                (Judged::Refused(sentence), Some(expected)) => assert_eq!(
                    sentence, expected,
                    "case {case:?}: expected {expected:?}, got {sentence:?}"
                ),
                (judged, expected) => panic!(
                    "case {case:?}: expected refused={expected:?}, got {judged:?}"
                ),
            }
        }
    }

    /// RULE: an authorizer output is the two members such an output declares; a return value
    /// missing either is not one, and only scalar `context` entries are published.
    #[test]
    fn an_authorizer_output_is_read_as_the_members_it_declares() {
        let ttl = Duration::from_secs(300);
        let allow = "{\"Version\":\"2012-10-17\",\"Statement\":[{\"Effect\":\"Allow\",\
                     \"Action\":\"execute-api:Invoke\",\"Resource\":\"*\"}]}";
        // Rows differ along the shape of what the function returned.
        let rows: &[(&str, String, bool)] = &[
            (
                "both members",
                format!("{{\"principalId\":\"u\",\"policyDocument\":{allow}}}"),
                true,
            ),
            (
                "both members and a context map",
                format!(
                    "{{\"principalId\":\"u\",\"policyDocument\":{allow},\
                     \"context\":{{\"tier\":\"gold\",\"calls\":3,\"ok\":true,\
                     \"nested\":{{\"a\":1}}}}}}"
                ),
                true,
            ),
            (
                "no principalId",
                format!("{{\"policyDocument\":{allow}}}"),
                false,
            ),
            ("no policyDocument", "{\"principalId\":\"u\"}".to_string(), false),
            (
                "a policyDocument that is not a document",
                "{\"principalId\":\"u\",\"policyDocument\":\"Allow\"}".to_string(),
                false,
            ),
            ("not a JSON document at all", "Unauthorized".to_string(), false),
        ];
        for (case, returned, readable) in rows {
            let read = authorizer_output(returned.as_bytes(), ttl);
            assert_eq!(
                read.is_ok(),
                *readable,
                "case {case:?}: expected readable={readable}, got {read:?}"
            );
        }
        // The context map's scalars are published and its non-scalar is not.
        let with_context = authorizer_output(
            format!(
                "{{\"principalId\":\"u\",\"policyDocument\":{allow},\
                 \"context\":{{\"tier\":\"gold\",\"calls\":3,\"ok\":true,\
                 \"nested\":{{\"a\":1}}}}}}"
            )
            .as_bytes(),
            ttl,
        )
        .expect("the output is readable");
        let published = published(&with_context);
        let expected: &[(&str, &str)] = &[
            ("authorizer.principalId", "u"),
            ("authorizer.tier", "gold"),
            ("authorizer.calls", "3"),
            ("authorizer.ok", "true"),
        ];
        for (member, value) in expected {
            assert_eq!(
                published.get(*member).map(String::as_str),
                Some(*value),
                "case {member:?}: expected {value:?}, got {published:?}"
            );
        }
        assert!(
            !published.contains_key("authorizer.nested"),
            "case \"a non-scalar context value\": expected it left out, got {published:?}"
        );
    }
}
