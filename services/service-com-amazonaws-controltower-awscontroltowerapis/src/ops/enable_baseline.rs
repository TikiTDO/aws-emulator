//! @op EnableBaseline
//!
//! Applies a baseline to a target: persists an `EnabledBaseline` in [`crate::state`] and
//! starts the asynchronous `ENABLE_BASELINE` operation `GetBaselineOperation` reports.
//! The request is checked against the service's baseline catalog first — the baseline, the
//! version it offers, the organizational-unit target and the parameters that baseline
//! declares — so only an enablement that could exist is persisted. A `tags` member lands
//! in the one tag store `ListTagsForResource` reads, so it is held to the same rule
//! `TagResource` applies: a key in the reserved
//! [`crate::state::RESERVED_TAG_KEY_PREFIX`] namespace names a tag Amazon Web Services
//! applies itself, so a request carrying one is refused with the modelled
//! `ValidationException` (400) and nothing is written.
//!
//! The baseline that brings a target under AWS Control Tower's governance also makes the
//! service apply the MANDATORY controls to that target itself, so enabling it writes those
//! enablements into the one control store `ListEnabledControls`/`GetEnabledControl` read
//! (`crate::state::ComAmazonawsControltowerAwscontroltowerapisState::apply_governance_controls`);
//! `DisableBaseline` withdraws them again.
//!
//! Served only for an account Control Tower has been set up in
//! ([`crate::state::ComAmazonawsControltowerAwscontroltowerapisState::is_set_up`]): setting
//! it up is what creates the service role the baseline enablement APIs act through, so in
//! one it has provisioned nothing in the call is the modelled `ValidationException` (400)
//! reporting that it could not assume that role — ahead of the target lookup, and before
//! anything is persisted or an operation minted. See `crate::state` for the one precondition
//! the enablement calls share.
//!
//! A baseline is enabled at most once per target, and the refusal of a repeat is
//! classified by the STATE of the enablement already holding the pair, as `EnableControl`
//! classifies its own: while that enablement is still being deployed the repeat would race
//! a change in flight, the inconsistent state the modelled `ConflictException` (409)
//! reports; once it is deployed nothing is in flight and the request asks for a resource
//! that already exists, which the modelled `ValidationException` (400) reports.
//!//! Implemented here because `GetBaselineOperation` has nothing to resolve until some call
//! mints a baseline operation; the remaining baseline operations keep their own stub
//! issues.
//!
