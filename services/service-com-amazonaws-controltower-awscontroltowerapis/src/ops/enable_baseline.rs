impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for EnableBaseline<Eng>
{
    type Input = EnableBaselineInput;
    type Output = EnableBaselineOutput;
    type Error = EnableBaselineError;

    const NAME: &'static str = "EnableBaseline";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::ENABLE_BASELINE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::ENABLE_BASELINE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // AWS takes the authorization decision at the IAM layer, ahead of the service
        // reading anything. An enablement names no enabled baseline of its own — the ARN
        // its create mints is no value a policy could have been written against — so the
        // decision is made against every enabled baseline of the caller's Region.
        crate::service::authorization::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            crate::service::authorization::Addressed::EnabledBaseline,
            None,
        )
        .map_err(EnableBaselineErrorModeled::AccessDeniedException)?;

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(EnableBaselineErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the AWS Control Tower emulator is mounted on an engine that \
                              holds no state"
                        .to_string(),
                },
            )
            .into());
        };

        // WHAT the request asks for is settled before any state is touched, so a request
        // naming something that could not exist writes nothing: the baseline must be one
        // the service's catalog publishes, at a version that baseline offers, applied to
        // an organizational unit, configured only by parameters that baseline declares.
        // `baselineIdentifier` and `targetIdentifier` are both typed as the generic `Arn`,
        // whose pattern cannot express either kind of resource, so these are the handler's
        // to check.
        let baseline = match crate::state::resolve_baseline(&input.baseline_identifier) {
            Some(baseline) => baseline,
            // An ARN of the right shape that names no catalog baseline is a reference to a
            // resource that does not exist; anything else is not a baseline reference at
            // all, which is a malformed input rather than a missing resource.
            None if crate::state::is_baseline_arn(&input.baseline_identifier) => {
                return Err(EnableBaselineErrorModeled::ResourceNotFoundException(
                    ResourceNotFoundException {
                        message: format!(
                            "no baseline matches baselineIdentifier {}",
                            input.baseline_identifier
                        ),
                    },
                )
                .into());
            }
            None => {
                return Err(EnableBaselineErrorModeled::ValidationException(
                    ValidationException {
                        message: format!(
                            "baselineIdentifier {:?} is not the ARN of an AWS Control Tower \
                             baseline; a baseline is named by the ARN ListBaselines and \
                             GetBaseline report for it",
                            input.baseline_identifier
                        ),
                    },
                )
                .into());
            }
        };

        if let Some(message) =
            crate::state::non_organizational_unit_target_message(&input.target_identifier)
        {
            return Err(
                EnableBaselineErrorModeled::ValidationException(ValidationException { message })
                    .into(),
            );
        }

        if let Some(message) = crate::state::unsupported_baseline_version_message(
            baseline,
            &input.baseline_version,
        ) {
            return Err(
                EnableBaselineErrorModeled::ValidationException(ValidationException { message })
                    .into(),
            );
        }

        let parameters: Vec<(String, ::aws_smithy_types::Document)> = input
            .parameters
            .unwrap_or_default()
            .into_iter()
            .map(|parameter| (parameter.key, parameter.value))
            .collect();
        if let Some(message) = crate::state::unacceptable_parameters_message(baseline, &parameters)
        {
            return Err(
                EnableBaselineErrorModeled::ValidationException(ValidationException { message })
                    .into(),
            );
        }

        // A tag key Amazon Web Services keeps for itself is not a caller's to write, and
        // this member lands in the same tag store `TagResource` merges into. Read off the
        // REQUEST alone, so the refusal is settled before any state is touched and the
        // enablement is not recorded either.
        if let Some(message) = crate::state::reserved_tag_key_message(
            "tags",
            input.tags.iter().flatten().map(|(key, _)| key.as_str()),
        ) {
            return Err(
                EnableBaselineErrorModeled::ValidationException(ValidationException { message })
                    .into(),
            );
        }

        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();
        store.settle(now);

        // Control Tower applies a baseline through the service role setting it up creates,
        // so an account it has provisioned nothing in has no role for this call to deploy
        // the baseline through and it reports that it could not assume it. Asked BEFORE the
        // target is looked up and before anything is persisted or an operation minted, so
        // no enablement — and no operation to poll for one — exists for an account the
        // service was never set up in. See `crate::state` for the one precondition the
        // enablement calls share.
        if !store.is_set_up() {
            return Err(EnableBaselineErrorModeled::ValidationException(
                ValidationException {
                    message: crate::state::SETUP_REQUIRED_FOR_BASELINES.to_string(),
                },
            )
            .into());
        }

        // One baseline per target: the pair is what identifies an enablement, so a second
        // enable of the same pair would leave two `EnabledBaseline` resources describing
        // one target. The pair is read off the CATALOG ENTRY this request resolved to, not
        // off the identifier's text, so a repeat written with any of the other identifiers
        // that name the same baseline is the same pair. The rule is read off the store, so
        // it holds whichever call enabled the existing one. (A baseline whose DISABLE has
        // become due is already out of the map above, so that pair enables again.)
        //
        // The refusal is classified by the STATE of the enablement the repeat collided
        // with, the same way `EnableControl` classifies its own: a repeat while the first
        // enablement is still being deployed would race that change, which is the
        // inconsistent state `ConflictException` reports; once it is deployed nothing is
        // in flight and the request simply asks for a resource that already exists, which
        // is a constraint on the input the modelled `ValidationException` reports.
        if let Some(existing) = store.enabled_baseline_on_target(baseline, &input.target_identifier)
        {
            let existing_arn = existing.arn.clone();
            if existing.status == crate::state::EnablementStatus::UnderChange {
                return Err(EnableBaselineErrorModeled::ConflictException(
                    ConflictException {
                        message: format!(
                            "enabled baseline {existing_arn} is still being deployed on \
                             target {}; enabling baseline {} again now would leave it in an \
                             inconsistent state",
                            input.target_identifier, input.baseline_identifier
                        ),
                    },
                )
                .into());
            }
            return Err(EnableBaselineErrorModeled::ValidationException(
                ValidationException {
                    message: format!(
                        "baseline {} is already enabled on target {} as {existing_arn}",
                        input.baseline_identifier, input.target_identifier
                    ),
                },
            )
            .into());
        }

        let region = crate::state::request_region(ctx.parts());
        let arn = crate::state::enabled_baseline_arn(
            &region,
            &crate::state::new_enabled_baseline_id(),
        );

        // The single insertion site for an enablement, which is what bounds that store:
        // past its cap nothing is written and the request is refused with the quota error
        // the model declares for this operation.
        let Some(operation_identifier) = store.record_enablement(
            &arn,
            // Checked against the catalog above, so what is persisted and reported back is
            // a baseline this service publishes, at a version that baseline offers.
            &input.baseline_identifier,
            &input.baseline_version,
            &input.target_identifier,
            parameters,
            now,
        ) else {
            return Err(EnableBaselineErrorModeled::ServiceQuotaExceededException(
                ServiceQuotaExceededException {
                    message: format!(
                        "this account already holds the maximum of {} enabled baselines; \
                         disable one before enabling another",
                        crate::state::MAX_ENABLED_BASELINES
                    ),
                },
            )
            .into());
        };

        if let Some(tags) = input.tags {
            store.tags.insert(arn.clone(), tags.into_iter().collect());
        }

        // Enabling the baseline that brings a target under AWS Control Tower's governance
        // makes the service responsible for that target, and the controls it applies to a
        // governed target itself are the mandatory ones — so they land in the one control
        // store the control reporting operations read, started together with this
        // enablement. A baseline that establishes no governance applies nothing.
        store.apply_governance_controls(baseline, &input.target_identifier, &region, now);

        Ok(EnableBaselineOutput {
            arn,
            operation_identifier,
        })
    }
}
