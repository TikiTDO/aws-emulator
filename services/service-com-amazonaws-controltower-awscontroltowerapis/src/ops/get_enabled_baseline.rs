//! Reports one `EnabledBaseline` from [`crate::state`]: the baseline and target it
//! applies, the version and parameters currently applied, and its enablement status
//! summary. Implemented alongside `UpdateEnabledBaseline`, which has nothing else to
//! read its writes back through.
//!
//! `@readonly`: the only write this handler makes is `settle`'s, which materialises
//! transitions the CLOCK already owed (an operation becoming due, a pending update
//! applying, a torn-down enablement disappearing) and would hold at the same instant
//! whether or not anybody called.
//!
//! Served only for an account Control Tower has been set up in
//! ([`crate::state::ComAmazonawsControltowerAwscontroltowerapisState::is_set_up`]): in one
//! it has provisioned nothing there is no landing zone and no service role to read
//! enablement state through, so the call is the modelled `ValidationException` (400)
//! naming the role rather than a report about the identifier — see `crate::state` for the
//! one precondition the enablement reads share.
//!
//! `driftStatusSummary` reports the INHERITANCE drift of the enablement, which is the one
//! drift type the model declares for a baseline: Control Tower "detects inheritance drift
//! on the enabled baselines that target OUs" and "does not detect drift on the baselines
//! that apply to your landing zone", so the summary is present for an enablement of a
//! drift-assessed baseline whose deployment the clock has made due and absent otherwise —
//! the status is stored on the enablement and materialised by `settle`, never computed
//! here.
//!
//! `parentIdentifier` is the enablement a reported one INHERITED its configuration from:
//! it "represents the parent EnabledBaseline at the Organizational Unit (OU) level, from
//! which the child EnabledBaseline inherits its configuration" and "the value is returned
//! by GetEnabledBaseline". It is read off the stored record rather than decided here, and
//! an enablement `EnableBaseline` applied directly to its target inherits from nothing, so
//! the member is absent for every enablement this service holds: a child of one is a
//! deployment into a member ACCOUNT of the target organizational unit
//! (`EnabledBaselineInheritanceDrift` has inheritance drift occurring "when any accounts in
//! the target OU do not match the baseline configuration defined on that OU"), which takes
//! the organization's membership — and no call this service serves states that an account
//! is a member of a unit, nor does any rule derive one from a unit's opaque identifier. So
//! no parent is named rather than one being invented.
