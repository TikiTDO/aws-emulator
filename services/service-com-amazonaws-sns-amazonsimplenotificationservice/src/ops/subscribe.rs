impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> Subscribe<Eng> {
    /// Create (or re-apply) the subscription the request names, and report the answer
    /// beside the deliveries the replay it may have started owes to that subscription's
    /// endpoint.
    ///
    /// The whole store-touching half of the operation, so the store's lock is taken and
    /// released here and the caller performs the deliveries with it released.
    ///
    /// The region the request is addressed to — read from `ctx`, which the ARN it names has
    /// to belong to — is also what the authorization decision below is taken through.
    fn subscribe_into_store(
        &self,
        input: SubscribeInput,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<(SubscribeOutput, super::publish::Deliveries), SubscribeError> {
        let region = crate::state::request_region(ctx.parts());
        // Argument validation, BEFORE the store is consulted: a `TopicArn` that is
        // not an ARN at all — or one naming another region, which this endpoint does
        // not serve — is bad input, not a topic that does not exist. The ENDPOINT is
        // held to no such rule: a subscriber is reached in the region its own ARN
        // names, which need not be the topic's.
        if let Some(message) =
            crate::state::regional_arn_refusal("TopicArn", &input.topic_arn, &region)
        {
            return Err(SubscribeErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(message),
                },
            )
            .into());
        }

        let protocol = input.protocol.to_ascii_lowercase();
        if !PROTOCOLS.contains(&protocol.as_str()) {
            return Err(SubscribeErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    // The sentence SNS states for an unsupported protocol, which
                    // names the string the caller sent because SNS's own sentence
                    // does — it is what the caller has to change.
                    message: Some(format!(
                        "Invalid parameter: Amazon SNS does not support this protocol string: {}",
                        input.protocol
                    )),
                },
            )
            .into());
        }

        // Every protocol addresses its endpoint in a form of its own, and SNS refuses
        // an endpoint that is not in that form BEFORE any state is written: a
        // subscription to an endpoint that cannot exist is never created. The endpoint
        // is also required — there is no protocol SNS delivers to without one.
        let valid_endpoint = input
            .endpoint
            .as_deref()
            .is_some_and(|endpoint| endpoint_matches_protocol(&protocol, endpoint));
        if !valid_endpoint {
            return Err(SubscribeErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(format!(
                        "Invalid parameter: {}",
                        endpoint_requirement(&protocol)
                    )),
                },
            )
            .into());
        }

        // Authorization, before the store is consulted: AWS decides whether the caller may
        // perform the action on the topic ahead of the service resolving it, so a refused
        // call creates no subscription.
        if let Some(message) = crate::state::authorization::topic_refusal(
            &*self.engine,
            ctx,
            crate::state::authorization::SUBSCRIBE,
            &input.topic_arn,
        ) {
            return Err(SubscribeErrorModeled::AuthorizationErrorException(
                AuthorizationErrorException {
                    message: Some(message),
                },
            )
            .into());
        }

        let Some(store) = crate::state::service_state(&*self.engine) else {
            return Err(SubscribeErrorModeled::InternalErrorException(
                InternalErrorException {
                    message: Some("the SNS store is unavailable".to_string()),
                },
            )
            .into());
        };
        let mut store = store.lock();

        if !store.topics.contains_key(&input.topic_arn) {
            return Err(SubscribeErrorModeled::NotFoundException(NotFoundException {
                message: Some(state::TOPIC_DOES_NOT_EXIST.to_string()),
            })
            .into());
        }

        // A FIFO queue may be subscribed only to a FIFO topic: it is delivered to in
        // the published order, which only a FIFO topic's messages carry. The pairing is
        // judged BEFORE any subscription record or subscription counter is written, so a
        // topic SNS refuses the endpoint for keeps an empty subscriber list. The queue's
        // kind is read through the crate's one definition of it
        // ([`state::addresses_fifo_queue`]), the same one a delivery reads. The other
        // direction is NOT refused: a FIFO topic delivers to a standard queue.
        let endpoint_is_fifo_queue = protocol == "sqs"
            && input
                .endpoint
                .as_deref()
                .is_some_and(state::addresses_fifo_queue);
        let topic_is_fifo = store
            .topics
            .get(&input.topic_arn)
            .is_some_and(|topic| topic.is_fifo);
        if endpoint_is_fifo_queue && !topic_is_fifo {
            return Err(SubscribeErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(FIFO_QUEUE_ON_STANDARD_TOPIC_REFUSAL.to_string()),
                },
            )
            .into());
        }

        // Subscribe is idempotent in the endpoint: one topic holds at most one
        // subscription per (protocol, endpoint) pair, so re-subscribing the same
        // endpoint answers with the subscription that already exists.
        let existing = store
            .subscriptions_of(&input.topic_arn)
            .into_iter()
            .find(|sub| sub.protocol == protocol && sub.endpoint == input.endpoint)
            .map(|sub| (sub.arn.clone(), sub.pending_confirmation));

        let attributes = input.attributes.unwrap_or_default();
        // SNS defines a closed set of subscription attribute names and refuses any
        // other; the closed set is also what keeps one subscription record from
        // growing for ever. The refusal is built from the request — the member the
        // map arrived in, and the key that was not recognised — so the caller can
        // find the entry it has to fix.
        if let Some(unknown) =
            state::unknown_attribute_name(&attributes, state::is_subscription_attribute)
        {
            return Err(SubscribeErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(state::unknown_attribute_refusal(
                        state::ATTRIBUTES_MEMBER,
                        unknown,
                    )),
                },
            )
            .into());
        }
        // A policy-valued attribute is REMOVED by an empty value, so an attribute a
        // request carries empty leaves the subscription holding none of it rather than
        // naming a document that failed to parse.
        let cleared: Vec<String> = attributes
            .iter()
            .filter(|(name, value)| state::clears_attribute(name, value))
            .map(|(name, _)| name.clone())
            .collect();
        let attributes: ::std::collections::HashMap<String, String> = attributes
            .into_iter()
            .filter(|(name, _)| !cleared.contains(name))
            .collect();
        // An attribute carries only the values SNS documents for it, and only on a
        // subscription of a protocol SNS documents it for — the SAME two rules
        // `SetSubscriptionAttributes` holds a write to, so an attribute this call
        // accepts is one that call accepts too, refused with the same message. A bad
        // VALUE names the member whose constraint it failed; the protocol-scope
        // refusal is SNS's own whole sentence, so it is not framed again here.
        for (name, value) in &attributes {
            let refusal = state::subscription_attribute_refusal(name, value).or_else(|| {
                state::subscription_attribute_protocol_refusal(name, value, &protocol)
            });
            if let Some(message) = refusal {
                return Err(SubscribeErrorModeled::InvalidParameterException(
                    InvalidParameterException {
                        message: Some(message),
                    },
                )
                .into());
            }
        }
        // And the filter policy and its scope are judged against EACH OTHER, which
        // neither per-attribute rule above can do on its own.
        if let Some(message) = state::filter_policy_pair_refusal(&attributes) {
            return Err(SubscribeErrorModeled::InvalidParameterException(
                InvalidParameterException {
                    message: Some(message),
                },
            )
            .into());
        }
        // An attribute the TOPIC gives nothing to govern is refused too — a replay of a
        // topic that archives nothing — under the rule every write of a subscription
        // attribute shares.
        for name in attributes.keys() {
            if let Some(message) = state::subscription_attribute_topic_refusal(
                name,
                store.topics.get(&input.topic_arn),
            ) {
                return Err(SubscribeErrorModeled::InvalidParameterException(
                    InvalidParameterException {
                        message: Some(message),
                    },
                )
                .into());
            }
        }
        // What SNS holds is the MEANING of each value, in the form it reports back, so a
        // subscription reads the same whichever call carried the attribute.
        let attributes: ::std::collections::HashMap<String, String> = attributes
            .into_iter()
            .map(|(name, value)| {
                let stored = state::stored_subscription_attribute_value(&name, &value);
                (name, stored)
            })
            .collect();
        // Whether THIS call asks for a message replay: a replay is started by the write of
        // a `ReplayPolicy`, so a re-subscribe that carries none does not replay the
        // archive again to a subscription that already holds one.
        let asked_for_replay = attributes.contains_key(state::REPLAY_POLICY_ATTRIBUTE);

        let (arn, pending_confirmation, wrote_attributes) = match existing {
            Some((arn, pending_confirmation)) => {
                // Subscribe is idempotent only in a request that asks for what the
                // subscription already is: one asking for an attribute value it does not
                // hold — a value of its own, or the removal of one it holds — would
                // change the delivery a running consumer is already receiving, so it is
                // refused and NOTHING is written. A request that carries no attribute at
                // all asks for no change, so it is the idempotent one.
                let held = store
                    .subscriptions
                    .get(&arn)
                    .map(|held| held.attributes.clone())
                    .unwrap_or_default();
                let asks_for_a_change = attributes
                    .iter()
                    .any(|(name, value)| held.get(name) != Some(value))
                    || cleared.iter().any(|name| held.contains_key(name));
                if asks_for_a_change {
                    return Err(SubscribeErrorModeled::InvalidParameterException(
                        InvalidParameterException {
                            message: Some(SUBSCRIPTION_ALREADY_EXISTS_REFUSAL.to_string()),
                        },
                    )
                    .into());
                }
                // Its confirmation token is left as it is: the token already sent to
                // that endpoint still names this subscription, so a subscriber part way
                // through confirming is not stranded by a re-subscribe.
                (arn, pending_confirmation, false)
            }
            None => {
                if let Some(refusal) = oversized(&attributes) {
                    return Err(refusal);
                }
                if store.subscriptions.len() >= state::MAX_RECORDS_PER_STORE {
                    return Err(
                        SubscribeErrorModeled::SubscriptionLimitExceededException(
                            SubscriptionLimitExceededException {
                                message: Some(state::limit_exceeded_message("subscriptions")),
                            },
                        )
                        .into(),
                    );
                }
                let pending_confirmation =
                    PROTOCOLS_NEEDING_CONFIRMATION.contains(&protocol.as_str());
                // A subscription whose subscriber has to confirm gets the token SNS
                // sends to its endpoint; one SNS confirms itself never has one to send.
                let confirmation_token =
                    pending_confirmation.then(|| store.next_confirmation_token());
                let arn = {
                    let id = store.next_unique_id();
                    state::subscription_arn(&input.topic_arn, &id)
                };
                let owner = state::owner_account_id();
                store.subscriptions.insert(
                    arn.clone(),
                    SubscriptionRecord {
                        arn: arn.clone(),
                        topic_arn: input.topic_arn.clone(),
                        protocol,
                        endpoint: input.endpoint,
                        // The principal this subscription was created by: the identity
                        // every call this emulator serves is made by.
                        principal: state::calling_principal_arn(),
                        owner,
                        attributes,
                        pending_confirmation,
                        confirmation_token,
                        created_at: std::time::SystemTime::now(),
                        // No replay has been asked for yet: the write below is what starts
                        // the one a `ReplayPolicy` carried on this call asks for.
                        replay: None,
                    },
                );
                (arn, pending_confirmation, true)
            }
        };

        // A `ReplayPolicy` this call WROTE asks for the topic's archived messages to be
        // redelivered to this subscription, which is the same redelivery
        // `SetSubscriptionAttributes` starts when it writes one. An idempotent
        // re-subscribe writes nothing, so it starts no second replay of a policy the
        // subscription already holds.
        let replay = if asked_for_replay && wrote_attributes {
            super::publish::replay_deliveries(&mut store, &arn)
        } else {
            super::publish::Deliveries::default()
        };

        // An unconfirmed subscription's ARN is withheld unless the caller asked for it.
        let reported = if pending_confirmation && !input.return_subscription_arn {
            state::PENDING_CONFIRMATION_REPORTED.to_string()
        } else {
            arn
        };
        Ok((
            SubscribeOutput {
                subscription_arn: Some(reported),
            },
            replay,
        ))
    }
}
