//! @op PutTaxExemption
//!
//! Records one tax exemption for each account the request names: the exemption
//! type it asks for, in the jurisdiction its `authority` names. One
//! applied submission opens one support case and answers its `caseId`, because
//! it submits one certificate.
//!
//! That case is a real AWS Support case, opened in the Support store on the
//! shared engine with the submitted certificate attached to it
//! ([`crate::state::support_case`]): `caseId` is "The customer support case ID",
//! the handle the caller hands to `support:DescribeCases` to follow the review of
//! the document — which is also why this operation models a failed upload of that
//! document to a Support case and the Support case-creation limit. Neither the id
//! nor the document is this service's to invent or to drop.
//!
//! The exemption's identity is its type and its jurisdiction — the request
//! carries no exemption id — so submitting the same exemption for an account
//! again REPLACES that account's record, which is what makes this a `Put`. The
//! submission is applied whole or not at all: a bound it would take the store
//! past is refused before any record is written, and no case is opened for a
//! submission that was not applied.
//!
//! The type a submission names is a free-form string the model constrains only
//! in length and by a pattern that admits every character, and the model
//! enumerates no legal values for it, so the submission is admitted on those
//! constraints and the token is recorded as the caller spelled it — as the entry
//! of the collection `GetTaxExemptionTypes` publishes when it names one
//! ([`crate::state::submitted_exemption_type`]). The jurisdiction is admitted on
//! the constraints the model states for `Authority` as well: the only refusal
//! left here is the blank `state` its pattern forbids and the boundary cannot
//! check.
//!
//! The accounts a submission names are NOT screened. The request addresses "a
//! single account or all accounts listed in a consolidated billing family", and
//! membership in that family is not something this service is ever told: it
//! models no organization and no operation enrolls an account, so a well-formed
//! account id this service happens to hold no other resource for is
//! indistinguishable from a family member — a brand-new member account holds no
//! tax registration at all, and whether it holds one has nothing to do with
//! submitting an exemption for it. The record the submission writes is what makes
//! the account one the exemption reads then report on.
//!
//! The exemption a submission stores is `Pending`, the status the model gives
//! one whose certificate has not been reviewed: the certificate is attached to a
//! support case for review, and granting the exemption is that reviewer's
//! decision rather than a transition the clock makes due — see
//! [`crate::state::StoredTaxExemption::reported_status`], where lapsing is the
//! transition the clock owes a stored exemption. It carries no effective or
//! expiration date, because both are facts about the submitted certificate and
//! nothing here reads that document.
//!
