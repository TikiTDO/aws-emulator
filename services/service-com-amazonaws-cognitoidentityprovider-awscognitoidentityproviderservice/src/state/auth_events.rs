//! The threat-protection event log of a user pool: the authentication events a pool
//! with its add-ons switched on records about one of its users, and the feedback a
//! submitter leaves on one.
//!
//! A pool whose threat protection is active does not only SERVE its authentication
//! traffic, it logs it: an event log is "a history of user activity and any risks
//! detected as part of Amazon Cognito threat protection"
//! (`AdminListUserAuthEvents`), one entry of which is "one authentication event that
//! Amazon Cognito logged in a user pool with threat protection active"
//! (`AuthEventType`, this service's model). So every call that attempts an
//! authentication, a registration, a password change, a password recovery or a code
//! resend against such a pool adds one entry to the log of the user it was attempted
//! for, and a pool with its add-ons off ([`super::UserPool::add_ons_enabled`]) logs
//! nothing at all — which is also why the operations that read and write the log
//! refuse on such a pool.
//!
//! # What one call contributes
//!
//! Which event type an entry carries follows what the call attempted rather than
//! which operation served it ([`EventType`]), the same way the metric series a call
//! publishes does ([`super::auth_metrics`]), so the self-service and the
//! administrative surface of one attempt log the same kind of event.
//!
//! The entry's `EventResponse` is the OUTCOME the call reached, read from the same
//! classification the metric publisher uses ([`super::auth_metrics::Attempt`]): an
//! attempt the call completed passed, one it refused failed, and one it answered with
//! a challenge is still in progress until the call that answers that challenge
//! finishes it. A call that CONTINUES an attempt — a challenge response — therefore
//! updates the entry the call that started the attempt logged, appending the result of
//! the challenge it checked, rather than logging a second event for the same sign-in.
//!
//! # The risk assessment
//!
//! `EventRisk` is "the risk evaluation by adaptive authentication" (`AuthEventType`).
//! This emulator makes no outbound call and holds no device or address reputation, so
//! an evaluation has no risk signal to find and the recorded decision is
//! [`super::auth_metrics::NO_RISK`] with no compromised credentials detected — exactly
//! what the same pool publishes as the risk outcome of the same traffic. No risk level
//! is recorded: a level is what adaptive authentication "assessed for the
//! authentication event" (`EventRiskType.RiskLevel`), and an evaluation that found no
//! risk assessed none.

use ::std::time::SystemTime;

use crate::ops::types::{
    AuthEventType, ChallengeResponseType, EventContextDataType, EventFeedbackType, EventRiskType,
};

use super::auth_metrics::{Attempt, NO_RISK};
use super::{User, non_empty, random_token, to_date_time};

/// The most events one user's log holds; the oldest are evicted past it. A
/// capacity bound of this emulator, like the other stores it keeps in memory —
/// Amazon Cognito's own retention of event history is a window of time, not a
/// count, and nothing in this API reports either.
pub const MAX_AUTH_EVENTS_PER_USER: usize = 500;

/// How many characters a minted `FeedbackToken` carries. The token is "an
/// encrypted object generated by Amazon Cognito and passed to your user in the
/// notification email message from the event"
/// (`UpdateAuthEventFeedback.FeedbackToken`), so it is an opaque secret of this
/// emulator's own minting, shaped to `TokenModelType`'s pattern
/// `^[A-Za-z0-9-_=.]+$`.
const FEEDBACK_TOKEN_LENGTH: usize = 64;

/// What one logged call attempted. The values are `EventType`'s
/// (`smithy_query(query="shape",shape="EventType")`), and which one an entry
/// carries follows what the call attempted rather than the operation that served
/// it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EventType {
    /// Authenticating a user: the credential-checking flows of `InitiateAuth` and
    /// `AdminInitiateAuth`, and the challenge responses that complete one.
    SignIn,
    /// Registering a user through an app client.
    SignUp,
    /// Starting the recovery of a forgotten password.
    ForgotPassword,
    /// Replacing the password a user holds, by that user.
    PasswordChange,
    /// Sending a registration confirmation code again.
    ResendCode,
}

impl EventType {
    /// The `EventType` value this kind of event is reported as.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::SignIn => "SignIn",
            Self::SignUp => "SignUp",
            Self::ForgotPassword => "ForgotPassword",
            Self::PasswordChange => "PasswordChange",
            Self::ResendCode => "ResendCode",
        }
    }
}

/// `EventResponseType`'s value for an attempt the call COMPLETED.
pub const EVENT_RESPONSE_PASS: &str = "Pass";

/// `EventResponseType`'s value for an attempt the call REFUSED.
pub const EVENT_RESPONSE_FAIL: &str = "Fail";

/// `EventResponseType`'s value for an attempt that is not over: the call answered
/// with a challenge, and the response to that challenge finishes it.
pub const EVENT_RESPONSE_IN_PROGRESS: &str = "InProgress";

/// `ChallengeName`'s value for the credential challenge a password sign-in
/// checks; the enumeration carries exactly two values
/// (`smithy_query(query="shape",shape="ChallengeName")`).
pub const PASSWORD_CHALLENGE: &str = "Password";

/// `ChallengeName`'s value for the second factor a sign-in is challenged for.
pub const MFA_CHALLENGE: &str = "Mfa";

/// `ChallengeResponse`'s value for a challenge the user answered correctly.
pub const CHALLENGE_SUCCESS: &str = "Success";

/// `ChallengeResponse`'s value for a challenge the user did not answer
/// correctly.
pub const CHALLENGE_FAILURE: &str = "Failure";

/// The `EventFeedbackType.Provider` of feedback the ADMINISTRATIVE operation
/// submitted: "if you submit event feedback in the Amazon Cognito console, this
/// value is `Admin`" (`EventFeedbackType.Provider` in this service's model), and
/// `AdminUpdateAuthEventFeedback` is the operation that console submits with.
pub const ADMIN_FEEDBACK_PROVIDER: &str = "Admin";

/// The `EventFeedbackType.Provider` of feedback the USER submitted for itself:
/// "users invoke this operation when they select the link that corresponds to
/// {one-click-link-valid} or {one-click-link-invalid} in your notification
/// template" (`UpdateAuthEventFeedback`), so the submitter of that feedback is
/// the user rather than an administrator.
pub const USER_FEEDBACK_PROVIDER: &str = "User";

/// The `EventResponse` an attempt in this state is logged with.
#[must_use]
pub fn event_response(attempt: Attempt) -> &'static str {
    match attempt {
        Attempt::Completed => EVENT_RESPONSE_PASS,
        Attempt::Refused => EVENT_RESPONSE_FAIL,
        Attempt::Outstanding => EVENT_RESPONSE_IN_PROGRESS,
    }
}

/// The `ChallengeResponse` a challenge the call checked is logged with: the
/// challenge was answered unless the call refused the attempt.
#[must_use]
pub fn challenge_response(attempt: Attempt) -> &'static str {
    match attempt {
        Attempt::Refused => CHALLENGE_FAILURE,
        Attempt::Completed | Attempt::Outstanding => CHALLENGE_SUCCESS,
    }
}

/// The feedback a submitter left on one logged event.
#[derive(Debug, Clone)]
pub struct Feedback {
    /// `FeedbackValueType`: whether the submitter judged the session valid.
    pub value: String,
    /// Who submitted it ([`ADMIN_FEEDBACK_PROVIDER`],
    /// [`USER_FEEDBACK_PROVIDER`]).
    pub provider: String,
    /// When it was submitted.
    pub submitted_at: SystemTime,
}

/// One logged authentication event of one user.
#[derive(Clone)]
pub struct AuthEvent {
    /// The id this event is addressed by, inside `EventIdType`'s modelled length
    /// 1..50 and pattern `^[\w+-]+$`.
    pub event_id: String,
    /// `EventType`: what the call that logged it attempted.
    pub event_type: String,
    pub creation_date: SystemTime,
    /// `EventResponseType`: the outcome the attempt reached so far.
    pub response: String,
    /// The challenges the user was asked to answer during the attempt, in the
    /// order they were checked.
    pub challenge_responses: Vec<ChallengeResponseType>,
    /// The source address the request reported for the user's device, for a
    /// request that carried one, and `None` otherwise: the context data is "the
    /// user context data captured at the time of an event request"
    /// (`AuthEventType.EventContextData`), so nothing is recorded that the
    /// request did not carry.
    pub ip_address: Option<String>,
    /// The feedback submitted on this event, once some was.
    pub feedback: Option<Feedback>,
    /// The challenge session the attempt this event records is WAITING ON, for an
    /// attempt a challenge is outstanding for, and `None` once it is over.
    ///
    /// It is what identifies the attempt a later call continues: `Session` is "the
    /// session identifier that maintains the state of authentication requests and
    /// challenge responses" (this service's model), so the response carrying that
    /// session belongs to THIS attempt and not to another the same user started.
    /// A session token authorizes a challenge response, so it is never rendered,
    /// logged or put in a response (see the [`::std::fmt::Debug`] impl below).
    pub outstanding_session: Option<String>,
    /// The `FeedbackToken` this event's one-click feedback links carry, which is
    /// what `UpdateAuthEventFeedback` authorizes a user's own feedback with. A
    /// secret, so it is never rendered, logged or put in a response (see the
    /// [`::std::fmt::Debug`] impl below).
    pub feedback_token: String,
}

/// Renders the logged event WITHOUT its feedback token or its challenge session:
/// each authorizes a call on this event, so neither is logged or traced.
impl ::std::fmt::Debug for AuthEvent {
    fn fmt(&self, formatter: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {
        formatter
            .debug_struct("AuthEvent")
            .field("event_id", &self.event_id)
            .field("event_type", &self.event_type)
            .field("creation_date", &self.creation_date)
            .field("response", &self.response)
            .field("challenge_responses", &self.challenge_responses)
            .field("ip_address", &self.ip_address)
            .field("feedback", &self.feedback)
            .finish_non_exhaustive()
    }
}

impl AuthEvent {
    /// The modelled view of this event, rendered from what is stored.
    #[must_use]
    pub fn to_auth_event_type(&self) -> AuthEventType {
        AuthEventType {
            event_id: Some(self.event_id.clone()),
            event_type: Some(self.event_type.clone()),
            creation_date: Some(to_date_time(self.creation_date)),
            event_response: Some(self.response.clone()),
            event_risk: Some(EventRiskType {
                risk_decision: Some(NO_RISK.to_string()),
                // An evaluation that found no risk assessed no level.
                risk_level: None,
                compromised_credentials_detected: Some(false),
            }),
            challenge_responses: non_empty(&self.challenge_responses),
            event_context_data: self.ip_address.as_ref().map(|ip_address| {
                EventContextDataType {
                    ip_address: Some(ip_address.clone()),
                    // The remaining members are what Amazon Cognito derives from
                    // the device and the address of the request; this emulator
                    // holds no device fingerprint and no geolocation of an
                    // address, so it reports none.
                    device_name: None,
                    timezone: None,
                    city: None,
                    country: None,
                }
            }),
            event_feedback: self.feedback.as_ref().map(|feedback| EventFeedbackType {
                feedback_value: feedback.value.clone(),
                provider: feedback.provider.clone(),
                feedback_date: Some(to_date_time(feedback.submitted_at)),
            }),
        }
    }

    /// Record `value` as the feedback `provider` submitted on this event as of
    /// `at`, replacing any feedback submitted before: the event carries ONE
    /// verdict, the latest one.
    pub fn submit_feedback(&mut self, value: String, provider: &str, at: SystemTime) {
        self.feedback = Some(Feedback {
            value,
            provider: provider.to_string(),
            submitted_at: at,
        });
    }

    /// Whether `presented` is the `FeedbackToken` this event's own one-click
    /// feedback links carry, which is what authorizes a user to submit feedback
    /// on it for itself.
    ///
    /// "This operation requires a `FeedbackToken` that Amazon Cognito generates
    /// and adds to notification emails when users have potentially suspicious
    /// authentication events" (`UpdateAuthEventFeedback` in this service's
    /// model), so the only value accepted is the one minted for THIS event; a
    /// token of another event proves nothing about holding this one's. The
    /// comparison is a constant-time one, so a rejected token tells a caller
    /// nothing about how much of it was right.
    #[must_use]
    pub fn authorizes_feedback(&self, presented: &str) -> bool {
        bool::from(::subtle::ConstantTimeEq::ct_eq(
            presented.as_bytes(),
            self.feedback_token.as_bytes(),
        ))
    }
}

/// The message the refusal of a `FeedbackToken` that was minted for no event
/// carries.
///
/// The token is what "maintains the state" of the one-click feedback the
/// notification email invited, so Amazon Cognito reports a value it did not mint
/// for the event as the invalid session it is, in fixed text that names neither
/// the token nor the event.
pub const FEEDBACK_TOKEN_INVALID_MESSAGE: &str = "Invalid session provided";

/// How the feedback operations report an `EventId` that names no event of the
/// user's history.
///
/// The event is the resource the feedback is left on, so a request naming one
/// that does not exist is answered the way this service answers every absent
/// resource: with what was asked for and that it does not exist.
#[must_use]
pub fn event_not_found_message(event_id: &str) -> String {
    format!("Event {event_id} does not exist.")
}

/// What one call contributes to the log: who it was attempted for, what it
/// attempted and what it was answered.
#[derive(Debug)]
pub struct Logged<'a> {
    /// The pool the request named, for an operation that models one, and `None`
    /// where the app client alone names it.
    pub user_pool_id: Option<&'a str>,
    /// The app client the attempt ran against, for an operation that names one.
    pub client_id: Option<&'a str>,
    /// The user the attempt was made for, named however the request named it.
    pub username: &'a str,
    pub event_type: EventType,
    /// What the call did to the attempt.
    pub attempt: Attempt,
    /// The `ChallengeName` of the credential this call checked, for a call that
    /// checked one.
    pub challenge: Option<&'static str>,
    /// The source address the request reported for the user's device.
    pub ip_address: Option<String>,
    /// The challenge session this call ANSWERED, for a call that continues an
    /// attempt an earlier call started: it finishes that attempt's own event
    /// instead of logging a new one.
    pub answered_session: Option<String>,
    /// The challenge session the attempt is left WAITING ON, for an answer that
    /// left a challenge outstanding.
    pub outstanding_session: Option<String>,
}

/// Log what one call contributed to the event history of the user it was
/// attempted for.
///
/// Call it with no state guard of this service held: this takes the lock itself,
/// once the call it reports has already been answered. Nothing is logged for a
/// pool this service does not hold, for a pool the named app client does not
/// belong to, for a pool whose threat protection is switched off, or for a user
/// the pool does not hold — in each case there is no event history for the
/// attempt to belong to.
pub fn record<Eng: Send + Sync + 'static>(engine: &Eng, logged: &Logged<'_>, at: SystemTime) {
    let Some(state) = super::service_state(engine) else {
        return;
    };
    let mut guard = state.lock();
    let Some(user_pool_id) = addressed_pool(&guard, logged) else {
        return;
    };
    let Some(pool) = guard.pool_mut(&user_pool_id) else {
        return;
    };
    if !pool.add_ons_enabled() {
        return;
    }
    let Some(user) = pool.user_mut(logged.username) else {
        return;
    };
    log(user, logged, at);
}

/// The id of the stored pool `logged` is about, or `None` when it names none
/// this service holds.
fn addressed_pool(
    state: &super::ComAmazonawsCognitoidentityproviderAwscognitoidentityproviderserviceState,
    logged: &Logged<'_>,
) -> Option<String> {
    let pool = match (logged.user_pool_id, logged.client_id) {
        // Both named: the attempt ran against an app client OF that pool, so a
        // client the pool does not hold is not an attempt against it.
        (Some(user_pool_id), Some(client_id)) => state
            .pool(user_pool_id)
            .filter(|pool| pool.clients.contains_key(client_id)),
        (Some(user_pool_id), None) => state.pool(user_pool_id),
        (None, Some(client_id)) => state.pool_of_client(client_id),
        (None, None) => None,
    };
    pool.map(|pool| pool.id.clone())
}

/// Append what `logged` reports to `user`'s event history, or finish the event of
/// the attempt it continues.
fn log(user: &mut User, logged: &Logged<'_>, at: SystemTime) {
    let event_type = logged.event_type.as_str();
    if let Some(answered) = logged.answered_session.as_deref() {
        // The attempt this call continues is the one WAITING ON the session the
        // call answered, so a user with two sign-ins in flight has each response
        // finish its own attempt's event.
        if let Some(event) = user.auth_events.iter_mut().rev().find(|event| {
            event.outstanding_session.as_deref() == Some(answered) && event.event_type == event_type
        }) {
            event.response = event_response(logged.attempt).to_string();
            event.outstanding_session = logged.outstanding_session.clone();
            if let Some(challenge) = logged.challenge {
                event
                    .challenge_responses
                    .push(challenge_result(challenge, logged.attempt));
            }
            return;
        }
    }
    let event = AuthEvent {
        event_id: new_event_id(),
        event_type: event_type.to_string(),
        creation_date: at,
        response: event_response(logged.attempt).to_string(),
        challenge_responses: logged
            .challenge
            .map(|challenge| vec![challenge_result(challenge, logged.attempt)])
            .unwrap_or_default(),
        ip_address: logged.ip_address.clone(),
        feedback: None,
        outstanding_session: logged.outstanding_session.clone(),
        feedback_token: new_feedback_token(),
    };
    user.auth_events.push(event);
    // The log is bounded, and it is the OLDEST history that is dropped: the
    // reader serves the most recent events first.
    let held = user.auth_events.len();
    if held > MAX_AUTH_EVENTS_PER_USER {
        user.auth_events.drain(..held - MAX_AUTH_EVENTS_PER_USER);
    }
}

/// One entry of an event's `ChallengeResponses`: the challenge the call checked
/// and whether it was answered.
fn challenge_result(challenge: &str, attempt: Attempt) -> ChallengeResponseType {
    ChallengeResponseType {
        challenge_name: Some(challenge.to_string()),
        challenge_response: Some(challenge_response(attempt).to_string()),
    }
}

/// A fresh `EventId`: a v4 UUID, which is 36 characters of the randomness every
/// other minted value of this service draws on ([`super::new_uuid`]) and
/// satisfies `EventIdType`'s modelled length 1..50 and pattern `^[\w+-]+$`.
fn new_event_id() -> String {
    super::new_uuid()
}

/// A fresh `FeedbackToken`: [`FEEDBACK_TOKEN_LENGTH`] characters of the same
/// randomness, inside `TokenModelType`'s pattern `^[A-Za-z0-9-_=.]+$`.
fn new_feedback_token() -> String {
    random_token(FEEDBACK_TOKEN_LENGTH)
}

/// The event-log `ChallengeName` a response to the challenge `challenge_name`
/// records, or `None` for a challenge that checks neither the user's password nor a
/// second factor.
///
/// The log's own enumeration carries exactly two challenges, `Password` and `Mfa`
/// (`smithy_query(query="shape",shape="ChallengeName")`), while a sign-in is
/// challenged by any member of `ChallengeNameType`
/// (`smithy_query(query="shape",shape="ChallengeNameType")`): each of those is
/// recorded as the one of the two it is. A challenge that presents the user's own
/// password — including the one that asks for a replacement — is the password
/// challenge; every challenge of a second factor, and the setup or selection of
/// one, is the MFA challenge. The remaining members choose a challenge
/// (`SELECT_CHALLENGE`), run a pool's own Lambda challenge (`CUSTOM_CHALLENGE`) or
/// authenticate the device rather than the user, so they record neither.
#[must_use]
pub fn challenge_of(challenge_name: &str) -> Option<&'static str> {
    match challenge_name {
        "PASSWORD" | "PASSWORD_SRP" | "PASSWORD_VERIFIER" | "NEW_PASSWORD_REQUIRED"
        | "ADMIN_NO_SRP_AUTH" => Some(PASSWORD_CHALLENGE),
        "SMS_MFA" | "SMS_OTP" | "EMAIL_OTP" | "SOFTWARE_TOKEN_MFA" | "SELECT_MFA_TYPE"
        | "MFA_SETUP" | "WEB_AUTHN" => Some(MFA_CHALLENGE),
        _ => None,
    }
}

/// One page of a user's event history: the events it serves, rendered, and the
/// `NextToken` the page after it resumes at.
#[derive(Debug, Clone)]
pub struct HistoryPage {
    pub events: Vec<AuthEventType>,
    pub next_token: Option<String>,
}

/// The page of `events` that `max_results` and `next_token` ask for, in the order
/// `events` are given in, or `None` when `next_token` is not a token this listing
/// minted — which the calling operation refuses with its own modelled error.
///
/// `scope` names the listing the token belongs to, as every other paginated
/// listing of this service names its own ([`super::encode_page_token`]). The page
/// resumes after the EVENT the token names, found by its id: the history is served
/// most recent first, so its order is not an order on those ids and a position in
/// it is no bound on them. Events logged between two pages are logged ahead of the
/// one the token names, so they belong to no later page of the same pass; a token
/// whose event the log no longer holds resumes at the newest event left.
#[must_use]
pub fn page_of_history(
    scope: &str,
    events: &[&AuthEvent],
    max_results: Option<i32>,
    next_token: Option<&str>,
) -> Option<HistoryPage> {
    let start = match next_token {
        None => 0,
        Some(token) => {
            let after = super::decode_page_token(scope, token)?;
            events
                .iter()
                .position(|event| event.event_id == after)
                .map_or(0, |at| at.saturating_add(1))
        }
    };
    let end = start
        .saturating_add(super::page_size(max_results))
        .min(events.len());
    let served = events.get(start..end).unwrap_or_default();
    let next_token = match served.last() {
        Some(last) if end < events.len() => {
            Some(super::encode_page_token(scope, &last.event_id))
        }
        _ => None,
    };
    Some(HistoryPage {
        events: served
            .iter()
            .map(|event| event.to_auth_event_type())
            .collect(),
        next_token,
    })
}

impl User {
    /// This user's logged authentication events MOST RECENT FIRST, which is the
    /// order the reader of the history serves them in.
    #[must_use]
    pub fn auth_events_newest_first(&self) -> Vec<&AuthEvent> {
        self.auth_events.iter().rev().collect()
    }

    /// The logged event `event_id` names, mutably, or `None` when this user's
    /// history holds no such event.
    pub fn auth_event_mut(&mut self, event_id: &str) -> Option<&mut AuthEvent> {
        self.auth_events
            .iter_mut()
            .find(|event| event.event_id == event_id)
    }
}
