impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> ResendConfirmationCode<Eng> {
    /// Issue the code `input` asks to be resent, and report what that left behind.
    ///
    /// Everything here happens under this service's lock, which this call OWNS: the lock
    /// is taken and released inside it, so its caller holds none of it while it invokes a
    /// trigger function.
    fn resend(&self, input: &ResendConfirmationCodeInput) -> Result<Resent, ResendConfirmationCodeError> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(internal_error());
        };
        let now = ::std::time::SystemTime::now();

        let mut guard = state.lock();
        // This operation models no `UserPoolId`: the app client the request names is
        // what resolves the pool the user signed up in.
        let pool = guard
            .pool_of_client(&input.client_id)
            .ok_or_else(|| client_not_found(&input.client_id))?;
        let user_pool_id = pool.id.clone();
        let client = pool
            .clients
            .get(&input.client_id)
            .ok_or_else(|| client_not_found(&input.client_id))?;
        if let Some(defect) =
            client.secret_hash_defect(&input.username, input.secret_hash.as_deref())
        {
            return Err(secret_hash_refused(defect, &input.client_id));
        }
        let hides_user_existence = client.hides_user_existence();

        let Some(user) = pool.user(&input.username) else {
            // `PreventUserExistenceErrors = ENABLED` "suppresses messages that might
            // indicate a valid user exists" (this service's model), so a request
            // naming a user nobody registered is answered the way a request naming
            // one that exists is: with a reported delivery, to a SIMULATED
            // destination, since nothing was sent and no code is stored for a user
            // that does not exist. `LEGACY` answers `UserNotFoundException`.
            if hides_user_existence {
                return Ok(Resent {
                    answer: ResendConfirmationCodeOutput {
                        code_delivery_details: crate::state::simulated_code_delivery_details(),
                    },
                    issued: None,
                });
            }
            return Err(user_not_found());
        };
        if !user.enabled {
            return Err(not_authorized("User is disabled."));
        }
        // This operation "resends the code that confirms a new account for a user who
        // has signed up in your user pool" (its own doc), so a user whose account is
        // already confirmed has no such code to resend.
        if user.status != crate::state::UserStatus::Unconfirmed {
            return Err(invalid_parameter("User is already confirmed.".to_string()));
        }
        let username = user.username.clone();

        // "Amazon Cognito sends confirmation codes to the user attribute in the
        // `AutoVerifiedAttributes` property of your user pool" (this operation's own
        // doc), so a pool that auto-verifies nothing the user holds a value for has
        // nowhere to send the code.
        let Some((attribute, destination)) = pool.confirmation_destination(user) else {
            return Err(invalid_parameter(
                "Cannot resend codes. No registered/verified email or phone_number".to_string(),
            ));
        };

        // Sending the code is what this operation DOES: the fresh code becomes the ONE
        // code outstanding for this user's sign-up, so the code the sign-up sent is
        // superseded and no longer accepted.
        let code = crate::state::VerificationCode::issued(&attribute, &destination, now);
        let user = guard
            .pool_mut(&user_pool_id)
            .and_then(|pool| pool.user_mut(&username))
            .ok_or_else(internal_error)?;
        let stored = user.issue_code(crate::state::CodePurpose::SignUpConfirmation, code);
        Ok(Resent {
            answer: ResendConfirmationCodeOutput {
                code_delivery_details: stored.delivery_details(),
            },
            issued: Some(IssuedCode {
                user_pool_id,
                username,
                code: stored.code,
            }),
        })
    }
}

