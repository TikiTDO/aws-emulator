/// The largest page the model allows: the `max` of `MaxResults`'s range
/// (`smithy_query(query="operation", operation="ListSpeechSynthesisTasks")`). The
/// boundary validator already refuses anything outside that range, so this only
/// bounds the window the handler builds.
const MAX_RESULTS_CEILING: i32 = 100;

/// The most tasks ONE response will ever materialise, whatever the store holds.
///
/// Not a page size, and nothing the caller can raise: `MaxResults` is the only page
/// bound this operation has, and a request that names none is answered in full. This is
/// the ceiling on the window the handler builds and clones, so the memory and the
/// response one request can cost do not follow the store without limit. CHOSEN: far
/// above any number of synthesis tasks a caller lists in one call, so an unbounded
/// report is in practice never cut here; when it is, the report pages on through the
/// same `NextToken` cursor and no task is lost.
pub const REPORT_MATERIALISATION_CEILING: usize = 5_000;

/// The field separator inside a page cursor. An ASCII unit separator, so it cannot
/// occur in a `TaskId` (`^[a-zA-Z0-9_-]{1,100}$`) or in a `TaskStatus` value.
const CURSOR_SEPARATOR: char = '\u{1f}';

/// Encode the cursor a `NextToken` carries: the position in the task order the page
/// ended at, AND the `Status` filter it was reached under.
///
/// The position is the ORDER KEY of the last task on the page, not an index into the
/// list, so a task created between two pages cannot shift the window and make the
/// next page skip or repeat a task. The filter travels with it because a position
/// under one filter means nothing under another; [`decode_task_cursor`] refuses such
/// a token rather than serving a silently wrong page.
///
/// The token is minted under this store's page-token key, so what comes back is a token
/// this service ISSUED and not merely one of the right shape.
fn encode_task_cursor(
    key: &crate::state::PageTokenKey,
    created_millis: i64,
    task_id: &str,
    status: Option<&str>,
) -> String {
    crate::state::encode_page_token(
        key,
        &format!(
            "{created_millis}{CURSOR_SEPARATOR}{task_id}{CURSOR_SEPARATOR}{}",
            status.unwrap_or_default()
        ),
    )
}

/// The order key a `NextToken` resumes after, or `None` if this service did not mint
/// the token or minted it for a different `Status` filter.
///
/// The first test is the one the caller cannot pass by construction: the token must
/// carry this store's authenticator over the cursor it travels with
/// ([`crate::state::decode_page_token`]), so a hand-built token of the right shape names
/// no position at all. Only then does the cursor's own content decide, and a cursor
/// minted under another `Status` filter is refused too.
fn decode_task_cursor(
    key: &crate::state::PageTokenKey,
    token: &str,
    status: Option<&str>,
) -> Option<(i64, String)> {
    let cursor = crate::state::decode_page_token(key, token)?;
    let mut fields = cursor.split(CURSOR_SEPARATOR);
    let created_millis = fields.next()?.parse::<i64>().ok()?;
    let task_id = fields.next()?.to_string();
    let minted_for = fields.next()?;
    if fields.next().is_some() {
        return None;
    }
    (minted_for == status.unwrap_or_default()).then_some((created_millis, task_id))
}

/// The total order the report pages in.
///
/// "Returns a list of SpeechSynthesisTask objects ordered by their creation date" — the
/// MOST RECENTLY created task first, which is the order the service reports and the order a
/// client reading the first page to find its latest task depends on. This key is the
/// creation date and the `TaskId`, and the report sorts by it DESCENDING: the date decides,
/// and the `TaskId` breaks a tie so the order is TOTAL and a page token can resume it
/// exactly. The date is taken at millisecond precision, the precision the cursor carries, so
/// sorting and resuming cannot disagree.
fn order_key(task: &crate::state::StoredSynthesisTask) -> (i64, &str) {
    let created_millis = task
        .creation_time
        .duration_since(::std::time::SystemTime::UNIX_EPOCH)
        .map_or(0, |since_epoch| {
            i64::try_from(since_epoch.as_millis()).unwrap_or(i64::MAX)
        });
    (created_millis, task.task_id.as_str())
}

