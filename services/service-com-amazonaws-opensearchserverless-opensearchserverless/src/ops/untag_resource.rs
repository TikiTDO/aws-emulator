    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UNTAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        // `tagKeys` is a SET of keys — "All tag keys in the request must be unique" — and
        // the list carries no `@uniqueItems`, so the boundary admits a repeat and the rule
        // is held here: a member that names one key twice is the invalid input
        // `ValidationException` describes, and nothing is removed.
        if let Some(repeated) =
            crate::state::first_repeated_element(input.tag_keys.iter().map(String::as_str))
        {
            return Err(UntagResourceErrorModeled::ValidationException(
                ValidationException {
                    message: Some(crate::state::repeated_element_message(
                        "tagKeys", &repeated,
                    )),
                },
            )
            .into());
        }

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(UntagResourceErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some(crate::state::STORE_UNREACHABLE.to_string()),
                },
            )
            .into());
        };

        let mut store = state.lock();
        store.settle_due_transitions();

        // A `resourceArn` addresses an ACTIVE resource this account holds, whichever KIND
        // of resource it names. A value that is no ARN at all names nothing a lookup could
        // resolve, so it is refused as malformed input rather than as a missing resource; a
        // collection whose deletion has been accepted is on its way out and its tags are no
        // longer addressable, so it answers the same not-found refusal as a resource that
        // was never there.
        if let Err(refusal) = store.resolve_tag_resource_arn(&input.resource_arn) {
            return Err(match refusal {
                crate::state::ResourceArnRefusal::Invalid(message) => {
                    UntagResourceErrorModeled::ValidationException(ValidationException {
                        message: Some(message),
                    })
                }
                crate::state::ResourceArnRefusal::NotFound(message) => {
                    UntagResourceErrorModeled::ResourceNotFoundException(
                        ResourceNotFoundException {
                            message: Some(message),
                        },
                    )
                }
            }
            .into());
        }
        // Removing tags REWRITES the resource, so the write instant is what its
        // `lastModifiedDate` reports from here on: the stamping accessor applies it.
        let written_at = crate::state::now_epoch_millis();
        let Some(stored) = store.tags_by_arn_for_write(&input.resource_arn, written_at) else {
            return Err(UntagResourceErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::state::resource_not_found_message(
                        &input.resource_arn,
                    )),
                },
            )
            .into());
        };

        // Removing a key the resource does not carry removes nothing: the request asks for
        // a state (these keys absent) rather than for an event, so it is not a failure.
        stored.retain(|tag| !input.tag_keys.contains(&tag.key));

        // `UntagResourceResponse` models no members: what the call produced is the stored
        // tag set, which `ListTagsForResource` reports.
        Ok(UntagResourceOutput {})
    }
