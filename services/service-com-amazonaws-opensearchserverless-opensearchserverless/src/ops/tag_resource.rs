impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        // A tag set is a map keyed by tag key — "All tag keys in the request must be
        // unique" — and `Tags` carries no `@uniqueItems`, so the boundary admits a repeat
        // and the rule is held here: a member that names one key twice is the invalid input
        // `ValidationException` describes, and nothing is stored.
        if let Some(repeated) =
            crate::state::first_repeated_element(input.tags.iter().map(|tag| tag.key.as_str()))
        {
            return Err(TagResourceErrorModeled::ValidationException(
                ValidationException {
                    message: Some(crate::state::repeated_element_message("tags", &repeated)),
                },
            )
            .into());
        }

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(TagResourceErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some(crate::state::STORE_UNREACHABLE.to_string()),
                },
            )
            .into());
        };

        let mut store = state.lock();
        store.settle_due_transitions();

        // A `resourceArn` addresses an ACTIVE resource this account holds, whichever KIND
        // of resource it names. A value that is no ARN at all names nothing a lookup could
        // resolve, so it is refused as malformed input rather than as a missing resource; a
        // collection whose deletion has been accepted is on its way out and its tags are no
        // longer addressable, so it answers the same not-found refusal as a resource that
        // was never there.
        if let Err(refusal) = store.resolve_tag_resource_arn(&input.resource_arn) {
            return Err(match refusal {
                crate::state::ResourceArnRefusal::Invalid(message) => {
                    TagResourceErrorModeled::ValidationException(ValidationException {
                        message: Some(message),
                    })
                }
                crate::state::ResourceArnRefusal::NotFound(message) => {
                    TagResourceErrorModeled::ResourceNotFoundException(
                        ResourceNotFoundException {
                            message: Some(message),
                        },
                    )
                }
            }
            .into());
        }

        // The resulting tag set, computed before anything is stored: a key the resource
        // already carries takes the new value (a tag set is a map keyed by `key`), and a
        // key it does not is added.
        let mut tags = store
            .tags_by_arn(&input.resource_arn)
            .cloned()
            .unwrap_or_default();
        for tag in input.tags {
            match tags.iter_mut().find(|stored| stored.key == tag.key) {
                Some(stored) => stored.value = tag.value,
                None => tags.push(tag),
            }
        }
        if tags.len() > crate::state::MAX_TAGS_PER_RESOURCE {
            let resource_type = crate::state::parse_resource_arn(&input.resource_arn)
                .map(|(kind, _)| kind.resource_type())
                .unwrap_or(crate::state::TAGGED_RESOURCE_TYPE);
            return Err(
                TagResourceErrorModeled::ServiceQuotaExceededException(
                    ServiceQuotaExceededException {
                        message: format!(
                            "Maximum number of tags exceeded: {}",
                            crate::state::MAX_TAGS_PER_RESOURCE
                        ),
                        resource_id: Some(input.resource_arn.clone()),
                        resource_type: Some(resource_type.to_string()),
                        service_code: crate::state::ARN_NAMESPACE.to_string(),
                        quota_code: None,
                    },
                )
                .into(),
            );
        }

        // Storing tags REWRITES the resource, so the write instant is what its
        // `lastModifiedDate` reports from here on: the stamping accessor applies it. The ARN
        // resolved above, so the accessor reaches the same record.
        let written_at = crate::state::now_epoch_millis();
        let Some(stored) = store.tags_by_arn_for_write(&input.resource_arn, written_at) else {
            return Err(TagResourceErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::state::resource_not_found_message(
                        &input.resource_arn,
                    )),
                },
            )
            .into());
        };
        *stored = tags;

        // `TagResourceResponse` models no members: what the call produced is the stored
        // tag set, which `ListTagsForResource` reports.
        Ok(TagResourceOutput {})
    }
}
