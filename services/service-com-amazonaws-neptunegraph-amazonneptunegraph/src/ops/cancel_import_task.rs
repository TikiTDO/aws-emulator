impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CancelImportTask<Eng>
{
    type Input = CancelImportTaskInput;
    type Output = CancelImportTaskOutput;
    type Error = CancelImportTaskError;

    const NAME: &'static str = "CancelImportTask";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CANCEL_IMPORT_TASK_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CANCEL_IMPORT_TASK_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(CancelImportTaskErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the neptune-graph store is not mounted on this engine".to_string(),
                },
            )
            .into());
        };

        // An import task lives in exactly one Region, so the Region this request was
        // signed for is part of the lookup: a task of another Region is not found here.
        let region = crate::state::request_region(ctx);
        let (mut store, now) = crate::state::locked_store_now(&state);

        // The lookup settles the transition the clock already made due first, so a
        // task whose load has already stopped is judged on the status it stopped in
        // rather than on the status it was accepted with.
        let Some(task) = store.settled_import_task_mut(&input.task_identifier, &region, now)
        else {
            // The CANCEL operations word the identifier clause of this refusal as the
            // bare `task id`, where the READ operations spell the task's own kind in
            // front of it: one builder per operation in `crate::state`, so neither can
            // inherit the other's wording.
            return Err(CancelImportTaskErrorModeled::ResourceNotFoundException(
                crate::state::import_task_not_found_on_cancel(&input.task_identifier),
            )
            .into());
        };

        // Only a task whose import is still in flight has work to stop: one that has
        // already stopped, and one that is already winding down, is a conflict rather
        // than a second cancellation. The wording is the service's one precondition
        // refusal (`crate::state::import_task_state_conflict`), which fronts no
        // identifier: the task was addressed by one the caller sent.
        let status = task.status;
        if !status.is_cancellable() {
            return Err(CancelImportTaskErrorModeled::ConflictException(
                crate::state::import_task_state_conflict("cancel", status),
            )
            .into());
        }

        // Cancellation is ACCEPTED, not completed: the modelled status of a cancelled
        // task is CANCELLING ("Because you cancelled the import task, cancellation is
        // in progress"), and the clock owes the move to CANCELLED a fixed span later
        // (`crate::state::CANCELLATION_SPAN`), so a caller that reads the task straight
        // after this call still sees it winding down. The elements the load had read
        // are released: a cancelled load writes nothing.
        task.begin_cancellation(now);
        let graph_id = task.graph_id.clone();
        // Report the record that was stored, so this response cannot drift from what a
        // later GetImportTask answers.
        let output = Self::Output::from(&*task);

        // The graph is IMPORTING for as long as the task runs, so stopping the task is
        // what ends that: the graph settles back to AVAILABLE when the cancellation
        // completes rather than when the cancelled load would have finished. A graph
        // whose own transition has already come due, or that was deleted meanwhile, is
        // left alone.
        if let Some(graph) = store.settled_graph_mut(&graph_id, &region, now) {
            if graph.status == crate::state::GraphStatus::Importing {
                graph.begin_transition(
                    crate::state::GraphStatus::Importing,
                    crate::state::GraphStatus::Available,
                    now,
                );
            }
        }

        Ok(output)
    }
}
