//! @op ImportKeyMaterial
//! IMPLEMENTED: imports the key material a caller wrapped under the public key
//! `GetParametersForImport` handed out, making the KMS key a `KeyId` names usable. This
//! is the ONLY file to touch for this operation.
//!
//! The material is really UNWRAPPED, with the private half of the wrapping key pair
//! this store kept against the import token ([`crate::state::unwrap_key_material`]), so
//! what the key ends up holding is exactly the material the caller supplied — and a
//! blob wrapped under some other key, or under a key pair whose token has expired,
//! cannot be imported.
//!
//! Importing applies only to a key created with no key material, so this operation's
//! precondition is the key's ORIGIN, the same gate `GetParametersForImport` and
//! `DeleteImportedKeyMaterial` apply.
//!
//! The material a key of an ASYMMETRIC spec takes is the PRIVATE KEY of the key pair
//! that spec names, as PKCS#8 DER, and it is parsed and checked against the spec before
//! it becomes the key's material ([`crate::state::imported_key_pair`]). Its wrapping is
//! the `RSA_AES` one such a key calls for, which seals an AES key under the RSA public
//! key and the material under that AES key; both steps are really performed.
//!
//! An import never replaces material with the SAME material: `ImportType`
//! `NEW_KEY_MATERIAL` says the material is not one this key already has, and material it
//! does have is refused, so a replayed import is not a second one. New material for a key
//! that already holds some does not become the material the key encrypts under either: it
//! waits in `PENDING_ROTATION` until `RotateKeyOnDemand` completes the rotation it was
//! imported for.
//!
//! Imported material is also the key's OWN material for good: a key that has held
//! material keeps the identity of that material ([`crate::state::Cmk`]'s imported-material
//! history), so the material a later import ADOPTS has to be material the key has held
//! before — after `DeleteImportedKeyMaterial` took it away, after it expired, or when a
//! replica of a multi-Region key is given the material its primary key holds. Material the
//! key has never held is refused `IncorrectKeyMaterialException`, naming the identifier
//! the key expects, and nothing about the key changes; the one import that may carry
//! material the key has never held is the one that STAGES a rotation, which leaves the
//! material the key encrypts under where it is.
