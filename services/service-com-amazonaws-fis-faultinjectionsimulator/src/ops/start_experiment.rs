impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> StartExperiment<Eng> {
    /// Everything this start does to the STORE, under ONE guard that this call takes and
    /// releases: the settle, the idempotency check, the template lookup, the role checks,
    /// the quotas and the experiment this start persists.
    ///
    /// It hands back the `Experiment` the response reports — or the refusal this start
    /// answers with — BESIDE the log records the start left for the destination each
    /// template configured, written by the caller with no guard held (see
    /// [`crate::state::experiment_logs`]). Splitting it out is what keeps the guard out of
    /// `handle`'s future, which has to be `Send`.
    ///
    /// The outcome and the records travel together rather than the records being dropped
    /// on a refusal: the settle below materialises the end of every run that elapsed, so
    /// this call is the one that produced those runs' terminal records whatever it then
    /// answers the caller.
    #[allow(clippy::type_complexity)]
    fn start_under_guard(
        &self,
        input: &StartExperimentInput,
        actions_mode: &str,
        region: &str,
        now: ::std::time::SystemTime,
    ) -> (
        Result<Experiment, StartExperimentError>,
        Vec<crate::state::experiment_logs::PendingDelivery>,
    ) {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return (
                Err(crate::scaffolded::Scaffolded::internal_failure(
                    crate::state::STORE_UNAVAILABLE,
                )),
                Vec::new(),
            );
        };
        let breaches = crate::state::stop_conditions::AlarmBreaches::read(&*self.engine);
        // The resources this start's tag-identified targets resolve against, read out of
        // the stores of the services that OWN them before this store's guard is taken —
        // exactly as the alarm states above are read.
        let resources = crate::state::TargetableResources::read(&*self.engine, region);
        let mut store = state.lock();

        // Settle first: an experiment whose run already elapsed is no longer active, so
        // the quota below is taken against the experiments that are genuinely running
        // and not against ones the clock finished before this call.
        store.settle_experiments(now, &breaches);

        let outcome =
            self.mint_under_guard(&mut store, input, actions_mode, region, now, &resources);

        // Every record this call made true — the settle above for a run that elapsed, and
        // what a start it accepted parked on the experiment it minted — drained here, on
        // the refusal paths as much as on the accepted one.
        let deliveries = store.take_pending_log_deliveries();
        (outcome, deliveries)
    }

    /// The experiment this start PERSISTS, on a store the caller has already settled and
    /// holds the guard for: the idempotency check, the template lookup, the role checks,
    /// the quotas and the record itself — or the refusal the start answers with.
    ///
    /// It drains no outbox: [`Self::start_under_guard`] does that once, for whatever this
    /// answers.
    #[allow(clippy::too_many_arguments)]
    fn mint_under_guard(
        &self,
        store: &mut crate::state::ComAmazonawsFisFaultinjectionsimulatorState,
        input: &StartExperimentInput,
        actions_mode: &str,
        region: &str,
        now: ::std::time::SystemTime,
        resources: &crate::state::TargetableResources,
    ) -> Result<Experiment, StartExperimentError> {
        // The token is `@idempotencyToken`: replaying it with the SAME request reports
        // the experiment the first call started, while reusing it for a different request
        // is the parameter mismatch FIS answers with `ConflictException` rather than
        // reporting another template's run. "The same request" is decided over what the
        // start PERSISTS — the resolved actions mode and the tag map the experiment is
        // tagged with — so a retry that spells a default out, or that normalises an
        // omitted map to an empty one, is still a retry of the call that started the
        // experiment it describes (see [`crate::state::start_experiment_fingerprint`]).
        let fingerprint = crate::state::start_experiment_fingerprint(input, actions_mode);
        match store.replayed(
            crate::state::IdempotentResource::Experiment,
            &input.client_token,
            &fingerprint,
        ) {
            crate::state::TokenReplay::Replay(id) => {
                if let Some(record) = store.experiments.get(&id) {
                    // Reported with every write the clock owed it materialised: the settle
                    // the caller performed, and the report generation `handle`
                    // materialised before taking this guard.
                    return Ok(record.to_experiment());
                }
            }
            crate::state::TokenReplay::Mismatch => {
                return Err(StartExperimentErrorModeled::ConflictException(
                    crate::state::token_conflict(&input.client_token),
                )
                .into())
            }
            crate::state::TokenReplay::Fresh => {}
        }

        // The account's safety lever keeps experiments from starting for as long as it is
        // engaged, which is what FIS documents engaging it as doing — so a start is
        // refused while it holds, and nothing is minted for it. Asked AFTER the
        // idempotency replay above: a retry of a start this service already accepted
        // reports that experiment rather than being refused for a lever engaged since.
        let lever_status = store.settled_safety_lever(now).status;
        if lever_status.holds_experiments() {
            return Err(StartExperimentErrorModeled::ConflictException(
                crate::state::safety_lever_engaged_refusal(lever_status),
            )
            .into());
        }

        // The experiment is built from the PERSISTED template, so it carries what that
        // template holds and not what any request said.
        let Some(template) = store
            .experiment_templates
            .get(&input.experiment_template_id)
            .cloned()
        else {
            return Err(StartExperimentErrorModeled::ResourceNotFoundException(
                crate::state::template_not_found(),
            )
            .into());
        };

        // A template's account targeting and the target account configurations it holds
        // state ONE thing between them — which accounts the experiment runs in — so a
        // template that targets multiple accounts and names none of them describes a run
        // this call cannot carry out, and is refused before any experiment is minted (see
        // [`crate::state::multi_account_configuration_refusal`]).
        if let Some(refusal) = crate::state::multi_account_configuration_refusal(&template) {
            return Err(StartExperimentErrorModeled::ValidationException(refusal).into());
        }

        // FIS runs the experiment as the template's role, so it checks up front that the
        // role lets it: a start it could never carry out is refused here instead of
        // producing an experiment id for a run that cannot happen. The IAM store is a
        // different store in the same engine, and no IAM handler reads this one, so
        // holding both guards cannot cycle.
        let Some(iam) = crate::state::iam_state(&*self.engine) else {
            return Err(crate::scaffolded::Scaffolded::internal_failure(
                crate::state::STORE_UNAVAILABLE,
            ));
        };
        // One guard for both things the IAM store is READ for here: whether the TEMPLATE's
        // role lets FIS assume it at all, and which policy documents are in force on each
        // role the actions are performed under ([`acting_roles`] — the template's own role
        // for a single-account run, and the role each targeted account's configuration
        // names for a multi-account one). Everything is taken out of the guard as owned
        // values, so the guard is dropped before anything is decided from them — the IAM
        // store is not locked while this handler thinks.
        let acting_roles = crate::state::action_permissions::acting_roles(&template);
        let (trust_refusal, acting_documents) = {
            let iam = iam.lock();
            let documents: Vec<(String, Option<Vec<String>>)> = acting_roles
                .into_iter()
                .map(|role_arn| {
                    let documents =
                        crate::state::action_permissions::role_documents(&role_arn, &iam);
                    (role_arn, documents)
                })
                .collect();
            (
                crate::state::role_trust_refusal(&template.role_arn, &iam),
                documents,
            )
        };
        if let Some(refusal) = trust_refusal {
            return Err(StartExperimentErrorModeled::ValidationException(refusal).into());
        }

        // The published active-experiments quota, which creates no experiment when it is
        // reached.
        if store.active_experiments() >= crate::state::MAX_ACTIVE_EXPERIMENTS {
            return Err(StartExperimentErrorModeled::ServiceQuotaExceededException(
                crate::state::active_quota_exceeded(),
            )
            .into());
        }

        if store.experiments.len() >= crate::state::MAX_EXPERIMENTS {
            return Err(StartExperimentErrorModeled::ServiceQuotaExceededException(
                crate::state::store_full("experiment", crate::state::MAX_EXPERIMENTS),
            )
            .into());
        }

        // The experiment's own name, minted once every refusal is behind us: the actions
        // are decided against it as well as against the resources their targets name,
        // because the FIS-namespaced grants of the inject-api family are scoped to the
        // EXPERIMENT (see [`crate::state::action_permissions::action_resources`]).
        let id = store.mint_experiment_id();
        let arn = crate::state::experiment_arn(region, &id);

        // Whether those documents SHOW a role cannot perform an action's own API calls.
        // Decided after the quotas above, so a start this service refuses outright pays
        // nothing for it, and from the documents already read rather than from the store.
        // It does NOT refuse the start — an experiment AWS starts under an
        // under-privileged role is accepted and then FAILS, which is the attribution a
        // client reads off its state — so it is carried onto the record and spent when the
        // run reaches its end.
        //
        // The question is asked about the actions this run CARRIES OUT and no others: an
        // action the experiment options skip is never run under the role, so nothing the
        // role may not do can be attributed to it. Under `actionsMode: skip-all` that is
        // every action, so no permission failure is possible at all. A role the account's
        // IAM store shows nothing about leaves the run to go ahead, which is why a run is
        // only failed for a role whose documents were read.
        let plan = crate::state::plan_run(&template, actions_mode, resources);
        let permission_failure = acting_documents.into_iter().find_map(|(role_arn, documents)| {
            documents.and_then(|documents| {
                crate::state::action_permissions::permission_failure(
                    &role_arn,
                    &plan.carried_out,
                    &template.targets,
                    &arn,
                    &documents,
                )
            })
        });

        let record = crate::state::ExperimentRecord::from_template(
            id.clone(),
            arn,
            &template,
            actions_mode,
            input.tags.clone(),
            now,
            permission_failure,
            resources,
        );
        let experiment = record.to_experiment();
        store.experiments.insert(id.clone(), record);
        store.remember_token(
            crate::state::IdempotentResource::Experiment,
            &input.client_token,
            &id,
            &fingerprint,
        );

        // Every record the START of this run makes true — the experiment itself and what
        // its targets resolved to — is already parked on the record `from_template` built,
        // for the caller to drain beside anything the settle materialised for a run
        // already under way.
        Ok(experiment)
    }
}

impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for StartExperiment<Eng>
{
    type Input = StartExperimentInput;
    type Output = StartExperimentOutput;
    type Error = StartExperimentError;

    const NAME: &'static str = "StartExperiment";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::START_EXPERIMENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::START_EXPERIMENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `actionsMode` is enum-typed, which the boundary validator does not check, and
        // it is persisted on the experiment — so a value `ActionsMode` does not admit is
        // refused here rather than stored.
        let actions_mode = match crate::state::resolve_actions_mode(
            input
                .experiment_options
                .as_ref()
                .and_then(|options| options.actions_mode.as_deref()),
        ) {
            Ok(mode) => mode,
            Err(refusal) => {
                return Err(StartExperimentErrorModeled::ValidationException(refusal).into())
            }
        };

        // The tags this start would persist onto the experiment: a map's KEY target is not
        // reached by the boundary validator (its VALUE target is), so `TagKey`'s modelled
        // bounds are enforced here — before the store is reached, so a refused start mints
        // no experiment, consumes no token and leaves no out-of-bounds key for a later read
        // to report.
        if let Some(refusal) = crate::state::map_keys_refusal(
            "tags",
            crate::state::TAG_KEY_BOUNDS,
            input.tags.iter().flatten().map(|(key, _)| key.as_str()),
        ) {
            return Err(StartExperimentErrorModeled::ValidationException(refusal).into());
        }

        let region = crate::state::request_region(ctx.parts());
        let now = ::std::time::SystemTime::now();

        // The action effects the clock has made due for every run under way, carried out on
        // the services that own the targeted resources before anything is reported. This
        // call settles every experiment (its quota is taken against the runs genuinely under
        // way), so it reaches every action the clock has got to and owes what each one does
        // ([`crate::state::action_execution`]).
        crate::state::materialise_action_effects(&*self.engine, now);

        // The report generation every ENDED experiment owes the clock. The start below
        // SETTLES every experiment — its active-experiment quota is taken against the runs
        // genuinely under way — so it materialises the end of every run that elapsed, which
        // is the event that makes the generation due, and owes the second write for each of
        // them: the report object is written to the configured output and a later read
        // reports the generation that happened. That covers the experiment a replay of this
        // token reports, so the replay reports the same report state as any other read at
        // this instant. It takes the store lock itself and holds it across no call, so it
        // runs before the start below takes its guard; a run that has not ended, and an
        // experiment this call is about to mint, owe nothing.
        crate::state::materialise_experiment_reports(&*self.engine, ctx, &region, now).await;

        let (outcome, deliveries) = self.start_under_guard(&input, &actions_mode, &region, now);

        // The run's first records, written with the state guard released, to the
        // destination the template configured (see [`crate::state::experiment_logs`]) —
        // beside the records the settle inside the start materialised for a run that had
        // elapsed, which this call owes the destination whether or not it accepts the
        // start.
        crate::state::experiment_logs::deliver(ctx, &region, deliveries).await;

        // Only now is the refusal, if there was one, the caller's answer: the write this
        // call owed the destination has already happened.
        let experiment = outcome?;
        Ok(StartExperimentOutput {
            experiment: Some(experiment),
        })
    }
}
