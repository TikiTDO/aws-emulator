//! @op StartExperiment
//! Starts an experiment from a persisted experiment template: mints the experiment's
//! `id` and `arn`, COPIES the template's `roleArn`, targets, actions, stop conditions and
//! configuration onto the new record, stamps `creationTime` / `startTime` and persists it
//! with `state.status` `initiating`.
//!
//! A template that configures `logConfiguration` makes the run DELIVER its records to the
//! destination it names, so this call also writes the records the start makes true — the
//! experiment and what its targets resolved to — to the emulator's own CloudWatch Logs
//! and Amazon S3 services. See [`crate::state::experiment_logs`].
//!
//! The move to `running`, the span the run lasts and the terminal status it earns after it
//! are owed to the clock rather than to this call, so a caller reading the experiment
//! immediately still sees it initiating; see [`crate::state::ExperimentRecord::settle`].
//!
//! The experiment's targets are RESOLVED here, once: a target that names its resources
//! resolves to the ones it named, and one that identifies them by `resourceTags` resolves
//! to the resources of its `resourceType` the services that OWN them hold in this same
//! engine carrying those tags, narrowed by the target's `filters` and scoped by its
//! `selectionMode` — see [`crate::state::target_resolution`]. What that resolution came to
//! is what `ListExperimentResolvedTargets` reports and what the run's actions act on.
//!
//! A request whose `@idempotencyToken` already started an experiment REPORTS that
//! experiment and starts nothing, so it is a READ of it: every write the clock owes that
//! experiment is materialised before it is reported — the settle, and the report
//! generation an ENDED experiment that configured one owes. This call SETTLES every
//! experiment (its quota is taken against the runs genuinely under way), so it materialises
//! the end of every run that elapsed and owes that second write for each of them
//! ([`crate::state::materialise_experiment_reports`]) — so this replay and a
//! `GetExperiment` at the same instant report the same status and the same
//! `experimentReport`.
//! What this call decides about the run is what the account's IAM store SHOWS about it:
//! whether the template's role lets FIS assume it (a start it could never carry out is
//! refused), and whether that role is allowed to perform the API calls the actions this run
//! CARRIES OUT make — an action it is not allowed to perform does not refuse the start, it
//! makes the run end `failed` with an insufficient-privileges reason, which is what AWS
//! reports for it. WHICH actions the run carries out is what the experiment options decide
//! ([`crate::state::plan_run`]): `experimentOptions.actionsMode` `skip-all` carries out
//! none of them, and the template's `emptyTargetResolutionMode` decides what an empty
//! target resolution does — skip the actions that name such a target, or fail the run.
//! A template id naming no record answers `ResourceNotFoundException`
//! (HTTP 404); a template whose role does not let FIS assume it, one that targets
//! MULTIPLE accounts while holding no target account configuration to name them, and a
//! request carrying a tag key outside `TagKey`'s modelled bounds answer
//! `ValidationException` (HTTP 400); a start beyond the published active-experiments quota
//! answers `ServiceQuotaExceededException` (HTTP 402); and the `@idempotencyToken` either
//! replays the experiment it already started or, when the request differs from the one it
//! belongs to, answers `ConflictException` (HTTP 409).
//!
