/// What this call did with the node one identifier named.
enum Outcome {
    /// The node's replacement was initiated, so the identifier is reported as successful.
    Replaced,
    /// No node of the cluster answers to the identifier.
    NotFound,
    /// A replacement is already in flight on the node.
    InUse,
    /// The node is mid-change, so it cannot take a replacement right now.
    InvalidStatus,
}

/// Start the replacement of the node an identifier resolved to, when its state admits
/// one, and answer what this call reports for that identifier.
///
/// The ONE decision both identifier lists are classified by, so the same node named by
/// its instance id and by its logical id is never judged two different ways.
fn replace(node: Option<&mut crate::state::ClusterNode>, now: ::std::time::SystemTime) -> Outcome {
    match node {
        None => Outcome::NotFound,
        Some(node) if node.is_replacing() => Outcome::InUse,
        Some(node) if !node.accepts_replacement() => Outcome::InvalidStatus,
        Some(node) => {
            node.begin_replacement(now);
            Outcome::Replaced
        }
    }
}

