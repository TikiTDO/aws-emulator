/// Which constraint a hyperparameter range breaks, of the rules the model's own
/// constraints cannot express.
///
/// `MinValue`/`MaxValue` are modelled as free strings (`pattern .*`), so the type the
/// range declares and the ordering of its two bounds are rules the service enforces
/// itself: an integer range carries integers, a continuous range carries finite
/// floating-point values, and in both the minimum may not exceed the maximum.
#[derive(Clone, Copy, PartialEq, Eq)]
enum RangeViolation {
    IntegerBoundsReversed,
    IntegerBoundsNotIntegers,
    ContinuousBoundsReversed,
    ContinuousBoundsNotNumbers,
    ContinuousBoundsNotFinite,
}

impl RangeViolation {
    /// What the refusal states after naming the offending ranges: the constraint the
    /// range kind requires, then the value to send instead.
    ///
    /// The sentence names the MEMBERS and the requirement, never a parsed number: the
    /// values the caller sent are its own, and re-rendering them (`1.0` read back as `1`)
    /// would report something it did not write.
    fn constraint(self) -> &'static str {
        match self {
            Self::IntegerBoundsReversed => {
                "For integer parameter ranges, the value of MinValue must be smaller than \
                 the value of MaxValue. Specify a value for MinValue that is smaller than \
                 the value of MaxValue."
            }
            Self::IntegerBoundsNotIntegers => {
                "For integer parameter ranges, the values of MinValue and MaxValue must be \
                 integers. Specify integer MinValue and MaxValue values."
            }
            Self::ContinuousBoundsReversed => {
                "For continuous parameter ranges, the value of MinValue must be smaller \
                 than the value of MaxValue. Specify a value for MinValue that is smaller \
                 than the value of MaxValue."
            }
            Self::ContinuousBoundsNotNumbers => {
                "For continuous parameter ranges, the values of MinValue and MaxValue must \
                 be numbers. Specify numeric MinValue and MaxValue values."
            }
            Self::ContinuousBoundsNotFinite => {
                "For continuous parameter ranges, the values of MinValue and MaxValue must \
                 be finite numbers. Specify finite MinValue and MaxValue values."
            }
        }
    }
}

/// Every range of `ranges` whose bounds are not searchable: the constraint it breaks and
/// the hyperparameter it names, in the order the request lists them.
fn range_violations(ranges: &[&ParameterRanges]) -> Vec<(RangeViolation, String)> {
    let mut violations = Vec::new();
    for range in ranges {
        for integer in range.integer_parameter_ranges.iter().flatten() {
            let (Ok(min), Ok(max)) = (
                integer.min_value.trim().parse::<i64>(),
                integer.max_value.trim().parse::<i64>(),
            ) else {
                violations.push((
                    RangeViolation::IntegerBoundsNotIntegers,
                    integer.name.clone(),
                ));
                continue;
            };
            if min > max {
                violations.push((RangeViolation::IntegerBoundsReversed, integer.name.clone()));
            }
        }
        for continuous in range.continuous_parameter_ranges.iter().flatten() {
            let (Ok(min), Ok(max)) = (
                continuous.min_value.trim().parse::<f64>(),
                continuous.max_value.trim().parse::<f64>(),
            ) else {
                violations.push((
                    RangeViolation::ContinuousBoundsNotNumbers,
                    continuous.name.clone(),
                ));
                continue;
            };
            if !min.is_finite() || !max.is_finite() {
                violations.push((
                    RangeViolation::ContinuousBoundsNotFinite,
                    continuous.name.clone(),
                ));
                continue;
            }
            if min > max {
                violations.push((
                    RangeViolation::ContinuousBoundsReversed,
                    continuous.name.clone(),
                ));
            }
        }
    }
    violations
}

/// Why the hyperparameter ranges this request searches over are not valid, if they are
/// not — the 400 `ValidationException`'s message.
///
/// The refusal is built from the REQUEST: it names every range that breaks the first
/// constraint broken, as a bracketed comma-separated list of the hyperparameter names the
/// request gave them, and then states that constraint. So a client extracts the offending
/// hyperparameters from the list it sent rather than parsing prose, and a request with
/// several bad ranges is answered once with all of them instead of one per round trip.
fn parameter_ranges_refusal(ranges: &[&ParameterRanges]) -> Option<String> {
    let violations = range_violations(ranges);
    let (broken, _) = *violations.first()?;
    let names: Vec<&str> = violations
        .iter()
        .filter(|(violation, _)| *violation == broken)
        .map(|(_, name)| name.as_str())
        .collect();
    Some(format!(
        "The hyperparameter ranges [{}] are not valid. {}",
        names.join(","),
        broken.constraint()
    ))
}

/// Why this request is not a tuning job the service can start, if it is not — every rule
/// the model's own constraints cannot express, checked over the whole request.
fn validation_refusal(input: &CreateHyperParameterTuningJobInput) -> Option<String> {
    let config = &input.hyper_parameter_tuning_job_config;

    // The two members are alternatives: one definition, or a list of them. The model
    // makes both optional, so "exactly one" is this operation's own rule.
    match (
        input.training_job_definition.is_some(),
        input.training_job_definitions.is_some(),
    ) {
        (false, false) => {
            return Some(
                "Either TrainingJobDefinition or TrainingJobDefinitions must be provided."
                    .to_string(),
            )
        }
        (true, true) => {
            return Some(
                "Only one of TrainingJobDefinition and TrainingJobDefinitions may be provided."
                    .to_string(),
            )
        }
        _ => {}
    }

    let ranges = parameter_ranges(input);
    if let Some(message) = parameter_ranges_refusal(&ranges) {
        return Some(message);
    }

    // The bound is on the hyperparameters ONE training job definition searches: the
    // tuning job config's ranges plus that definition's own. `ParameterRanges`' doc says
    // the figure the model states per list is "also the maximum for the hyperparameter
    // tuning job itself", and a request carrying several definitions tunes a different
    // algorithm in each, so the counts are summed per definition rather than across them
    // — the narrower reading, so a multi-algorithm request the service accepts is not
    // refused here.
    let config_searched = config
        .parameter_ranges
        .as_ref()
        .map_or(0, searched_hyperparameters);
    let searched = input
        .training_job_definition
        .iter()
        .chain(input.training_job_definitions.iter().flatten())
        .map(|definition| {
            config_searched
                + definition
                    .hyper_parameter_ranges
                    .as_ref()
                    .map_or(0, searched_hyperparameters)
        })
        .max()
        .unwrap_or(config_searched);
    if searched > crate::state::MAX_SEARCHED_HYPERPARAMETERS {
        return Some(format!(
            "A hyperparameter tuning job can search over at most {} hyperparameters, but {} \
             integer, continuous and categorical ranges were specified.",
            crate::state::MAX_SEARCHED_HYPERPARAMETERS,
            searched
        ));
    }

    // `HyperParameterTuningJobStrategyType`'s doc for Grid: the strategy evaluates every
    // combination of the values given, so there is nothing to enumerate for a numeric
    // range — a grid search tunes categorical hyperparameters only.
    if config.strategy == STRATEGY_GRID {
        let numeric = ranges.iter().any(|range| {
            searched_hyperparameters(range)
                > range
                    .categorical_parameter_ranges
                    .as_ref()
                    .map_or(0, Vec::len)
        });
        if numeric {
            return Some(format!(
                "The {STRATEGY_GRID} strategy searches categorical hyperparameters only, but \
                 integer or continuous parameter ranges were specified."
            ));
        }
    }

    if config.strategy == STRATEGY_HYPERBAND {
        // `TrainingJobEarlyStoppingType`'s doc: because Hyperband has its own advanced
        // internal early stopping mechanism, the member must be `Off` to use Hyperband.
        if config.training_job_early_stopping_type.as_deref() == Some(EARLY_STOPPING_AUTO) {
            return Some(format!(
                "TrainingJobEarlyStoppingType must be Off when the tuning strategy is \
                 {STRATEGY_HYPERBAND}, which has its own internal early stopping."
            ));
        }
    }

    // `HyperbandStrategyConfig`'s two bounds are the resource a training job starts with
    // and the most it may use, so the minimum may not exceed the maximum.
    if let Some(hyperband) = config
        .strategy_config
        .as_ref()
        .and_then(|strategy| strategy.hyperband_strategy_config.as_ref())
    {
        if let (Some(min), Some(max)) = (hyperband.min_resource, hyperband.max_resource) {
            if min > max {
                return Some(format!(
                    "HyperbandStrategyConfig has MinResource {min}, which is greater than its \
                     MaxResource {max}."
                ));
            }
        }
    }

    // A parallel bound is drawn from the total the job may launch, so it cannot exceed
    // it. `handle` runs `limit_refusal` before this function, so a request past BOTH the
    // published quota and its own total is answered as the limit failure it is.
    if let Some(total) = config.resource_limits.max_number_of_training_jobs {
        let parallel = config.resource_limits.max_parallel_training_jobs;
        if parallel > total {
            return Some(format!(
                "MaxParallelTrainingJobs {parallel} is greater than MaxNumberOfTrainingJobs \
                 {total}: a tuning job cannot run more training jobs at once than it may \
                 launch in total."
            ));
        }
    }

    // Rules a single training job definition has to hold, applied to every definition
    // the request carries rather than to the first one.
    for definition in input
        .training_job_definition
        .iter()
        .chain(input.training_job_definitions.iter().flatten())
    {
        let named = definition
            .definition_name
            .as_deref()
            .map_or(String::new(), |name| format!(" \"{name}\""));

        // `StoppingCondition$MaxWaitTimeInSeconds`' doc: the wait covers the time spent
        // waiting for capacity PLUS the time the job may run, so "it must be equal to or
        // greater than MaxRuntimeInSeconds".
        if let (Some(wait), Some(runtime)) = (
            definition.stopping_condition.max_wait_time_in_seconds,
            definition.stopping_condition.max_runtime_in_seconds,
        ) {
            if wait < runtime {
                return Some(format!(
                    "The training job definition{named} has MaxWaitTimeInSeconds {wait}, which \
                     is less than its MaxRuntimeInSeconds {runtime}."
                ));
            }
        }

        // `HyperParameterTrainingJobDefinition$ResourceConfig`'s doc names
        // `HyperParameterTuningResourceConfig` as the alternative to use instead of it, so
        // the two are alternatives rather than a pair.
        if definition.resource_config.is_some()
            && definition.hyper_parameter_tuning_resource_config.is_some()
        {
            return Some(format!(
                "The training job definition{named} may carry only one of ResourceConfig and \
                 HyperParameterTuningResourceConfig."
            ));
        }
    }

    // The ML compute each training job definition would RUN on: a definition whose
    // `ResourceConfig` names no instance type with a count greater than zero names no
    // compute to launch at all. The reading is the `ResourceConfig` SHAPE's own
    // ([`crate::state::resource_config_refusal`]), so this operation and
    // `CreateTrainingJob` hold one configuration to the same rule.
    for definition in input
        .training_job_definition
        .iter()
        .chain(input.training_job_definitions.iter().flatten())
    {
        if let Some(config) = definition.resource_config.as_ref() {
            if let Some(refusal) = crate::state::resource_config_refusal(config) {
                return Some(refusal);
            }
        }
    }

    None
}

/// Why the capacity this request asks for is past an account-level quota, if it is — the
/// modelled `ResourceLimitExceeded`'s message.
///
/// The quotas are the ACCOUNT's published quotas on the training jobs a tuning job runs,
/// and they are evaluated with the parallel one FIRST: a request is classified against
/// the dimension SageMaker weighs first, so a request that is legal for one dimension and
/// illegal for the other is answered about the one that actually blocks it.
///
/// `in_use` is what the account is using of those quotas now — see
/// `crate::state::ComAmazonawsSagemakerSagemakerState::parallel_training_jobs_in_use`,
/// which is where it is counted — because the message states the utilisation beside the
/// limit, not just the member of the request that exceeded it.
fn limit_refusal(limits: &ResourceLimits, in_use: usize) -> Option<String> {
    let quotas = [
        (
            crate::state::PARALLEL_TRAINING_JOBS_PER_TUNING_JOB_QUOTA_NAME,
            limits.max_parallel_training_jobs,
            crate::state::MAX_PARALLEL_TRAINING_JOBS_PER_TUNING_JOB,
        ),
        (
            crate::state::TRAINING_JOBS_PER_TUNING_JOB_QUOTA_NAME,
            limits.max_number_of_training_jobs.unwrap_or(0),
            crate::state::MAX_TRAINING_JOBS_PER_TUNING_JOB,
        ),
    ];
    quotas
        .into_iter()
        .find(|(_, requested, quota)| requested > quota)
        .map(|(quota_name, requested, quota)| {
            crate::state::account_quota_exceeded(
                quota_name,
                crate::state::TRAINING_JOBS_UNIT,
                i64::from(quota),
                in_use as i64,
                i64::from(requested),
            )
        })
}

