                record.failed.push(failure(
                    spec,
                    ERROR_INCOMPATIBLE_INSTANCE_TYPES,
                    format!(
                        "Instance group {:?} runs {admitted:?}.",
                        group.instance_group_name
                    ),
                ));
                continue;
