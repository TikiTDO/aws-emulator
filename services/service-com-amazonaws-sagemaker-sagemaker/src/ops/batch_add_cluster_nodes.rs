                record.failed.push(failure(
                    spec,
                    ERROR_INSTANCE_GROUP_NOT_FOUND,
                    format!(
                        "Cluster {} has no instance group {:?}.",
                        cluster.arn, spec.instance_group_name
                    ),
                ));
                continue;
