/// The bytes the reference resolves to IN AMAZON S3, or the reason it is not
/// readable — an `InvalidContentLocation` for the caller, and this string for the
/// access record.
///
/// The object belongs to S3, not to this service: the model documents
/// `S3Reference` as "Amazon S3 object representing the updated message content, in
/// MIME format" (`smithy_query(query="shape", shape="S3Reference")`), so what a
/// client uploaded with `PutObject` is what this reads, through
/// [`crate::state::referenced_object`]. Nothing about the reference is echoed into
/// the message: the bytes come out of the stored object.
///
/// Four conditions make an object unreadable, and the model's own
/// `InvalidContentLocation` documentation
/// (`smithy_query(query="doc", shape="InvalidContentLocation")`) names three of
/// them: "You made the request in a region other than your S3 bucket region", "The
/// S3 bucket owner is not the same as the calling AWS account" and "You have an
/// incomplete or missing S3 bucket policy" — the last because the content is
/// fetched by WorkMail itself, as its own service principal, which only the
/// bucket's resource policy can authorize ([`crate::state::bucket_policy`]). The
/// fourth is the reference naming no object at all — no such bucket, no such key, a
/// key whose current version is a delete marker, or a versioned reference naming a
/// version that is not stored, since the model documents `objectVersion` as
/// selecting one version of the object.
fn resolve_content<Eng: ::std::marker::Send + ::std::marker::Sync + 'static>(
    engine: &Eng,
    reference: &S3Ref,
    request_region: &str,
) -> Result<Vec<u8>, Unreadable> {
    let Some(resolved) =
        crate::state::referenced_object(engine, reference, request_region, MAX_CONTENT_OCTETS)
    else {
        return Err(Unreadable::S3Unavailable);
    };
    match resolved {
        crate::state::ReferencedObject::Content(bytes) => Ok(bytes),
        crate::state::ReferencedObject::NoObject => Err(Unreadable::Location(
            "no object is stored at that bucket, key and object version".to_string(),
        )),
        crate::state::ReferencedObject::OtherRegion { bucket_region } => {
            Err(Unreadable::Location(format!(
                "the bucket is in region {bucket_region} but the request was made in region \
                 {request_region}"
            )))
        }
        crate::state::ReferencedObject::OtherAccount => Err(Unreadable::Location(format!(
            "the bucket is not one the calling AWS account {} holds",
            ::engine::emulator_account_id()
        ))),
        crate::state::ReferencedObject::NotPermitted => Err(Unreadable::Location(
            "the bucket's policy does not grant WorkMail read access to the object".to_string(),
        )),
        crate::state::ReferencedObject::Oversize { octets } => Err(Unreadable::Oversize(octets)),
    }
}

/// Why a reference did not yield content this operation can work on.
enum Unreadable {
    /// The object is not readable at all, and this is the reason for the access
    /// record — the model's `InvalidContentLocation` for the caller.
    Location(String),
    /// The object is readable, and carries more octets than [`MAX_CONTENT_OCTETS`],
    /// the ceiling this emulator reads content up to. A statement about the
    /// content, so it is answered as unusable content and not as a location
    /// failure.
    Oversize(usize),
    /// Amazon S3's own store is not reachable at all, so whether the reference
    /// resolves is not known — see [`s3_store_unavailable`]. Not a location
    /// failure: nothing was learned about the object.
    S3Unavailable,
}

/// Headers RFC 5322 §3.6 permits at most once in a message.
///
/// The model's `RawMessageContent` documentation
/// (`smithy_query(query="doc", shape="RawMessageContent")`) requires that "certain
/// unique headers can only appear once"; RFC 5322 §3.6 is the list of which ones.
const SINGLETON_HEADERS: &[&str] = &[
    "date",
    "from",
    "sender",
    "reply-to",
    "to",
    "cc",
    "bcc",
    "message-id",
    "in-reply-to",
    "references",
    "subject",
];

/// Headers RFC 5322 §3.6 requires every message to carry, lowercased.
///
/// The model's `RawMessageContent` documentation
/// (`smithy_query(query="doc", shape="RawMessageContent")`) requires that "the
/// message must contain all the required header fields"; it names no field, and
/// RFC 5322 §3.6 — the same section that states which headers may appear only
/// once, above — is the list of which ones: `orig-date` (`Date`) and `from`
/// (`From`) are the two every message must have, and both must appear exactly
/// once, which [`SINGLETON_HEADERS`] is the other half of.
const REQUIRED_HEADERS: &[&str] = &["date", "from"];

/// Headers an update may not change, lowercased.
///
/// The model's `RawMessageContent` documentation requires that "the value of
/// immutable headers must remain unchanged"; it names no header, and what makes a
/// header unchangeable by this API is that the mail system, not the message's
/// author, set it before the message reached the flow: `Message-ID` is assigned by
/// the originating system and identifies this one message (RFC 5322 §3.6.4), and
/// the `Received` fields are the trace each relay that has already handled the
/// message added, which a later handler must not alter or reorder (RFC 5321 §4.4,
/// RFC 5322 §3.6.7). Everything else in the header block — the addresses, the
/// subject, the content type, the body — is what an update exists to rewrite.
const IMMUTABLE_HEADERS: &[&str] = &["message-id", "received"];

/// The longest a line of a message may be, including its CRLF.
///
/// From the model's `RawMessageContent` documentation: "Per RFC 5321, the maximum
/// length of each line of text, including the <CRLF>, must not exceed 1,000
/// characters."
const MAX_LINE_OCTETS: usize = 1000;

/// The most content this emulator will read, as a guard on the process rather
/// than a service rule.
///
/// Not a fidelity limit: WorkMail's own raw-message quota is in neither the model
/// nor its documentation, so this is deliberately set far above any size a mail
/// system accepts (every AWS mail service's documented maximum is a few tens of
/// MiB), and therefore refuses nothing the real service takes. It exists because
/// the scans below are linear in the content and run inside one request.
const MAX_CONTENT_OCTETS: usize = 128 * 1024 * 1024;

/// The most of a message's HEADER BLOCK this emulator will read — the second guard
/// on the process, for the same reason as [`MAX_CONTENT_OCTETS`] and with a bound
/// of its own because the block is the one part of the content this operation
/// takes APART into fields: reading it costs memory per line and not only per
/// octet, and it is the caller who decides how many lines stand before the empty
/// line that ends the block.
///
/// Not a fidelity limit, and far above any header block a mail system accepts — a
/// message carries tens of header fields and a few KiB of them, and a widely
/// deployed mail transfer agent's default ceiling is around a hundred KiB — so it
/// refuses nothing the real service takes. Content beyond it is refused as
/// unusable, with a message that says the ceiling is this emulator's.
const MAX_HEADER_BLOCK_OCTETS: usize = 1024 * 1024;

/// How many header lines this emulator will read out of one header block, the
/// other half of the guard [`MAX_HEADER_BLOCK_OCTETS`] states.
const MAX_HEADER_FIELDS: usize = 10_000;

/// One header field of a message: its ASCII-lowercased name and its value, both
/// as the OCTETS the message carries — the pair [`header_field`] reads off a line.
type HeaderField = (Vec<u8>, Vec<u8>);

/// A message's header block: its fields in the order the message carries them,
/// which is what [`header_fields`] reads and [`validate_mime`] hands back.
type HeaderBlock = Vec<HeaderField>;

/// Whether `content` is usable MIME content on its own, answering why it is not
/// when it is not — the `message` of `MessageRejected`, which the model documents
/// as carrying "more information about what caused the error".
///
/// Every rule is one the model's `RawMessageContent` documentation states:
///
/// 1. the object must carry content at all, and that content must begin with a
///    header field, so the message HAS a header block;
/// 2. that header block must carry every field in [`REQUIRED_HEADERS`] — "The
///    message must contain all the required header fields";
/// 3. no line may exceed [`MAX_LINE_OCTETS`] including its CRLF;
/// 4. a header from [`SINGLETON_HEADERS`] may not appear twice.
///
/// The one remaining documented criterion is not a property of the content alone:
/// "the value of immutable headers must remain unchanged" is a COMPARISON against
/// the message in transit, and [`immutable_header_conflict`] decides it where that
/// message is reachable.
///
/// Two documented criteria are deliberately NOT enforced, because neither the
/// model nor the service's documentation says what to enforce them against: that
/// "each part of a multipart MIME message" is "formatted properly" (the
/// documentation states no rule for what makes a part malformed, and a message is
/// not refused for failing a rule this emulator invented) and the set of
/// attachment content types Amazon SES supports (an external appendix).
///
/// One refusal is not a fidelity rule but a guard on this process, and says so in
/// the message it produces: content beyond [`MAX_CONTENT_OCTETS`], or a header
/// block beyond [`MAX_HEADER_BLOCK_OCTETS`] or [`MAX_HEADER_FIELDS`]. Those
/// ceilings sit far above anything a mail system accepts, so they refuse nothing
/// the real service takes. What they buy is that every scan here is bounded: the
/// ones before them are linear in the content and allocate nothing, and the walk
/// that reads the block ([`bounded_header_block`]) stops at them, so the fields
/// are taken apart out of a block that is already inside them.
///
/// The fields this read come back, so the content is taken apart ONCE per request:
/// the comparison [`immutable_header_conflict`] makes against the message in
/// transit reads the update's fields from what this returns.
fn validate_mime(content: &[u8]) -> Result<HeaderBlock, String> {
    if content.is_empty() {
        return Err(
            "The message content is empty; a message must contain the required header fields."
                .to_string(),
        );
    }

    if content.len() > MAX_CONTENT_OCTETS {
        return Err(oversize_content(content.len()));
    }

    if !starts_with_header_field(content) {
        return Err(
            "The message does not begin with a header field; a message must contain the required \
             header fields."
                .to_string(),
        );
    }

    if let Some((number, octets)) = overlong_line(content) {
        return Err(format!(
            "Line {number} of the message is {octets} octets long, which exceeds the \
             {MAX_LINE_OCTETS}-octet limit including the CRLF."
        ));
    }

    // ONE walk of the header block, in [`bounded_header_block`]: it decides the
    // ceilings and hands back the lines it read, so no content beyond them is
    // taken apart into fields and the block is walked once per request.
    let block = bounded_header_block(content);
    if let Some(reason) = block.past_ceiling {
        return Err(reason);
    }

    let fields = header_fields_of(&block.lines);
    let counts = field_counts(&fields);

    let missing: Vec<&str> = REQUIRED_HEADERS
        .iter()
        .copied()
        .filter(|name| counts.get(name.as_bytes()).copied().unwrap_or_default() == 0)
        .collect();
    if !missing.is_empty() {
        return Err(format!(
            "The message is missing the required header field(s) {}.",
            missing.join(", ")
        ));
    }

    for name in SINGLETON_HEADERS {
        if counts.get(name.as_bytes()).copied().unwrap_or_default() > 1 {
            return Err(format!(
                "The message carries more than one {name} header, which may only appear once."
            ));
        }
    }

    Ok(fields)
}

/// The refusal for content of `octets` octets, which is beyond
/// [`MAX_CONTENT_OCTETS`]. One wording in one place: the ceiling is decided where
/// the object is still in the store ([`resolve_content`]), so nothing that large
/// is copied to refuse it, and again of the bytes themselves ([`validate_mime`]).
fn oversize_content(octets: usize) -> String {
    format!(
        "The message is {octets} octets long, beyond the {MAX_CONTENT_OCTETS} octets this \
         emulator will read."
    )
}

/// A message's header block as far as this emulator reads it: the block's header
/// lines, and why the block runs past a ceiling when it does.
///
/// What [`bounded_header_block`] hands back, and the one thing both halves of this
/// module's header handling work from: [`validate_mime`] answers
/// [`Self::past_ceiling`] to the caller, and [`header_fields_of`] takes
/// [`Self::lines`] apart into fields.
struct BoundedHeaderBlock<'a> {
    /// The block's header lines, in the order the message carries them, each
    /// without the CR that ended it and never the empty line that closes the
    /// block. The lines BORROW the content, so holding them copies no octet.
    lines: Vec<&'a [u8]>,
    /// Why the block is past one of the ceilings [`MAX_HEADER_BLOCK_OCTETS`] and
    /// [`MAX_HEADER_FIELDS`] state — the `message` of the refusal — and `None`
    /// when it is inside both, in which case [`Self::lines`] is the WHOLE block.
    past_ceiling: Option<String>,
}

/// `content`'s header block, read up to the ceilings [`MAX_HEADER_BLOCK_OCTETS`]
/// and [`MAX_HEADER_FIELDS`] state.
///
/// The ONE place this module walks a header block, so the rule is stated once: the
/// block is the content up to the first empty line, a line's octets are its own
/// plus the one line feed that ended it, the empty line closes the block and
/// belongs to neither ceiling, and the second ceiling counts the block's LINES —
/// every line standing before that empty line, a folded continuation among them —
/// and not the fields they parse into.
///
/// It is the caller who decides how long the block is and how many lines it
/// carries, so the walk stops at the first ceiling it crosses: what comes back is
/// bounded by the ceilings rather than by the content, at most
/// [`MAX_HEADER_FIELDS`] borrowed line slices spanning at most
/// [`MAX_HEADER_BLOCK_OCTETS`] octets.
fn bounded_header_block(content: &[u8]) -> BoundedHeaderBlock<'_> {
    let mut lines: Vec<&[u8]> = Vec::new();
    let mut octets = 0usize;
    for raw in content.split(|byte| *byte == b'\n') {
        let line = raw.strip_suffix(b"\r").unwrap_or(raw);
        if line.is_empty() {
            // The end of the header block: the empty line closes the block and is
            // no part of it, so neither it nor its octets count towards a ceiling.
            break;
        }
        // The LF that ended the line belongs to the block as well.
        octets = octets.saturating_add(raw.len()).saturating_add(1);
        if octets > MAX_HEADER_BLOCK_OCTETS {
            return BoundedHeaderBlock {
                lines,
                past_ceiling: Some(format!(
                    "The message's header block is longer than the {MAX_HEADER_BLOCK_OCTETS} \
                     octets this emulator will read."
                )),
            };
        }
        if lines.len() == MAX_HEADER_FIELDS {
            // This line is one more than the ceiling admits.
            return BoundedHeaderBlock {
                lines,
                past_ceiling: Some(format!(
                    "The message's header block carries more than the {MAX_HEADER_FIELDS} header \
                     lines this emulator will read."
                )),
            };
        }
        lines.push(line);
    }
    BoundedHeaderBlock {
        lines,
        past_ceiling: None,
    }
}

/// Why `updated` may not replace `current`, when it changes the value of a header
/// in [`IMMUTABLE_HEADERS`], and `None` when every one of those headers reads
/// exactly as it does on the message in transit.
///
/// `updated` is the header block [`validate_mime`] already read, so this reads
/// only the message in transit — one bounded walk, which is all this decision
/// costs inside the critical section that installs the bytes.
///
/// "Unchanged" is compared over the whole sequence of a header's values, in order:
/// a header that may legitimately appear several times (the `Received` trace) is
/// unchanged only when the update carries the same values in the same order, so
/// rewriting one of them, dropping one, reordering them or adding one are all
/// changes, as is removing or inventing a header that appears once.
///
/// A value is the OCTETS the message carries for the field, never text decoded
/// out of them: a message's content is arbitrary bytes, and any decoding that
/// maps distinct byte sequences onto one string would read two different values
/// as the same one and let a change through.
fn immutable_header_conflict(current: &[u8], updated: &[HeaderField]) -> Option<String> {
    let before = header_fields(current);
    for name in IMMUTABLE_HEADERS {
        let before: Vec<&[u8]> = values_of(&before, name);
        let after: Vec<&[u8]> = values_of(updated, name);
        if before == after {
            continue;
        }
        return Some(if before.len() == after.len() {
            format!(
                "The update changes the value of the {name} header, which is immutable and must \
                 remain unchanged."
            )
        } else {
            format!(
                "The message in transit carries {} {name} header field(s) and the update carries \
                 {}; the value of an immutable header must remain unchanged.",
                before.len(),
                after.len()
            )
        });
    }
    None
}

/// The values of the header field `name` in `fields`, in the order the message
/// carries them. `name` is an ASCII-lowercased field name, which is the form
/// [`header_fields`] keys a field by.
fn values_of<'a>(fields: &'a [HeaderField], name: &str) -> Vec<&'a [u8]> {
    fields
        .iter()
        .filter(|(field, _)| field.as_slice() == name.as_bytes())
        .map(|(_, value)| value.as_slice())
        .collect()
}

/// How many times each header field name appears in `fields`, the header block
/// [`header_fields`] read: names are lowercased there, because RFC 5322 makes
/// field names case-insensitive.
///
/// A name is counted by its octets, so two fields are the same field only when
/// their names are the same bytes up to ASCII case: a name that merely resembles
/// another once its bytes are decoded is a different field and is counted on its
/// own. The names are BORROWED from `fields`, so counting copies none of them.
fn field_counts<'a>(fields: &'a [HeaderField]) -> ::std::collections::BTreeMap<&'a [u8], usize> {
    let mut counts: ::std::collections::BTreeMap<&'a [u8], usize> =
        ::std::collections::BTreeMap::new();
    for (name, _) in fields {
        *counts.entry(name.as_slice()).or_default() += 1;
    }
    counts
}

/// The message's header block as (ASCII-lowercased name, value) pairs of OCTETS,
/// in order.
///
/// The block is the content up to the first empty line, and a line that opens with
/// a space or a tab continues the field before it (RFC 5322 §2.2.3 folding) rather
/// than starting a new one, so a folded value is compared as the one value it is.
/// Every other line is read by [`header_field`], the single rule this module
/// decides what field a line carries by.
///
/// Both halves stay bytes. A message's content is an arbitrary octet stream — the
/// model recommends encoding anything outside 7-bit ASCII but requires nothing —
/// so a field is split and compared on its bytes: decoding to text first would
/// map byte sequences that differ onto one string and read two different fields,
/// or two different values, as one. Only [`trim_wsp`] comes off either half, so
/// every octet that is not RFC 5322 whitespace belongs to the name or the value.
///
/// Reading stops where [`bounded_header_block`] stops, so what this holds is
/// bounded however long the content is. Content this operation installs is inside
/// those ceilings — [`validate_mime`] refuses it otherwise, out of the same walk —
/// so only content that reached the store by another route can have a block that
/// ends at a ceiling rather than at its empty line.
fn header_fields(content: &[u8]) -> HeaderBlock {
    header_fields_of(&bounded_header_block(content).lines)
}

/// The fields `lines` carries, as [`header_fields`] describes them: `lines` is a
/// header block [`bounded_header_block`] read, so the ceilings and the end of the
/// block are already decided there and this only takes the lines apart.
fn header_fields_of(lines: &[&[u8]]) -> HeaderBlock {
    let mut fields: HeaderBlock = Vec::new();
    for line in lines {
        if is_folded_continuation(line) {
            // A folded continuation of the field above: unfolding removes the line
            // break and keeps the rest of the line, including its leading
            // whitespace.
            if let Some((_, value)) = fields.last_mut() {
                value.extend_from_slice(line);
            }
            continue;
        }
        let Some(field) = header_field(line) else {
            continue;
        };
        fields.push(field);
    }
    fields
}

/// Whether `line` continues the field above it instead of carrying one of its own:
/// RFC 5322 §2.2.3 folds a long field by breaking the line and opening the next
/// one with whitespace, so a line that starts with whitespace belongs to the field
/// before it.
fn is_folded_continuation(line: &[u8]) -> bool {
    matches!(line.first(), Some(b' ' | b'\t'))
}

/// The (ASCII-lowercased name, value) octets of the header field `line` carries,
/// and `None` when it carries none.
///
/// This is the ONE rule this module decides what field a line is by, wherever the
/// line sits in the block: [`header_fields`] reads the whole block with it and
/// [`starts_with_header_field`] asks it about the first line, so one and the same
/// line is the same field first, last or in the middle.
///
/// A line carries a field when it has a colon on it and the octets before that
/// colon are a field name: RFC 5322 §3.6.8 makes a name one or more printable
/// US-ASCII octets other than the colon, and the obsolete field syntax of §4.5.8
/// admits ASCII whitespace between the name and the colon, which [`trim_wsp`]
/// takes off — so a name padded with a space or a horizontal tab is still the
/// field it names. A line with no colon, with nothing but whitespace before it, or
/// whose name carries an octet outside those printable ones carries no field.
///
/// The name is ASCII-lowercased because RFC 5322 makes field names
/// case-insensitive; the value is not, since a value is what it says.
fn header_field(line: &[u8]) -> Option<HeaderField> {
    let colon = line.iter().position(|byte| *byte == b':')?;
    let name = trim_wsp(&line[..colon]);
    if name.is_empty() || !name.iter().copied().all(is_field_name_octet) {
        return None;
    }
    Some((
        name.to_ascii_lowercase(),
        trim_wsp(&line[colon + 1..]).to_vec(),
    ))
}

/// Whether `byte` is an octet a header field name is made of: printable US-ASCII,
/// which RFC 5322 §3.6.8 calls `ftext`. The colon is inside that range and
/// excluded by taking a name up to the FIRST colon on its line, so no name this
/// module reads can carry one.
fn is_field_name_octet(byte: u8) -> bool {
    (33..=126).contains(&byte)
}

/// `octets` without the whitespace RFC 5322 pads a header field with.
///
/// That whitespace is the space and the horizontal tab (§3.2.2 `WSP`), and
/// nothing else: every other octet, printable or not, is part of the field name
/// or of its value, so trimming any of them would read two fields that differ as
/// the same one.
fn trim_wsp(octets: &[u8]) -> &[u8] {
    let is_wsp = |byte: u8| byte == b' ' || byte == b'\t';
    let start = octets
        .iter()
        .position(|byte| !is_wsp(*byte))
        .unwrap_or(octets.len());
    let end = octets
        .iter()
        .rposition(|byte| !is_wsp(*byte))
        .map_or(start, |index| index + 1);
    &octets[start..end]
}

/// The 1-based number and octet length of the first line of `content` longer than
/// [`MAX_LINE_OCTETS`], counting the line terminator the way RFC 5321 does: a line
/// terminator is a CRLF and counts two octets, so a line a sender terminated with a
/// bare LF is measured as though it carried the CRLF the RFC requires.
fn overlong_line(content: &[u8]) -> Option<(usize, usize)> {
    let mut number = 0usize;
    let mut rest = content;
    while !rest.is_empty() {
        number += 1;
        let (octets, next) = match rest.iter().position(|byte| *byte == b'\n') {
            // The CR, when the sender sent one, is already inside the segment; a
            // bare LF stands for a CRLF, so it counts for two.
            Some(index) => {
                let terminator = if rest[..index].last() == Some(&b'\r') { 1 } else { 2 };
                (index + terminator, &rest[index + 1..])
            }
            // A final line the content does not terminate has no terminator.
            None => (rest.len(), &rest[rest.len()..]),
        };
        if octets > MAX_LINE_OCTETS {
            return Some((number, octets));
        }
        rest = next;
    }
    None
}

/// Whether `content` opens with an RFC 5322 header field, so the message has a
/// header block at all.
///
/// Decided by [`header_field`], the same rule [`header_fields`] reads every other
/// line of the block by, so a line that is a header field anywhere in the block is
/// one on the first line too: the first line opens a field when it is not a folded
/// continuation — there is no field above it to continue — and carries a field
/// name before a colon, whatever ASCII whitespace pads that name.
fn starts_with_header_field(content: &[u8]) -> bool {
    let first_line = content
        .split(|byte| *byte == b'\n')
        .next()
        .unwrap_or_default();
    let first_line = first_line.strip_suffix(b"\r").unwrap_or(first_line);
    !is_folded_continuation(first_line) && header_field(first_line).is_some()
}

