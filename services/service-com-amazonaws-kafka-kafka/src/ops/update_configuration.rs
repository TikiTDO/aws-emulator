impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdateConfiguration<Eng>
{
    type Input = UpdateConfigurationInput;
    type Output = UpdateConfigurationOutput;
    type Error = UpdateConfigurationError;

    const NAME: &'static str = "UpdateConfiguration";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CONFIGURATION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_CONFIGURATION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(
                UpdateConfigurationErrorModeled::InternalServerErrorException(
                    InternalServerErrorException {
                        invalid_parameter: None,
                        message: Some("the kafka service state is unavailable".to_string()),
                    },
                )
                .into(),
            );
        };
        let region = crate::state::request_region(ctx.parts());
        let now = std::time::SystemTime::now();

        // A configuration IS a `server.properties` file, and MSK configures a
        // published set of broker properties, so the body this update appends is
        // admitted on exactly the terms the create's is
        // ([`crate::state::server_properties`]): a declaration whose NAME is
        // outside that set is refused, naming each offending declaration and the
        // value the body gave it, and a value is never judged. A refused update
        // appends nothing, leaving the revision the configuration already reports
        // as its latest.
        //
        // The body is READ here, before the registry lock below is taken, and
        // only when it is inside the one ceiling both writers apply to a stored
        // body (the append path enforces it, so an oversized body is refused
        // there): the work this reading does is bounded by that ceiling, and none
        // of it happens while the lock is held. What the reading FOUND is answered
        // after the configuration has been resolved, so both body refusals sit on
        // the same side of the lookup and an unresolvable `Arn` is answered as
        // such whatever the body carried.
        let admission = if crate::state::server_properties_too_large(&input.server_properties) {
            Some(Vec::new())
        } else {
            crate::state::server_properties::unconfigurable_declarations(&input.server_properties)
        };

        let mut state = state.lock();
        // ONE condition, one refusal: an `Arn` that resolves to no configuration
        // of this endpoint's region — malformed, never minted, deleted and gone,
        // or another region's — is the configuration family's unresolvable-
        // reference bad request, resolved before anything is appended so a
        // refused update stores nothing.
        let Some(configuration) = state.settled_configuration_in_mut(&region, &input.arn, now)
        else {
            return Err(UpdateConfigurationErrorModeled::BadRequestException(
                crate::state::configuration_arn_not_found(),
            )
            .into());
        };

        // The configuration resolved, so whether this call may change it is the
        // state it is in: one the service is already taking out is refused with
        // the states a change IS accepted from, and nothing is appended. A
        // resource that is still there is never reported as a reference nothing
        // resolves.
        let accepted = crate::state::CONFIGURATION_STATES_A_CHANGE_IS_ACCEPTED_FROM;
        if !accepted.contains(&configuration.state.as_str()) {
            return Err(UpdateConfigurationErrorModeled::BadRequestException(
                crate::state::configuration_not_in_accepted_state(&accepted),
            )
            .into());
        }

        // What the reading of the body found, answered now that the configuration
        // it would be appended to has resolved: a body that is no properties
        // document at all is the parameter refusal, and one declaring a property
        // MSK does not configure names each offending declaration and the versions
        // this configuration's own record has them checked against.
        let Some(unconfigurable) = admission else {
            return Err(UpdateConfigurationErrorModeled::BadRequestException(
                crate::state::parameter_refusal(
                    crate::state::server_properties::SERVER_PROPERTIES_MEMBER,
                    crate::state::BAD_REQUEST_MESSAGE,
                ),
            )
            .into());
        };
        // BOUNDED at both factors, as the create's refusal is: at most
        // `MAX_REPORTED_PROPERTIES` declarations are reported, and the versions
        // each names are chosen from the versions this service publishes, so that
        // list is at most `catalogued_kafka_versions().len()` long whatever the
        // request or the record carried.
        let reported: Vec<_> = unconfigurable
            .into_iter()
            .take(crate::state::server_properties::MAX_REPORTED_PROPERTIES)
            .collect();
        if !reported.is_empty() {
            let checked_versions: Vec<String> =
                crate::state::server_properties::checked_versions(&configuration.kafka_versions)
                    .into_iter()
                    .take(crate::state::catalogued_kafka_versions().len())
                    .collect();
            return Err(UpdateConfigurationErrorModeled::BadRequestException(
                BadRequestException {
                    invalid_parameter: Some(
                        crate::state::server_properties::SERVER_PROPERTIES_MEMBER.to_string(),
                    ),
                    message: Some(
                        crate::state::server_properties::unsupported_properties_message(
                            &reported,
                            &checked_versions,
                        ),
                    ),
                },
            )
            .into());
        }

        // The one append path on the record: the submitted body is stored as the
        // next revision, so the revision number reported here is computed from
        // the stored history rather than taken from the request, and every
        // revision an earlier call stored keeps the body it was stored with.
        // That path also enforces the history's ceilings, so a refused update
        // stores nothing and evicts nothing — a stored revision is immutable.
        //
        // `Description` is the description of the revision this call adds, as
        // the modelled member documents it, and a revision has none where the
        // request named none or named an empty one; the configuration's own
        // description is the one it was created with.
        let appended = configuration.append_revision(
            now,
            input.description,
            input.server_properties,
        );
        let latest = match appended {
            Ok(revision) => revision.to_configuration_revision(),
            // The submitted member is at fault for a body this emulator will
            // not store, so the refusal names it.
            Err(crate::state::RevisionRejected::BodyTooLarge) => {
                return Err(
                    UpdateConfigurationErrorModeled::BadRequestException(BadRequestException {
                        invalid_parameter: Some("ServerProperties".to_string()),
                        message: Some(format!(
                            "ServerProperties must be at most {} bytes.",
                            crate::state::MAX_SERVER_PROPERTIES_BYTES
                        )),
                    })
                    .into(),
                );
            }
            // No request member is at fault for a process-wide backstop, so
            // this one names none.
            Err(crate::state::RevisionRejected::HistoryFull) => {
                return Err(
                    UpdateConfigurationErrorModeled::BadRequestException(BadRequestException {
                        invalid_parameter: None,
                        message: Some(format!(
                            "This emulator keeps its maximum of {} revisions of one configuration.",
                            crate::state::MAX_REVISIONS_PER_CONFIGURATION
                        )),
                    })
                    .into(),
                );
            }
        };
        Ok(UpdateConfigurationOutput {
            arn: Some(configuration.arn.clone()),
            latest_revision: Some(latest),
        })
    }
}
