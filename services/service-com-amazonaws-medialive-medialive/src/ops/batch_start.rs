impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for BatchStart<Eng>
{
    type Input = BatchStartInput;
    type Output = BatchStartOutput;
    type Error = BatchStartError;

    const NAME: &'static str = "BatchStart";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::BATCH_START_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::BATCH_START_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;

        // The request's two id lists carry no modelled length constraint, and
        // each id costs a lookup and a projection plus one result entry, so the
        // batch is bounded BEFORE the state guard is taken: the guard is never
        // held for an amount of work the caller chose. The shared bound answers
        // the message; this operation lifts it into the modelled client error IT
        // declares.
        within_id_cap(
            Self::NAME,
            crate::state::MAX_BATCH_START_IDS,
            &[&input.channel_ids, &input.multiplex_ids],
        )
        .map_err(|message| {
            BatchStartErrorModeled::BadRequestException(BadRequestException {
                message: Some(message),
            })
        })?;

        let state = crate::state::service_state(&*self.engine, ctx.parts()).ok_or_else(unavailable)?;
        let now = ::std::time::SystemTime::now();

        let mut state = state.lock();
        // Transitions the clock had already made due were owed whether or not
        // this call ran, so they are materialised before anything is read: a
        // resource whose `CREATING` span has passed is `IDLE`, and that is the
        // state this start is judged against.
        state.settle(now);

        // "Starts existing resources": each named resource is attempted on its
        // own and reported on its own, so the call itself answers 200 even when
        // every resource named in it was refused.
        let mut results = Results::default();
        for id in input.channel_ids.unwrap_or_default() {
            results.push(start_channel(&mut state, &id, now)?);
        }
        for id in input.multiplex_ids.unwrap_or_default() {
            results.push(start_multiplex(&mut state, &id, now)?);
        }

        Ok(BatchStartOutput {
            failed: Some(results.failed),
            successful: Some(results.successful),
        })
    }
}

/// One channel's start, under exactly `StartChannel`'s rule: an id whose delete
/// has been accepted names no channel to start and is reported NOT FOUND, and a
/// channel that still exists runs only from the stopped `IDLE` — every other
/// state (still creating, already starting, running, stopping) is a conflict —
/// while an accepted start puts it in `STARTING`, owing the `RUNNING` the clock
/// then makes due.
fn start_channel(
    state: &mut State,
    id: &str,
    now: ::std::time::SystemTime,
) -> Result<Outcome, BatchStartError> {
    // The id is resolved through the shared channel guard FIRST, so a channel
    // whose delete has been accepted is reported with the NOT-FOUND code
    // `StartChannel` answers for it rather than with a state conflict. The guard
    // hands back the tombstone's own ARN for the entry to name.
    let channel = match state.mutable_channel(id) {
        Ok(channel) => channel,
        Err(dead) => {
            return Ok(refused(id, dead.arn, failure_code::NOT_FOUND, dead.message));
        }
    };
    if !channel.is_idle() {
        return Ok(refused(
            id,
            Some(channel.arn.clone()),
            failure_code::CONFLICT,
            crate::state::channel_not_startable_message(id, &channel.state),
        ));
    }
    crate::state::begin_start(channel, now);

    // Read the result back out of the store, so the entry reports what was
    // written rather than what this handler meant to write. A description that
    // is suddenly missing is a server fault, not an accepted start with empty
    // members — the same `unavailable()` `StartChannel` answers for it.
    accepted(
        id,
        state
            .channel_description(id)
            .map(|channel| (channel.arn, channel.state)),
    )
    .ok_or_else(unavailable)
}

/// One multiplex's start, under exactly `StartMultiplex`'s rule: a multiplex
/// runs only from the stopped `IDLE`, so one in any other state is refused
/// rather than treated as a no-op, and an accepted start puts it in `STARTING`,
/// owing the `RUNNING` the clock then makes due. This is the asymmetry with
/// `BatchStop`, which a multiplex that is not running answers as a no-op.
///
/// The tear-down states are among those "any other" ones rather than a
/// not-found: a multiplex's record stays resolvable once its delete has been
/// accepted, so a start of it is the state conflict naming that state, which is
/// what the real service answers (the recorded evidence is cited on
/// [`crate::state::MultiplexStartRefusal`]). That is where this arm differs from
/// the channel one above, whose family's delete takes the record out of
/// resolution.
fn start_multiplex(
    state: &mut State,
    id: &str,
    now: ::std::time::SystemTime,
) -> Result<Outcome, BatchStartError> {
    match state.start_multiplex(id, now) {
        Ok(()) => accepted(
            id,
            state
                .multiplex_description(id)
                .map(|multiplex| (multiplex.arn, multiplex.state)),
        )
        .ok_or_else(unavailable),
        Err(crate::state::MultiplexStartRefusal::NotFound) => Ok(not_found("Multiplex", id)),
        Err(crate::state::MultiplexStartRefusal::NotStartable(current)) => Ok(refused(
            id,
            state.multiplex_description(id).and_then(|m| m.arn),
            failure_code::CONFLICT,
            crate::state::multiplex_not_startable_message(id, &current),
        )),
    }
}

