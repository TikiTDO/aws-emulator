//! @op ExportComplianceInquiry
//! Exports one stored compliance inquiry as a document and answers with the presigned
//! URL that document is published under, beside the inquiry's own tags.
//!
//! Three rules shape the handler:
//!
//! * it reports on a PERSISTED inquiry: an id the store does not hold names no inquiry
//!   this account may export, which the front door answers with its 401 — the same
//!   refusal `GetComplianceInquiryMetadata` and `ListComplianceInquiryQueries` give for
//!   that id, rather than a 404 confirming the resource's absence — and the `tags` it
//!   answers with are read off that one record — the same projection
//!   `CreateComplianceInquiry` and `GetComplianceInquiryMetadata` return, so no two of
//!   them can disagree;
//! * `queryIdentifiers` selects WHICH of the inquiry's queries the export covers, so an
//!   identifier that names no query of that inquiry is refused with the modelled
//!   `ValidationException` naming the member and the requirement it failed; naming none
//!   covers every query the inquiry owns;
//! * exporting CREATES a document — this operation is not `@readonly`, unlike
//!   `ListComplianceInquiryQueries` — so every call mints an
//!   [`crate::state::InquiryExport`] and the URL carries that export's id. The inquiry
//!   itself is left as it stands (bar the transition the clock already owed it), so an
//!   export changes nothing a later reader of the inquiry sees.
//!
//! The URL this answers with is a promise the caller can FOLLOW it, so it names the
//! endpoint the caller reached this emulator on ([`crate::state::document_url_host`]) and
//! a path `crate::service` serves the stored export document at — the same rule `GetReport`
//! and `GetTermForReport` announce their documents under. It carries the export's own
//! download token, which is what authorises the unsigned fetch of that document, exactly
//! as the term grant's token authorises a report download: the URL is handed to ONE caller
//! and the token is the receipt that caller holds. No SigV4 signature is attached: this
//! emulator does not sign documents and does not fabricate a signature it did not compute.
//!
//! Minting that export persists a resource, so the call is ATTRIBUTABLE on the same terms as
//! this crate's other state changes: this handler leaves exactly one structured record naming
//! the caller (the access-key id and the credential-scope region the request presented), what
//! the call addressed and the outcome — on the refusal paths as much as on the success one,
//! since a state-changing call that changed nothing is still attributable. Never the URL,
//! whose `PresignedUrl` shape is `@sensitive`, nor the download token it carries, nor the
//! inquiry's name, content or queries.
//!
//! ## Shape of an operation
//!
//! Each operation is a struct that owns the shared engine and implements
//! [`smithy_server_runtime::Operation`]. The framework constructs one per service via
//! `ExportComplianceInquiry::new(engine)` and drives it through the centralized request walk:
//! deserialize → validate → `handle` → serialize. You write ONLY the `handle` body.
//!
//! ## Reaching this service's state
//!
//! The engine is held on `self` (constructor-injected), NOT passed per request — so
//! engine access is guaranteed by the time any request runs. Reach the store through
//! [`crate::state::service_state`] and read and write it through the guard it hands back:
//!
//! ```ignore
//!     let state = crate::state::service_state(&*self.engine)
//!         .ok_or(/* a modelled server error */)?;
//!     state.lock().your_field = /* ... */;
//! ```
//!
//! `ctx` ([`smithy_server_runtime::OperationContext`]) carries request metadata only —
//! headers, URI, method, and anything middleware placed in `ctx.parts().extensions`.
//! The engine is NOT reached through `ctx`.
