///
/// A predefined metric is a metric of one service's resources, so it only describes the
/// dimensions that service publishes it for ([`crate::state::predefined_metric_dimensions`])
/// — a read-capacity metric does not describe a write-capacity dimension, and an ECS
/// service metric does not describe a DynamoDB table at all. A customized metric is only
/// accepted where the dimension's owning service scales from a signal of the caller's
/// choosing ([`crate::state::customized_metric_supported`]). And where the owning service
/// publishes the window its target utilisation must lie in
/// ([`crate::state::predefined_metric_target_range`]), a target outside it is not a
/// utilisation that service can hold.
fn check_tracked_metric(
    scalable_dimension: &str,
    config: &TargetTrackingScalingPolicyConfiguration,
) -> Result<(), PutScalingPolicyError> {
    if config.customized_metric_specification.is_some()
        && !crate::state::customized_metric_supported(scalable_dimension)
    {
        return Err(validation(
            crate::state::unsupported_customized_metric_message(scalable_dimension),
        ));
    }
    let Some(predefined) = config.predefined_metric_specification.as_ref() else {
        return Ok(());
    };
    let metric_type = predefined.predefined_metric_type.as_str();
    // A type outside the enum is already refused by `check_target_tracking_config`; one
    // inside it that this dimension is not scaled on — including one with no catalog row,
    // which is published for no dimension at all — is refused with the set the dimension
    // DOES support, which is what a caller recovers from.
    let supported = crate::state::predefined_metric_dimensions(metric_type).unwrap_or_default();
    if !supported.contains(&scalable_dimension) {
        return Err(validation(
            crate::state::unsupported_predefined_metric_message(scalable_dimension),
        ));
    }
    if let Some((low, high)) = crate::state::predefined_metric_target_range(metric_type) {
        if config.target_value < low || config.target_value > high {
            return Err(validation(
                crate::state::target_value_outside_range_message(
                    metric_type,
                    (low, high),
                    config.target_value,
                ),
            ));
        }
    }
    Ok(())
}

/// Refuse a step-scaling configuration whose steps cannot be evaluated.
///
/// Every rule is the model's own — "at least one step adjustment is required if you are
/// adding a new step scaling policy configuration", and of a step adjustment's bounds, "the
/// upper and lower bound can't be null in the same step adjustment" with "at most one step
/// adjustment can have a null lower bound" and the same for the upper bound, and "the ranges
/// of your step adjustments can't overlap or have a gap" — and each refusal states that rule
/// in the SERVICE's own sentence for it rather than in the documentation's prose about the
/// member.
///
/// A step adjustment's range is an interval of the difference between the metric and the
/// alarm threshold, "the lower bound is inclusive […] the upper bound is exclusive", with a
/// null bound meaning unbounded in that direction. A metric breach picks the adjustment
/// whose range it falls in, so the ranges have to partition the differences the policy is
/// evaluated over: two that share a point name two adjustments for one breach, and two that
/// leave a gap name none for a breach inside it.
fn check_step_config(
    config: &StepScalingPolicyConfiguration,
) -> Result<(), PutScalingPolicyError> {
    if let Some(adjustment_type) = config.adjustment_type.as_deref() {
        crate::state::check_enum("adjustmentType", adjustment_type, ADJUSTMENT_TYPE_VALUES)
            .map_err(validation)?;
    }
    if let Some(aggregation) = config.metric_aggregation_type.as_deref() {
        crate::state::check_enum(
            "metricAggregationType",
            aggregation,
            METRIC_AGGREGATION_TYPE_VALUES,
        )
        .map_err(validation)?;
    }
    let adjustments = config.step_adjustments.as_deref().unwrap_or(&[]);
    if adjustments.is_empty() {
        return Err(validation(AT_LEAST_ONE_STEP_ADJUSTMENT));
    }
    let mut unbounded_below = 0usize;
    let mut unbounded_above = 0usize;
    for adjustment in adjustments {
        match (
            adjustment.metric_interval_lower_bound,
            adjustment.metric_interval_upper_bound,
        ) {
            (None, None) => return Err(validation(STEP_ADJUSTMENT_WITHOUT_A_BOUND)),
            (None, Some(_)) => unbounded_below += 1,
            (Some(_), None) => unbounded_above += 1,
            (Some(_), Some(_)) => {}
        }
    }
    if unbounded_below > 1 {
        return Err(validation(
            "At most one step adjustment can have a null lower bound",
        ));
    }
    if unbounded_above > 1 {
        return Err(validation(
            "At most one step adjustment can have a null upper bound",
        ));
    }
    check_step_ranges(adjustments)?;
    Ok(())
}

/// Refuse step adjustments whose ranges do not partition the metric differences the policy
/// is evaluated over.
///
/// Each range is read as `[lower, upper)` over the metric-to-threshold difference, with a
/// null bound unbounded in that direction and a bound that is not a finite number treated
/// as unbounded too (nothing can be compared against it). Sorting the ranges by their lower
/// bound makes the rule local: consecutive ranges are neither overlapping nor gapped exactly
/// when each one STARTS where the previous one ends. A range whose lower bound is not below
/// its upper bound is empty, so it selects no difference at all and is refused on its own
/// terms.
fn check_step_ranges(adjustments: &[StepAdjustment]) -> Result<(), PutScalingPolicyError> {
    let finite = |bound: Option<f64>| bound.filter(|value| value.is_finite());
    let mut ranges: Vec<(f64, f64)> = adjustments
        .iter()
        .map(|adjustment| {
            (
                finite(adjustment.metric_interval_lower_bound).unwrap_or(f64::NEG_INFINITY),
                finite(adjustment.metric_interval_upper_bound).unwrap_or(f64::INFINITY),
            )
        })
        .collect();
    for (lower, upper) in &ranges {
        if lower >= upper {
            return Err(validation(STEP_BOUNDS_OUT_OF_ORDER));
        }
    }
    ranges.sort_by(|left, right| left.0.total_cmp(&right.0));
    for pair in ranges.windows(2) {
        let ((_, upper), (next_lower, _)) = (pair[0], pair[1]);
        // Compared by `total_cmp` rather than by `==`/`<`, so the two unbounded ends are
        // ordered against a finite bound without a float-equality comparison.
        match next_lower.total_cmp(&upper) {
            ::std::cmp::Ordering::Less => return Err(validation(STEP_INTERVALS_OVERLAP)),
            ::std::cmp::Ordering::Greater => return Err(validation(STEP_INTERVALS_HAVE_A_GAP)),
            ::std::cmp::Ordering::Equal => {}
        }
    }
    Ok(())
}

/// Refuse a predictive scaling configuration that does not describe exactly one load to
/// forecast.
///
/// The model states the count in prose: "This is an array, but we currently only support a
/// single metric specification. That is, you can specify a target value and a single metric
/// pair, or a target value and one scaling metric and one load metric"
/// ([`crate::state::MAX_PREDICTIVE_METRIC_SPECIFICATIONS`]). A configuration carrying none
/// has no load to forecast, and one carrying more is not a configuration this service
/// supports — and the count is what bounds the work a forecast of the policy does, so it is
/// held at ADMISSION rather than at the read.
fn check_predictive_config(
    config: &PredictiveScalingPolicyConfiguration,
) -> Result<(), PutScalingPolicyError> {
    let supported = crate::state::MAX_PREDICTIVE_METRIC_SPECIFICATIONS;
    let count = config.metric_specifications.len();
    if count == 0 || count > supported {
        return Err(validation(format!(
            "We currently only support a single metric specification, so a predictive scaling \
             policy configuration takes {supported} of them; got {count}"
        )));
    }
    // Both members are closed enums, and both are READ later — the mode by the policy's
    // evaluation and the breach behaviour by `GetPredictiveScalingForecast` — so a value
    // outside the enum is refused here rather than resolving to one of them at the read.
    if let Some(mode) = config.mode.as_deref() {
        crate::state::check_enum("mode", mode, PREDICTIVE_SCALING_MODE_VALUES)
            .map_err(validation)?;
    }
    if let Some(behavior) = config.max_capacity_breach_behavior.as_deref() {
        crate::state::check_enum(
            "maxCapacityBreachBehavior",
            behavior,
            PREDICTIVE_SCALING_MAX_CAPACITY_BREACH_BEHAVIOR_VALUES,
        )
        .map_err(validation)?;
    }
    Ok(())
}

/// A target-tracking configuration carrying BOTH metric specifications.
///
/// "A predefined metric. You can specify either a predefined metric or a customized metric"
/// — either, so a configuration naming both describes two metrics to track. One fixed
/// sentence, naming the two MODELLED members between which exactly one may be set, so a
/// caller is told which field to drop.
const ONE_METRIC_SPECIFICATION: &str = "Only one of PredefinedMetricSpecification or \
                                        CustomizedMetricSpecification can be set for target \
                                        tracking scaling.";

/// A step-scaling configuration whose step adjustments are empty, so no breach selects an
/// adjustment: "at least one step adjustment is required if you are adding a new step scaling
/// policy configuration" (`StepScalingPolicyConfiguration$StepAdjustments`), stated as the
/// one fixed sentence the service refuses it with.
const AT_LEAST_ONE_STEP_ADJUSTMENT: &str = "There must be at least one step adjustment";

/// One step adjustment with neither bound, whose range is every metric-to-threshold
/// difference there is: "the upper and lower bound can't be null in the same step adjustment"
/// (`StepAdjustment`), stated as the one fixed sentence the service refuses it with.
const STEP_ADJUSTMENT_WITHOUT_A_BOUND: &str =
    "Both lower and upper bounds of a step adjustment cannot be left unspecified";

/// How this service states a second target-tracking policy on a metric one of the
/// target's policies already tracks.
///
/// "You can have one or more target tracking scaling policies" — but not two tracking ONE
/// metric, and the refusal is about that rule rather than about either policy, so it names
/// neither.
const ONE_POLICY_PER_METRIC: &str =
    "Only one TargetTrackingScaling policy for a given metric specification is allowed.";

/// Re-putting an existing policy name under another `PolicyType`.
///
/// The service states the rule in ONE fixed sentence, with no variable part: neither the policy
/// it is about nor the type it already carries is interpolated, so a client that matches the
/// refusal matches the same text whichever policy it put.
const POLICY_TYPE_IS_NOT_CHANGEABLE: &str =
    "You cannot change a StepScaling policy to a non StepScaling policy, or vice versa.";

/// Two step adjustments whose ranges share a metric-to-threshold difference, which names two
/// adjustments for one breach. One fixed sentence: the offending ranges are the caller's own
/// request and are not rendered back into it.
const STEP_INTERVALS_OVERLAP: &str = "Step adjustment intervals cannot overlap";

/// Two step adjustments that leave a metric-to-threshold difference between them, which names
/// no adjustment for a breach inside it — the other half of "the ranges of your step
/// adjustments can't overlap or have a gap" (`StepAdjustment`), stated the same way.
const STEP_INTERVALS_HAVE_A_GAP: &str = "The ranges of your step adjustments can't have a gap";

/// One step adjustment whose lower bound is not below its upper bound, so its range holds no
/// metric-to-threshold difference at all and the adjustment selects no breach.
const STEP_BOUNDS_OUT_OF_ORDER: &str =
    "A step adjustment's lower bound must be less than its upper bound";

/// This operation's modelled `ValidationException`, carrying `message`.
fn validation(message: impl Into<String>) -> PutScalingPolicyError {
    PutScalingPolicyErrorModeled::ValidationException(ValidationException {
        message: Some(message.into()),
    })
    .into()
}
