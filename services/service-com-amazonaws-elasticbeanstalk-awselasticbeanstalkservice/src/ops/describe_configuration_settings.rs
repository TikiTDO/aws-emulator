impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for DescribeConfigurationSettings<Eng>
{
    type Input = DescribeConfigurationSettingsInput;
    type Output = DescribeConfigurationSettingsOutput;
    type Error = DescribeConfigurationSettingsError;

    const NAME: &'static str = "DescribeConfigurationSettings";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_CONFIGURATION_SETTINGS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::DESCRIBE_CONFIGURATION_SETTINGS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // The region the platform version a configuration set is for is named
        // in: the settings are RESOLVED against that version's option catalog,
        // whose ARNs are regional.
        let region = crate::state::request_region(ctx);

        // "You must specify either this parameter or an EnvironmentName, but not
        // both. If you specify both, Elastic Beanstalk returns an
        // InvalidParameterCombination error. If you do not specify either,
        // Elastic Beanstalk returns a MissingRequiredParameter error." Both are
        // statements about the REQUEST, so both are answered before the
        // application is resolved.
        let wanted = match (
            input.template_name.as_deref(),
            input.environment_name.as_deref(),
        ) {
            (Some(_), Some(_)) => {
                return Err(
                    DescribeConfigurationSettingsError::invalid_parameter_combination(
                        "You cannot specify both TemplateName and EnvironmentName.",
                    ),
                );
            }
            (None, None) => {
                return Err(
                    DescribeConfigurationSettingsError::missing_required_parameter(
                        "Must specify either a TemplateName or an EnvironmentName.",
                    ),
                );
            }
            (Some(template_name), None) => ConfigurationSet::Template(template_name),
            (None, Some(environment_name)) => ConfigurationSet::Environment(environment_name),
        };

        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            DescribeConfigurationSettingsError::internal_failure(
                "the Elastic Beanstalk store is unavailable",
            )
        })?;
        let mut store = state.lock();
        // This operation only REPORTS. The one write it performs is the clock's
        // own — an environment status change or an application deletion the
        // clock has already made due — which was owed at the same instant
        // whether or not anybody called.
        store.materialize_due_transitions();

        let settings: Vec<CreateConfigurationTemplateOutput> = match wanted {
            // "The name of the configuration template to describe." A template
            // name is unique per application, so the pair resolves one record.
            ConfigurationSet::Template(template_name) => {
                let Some(template) = store
                    .configuration_templates
                    .get(&(input.application_name.clone(), template_name.to_string()))
                else {
                    return Err(
                        DescribeConfigurationSettingsError::invalid_parameter_value(
                            crate::state::missing_configuration_template_message(
                                &input.application_name,
                                template_name,
                            ),
                        ),
                    );
                };
                let described = crate::state::configuration_settings_description!(
                    CreateConfigurationTemplateOutput,
                    store,
                    &region,
                    template
                );
                let details = store.resolved_configuration_setting_details(
                    &region,
                    template.solution_stack_name.as_deref(),
                    template.platform_arn.as_deref(),
                    &template.option_settings,
                );
                // "Templates aren't associated with any environment", so a
                // template's configuration set is for the tier every
                // configuration starts in — the EC2-based web server at the
                // latest compatible tier version.
                vec![read_of_a_configuration_set(
                    described,
                    details,
                    crate::state::environment_tier_with_defaults(None),
                )]
            }
            // "The name of the environment to describe" — the configuration set
            // associated with a running environment. A terminated environment
            // runs nothing, so it has no deployed configuration to report.
            ConfigurationSet::Environment(environment_name) => {
                let Some(environment) = store
                    .environment_name_index
                    .get(environment_name)
                    .and_then(|environment_id| store.environments.get(environment_id))
                    .filter(|environment| {
                        !environment.is_terminated()
                            && environment.application_name == input.application_name
                    })
                else {
                    return Err(
                        DescribeConfigurationSettingsError::invalid_parameter_value(
                            crate::state::missing_environment_message(None, Some(environment_name)),
                        ),
                    );
                };
                // "OptionSettings: a list of the configuration options and
                // their values in this configuration set." The set in force is
                // the RESOLVED one — the platform version's published option
                // catalog at its defaults with the settings deployed to this
                // environment over them — so an option nobody set is reported
                // at the default it is running at rather than left out.
                let deployed_settings = store.resolved_configuration_settings(
                    &region,
                    environment.solution_stack_name.as_deref(),
                    environment.platform_arn.as_deref(),
                    &environment.option_settings,
                );
                // Where each of those options got its effective value: the
                // settings deployed to this environment came from the API, the
                // rest from the platform version's own defaults.
                let deployed_details = store.resolved_configuration_setting_details(
                    &region,
                    environment.solution_stack_name.as_deref(),
                    environment.platform_arn.as_deref(),
                    &environment.option_settings,
                );
                // The tier this configuration set is for is the environment's
                // own, which an update cannot change.
                let tier = crate::state::environment_tier_with_defaults(environment.tier.as_ref());
                // The draft belongs to the platform version the update that
                // created it deploys, so it resolves against THAT version's
                // catalog rather than the running environment's.
                // "When describing the settings for the configuration set
                // associated with a running environment, it is possible to
                // receive two sets of setting descriptions. One is the deployed
                // configuration set, and the other is a draft configuration of
                // an environment that is either in the process of deployment or
                // that failed to deploy." The deployed one comes first, so a
                // caller reading one description reads the configuration the
                // environment is running.
                let deployed = CreateConfigurationTemplateOutput {
                    solution_stack_name: environment.solution_stack_name.clone(),
                    platform_arn: environment.platform_arn.clone(),
                    application_name: Some(environment.application_name.clone()),
                    // This configuration set belongs to an ENVIRONMENT, not to a
                    // template: `TemplateName` is "if not null, the name of the
                    // configuration template FOR THIS configuration set", which
                    // the environment's own settings have none of, and
                    // `EnvironmentName` is what names it instead.
                    template_name: None,
                    environment_name: Some(environment.environment_name.clone()),
                    // "Describes this configuration set." The store holds no
                    // description of its own for an environment's configuration
                    // — `UpdateEnvironment` deploys settings onto the
                    // environment rather than describing the set they form — so
                    // the environment's own description is what describes it,
                    // rather than a sentence invented here.
                    description: environment.description.clone(),
                    // "deployed: This is the configuration that is currently
                    // deployed to the associated running environment."
                    deployment_status: Some(crate::state::DEPLOYMENT_STATUS_DEPLOYED.to_string()),
                    date_created: Some(environment.date_created),
                    date_updated: Some(environment.date_updated),
                    option_settings: Some(deployed_settings),
                    // A configuration set associated with a running
                    // environment is not a saved template, so it has no stored
                    // template document and no location for one; the three
                    // members a READ carries are added below.
                    ..Default::default()
                };
                let deployed =
                    read_of_a_configuration_set(deployed, deployed_details, tier.clone());
                let draft = environment.draft_configuration.as_ref().map(|draft| {
                    let described = CreateConfigurationTemplateOutput {
                        // The platform version the DRAFT belongs to, which is
                        // the one the update that created it deploys.
                        solution_stack_name: draft.solution_stack_name.clone(),
                        platform_arn: draft.platform_arn.clone(),
                        application_name: Some(environment.application_name.clone()),
                        // A draft of an environment's configuration is no more a
                        // template than the deployed one is.
                        template_name: None,
                        environment_name: Some(environment.environment_name.clone()),
                        description: environment.description.clone(),
                        // `pending` while the deployment that created it is in
                        // flight, `failed` once that deployment was cancelled:
                        // "the DeploymentStatus for the draft configuration
                        // indicates whether the deployment is in process or has
                        // failed".
                        deployment_status: Some(draft.deployment_status.clone()),
                        // The draft is a configuration set of its own, so it
                        // reports when IT was created and last changed — not the
                        // environment's instants.
                        date_created: Some(draft.date_created),
                        date_updated: Some(draft.date_updated),
                        option_settings: Some(store.resolved_configuration_settings(
                            &region,
                            draft.solution_stack_name.as_deref(),
                            draft.platform_arn.as_deref(),
                            &draft.option_settings,
                        )),
                        ..Default::default()
                    };
                    // The draft's OWN settings are what its detail is about,
                    // resolved and attributed against the catalog of the
                    // platform version IT deploys; an update cannot change the
                    // environment's tier, so the draft is a configuration for
                    // the same tier.
                    let details = store.resolved_configuration_setting_details(
                        &region,
                        draft.solution_stack_name.as_deref(),
                        draft.platform_arn.as_deref(),
                        &draft.option_settings,
                    );
                    read_of_a_configuration_set(described, details, tier.clone())
                });
                [Some(deployed), draft].into_iter().flatten().collect()
            }
        };

        Ok(DescribeConfigurationSettingsOutput {
            configuration_settings: Some(settings),
        })
    }
}

/// The members a READ of a configuration set carries beyond the modelled
/// `ConfigurationSettingsDescription`, added to the projection `description`
/// holds.
///
/// RECORDED BEHAVIOUR, not modelled: every `ConfigurationSettings` member of a
/// `DescribeConfigurationSettings` answer carries `OptionSettingDetails` (where
/// each resolved option's value came from), `EnvironmentLinkPoints` and the
/// `Tier` the configuration is for. `EnvironmentLinkPoints` is reported empty:
/// a configuration set links to no environment here — `EnvironmentLink` is a
/// member of an ENVIRONMENT's description, not of a configuration set — so
/// there is no link point to name in it.
///
/// The one place those three are written, so the template branch, the deployed
/// configuration and the draft cannot report them three ways.
fn read_of_a_configuration_set(
    description: CreateConfigurationTemplateOutput,
    option_setting_details: Vec<OptionSettingDetail>,
    tier: EnvironmentTier,
) -> CreateConfigurationTemplateOutput {
    CreateConfigurationTemplateOutput {
        option_setting_details: Some(option_setting_details),
        environment_link_points: Some(String::new()),
        tier: Some(tier),
        ..description
    }
}

/// Which configuration set the request named: "either a configuration template
/// or the configuration set associated with a running environment". The request
/// names exactly one of the two, so the pair of optional members is reduced to
/// this choice once, before anything is resolved.
enum ConfigurationSet<'a> {
    /// `TemplateName`, resolved inside the request's application.
    Template(&'a str),
    /// `EnvironmentName`.
    Environment(&'a str),
}
