/// The segment that names THIS service's webhook trigger plane behind
/// [`EMULATOR_PATH_NAMESPACE`].
///
/// Service-qualified, as the sibling planes of this tree are: more than one AWS service
/// publishes a webhook URL (CodeBuild's projects carry a `payloadUrl` of their own), so a
/// label naming only the KIND of plane would be a path two services could both claim.
const WEBHOOK_PLANE_LABEL: &str = "codepipeline-webhooks";

/// The last path segment of a published trigger URL: the action a POST to it performs.
const TRIGGER_SEGMENT: &str = "trigger";

/// The query parameter carrying the opaque token that names which webhook is being
/// triggered — the only part of the URL that identifies it.
const TOKEN_PARAMETER: &str = "t";

/// The query parameter stating which form of trigger URL this is, and the one value this
/// plane publishes. CodePipeline's own trigger URLs carry it, so a URL a client holds names
/// the form it was minted in rather than relying on the path alone.
const URL_VERSION_PARAMETER: &str = "v";
/// See [`URL_VERSION_PARAMETER`].
const URL_VERSION: &str = "1";

/// The status a trigger request is ACKNOWLEDGED with, whether or not it started an
/// execution. A provider reads a 2xx as "delivered"; whether the payload satisfied the
/// webhook's authentication and filters is not something it is told.
const ACCEPTED_STATUS: u16 = 200;

/// What an address naming no webhook of this account is answered with: the URL names no
/// resource here.
const NOT_FOUND_STATUS: u16 = 404;

/// What a method the published URL does not describe is answered with.
const METHOD_NOT_ALLOWED_STATUS: u16 = 405;

/// What a request this emulator cannot reach its own store for is answered with.
const STORE_UNAVAILABLE_STATUS: u16 = 500;

/// The media type this plane states an answer in: a sentence for whoever is reading the
/// response by hand, carrying nothing a caller sent.
const TEXT_CONTENT_TYPE: &str = "text/plain; charset=utf-8";

/// How large a payload this plane reads a trigger out of.
///
/// The provider's payload is CALLER-supplied and the JSON document is what the filters are
/// evaluated against, so the work one trigger costs is bounded before anything is parsed:
/// a body past this figure is acknowledged and starts nothing, exactly as a payload whose
/// filters do not match is. This emulator's own bound — no webhook payload size is
/// documented — chosen as the largest document a source-change notification carries in
/// practice.
const MAX_TRIGGER_PAYLOAD_BYTES: usize = 1024 * 1024;

/// How many nodes a payload this plane evaluates filters against may carry, and how deep it
/// may nest.
///
/// The byte bound alone does not bound the WORK, because a JsonPath descendant segment is
/// evaluated against every node an earlier segment selected: the cost of one expression is a
/// function of the document's node count and depth, not of its length. Both are therefore
/// counted before any expression runs ([`within_payload_bounds`]), by a walk that is itself
/// bounded by the node figure, and a document past either is one no filter is evaluated
/// against. Generous for what a source-change notification is — a few hundred nodes nested
/// half a dozen deep — so no real payload reaches either.
const MAX_PAYLOAD_NODES: usize = 4096;
/// See [`MAX_PAYLOAD_NODES`].
const MAX_PAYLOAD_DEPTH: usize = 16;

/// How many DESCENDANT segments (`..`) a `jsonPath` expression may carry for this plane to
/// evaluate it.
///
/// It is the exponent in the cost of one expression: with the document bounded by
/// [`MAX_PAYLOAD_NODES`] and [`MAX_PAYLOAD_DEPTH`], an expression carrying at most this many
/// descendant segments costs at most nodes × depth² node visits, so the work one trigger
/// costs is a function of bounded inputs and needs no clock to stop it. An expression
/// carrying more is one this plane does not evaluate, so its rule does not pass and the
/// trigger starts nothing — the same answer an unmatched filter gets. This emulator's own
/// bound; `WebhookFilterRule$jsonPath` admits any JsonPath expression, and the filters
/// CodePipeline's own documentation gives (`$.ref`, `$.repository.name`) carry none.
const MAX_DESCENDANT_SEGMENTS: usize = 2;

/// How a descendant segment is spelled in a JsonPath expression.
const DESCENDANT_SEGMENT: &str = "..";

/// The signature headers a provider proves a `GITHUB_HMAC` payload with, and the digest each
/// one is computed under.
///
/// GitHub signs a webhook payload with the webhook's secret and sends the result in
/// `X-Hub-Signature` (HMAC-SHA1) and `X-Hub-Signature-256` (HMAC-SHA256), each written
/// `<algorithm>=<hex digest>`. The algorithm a signature is checked under is the one its
/// VALUE names, so a header carrying a digest the other size is not verified under the wrong
/// one; the header names are the addresses those values arrive at.
const SIGNATURE_HEADERS: &[&str] = &["x-hub-signature", "x-hub-signature-256"];

/// The algorithm name an HMAC-SHA1 signature value carries.
const SIGNATURE_ALGORITHM_SHA1: &str = "sha1";

/// The algorithm name an HMAC-SHA256 signature value carries.
const SIGNATURE_ALGORITHM_SHA256: &str = "sha256";

/// The header a client or a proxy in front of this emulator states the address a request
/// came FROM in — the one an `IP` webhook's `AllowedIPRange` is checked against
/// ([`source_address`]), named here as the other planes of this tree name it.
const FORWARDED_FOR_HEADER: &str = "x-forwarded-for";

/// The character that opens a placeholder in `WebhookFilterRule$matchEquals`.
const PLACEHOLDER_OPEN: char = '{';

/// The character that closes one.
const PLACEHOLDER_CLOSE: char = '}';

/// One webhook's trigger URL on an address this emulator answers on:
/// `https://<authority>/_aws/codepipeline-webhooks/<region>/trigger?t=<token>&v=1`.
///
/// It carries what CodePipeline's own trigger host carries — the Region the webhook was
/// defined in — with that Region moved out of the host and into the PATH, because a client
/// on the machine this emulator runs on resolves no AWS hostname and the only address it can
/// dial is the endpoint it already reached. The token is the whole identity of the URL, as
/// it is on AWS.
///
/// The scheme is `https` whatever the endpoint base carries: every listener of this process
/// presents the core's certificate, and the trigger URL IS an HTTPS endpoint a provider is
/// configured with.
#[must_use]
pub fn trigger_url(authority: &str, region: &str, token: &str) -> String {
    format!(
        "https://{authority}/{EMULATOR_PATH_NAMESPACE}/{WEBHOOK_PLANE_LABEL}/{region}/\
         {TRIGGER_SEGMENT}?{TOKEN_PARAMETER}={token}&{URL_VERSION_PARAMETER}={URL_VERSION}"
    )
}

/// The trigger URL this service PUBLISHES for a webhook defined in `region`, resolved once
/// when the webhook is created and stored, so every later read reports the same value.
///
/// The address is the one this emulator is reached at, in the order every data plane served
/// at the front door announces one in:
///
/// * the EMULATOR'S OWN endpoint the defining request addressed
///   (`service_common::data_plane_addressing::reached_emulator_endpoint`) comes from a client
///   that resolves nothing else, so the URL is published there;
/// * a webhook defined through any other request on an emulator that IS served on a port
///   (`served_endpoint_authority`) is published on that port, the one address this process
///   answers on, so a webhook minted by an in-process call of another service publishes an
///   address its caller can reach too;
/// * an emulator served on no port at all has one base to name, the one
///   `OperationContext::endpoint` reports for it, and the URL is published there — a host
///   nothing resolves, which is the truth about an emulator that serves no port, rather than
///   an AWS hostname this emulator does not answer on.
#[must_use]
pub fn announced_trigger_url(
    ctx: &OperationContext<'_>,
    region: &str,
    token: &str,
) -> String {
    let base = ctx.endpoint();
    let authority = reached_emulator_endpoint(
        &ctx.parts().uri.to_string(),
        ctx.parts()
            .headers
            .get(::http::header::HOST)
            .and_then(|host| host.to_str().ok()),
    )
    .or_else(|| served_endpoint_authority(base.as_str()))
    .unwrap_or_else(|| url_authority(base.as_str()).trim_end_matches('/').to_string());
    trigger_url(&authority, region, token)
}

/// Which webhook a trigger request addresses: the Region its URL was minted in and the
/// opaque token that names it, which together name exactly one stored webhook
/// (`state::ComAmazonawsCodepipelineCodepipeline20150709State::webhook_by_trigger_token_mut`).
#[derive(Debug, Clone, PartialEq, Eq)]
struct AddressedWebhook {
    /// The Region segment the path carries.
    region: String,
    /// The token the `t` query parameter carries.
    token: String,
}

/// Whether `path` addresses this plane at all — the reserved namespace segment, the segment
/// that names this surface, a Region segment and the trigger segment, and nothing after
/// them.
///
/// It is what the service CLAIMS such a request on: a path on this plane is this service's to
/// answer however the rest of it reads, so a client holding a URL this service published is
/// never answered by the front door's "unknown service", and a URL whose token names no
/// webhook is answered here rather than there.
fn addresses_trigger_plane(path: &str) -> bool {
    addressed_region(path).is_some()
}

/// The Region a path on this plane names, or `None` for a path that is not one
/// [`trigger_url`] mints.
///
/// The inverse of that function, so what is recognised is exactly what is published: each
/// segment is compared whole, the Region segment has to be one an ARN of this service can
/// carry ([`crate::state::is_region_token`]) and the trigger segment has to be the last one,
/// bar an empty trailing segment — a URL a client pasted with its trailing slash.
fn addressed_region(path: &str) -> Option<&str> {
    let (namespace, rest) = first_segment(path)?;
    if namespace != EMULATOR_PATH_NAMESPACE {
        return None;
    }
    let (plane, rest) = first_segment(rest)?;
    if plane != WEBHOOK_PLANE_LABEL {
        return None;
    }
    let (region, rest) = first_segment(rest)?;
    if !crate::state::is_region_token(region) {
        return None;
    }
    let (trigger, rest) = first_segment(rest)?;
    (trigger == TRIGGER_SEGMENT && rest == "/").then_some(region)
}

/// The webhook a request URI addresses, or `None` when it addresses none: the path names the
/// plane and the Region, the query carries the token, and the version it states is the form
/// this plane publishes — a URL stating another is not one it minted, so it names no webhook.
fn addressed_webhook(uri: &str) -> Option<AddressedWebhook> {
    let region = addressed_region(::service_common::request_path(uri))?;
    let query = uri.split_once('?').map_or("", |(_path, query)| query);
    if ::service_common::query_parameter(query, URL_VERSION_PARAMETER) != Some(URL_VERSION) {
        return None;
    }
    let token = ::service_common::query_parameter(query, TOKEN_PARAMETER)?;
    (!token.is_empty()).then(|| AddressedWebhook {
        region: region.to_string(),
        token: token.to_string(),
    })
}

/// Whether the buffered request parts `Service::can_handle` is handed address this plane,
/// read by the same rule [`WebhookTriggerPlane::claims`] applies, so the claim and the answer
/// cannot disagree about which requests this plane serves.
#[must_use]
pub fn claims_parts(parts: &http::request::Parts) -> bool {
    addresses_trigger_plane(parts.uri.path())
}

/// The webhook trigger plane, as the one [`ErasedOperation`] the service holds for it.
///
/// Owns the shared engine exactly as a generated operation does, so every answer is computed
/// from the SAME per-service store the control plane's handlers write: a URL serves only
/// while the webhook it names is stored, and one `DeleteWebhook` removed serves nothing.
pub struct WebhookTriggerPlane<Eng> {
    engine: Arc<Eng>,
}

impl<Eng> WebhookTriggerPlane<Eng> {
    /// Build the plane from the shared engine.
    pub fn new(engine: Arc<Eng>) -> Self {
        Self { engine }
    }
}

impl<Eng: Send + Sync + 'static> ErasedOperation for WebhookTriggerPlane<Eng> {
    fn run<'r>(
        &'r self,
        _svc: &'r dyn Service,
        req: &'r RtRequest,
        ctx: &'r OperationContext<'r>,
    ) -> BoxFuture<'r, RtResponse> {
        Box::pin(async move { self.serve(req, ctx).await })
    }

    fn auth_schemes(&self) -> Option<&'static [&'static str]> {
        // A third party configured with a webhook's trigger URL presents no AWS credential
        // and holds none to sign with: it proves itself with the webhook's own
        // `authentication` instead, which this plane checks. The plane therefore declares no
        // scheme and serves the request however it arrived — it is not a modelled operation,
        // so no model states one for it, and it claims only an address this service
        // published.
        Some(&[])
    }
}

impl<Eng: Send + Sync + 'static> WebhookTriggerPlane<Eng> {
    /// Whether this plane serves `req`, by the one rule the claim uses
    /// ([`addresses_trigger_plane`]).
    pub fn claims(&self, req: &RtRequest) -> bool {
        addresses_trigger_plane(::service_common::request_path(req.uri()))
    }

    /// Serve one POST to a published trigger URL.
    ///
    /// Three phases, so no part of the caller-driven work happens while this service's store
    /// is locked: the store is READ (the webhook and its target's declaration) and released,
    /// the request is then judged against what was read with no lock held, and the store is
    /// taken again only to record what a satisfied trigger owes.
    async fn serve(&self, req: &RtRequest, ctx: &OperationContext<'_>) -> RtResponse {
        if req.method() != "POST" {
            return answered(
                METHOD_NOT_ALLOWED_STATUS,
                "A webhook is triggered with POST.",
            );
        }
        let Some(addressed) = addressed_webhook(req.uri()) else {
            return answered(NOT_FOUND_STATUS, "This URL names no webhook.");
        };
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return answered(
                STORE_UNAVAILABLE_STATUS,
                "The CodePipeline store is unavailable.",
            );
        };

        // PHASE 1 — what the store says, read under the lock and carried out of it: the
        // webhook this URL names, the Region it was defined in, and the declaration of the
        // pipeline it targets (where a `matchEquals` placeholder is resolved from). The lock
        // is held for these reads alone.
        let held = {
            let store = state.lock();
            store
                .webhook_by_trigger_token(&addressed.region, &addressed.token)
                .map(|webhook| {
                    let definition = webhook.definition.clone();
                    let declaration = store
                        .pipelines
                        .get(&definition.target_pipeline)
                        .map(|pipeline| pipeline.declaration.clone());
                    (definition, webhook.region.clone(), declaration)
                })
        };
        let Some((definition, region, declaration)) = held else {
            return answered(NOT_FOUND_STATUS, "This URL names no webhook.");
        };

        // PHASE 2 — whether this request is one the webhook acts on, judged with NO lock
        // held. The payload is BOUNDED first ([`MAX_TRIGGER_PAYLOAD_BYTES`]), so neither the
        // signature verification nor the document the filters are evaluated against is sized
        // by what a caller sent.
        let body = req.body().bytes().unwrap_or_default();
        let bounded: &[u8] = if body.len() <= MAX_TRIGGER_PAYLOAD_BYTES {
            body
        } else {
            &[]
        };
        let ignored = if !authenticates(&definition, bounded, req) {
            Some(Ignored::Authentication)
        } else if definition.filters.is_empty() {
            // "All defined rules must pass for the request to be accepted and the pipeline
            // started": a definition stating NO rule (`WebhookFilters` is
            // `@length(min: 0, max: 5)`) has none to fail, so an authenticated POST starts
            // the pipeline whatever its body carries — nothing is evaluated against it.
            None
        } else if bounded.len() != body.len() {
            Some(Ignored::PayloadPastTheBound)
        } else {
            match ::serde_json::from_slice::<::serde_json::Value>(bounded) {
                Err(_) => Some(Ignored::NotADocument),
                // The document's SHAPE is bounded before any expression is evaluated
                // against it, because that shape — not its length — is what the cost of a
                // JsonPath expression is a function of.
                Ok(payload) if !within_payload_bounds(&payload) => {
                    Some(Ignored::PayloadPastTheBound)
                }
                Ok(payload) => {
                    filters_match(&definition, declaration.as_ref(), &payload).err()
                }
            }
        };
        if let Some(ignored) = ignored {
            // The record a delivered trigger leaves: which webhook was dialled, that it
            // started nothing, and WHY — so a payload past the bound is diagnosable rather
            // than indistinguishable from an unmatched filter. Metadata only: no part of the
            // payload, and nothing of the secret it failed to prove.
            ::tracing::info!(
                webhook = %definition.name,
                region = %region,
                started = false,
                ignored = ignored.reason(),
                "a webhook trigger was delivered"
            );
            return acknowledged();
        }

        // PHASE 3 — what a satisfied trigger owes the store, under the lock again: the
        // execution it starts and the instant it fired. The webhook is re-resolved, so one
        // deleted while this request was being judged starts nothing.
        let started = {
            let mut store = state.lock();
            if store
                .webhook_by_trigger_token(&addressed.region, &addressed.token)
                .is_none()
            {
                return answered(NOT_FOUND_STATUS, "This URL names no webhook.");
            }
            let now = SystemTime::now();
            // "The pipeline defined in the webhook is started": the start that carries no
            // caller input, through the one path such a start takes.
            let started = crate::state::start_execution(
                &mut store,
                &definition.target_pipeline,
                crate::state::TRIGGER_TYPE_WEBHOOK,
                &region,
                now,
            );
            if started.is_some() {
                // "The date and time a webhook was last successfully triggered": recorded
                // only for a trigger that started the pipeline, so a request the filters
                // ignored — and one naming a pipeline this account no longer holds — leaves
                // the member absent.
                if let Some(webhook) =
                    store.webhook_by_trigger_token_mut(&addressed.region, &addressed.token)
                {
                    webhook.last_triggered = Some(now);
                }
            }
            ::tracing::info!(
                webhook = %definition.name,
                pipeline = %definition.target_pipeline,
                region = %region,
                started = started.is_some(),
                "a webhook trigger was delivered"
            );
            started.map(|_| (definition.target_pipeline, region))
        };

        // The execution's first step is not due yet (it becomes due a span from now), so this
        // only publishes the start and then sets this store's clock running, exactly as the
        // operations that start an execution do. The Region is the webhook's own: this
        // request is unsigned, so there is no credential scope to read one from.
        if let Some((pipeline_name, region)) = started {
            crate::state::driver::advance_in_region(
                &*self.engine,
                ctx.callback(),
                &region,
                &pipeline_name,
            )
            .await;
        }
        acknowledged()
    }
}

/// Why a delivered trigger started nothing — what the record of it states, so a payload past
/// the bounds, a body that is no document, an expression past the bound and a filter that did
/// not match are each diagnosable rather than one indistinguishable "ignored".
///
/// None of these reaches the CALLER: every delivered trigger is acknowledged the same way,
/// because a provider is not told whether the payload it signed satisfied the webhook.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Ignored {
    /// The request did not satisfy the webhook's `authentication`.
    Authentication,
    /// The body is larger than [`MAX_TRIGGER_PAYLOAD_BYTES`], or the document it carries
    /// more than [`MAX_PAYLOAD_NODES`] nodes or deeper than [`MAX_PAYLOAD_DEPTH`], so no
    /// filter was evaluated against it.
    PayloadPastTheBound,
    /// The body is not a JSON document, so no filter selects anything from it.
    NotADocument,
    /// Some filter's `jsonPath` carries more than [`MAX_DESCENDANT_SEGMENTS`] descendant
    /// segments, so this plane does not evaluate it.
    FilterPastTheBound,
    /// Some filter's `jsonPath` selected no value equal to its `matchEquals`.
    Filters,
}

impl Ignored {
    /// The one word the record states this with.
    fn reason(self) -> &'static str {
        match self {
            Self::Authentication => "authentication",
            Self::PayloadPastTheBound => "payload-past-the-bound",
            Self::NotADocument => "not-a-document",
            Self::FilterPastTheBound => "filter-past-the-bound",
            Self::Filters => "filters",
        }
    }
}

/// Whether `payload` is a document this plane evaluates filters against: at most
/// [`MAX_PAYLOAD_NODES`] nodes, nested at most [`MAX_PAYLOAD_DEPTH`] deep.
///
/// The walk is iterative and its own cost is bounded by the node figure — it stops at the
/// first node past it — so measuring a document is never more work than evaluating one.
/// Nothing recurses on caller-controlled depth.
fn within_payload_bounds(payload: &::serde_json::Value) -> bool {
    let mut pending: Vec<(&::serde_json::Value, usize)> = vec![(payload, 1)];
    let mut nodes = 0usize;
    while let Some((node, depth)) = pending.pop() {
        nodes += 1;
        if nodes > MAX_PAYLOAD_NODES || depth > MAX_PAYLOAD_DEPTH {
            return false;
        }
        match node {
            ::serde_json::Value::Array(items) => {
                pending.extend(items.iter().map(|item| (item, depth + 1)));
            }
            ::serde_json::Value::Object(members) => {
                pending.extend(members.values().map(|value| (value, depth + 1)));
            }
            _ => {}
        }
    }
    true
}

/// How many DESCENDANT segments `expression` carries — the exponent in what evaluating it
/// costs ([`MAX_DESCENDANT_SEGMENTS`]).
///
/// Counted on the expression as written, by non-overlapping occurrences of the two
/// characters that spell one; the expression is at most 150 characters (`JsonPath` is
/// `@length(min: 1, max: 150)`), so counting is bounded too.
fn descendant_segments(expression: &str) -> usize {
    expression.matches(DESCENDANT_SEGMENT).count()
}

/// Whether `req`, carrying `body`, satisfies the `authentication` the webhook `definition`
/// states.
///
/// `body` is the bounded payload the signature is verified over
/// ([`MAX_TRIGGER_PAYLOAD_BYTES`]), not the request's own bytes, so no part of what a caller
/// sent sizes the work one check costs.
///
/// `WebhookDefinition$authentication`'s own documentation states what each type requires,
/// and each is checked against the request rather than assumed:
///
/// * `GITHUB_HMAC` — the payload carries a signature computed with the webhook's
///   `SecretToken`, which is "an arbitrary string that you provide, which GitHub uses to
///   compute and sign the webhook payloads sent to CodePipeline, for protecting the
///   integrity and authenticity of the webhook payloads" ([`signature_proves`]).
/// * `IP` — the request comes from an address inside `AllowedIPRange`
///   ([`address_in_range`]).
/// * `UNAUTHENTICATED` — the type whose configuration carries no property at all, so there
///   is nothing for a request to prove.
///
/// A webhook whose configuration does not carry the property its type uses cannot be stored
/// (`state::validate_webhook_definition`), so an absent property here is a type that uses
/// none.
fn authenticates(definition: &WebhookDefinition, body: &[u8], req: &RtRequest) -> bool {
    let configuration = &definition.authentication_configuration;
    match definition.authentication.as_str() {
        crate::state::AUTHENTICATION_GITHUB_HMAC => configuration
            .secret_token
            .as_deref()
            .is_some_and(|secret| signature_proves(secret, body, req)),
        crate::state::AUTHENTICATION_IP => configuration
            .allowed_ip_range
            .as_deref()
            .is_some_and(|range| {
                source_address(req).is_some_and(|address| address_in_range(&address, range))
            }),
        crate::state::AUTHENTICATION_UNAUTHENTICATED => true,
        // `WebhookAuthenticationType` is a modelled enum and a definition carrying any other
        // value cannot be stored, so a webhook that reached this plane with one is a webhook
        // nothing can prove itself to.
        _ => false,
    }
}

/// Whether one of the signatures `req` carries proves `body` was signed with `secret`.
///
/// A provider sends the signature it computed in one of the headers that carry one
/// ([`SIGNATURE_HEADERS`]); a request that carries none proves nothing, and a request that
/// carries several proves the payload when any one of them verifies — which is what a client
/// sending both of GitHub's digests does.
///
/// The comparison is the MAC crate's own `verify_slice`, which compares in constant time, so
/// nothing about a wrong signature is learned from how long the answer took.
fn signature_proves(secret: &str, body: &[u8], req: &RtRequest) -> bool {
    SIGNATURE_HEADERS
        .iter()
        .filter_map(|header| req.headers().get(*header))
        .filter_map(|value| value.split_once('='))
        .any(|(algorithm, digest)| {
            let Ok(signature) = ::hex::decode(digest.trim()) else {
                return false;
            };
            match algorithm.trim().to_ascii_lowercase().as_str() {
                SIGNATURE_ALGORITHM_SHA1 => sha1_signs(secret, body, &signature),
                SIGNATURE_ALGORITHM_SHA256 => sha256_signs(secret, body, &signature),
                // A digest this plane does not compute cannot be checked, so it proves
                // nothing.
                _ => false,
            }
        })
}

/// Whether `signature` is the HMAC-SHA1 of `body` under `secret`.
fn sha1_signs(secret: &str, body: &[u8], signature: &[u8]) -> bool {
    use ::hmac::Mac as _;
    let Ok(mut mac) =
        <::hmac::Hmac<::sha1::Sha1> as ::hmac::Mac>::new_from_slice(secret.as_bytes())
    else {
        return false;
    };
    mac.update(body);
    mac.verify_slice(signature).is_ok()
}

/// Whether `signature` is the HMAC-SHA256 of `body` under `secret`.
fn sha256_signs(secret: &str, body: &[u8], signature: &[u8]) -> bool {
    use ::hmac::Mac as _;
    let Ok(mut mac) =
        <::hmac::Hmac<::sha2::Sha256> as ::hmac::Mac>::new_from_slice(secret.as_bytes())
    else {
        return false;
    };
    mac.update(body);
    mac.verify_slice(signature).is_ok()
}

/// The address a trigger request came FROM, as the request states it, or `None` when it
/// states none.
///
/// The emulator serves this plane at its own front door and the request carries its origin
/// only where a client or a proxy in front of it says so, in the forwarding header that
/// conventionally carries it — whose first element is the client the chain started at. A
/// request that states no origin address cannot be placed inside an `AllowedIPRange`, so an
/// `IP` webhook ignores it rather than being triggered by an address nothing established.
fn source_address(req: &RtRequest) -> Option<String> {
    let forwarded = req.headers().get(FORWARDED_FOR_HEADER)?;
    let first = forwarded.split(',').next().unwrap_or_default().trim();
    (!first.is_empty()).then(|| first.to_string())
}

/// Whether the address `address` names lies in the network `range` names.
///
/// Both sides are read as ADDRESSES rather than as text, by the tree's IP-network parser:
/// `AllowedIPRange` "must be set to a valid CIDR range", so a range holds for every address
/// of its block and not only for one spelling of it, and a range naming a single address is
/// the host network that address is.
fn address_in_range(address: &str, range: &str) -> bool {
    let Ok(address) = address.parse::<::std::net::IpAddr>() else {
        return false;
    };
    let range = range.trim();
    match range.parse::<::ipnet::IpNet>() {
        Ok(network) => network.contains(&address),
        Err(_) => range
            .parse::<::std::net::IpAddr>()
            .is_ok_and(|single| single == address),
    }
}

/// Whether every filter the webhook `definition` states passes over `payload`, and why not
/// when one does not.
///
/// "A list of rules applied to the body/payload sent in the POST request to a webhook URL.
/// All defined rules must pass for the request to be accepted and the pipeline started"
/// (`WebhookDefinition$filters`), and one rule passes when "the value selected by the
/// JsonPath expression … match[es] the value specified in the `MatchEquals` field"
/// (`WebhookFilterRule$jsonPath`). A definition stating NO filter states no rule to fail, so
/// every payload passes it.
///
/// What one evaluation COSTS is bounded by its inputs alone, with no clock in it: the
/// document carries at most [`MAX_PAYLOAD_NODES`] nodes at most [`MAX_PAYLOAD_DEPTH`] deep
/// (the caller checks that before calling, [`within_payload_bounds`]), the model admits at
/// most five expressions of at most 150 characters, and an expression carrying more than
/// [`MAX_DESCENDANT_SEGMENTS`] descendant segments is not evaluated at all — which is what
/// caps the one factor a length cannot, since a descendant segment is evaluated against
/// every node an earlier one selected.
///
/// `declaration` is the target pipeline's, which is where a `matchEquals` placeholder is
/// resolved from ([`resolved_match`]).
fn filters_match(
    definition: &WebhookDefinition,
    declaration: Option<&PipelineDeclaration>,
    payload: &::serde_json::Value,
) -> Result<(), Ignored> {
    for filter in &definition.filters {
        if descendant_segments(&filter.json_path) > MAX_DESCENDANT_SEGMENTS {
            return Err(Ignored::FilterPastTheBound);
        }
        // At most five expressions of at most 150 characters each reach the parser
        // (`WebhookFilters` is `@length(min: 0, max: 5)` and `JsonPath` 1..150), and a
        // definition carrying an expression that does not parse cannot be stored
        // (`state::validate_webhook_definition`), so one that does not parse here selects
        // nothing and its rule does not pass.
        let Ok(path) = ::serde_json_path::JsonPath::parse(&filter.json_path) else {
            return Err(Ignored::Filters);
        };
        let selected = path.query(payload);
        let passes = match filter.match_equals.as_deref() {
            // "The value selected by the JsonPath expression must match what is supplied in
            // the MatchEquals field. Otherwise, the request is ignored."
            Some(expected) => {
                let expected = resolved_match(expected, definition, declaration);
                selected
                    .iter()
                    .any(|node| selected_text(node) == expected)
            }
            // A rule stating no value to match states only that the expression selects
            // something from the payload.
            None => selected.iter().next().is_some(),
        };
        if !passes {
            return Err(Ignored::Filters);
        }
    }
    Ok(())
}

/// The text a selected JSON node matches as.
///
/// `MatchEquals` is a string, so a selected string matches as its own content — not as the
/// quoted JSON it was written in — and anything else matches as the JSON it is, which is the
/// only rendering a number, a boolean or a structure has.
fn selected_text(node: &::serde_json::Value) -> String {
    match node {
        ::serde_json::Value::String(text) => text.clone(),
        other => other.to_string(),
    }
}

/// `matchEquals` with its placeholders resolved.
///
/// "Properties from the target action configuration can be included as placeholders in this
/// value by surrounding the action configuration key with curly brackets. For example, if
/// the value supplied here is `refs/heads/{Branch}` and the target action has an action
/// configuration property called `Branch` with a value of `main`, the `MatchEquals` value is
/// evaluated as `refs/heads/main`" — so each `{Key}` is replaced by the value the webhook's
/// `targetAction` declares for that configuration key, and a placeholder naming a key that
/// action does not declare resolves to nothing and is left as written, which no payload
/// value matches.
fn resolved_match(
    match_equals: &str,
    definition: &WebhookDefinition,
    declaration: Option<&PipelineDeclaration>,
) -> String {
    if !match_equals.contains(PLACEHOLDER_OPEN) {
        return match_equals.to_string();
    }
    let configuration = declaration.and_then(|declaration| {
        declaration
            .stages
            .iter()
            .flat_map(|stage| stage.actions.iter())
            .find(|action| action.name == definition.target_action)
            .and_then(|action| action.configuration.as_ref())
    });
    let mut resolved = String::with_capacity(match_equals.len());
    let mut rest = match_equals;
    while let Some((before, after)) = rest.split_once(PLACEHOLDER_OPEN) {
        resolved.push_str(before);
        let Some((key, after)) = after.split_once(PLACEHOLDER_CLOSE) else {
            // An unclosed placeholder is not one: the rest of the value is its own text.
            resolved.push(PLACEHOLDER_OPEN);
            resolved.push_str(after);
            return resolved;
        };
        match configuration.and_then(|configuration| configuration.get(key)) {
            Some(value) => resolved.push_str(value),
            None => {
                resolved.push(PLACEHOLDER_OPEN);
                resolved.push_str(key);
                resolved.push(PLACEHOLDER_CLOSE);
            }
        }
        rest = after;
    }
    resolved.push_str(rest);
    resolved
}

/// The acknowledgement a delivered trigger is answered with: the payload reached the
/// webhook, and whether it started the pipeline is not something the provider is told.
fn acknowledged() -> RtResponse {
    answered(ACCEPTED_STATUS, "Accepted.")
}

/// One answer on this wire: the status and the sentence that says what happened, as fixed
/// text — an answer here quotes nothing a caller sent.
fn answered(status: u16, message: &str) -> RtResponse {
    let body = format!("{message}\n").into_bytes();
    let length = body.len();
    let mut answer = RtResponse::new(
        StatusCode::try_from(status).expect("the status is a constant of this module"),
        SdkBody::from(body),
    );
    let headers = answer.headers_mut();
    headers.insert("content-type", TEXT_CONTENT_TYPE.to_string());
    headers.insert("content-length", length.to_string());
    answer
}

