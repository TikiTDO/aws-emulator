//! The webhook TRIGGER plane: the wire `ListWebhookItem$url` publishes.
//!
//! # Not a modelled operation
//!
//! Every operation this service models is control plane: it defines webhooks, reads them
//! back, registers them with the third party and deletes them. What the third party then
//! does with the URL `PutWebhook`/`ListWebhooks` hand back is its own protocol — a plain
//! `POST <url>` carrying the provider's payload and the signature it computed over it.
//! None of that is a modelled operation and none of it carries an `X-Amz-Target`: it is
//! addressed by path and query, so nothing in the generated routing table can name it, and
//! it is reached through the two seams [`crate::service::EmulatedService`] has for a request
//! the model's routing key cannot name ([`claims_parts`], [`WebhookTriggerPlane`]).
//!
//! A provider calling a webhook holds no AWS credential — it holds the webhook's own secret
//! — so this plane declares no auth scheme and serves the request however it arrived. It
//! still claims only an address this service PUBLISHED, and answers only out of webhooks the
//! control plane persisted.
//!
//! # Where it is addressed
//!
//! `ListWebhookItem$url` is "a unique URL generated by CodePipeline. When a POST request is
//! made to this URL, the defined pipeline is started as long as the body of the post request
//! satisfies the defined authentication and filtering", so the URL is the data-plane address
//! a provider dials. An address a client dials has to be one this emulator itself answers
//! on, so the published URL names the endpoint the request that minted it reached
//! ([`announced_trigger_url`]), with the Region and this plane's own label in the PATH
//! behind the reserved segment every data plane served on the emulator's own endpoint sits
//! under (`service_common::data_plane_addressing`) — a path under that segment naming
//! another plane is never read as this one's.
//!
//! # What is served
//!
//! `POST /_aws/codepipeline-webhooks/<region>/trigger?t=<token>&v=1` starts one execution of
//! the webhook's
//! `targetPipeline` when, and only when, the request satisfies the webhook's own
//! `authentication` and every one of its `filters`; a request that satisfies them is
//! answered [`ACCEPTED_STATUS`] and a request that does not is answered the same way with
//! nothing started, because "otherwise, the request is ignored"
//! (`WebhookFilterRule$jsonPath`) — a provider is not told the payload it signed was
//! rejected, and an unauthenticated POST learns nothing about the secret it failed to prove.
//!
//! An address naming no webhook this account holds is [`NOT_FOUND_STATUS`], and every method
//! but `POST` is [`METHOD_NOT_ALLOWED_STATUS`]: the published URL describes the one write a
//! provider makes.
//!
//! Serving writes only what a trigger owes: the execution a satisfied request starts, and
//! that webhook's `lastTriggered` — "the date and time a webhook was last successfully
//! triggered". A request this plane ignores leaves the store exactly as it was.
//!
//! # What one trigger costs
//!
//! Both halves of the judgement are driven by CALLER input — the payload by this POST, the
//! `jsonPath` expressions by whoever defined the webhook — so each is bounded by its INPUTS
//! before it runs, and the store's lock is held for neither:
//!
//! * the body is read only up to [`MAX_TRIGGER_PAYLOAD_BYTES`], which bounds the one pass
//!   the signature verification makes and the parse;
//! * the document is evaluated against only while it carries at most [`MAX_PAYLOAD_NODES`]
//!   nodes at most [`MAX_PAYLOAD_DEPTH`] deep ([`within_payload_bounds`]);
//! * an expression is evaluated only while it carries at most [`MAX_DESCENDANT_SEGMENTS`]
//!   descendant segments, which is the one factor a length cannot bound.
//!
//! Those three make the cost of one trigger a function of bounded figures — at most
//! nodes × depth² node visits per expression, five expressions — rather than something a
//! clock has to interrupt. A payload or an expression past them is a trigger this plane does
//! not act on, which is the same answer an unmatched filter gets.

