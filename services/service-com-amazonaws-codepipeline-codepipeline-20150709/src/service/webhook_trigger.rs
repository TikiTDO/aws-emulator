    fn a_document_is_evaluated_against_only_inside_the_shape_bounds() {
        // The rows span both bounds and either side of each: an empty document, a scalar, a
        // document at the node bound and one past it, and one at the depth bound and one
        // past it. Each is built rather than written out, because a bound's own figure is
        // what the row is about.
        let wide = |count: usize| {
            ::serde_json::Value::Array(
                (0..count).map(|index| ::serde_json::json!(index)).collect(),
            )
        };
        let deep = |depth: usize| {
            let mut node = ::serde_json::json!("leaf");
            for _ in 1..depth {
                node = ::serde_json::json!({ "next": node });
            }
            node
        };
        let cases: &[(&str, ::serde_json::Value, bool)] = &[
            ("an empty object", ::serde_json::json!({}), true),
            ("a scalar", ::serde_json::json!("ref"), true),
            // The array itself is one node, so its items reach the bound one short.
            ("a document at the node bound", wide(MAX_PAYLOAD_NODES - 1), true),
            ("a document past the node bound", wide(MAX_PAYLOAD_NODES), false),
            ("a document at the depth bound", deep(MAX_PAYLOAD_DEPTH), true),
            ("a document past the depth bound", deep(MAX_PAYLOAD_DEPTH + 1), false),
        ];
        for (case, payload, within) in cases {
            let answered = within_payload_bounds(payload);
            assert_eq!(
                answered, *within,
                "case {case:?}: expected within_payload_bounds {within}, got {answered}"
            );
        }
    }

