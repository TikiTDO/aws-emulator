    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PUT_APPROVAL_RESULT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::require_state(&*self.engine)?;
        // The approval can only be answered once the action has actually been reached,
        // which is a step the clock owes (see `state::driver`).
        crate::state::advance(&*self.engine, ctx, &input.pipeline_name).await;

        // `ApprovalResult$status` is an `ApprovalStatus`: the framework has already
        // refused a value outside the enum, so reaching here means it is one of them.
        let approved = input.result.status == "Approved";
        let now = ::std::time::SystemTime::now();
        // WHO answered the approval, resolved BEFORE this service's store is locked, so
        // the STS and IAM stores the resolution reads are never reached while this
        // service's own guard is held.
        let reviewer = crate::state::caller_identity_arn(&*self.engine, ctx);

        let mut state = state.lock();
        if !state.pipelines.contains_key(&input.pipeline_name) {
            return Err(PutApprovalResultErrorModeled::PipelineNotFoundException(
                PipelineNotFoundException {
                    message: Some(crate::state::pipeline_not_found_message(
                        crate::state::PipelineNotFoundWording::Approval,
                        &input.pipeline_name,
                    )),
                },
            )
            .into());
        }
        if !state.pipelines[&input.pipeline_name]
            .declaration
            .stages
            .iter()
            .any(|stage| stage.name == input.stage_name)
        {
            return Err(PutApprovalResultErrorModeled::StageNotFoundException(
                StageNotFoundException {
                    message: Some(crate::state::stage_not_found_message(
                        crate::state::StageNotFoundWording::Approval,
                        &input.pipeline_name,
                        &input.stage_name,
                    )),
                },
            )
            .into());
        }
        if !state.pipelines[&input.pipeline_name]
            .declaration
            .stages
            .iter()
            .filter(|stage| stage.name == input.stage_name)
            .flat_map(|stage| &stage.actions)
            .any(|action| action.name == input.action_name)
        {
            return Err(PutApprovalResultErrorModeled::ActionNotFoundException(
                ActionNotFoundException {
                    message: Some(crate::state::action_not_found_message(
                        crate::state::ActionNotFoundWording::Approval,
                        &input.pipeline_name,
                        &input.stage_name,
                        &input.action_name,
                    )),
                },
            )
            .into());
        }
        // The action is declared — but this call "provides the response to a manual
        // approval request", which only an action of the `Approval` category publishes.
        // One addressing any other action is answered the same code with the OTHER
        // statement that code carries: there is no approval request of that name to
        // respond to, whatever token the caller holds.
        if !state.pipelines[&input.pipeline_name]
            .declaration
            .stages
            .iter()
            .filter(|stage| stage.name == input.stage_name)
            .flat_map(|stage| &stage.actions)
            .filter(|action| action.name == input.action_name)
            .any(|action| {
                action.action_type_id.category == crate::state::driver::CATEGORY_APPROVAL
            })
        {
            return Err(
                PutApprovalResultErrorModeled::InvalidApprovalTokenException(
                    InvalidApprovalTokenException {
                        message: Some(crate::state::not_an_approval_action_message(
                            &input.pipeline_name,
                            &input.action_name,
                        )),
                    },
                )
                .into(),
            );
        }

        // The newest execution whose named action is waiting for THIS approval. An
        // execution whose approval has already been answered is what
        // `ApprovalAlreadyCompletedException` reports; a token that names no waiting
        // approval is what `InvalidApprovalTokenException` reports, which is also the
        // answer to a STALE token (the action moved on, so the token it published is no
        // longer the one in force).
        let ids: Vec<String> = state
            .executions_by_pipeline
            .get(&input.pipeline_name)
            .map(|ids| ids.iter().rev().cloned().collect())
            .unwrap_or_default();
        let mut already_completed = false;
        for id in ids {
            let Some(record) = state.executions.get_mut(&id) else {
                continue;
            };
            let Some(action) = record
                .stages
                .iter_mut()
                .filter(|stage| stage.name == input.stage_name)
                .flat_map(|stage| stage.actions.iter_mut())
                .find(|action| action.name == input.action_name)
            else {
                continue;
            };
            if action.is_terminal() {
                already_completed = true;
                continue;
            }
            if !action.is_in_progress() {
                continue;
            }
            if action.token.as_deref() != Some(input.token.as_str()) {
                continue;
            }
            action.status = Some(
                if approved { "Succeeded" } else { "Failed" }.to_string(),
            );
            action.summary = Some(input.result.summary.clone());
            // `ActionExecution$lastUpdatedBy` is "the ARN of the user who last changed
            // the pipeline": the identity that ANSWERED this approval, which is the
            // principal this request speaks for.
            action.last_updated_by = Some(reviewer.clone());
            action.last_status_change = now;
            action.token = None;
            if !approved {
                action.error = Some((
                    "JobFailed".to_string(),
                    format!("the approval was rejected: {}", input.result.summary),
                ));
            }
            record.last_update_time = now;
            return Ok(PutApprovalResultOutput {
                approved_at: Some(crate::state::to_date_time(now)),
            });
        }

        if already_completed {
            return Err(
                PutApprovalResultErrorModeled::ApprovalAlreadyCompletedException(
                    ApprovalAlreadyCompletedException {
                        // Invariant text: see
                        // `crate::state::APPROVAL_ALREADY_COMPLETED_MESSAGE`. This class
                        // of refusal is worded the same way for every approval, so no
                        // request or state value is interpolated into it.
                        message: Some(
                            crate::state::APPROVAL_ALREADY_COMPLETED_MESSAGE.to_string(),
                        ),
                    },
                )
                .into(),
            );
        }
        Err(
            PutApprovalResultErrorModeled::InvalidApprovalTokenException(
                InvalidApprovalTokenException {
                    message: Some(crate::state::invalid_approval_token_message(
                        &input.token,
                        &input.action_name,
                        &input.stage_name,
                    )),
                },
            )
            .into(),
        )
    }
