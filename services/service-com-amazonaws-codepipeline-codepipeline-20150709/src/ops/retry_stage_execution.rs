impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for RetryStageExecution<Eng>
{
    type Input = RetryStageExecutionInput;
    type Output = RetryStageExecutionOutput;
    type Error = RetryStageExecutionError;

    const NAME: &'static str = "RetryStageExecution";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::RETRY_STAGE_EXECUTION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::RETRY_STAGE_EXECUTION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::require_state(&*self.engine)?;
        // Whether the stage failed at all is a fact the clock may still owe, so every
        // due step is materialised before the request is judged.
        crate::state::advance(&*self.engine, ctx, &input.pipeline_name).await;
        let now = ::std::time::SystemTime::now();

        {
            let mut state = state.lock();
            if !state.pipelines.contains_key(&input.pipeline_name) {
                return Err(
                    RetryStageExecutionErrorModeled::PipelineNotFoundException(
                        PipelineNotFoundException {
                            message: Some(crate::state::pipeline_not_found_message(
                                crate::state::PipelineNotFoundWording::ExecutionControl,
                                &input.pipeline_name,
                            )),
                        },
                    )
                    .into(),
                );
            }

            // "You can retry a stage that has failed without having to run a pipeline
            // again from the beginning" — and only for the LATEST execution of the
            // pipeline. Which refusal an OLDER one carries is what the two errors are
            // worded for: `NotLatestPipelineExecutionException` is "[t]he stage has failed
            // in a later run of the pipeline and the pipelineExecutionId associated with
            // the request is out of date", so it states a later run that failed at THIS
            // stage; an older execution no later run failed at that stage in has simply
            // been superseded, which is one of the three conditions
            // `StageNotRetryableException` states together.
            let ids = state
                .executions_by_pipeline
                .get(&input.pipeline_name)
                .cloned()
                .unwrap_or_default();
            if ids.last().map(String::as_str) != Some(input.pipeline_execution_id.as_str()) {
                // Everything the pipeline ran AFTER the execution the request named. An
                // id this pipeline never ran has nothing after it: it is not an execution
                // a later run superseded at a stage either.
                let later = ids
                    .iter()
                    .position(|id| *id == input.pipeline_execution_id)
                    .map(|position| &ids[position + 1..])
                    .unwrap_or_default();
                let failed_later = later.iter().any(|id| {
                    state.executions.get(id).is_some_and(|record| {
                        record.stages.iter().any(|stage| {
                            stage.name == input.stage_name
                                && stage.status.as_deref() == Some(crate::state::STATUS_FAILED)
                        })
                    })
                });
                if failed_later {
                    return Err(
                        RetryStageExecutionErrorModeled::NotLatestPipelineExecutionException(
                            NotLatestPipelineExecutionException {
                                message: Some(format!(
                                    "Pipeline execution {} is not the latest execution of \
                                     pipeline {}, so its stages cannot be retried",
                                    input.pipeline_execution_id, input.pipeline_name
                                )),
                            },
                        )
                        .into(),
                    );
                }
                return Err(RetryStageExecutionErrorModeled::StageNotRetryableException(
                    StageNotRetryableException {
                        message: Some(crate::state::stage_not_retryable_message(
                            &input.pipeline_name,
                            &input.stage_name,
                            &input.pipeline_execution_id,
                        )),
                    },
                )
                .into());
            }

            // Unreachable: the id just matched the pipeline's latest execution, so the
            // store holds it. Stated as the fact it would be — no such execution in
            // this pipeline — through the one formatter that words that fact, rather
            // than with a wording invented here.
            let Some(record) = state.executions.get_mut(&input.pipeline_execution_id) else {
                return Err(
                    RetryStageExecutionErrorModeled::NotLatestPipelineExecutionException(
                        NotLatestPipelineExecutionException {
                            message: Some(
                                crate::state::pipeline_execution_not_found_message(
                                    &input.pipeline_name,
                                    &input.pipeline_execution_id,
                                ),
                            ),
                        },
                    )
                    .into(),
                );
            };
            let Some(stage) = record
                .stages
                .iter_mut()
                .find(|stage| stage.name == input.stage_name)
            else {
                return Err(RetryStageExecutionErrorModeled::StageNotFoundException(
                    StageNotFoundException {
                        message: Some(crate::state::stage_not_found_message(
                            &input.pipeline_name,
                            &input.stage_name,
                        )),
                    },
                )
                .into());
            };
            // Only a FAILED stage is retryable.
            if stage.status.as_deref() != Some(crate::state::STATUS_FAILED) {
                return Err(RetryStageExecutionErrorModeled::StageNotRetryableException(
                    StageNotRetryableException {
                        message: Some(crate::state::stage_not_retryable_message(
                            &input.pipeline_name,
                            &input.stage_name,
                            &input.pipeline_execution_id,
                        )),
                    },
                )
                .into());
            }

            // `StageRetryMode`: `FAILED_ACTIONS` re-runs only the actions that failed,
            // `ALL_ACTIONS` re-runs every action of the stage. A re-run action starts
            // from scratch: no status, no due instant, a fresh execution id.
            let all_actions = input.retry_mode == "ALL_ACTIONS";
            for action in &mut stage.actions {
                let failed = action.status.as_deref() == Some(crate::state::STATUS_FAILED);
                if all_actions || failed {
                    action.status = None;
                    action.due = None;
                    action.claimed = None;
                    action.error = None;
                    action.summary = None;
                    action.token = None;
                    action.action_execution_id = crate::state::random_uuid_v4();
                    action.last_status_change = now;
                }
            }
            stage.status = Some("InProgress".to_string());
            record.status = crate::state::STATUS_IN_PROGRESS.to_string();
            record.status_summary = None;
            record.manual_retry_attempts = record.manual_retry_attempts.saturating_add(1);
            record.last_update_time = now;
        }

        // The retried actions become due a span from now, like any other step.
        crate::state::advance(&*self.engine, ctx, &input.pipeline_name).await;

        Ok(RetryStageExecutionOutput {
            pipeline_execution_id: Some(input.pipeline_execution_id),
        })
    }
}
