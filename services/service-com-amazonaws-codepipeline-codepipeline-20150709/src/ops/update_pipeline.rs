impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UpdatePipeline<Eng>
{
    type Input = UpdatePipelineInput;
    type Output = UpdatePipelineOutput;
    type Error = UpdatePipelineError;

    const NAME: &'static str = "UpdatePipeline";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_PIPELINE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UPDATE_PIPELINE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // The pipeline's ARN and its creation instant are fixed at create time, so this
        // call reads request metadata only for the REGION the declaration is judged in:
        // an action type is published per Region, and the region a request names cannot
        // move a stored resource.
        let region = crate::state::request_region(&ctx.parts().headers);
        let state = crate::state::require_state(&*self.engine)?;

        // The same role rule a create is held to: `PipelineDeclaration$roleArn` is the
        // role CodePipeline assumes to run the pipeline's actions, so an update that
        // names a role IAM positively reports absent would leave a stored pipeline that
        // cannot run. Only a definitive "no such role" refuses it (see
        // `state::role_is_absent`).
        let role_absent = crate::state::role_is_absent(ctx, &input.pipeline.role_arn).await;

        let name = input.pipeline.name.clone();
        let mut state = state.lock();
        // The name is resolved FIRST: an update that names no stored pipeline is refused
        // for that, whatever its declaration says, because there is nothing for the
        // declaration to replace.
        if !state.pipelines.contains_key(&name) {
            return Err(UpdatePipelineErrorModeled::PipelineNotFoundException(
                PipelineNotFoundException {
                    message: Some(crate::state::pipeline_not_found_message(
                        crate::state::PipelineNotFoundWording::Definition,
                        &name,
                    )),
                },
            )
            .into());
        }

        // The same structural rules a create is held to: the declaration the caller
        // sends is the FULL structure of the pipeline, so a structure that cannot
        // describe a pipeline is refused with the error shape modelling that defect.
        if role_absent {
            return Err(UpdatePipelineErrorModeled::InvalidStructureException(
                InvalidStructureException {
                    message: Some(format!(
                        "CodePipeline is not authorized to perform AssumeRole on role {}",
                        input.pipeline.role_arn
                    )),
                },
            )
            .into());
        }
        if let Err(problem) = crate::state::validate_declaration(&input.pipeline, &region) {
            let message = Some(problem.message().to_string());
            return Err(match problem {
                crate::state::DeclarationProblem::Structure(_) => {
                    UpdatePipelineErrorModeled::InvalidStructureException(
                        InvalidStructureException { message },
                    )
                }
                crate::state::DeclarationProblem::Stage(_) => {
                    UpdatePipelineErrorModeled::InvalidStageDeclarationException(
                        InvalidStageDeclarationException { message },
                    )
                }
                crate::state::DeclarationProblem::Action(_) => {
                    UpdatePipelineErrorModeled::InvalidActionDeclarationException(
                        InvalidActionDeclarationException { message },
                    )
                }
                // A declaration past a quota is not malformed: it is more than this
                // service runs, which is what `LimitExceededException` reports.
                crate::state::DeclarationProblem::Limit(_) => {
                    UpdatePipelineErrorModeled::LimitExceededException(LimitExceededException {
                        message,
                    })
                }
                // A requirement this service states over the input itself, rather than
                // a defect of the pipeline's structure.
                crate::state::DeclarationProblem::Validation(_) => {
                    UpdatePipelineErrorModeled::ValidationException(ValidationException {
                        message,
                    })
                }
            }
            .into());
        }

        let pipeline = state.pipelines.get_mut(&name).ok_or_else(|| {
            UpdatePipelineError::from(UpdatePipelineErrorModeled::PipelineNotFoundException(
                PipelineNotFoundException {
                    message: Some(crate::state::pipeline_not_found_message(
                        crate::state::PipelineNotFoundWording::Definition,
                        &name,
                    )),
                },
            ))
        })?;

        let stored = pipeline.update(input.pipeline, ::std::time::SystemTime::now());

        Ok(UpdatePipelineOutput {
            // Reported through the one declaration projection `GetPipeline` reports
            // from, so the update answers with the same structure a later read does.
            pipeline: Some(crate::state::reported_declaration(&stored)),
        })
    }
}
