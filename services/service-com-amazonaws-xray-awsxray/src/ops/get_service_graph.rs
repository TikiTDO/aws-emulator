impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetServiceGraph<Eng>
{
    type Input = GetServiceGraphInput;
    type Output = GetServiceGraphOutput;
    type Error = GetServiceGraphError;

    const NAME: &'static str = "GetServiceGraph";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_SERVICE_GRAPH_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_SERVICE_GRAPH_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(GetServiceGraphErrorModeled::ThrottledException(
                ThrottledException {
                    message: Some(
                        "the X-Ray trace store is unavailable on this emulator engine".to_string(),
                    ),
                },
            )
            .into());
        };

        let start = crate::state::epoch_seconds(&input.start_time);
        let end = crate::state::epoch_seconds(&input.end_time);
        let now = crate::state::now_epoch_seconds();
        if let Err(window) = crate::state::validate_window(start, end, now) {
            return Err(refuse(window.message(start, end)));
        }

        // How WIDE a window this read serves is the read's own published bound,
        // and it is not the bound of the trace-summaries read: the service map
        // is derived over a narrower window than the summaries are
        // ([`crate::state::MAX_SERVICE_GRAPH_WINDOW_HOURS`]). A request for a
        // wider one is refused rather than answered over part of it, so a client
        // that has to cut a long range into slices learns the bound from the
        // refusal.
        //
        // Checked AFTER the group is resolved: a request that names a group that
        // does not exist is refused for the group whatever window it asks about,
        // because the group is WHAT the graph would be derived for, so a caller
        // fixing its window would only reach the same refusal again.
        let store = state.lock();

        // A graph "based on which group" is the group's filter expression applied
        // to the window. The group has to exist, and its expression is what
        // selects the traces the graph is derived from — resolved and compiled by
        // the crate's ONE group resolution
        // ([`crate::state::ComAmazonawsXrayAwsxrayState::group_filter`], shared
        // with `GetTimeSeriesServiceStatistics`) and evaluated per trace below.
        // Only an expression the evaluator cannot answer is refused, because
        // answering a filtered request with the unfiltered graph would be a
        // wrong answer rather than a missing one.
        let group_filter = store
            .group_filter(
                &crate::state::request_region(ctx.parts()),
                input.group_name.as_deref(),
                input.group_arn.as_deref(),
            )
            .map_err(refuse)?;

        if let Err(window) = crate::state::validate_window_span(
            start,
            end,
            crate::state::MAX_SERVICE_GRAPH_WINDOW_HOURS,
        ) {
            return Err(refuse(window));
        }

        // The traces the graph is derived from: every stored one when no group
        // was named, and the ones the named group's expression selects when one
        // was. A trace with no segment in the window is skipped BEFORE the
        // expression is evaluated — it adds nothing to the graph, so it must not
        // spend the query budget either — and the expression itself is evaluated
        // under ONE budget for the whole request ([`crate::state::filter`]), so
        // a derivation that spends it is answered with the modelled throttling
        // error rather than with a graph that stopped halfway.
        let mut budget = crate::state::filter::QueryBudget::new();
        let selected = store.traces.values().filter(|trace| {
            trace.touches_window(start, end)
                && group_filter
                    .as_ref()
                    .is_none_or(|filter| filter.matches(trace, &mut budget))
        });
        let services = crate::state::service_graph(selected, Some((start, end)));
        if group_filter.is_some() && budget.exhausted() {
            return Err(GetServiceGraphErrorModeled::ThrottledException(
                ThrottledException {
                    message: Some(crate::state::FILTER_BUDGET_SPENT_MESSAGE.to_string()),
                },
            )
            .into());
        }
        let page = crate::state::page_service_graph(
            &services,
            input.next_token.as_deref(),
            SERVICE_GRAPH_PAGE_SIZE,
        )
        .map_err(refuse)?;

        Ok(GetServiceGraphOutput {
            start_time: Some(input.start_time),
            end_time: Some(input.end_time),
            services: Some(page.services),
            // The graph is derived from the stored segments at read time, never
            // from a cached older version of a group's filter expression.
            contains_old_group_versions: false,
            next_token: page.next_token,
        })
    }
}

/// How many `Service` values one page carries.
///
/// The model declares no page size for `GetServiceGraph`, so this is the
/// emulator's — and it is sized for the WHOLE map of a window rather than a
/// handful of its nodes. The service map has no selector but the window, every
/// `Edge` names its downstream node by a `ReferenceId` that may land on any
/// page, and a client reads the map to discover what it is talking to, so the
/// map is only useful complete: a client walks pages until the token runs out,
/// and whatever page size this read publishes is therefore the number of nodes
/// such a walk reaches per request it makes. A page of a few nodes puts the
/// nodes of an account with many services past any walk a client makes, which
/// reports a map that is silently missing services rather than a map. So a
/// `NextToken` is emitted only for a map larger than a page this size, and
/// resuming from that token returns the remainder.
pub const SERVICE_GRAPH_PAGE_SIZE: usize = 100;

/// Refuse the request with the error this operation models for an invalid one.
fn refuse(message: String) -> GetServiceGraphError {
    GetServiceGraphErrorModeled::InvalidRequestException(InvalidRequestException {
        message: Some(message),
    })
    .into()
}
