impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for PutTraceSegments<Eng>
{
    type Input = PutTraceSegmentsInput;
    type Output = PutTraceSegmentsOutput;
    type Error = PutTraceSegmentsError;

    const NAME: &'static str = "PutTraceSegments";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PUT_TRACE_SEGMENTS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PUT_TRACE_SEGMENTS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `ctx` carries request metadata: the Region the credential scope names,
        // which is the Region the spans log group is vended in when the account's
        // destination sends the accepted spans to CloudWatch Logs.
        let region = crate::state::request_region(ctx.parts());
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(PutTraceSegmentsErrorModeled::ThrottledException(ThrottledException {
                message: Some(
                    "the X-Ray trace store is unavailable on this emulator engine".to_string(),
                ),
            })
            .into());
        };

        // `TraceSegmentDocuments` carries no modelled length bound, so the batch
        // is bounded here: an over-long one is refused outright rather than
        // answered with one `UnprocessedTraceSegment` per document, which would
        // amplify the request into an equally unbounded response.
        let submitted = input.trace_segment_documents.len();
        if submitted > crate::state::MAX_SEGMENT_DOCUMENTS_PER_CALL {
            return Err(PutTraceSegmentsErrorModeled::InvalidRequestException(
                InvalidRequestException {
                    message: Some(format!(
                        "TraceSegmentDocuments carries {submitted} documents; at most {} are accepted per call",
                        crate::state::MAX_SEGMENT_DOCUMENTS_PER_CALL
                    )),
                },
            )
            .into());
        }

        // Parse OUTSIDE the lock, yielding between chunks, so a large batch
        // neither holds the shared store for the whole walk nor denies the
        // runtime a point at which a timeout or a shutdown can land.
        let mut parsed = Vec::new();
        let mut unprocessed = Vec::new();
        for (position, document) in input.trace_segment_documents.iter().enumerate() {
            if position > 0 && position % PARSE_YIELD_EVERY == 0 {
                ::tokio::task::yield_now().await;
            }
            match crate::state::parse_segment_document(document) {
                Ok(segment) => parsed.push(segment),
                Err(rejection) => unprocessed.push(rejection),
            }
        }

        // The ingestion holds this service's guard, so it is done in ONE
        // synchronous block and the guard is gone before the accepted spans are
        // handed to the store of the service that OWNS the log group they are
        // delivered to: a lock guard must not be held across a write into
        // another service's store.
        let accepted = {
            let mut store = state.lock();
            // Where the account's spans go is settled first: the move to the
            // configured destination was due at a fixed instant whether or not
            // anybody called, and a span is delivered to CloudWatch Logs only
            // once that switch is in effect.
            store.settle_trace_segment_destination(::std::time::Instant::now());
            let delivers = store.delivers_spans_to_cloud_watch_logs();
            let mut accepted: Vec<crate::state::span_delivery::Span> = Vec::new();
            for (trace_id, segment) in parsed {
                // Captured BEFORE the ingest takes the record: a span is
                // delivered only once this store has ACCEPTED it, so a document
                // the trace had no room for is reported as unprocessed and
                // delivered nowhere.
                let span = delivers.then(|| crate::state::span_delivery::Span {
                    document: segment.document.clone(),
                    start_time: segment.start_time,
                });
                match store.ingest_segment(&trace_id, segment) {
                    Ok(()) => accepted.extend(span),
                    Err(rejection) => unprocessed.push(rejection),
                }
            }
            accepted
        };

        // Transaction Search: with the destination settled on CloudWatch Logs,
        // each accepted span is also written into the log group that service
        // vends for them, which is where a client queries spans as logs.
        crate::state::span_delivery::deliver(&*self.engine, &region, &accepted);

        Ok(PutTraceSegmentsOutput {
            unprocessed_trace_segments: Some(
                unprocessed
                    .into_iter()
                    .map(|rejection| UnprocessedTraceSegment {
                        id: rejection.id,
                        error_code: Some(rejection.error_code),
                        message: Some(rejection.message),
                    })
                    .collect(),
            ),
        })
    }
}

/// How many documents are parsed between yields to the runtime.
const PARSE_YIELD_EVERY: usize = 64;

