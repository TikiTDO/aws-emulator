impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetTraceGraph<Eng>
{
    type Input = GetTraceGraphInput;
    type Output = GetTraceGraphOutput;
    type Error = GetTraceGraphError;

    const NAME: &'static str = "GetTraceGraph";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_TRACE_GRAPH_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_TRACE_GRAPH_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(GetTraceGraphErrorModeled::ThrottledException(
                ThrottledException {
                    message: Some(
                        "the X-Ray trace store is unavailable on this emulator engine".to_string(),
                    ),
                },
            )
            .into());
        };

        // `TraceIdList` carries no modelled bound, so the request is bounded
        // here, by the same cap `BatchGetTraces` puts on a requested-id list,
        // and refused with the same phrase, which is where that limit is stated.
        if input.trace_ids.len() > crate::state::MAX_TRACE_IDS_PER_CALL {
            return Err(refuse(
                crate::state::exceeding_maximum_query_size_message(),
            ));
        }

        // An id that is not of the documented trace-id form names no trace this
        // service could ever hold, so it is refused for its FORM — the same
        // refusal every reader of a trace id gives — before the lookup that
        // would otherwise report it as merely absent.
        if let Some(malformed) = input
            .trace_ids
            .iter()
            .find(|trace_id| !crate::state::is_trace_id(trace_id))
        {
            return Err(refuse(crate::state::malformed_trace_id_message(malformed)));
        }

        // The derivation is linear in the stored segments of the named traces
        // and bounded in the subsegments it walks, and the store is held only
        // for it: the page is cut after the lock is dropped.
        let services = {
            let store = state.lock();
            let mut traces = Vec::with_capacity(input.trace_ids.len());
            for trace_id in &input.trace_ids {
                let Some(trace) = store.traces.get(trace_id) else {
                    return Err(refuse(TRACE_ID_NOT_FOUND.to_string()));
                };
                traces.push(trace);
            }
            crate::state::service_graph(traces, None)
        };
        // A point for a cancellation or a timeout to land once the lock is
        // released, before this response is assembled.
        ::tokio::task::yield_now().await;

        let page = crate::state::page_service_graph(
            &services,
            input.next_token.as_deref(),
            TRACE_GRAPH_PAGE_SIZE,
        )
        .map_err(refuse)?;

        Ok(GetTraceGraphOutput {
            services: Some(page.services),
            next_token: page.next_token,
        })
    }
}

/// How many `Service` values one page carries.
///
/// The model declares no page size for `GetTraceGraph`, so this is the
/// emulator's, and it is the one the service map read publishes
/// ([`crate::ops::get_service_graph::SERVICE_GRAPH_PAGE_SIZE`]): both reads
/// answer the SAME derivation, and a graph is only useful complete — an `Edge`
/// names its downstream node by a `ReferenceId` that may land on any page — so
/// a page carries a whole graph rather than a handful of its nodes. A
/// `NextToken` is emitted only when the graph exceeded it, and resuming from
/// that token returns the remainder.
pub const TRACE_GRAPH_PAGE_SIZE: usize = crate::ops::get_service_graph::SERVICE_GRAPH_PAGE_SIZE;

/// What a requested trace id that is not stored is refused with.
