        // over the tasks still in flight here: one the clock carried to `COMPLETED`
        // or `CancelTask` moved to `CANCELED` is terminal and holds nothing, and a
        // task of another Region — which this one can neither describe nor list —
        // holds nothing here either. So the refusal is owed only while the quota is
        // actually exceeded, and it lifts of its own accord as tasks finish.
        if store.tasks_in_flight_in(&region) >= crate::state::IN_FLIGHT_TASK_QUOTA {
            return Err(CreateTaskErrorModeled::ServiceQuotaExceededException(
                ServiceQuotaExceededException {
                    message: format!(
                        "this region already has the maximum of {} tasks in progress",
                        crate::state::IN_FLIGHT_TASK_QUOTA
                    ),
                },
            )
            .into());
        }

        // The same bound over every Region at once. The Region a record is
        // partitioned by is the one the request was signed for, so the per-Region
        // count above bounds a partition and not what the process holds: a caller
        // naming a Region it has never used would otherwise get another empty
        // budget. This one lifts as tasks finish, exactly like the one above.
        if store.tasks_in_flight() >= crate::state::STORE_IN_FLIGHT_TASK_QUOTA {
            return Err(CreateTaskErrorModeled::ServiceQuotaExceededException(
                ServiceQuotaExceededException {
                    message: format!(
                        "this emulator already holds the maximum of {} tasks in progress \
                         across every region",
                        crate::state::STORE_IN_FLIGHT_TASK_QUOTA
                    ),
                },
            )
            .into());
        }

        let task_id = store.mint_task_id();
        let task = crate::state::Task {
            task_arn: crate::state::task_arn(&task_id, &region),
            task_id: task_id.clone(),
            region: region.clone(),
            targets: input.targets.clone(),
            command,
            description: input.description,
            // "Only one task is executed on a device at a time": the task is
            // running from the instant it is created, and finishes when every
            // execution it created has.
            state: "IN_PROGRESS".to_string(),
            tags: input.tags.unwrap_or_default().into_iter().collect(),
            created_at: now,
            last_updated_at: now,
            completed_at: None,
        };
        let task_arn = task.task_arn.clone();
        store.tasks.insert(task_id.clone(), task);

        // One execution per target device. A repeated target names the same
        // device, and a device runs one execution of a task, so the key pair is
        // what de-duplicates it.
        for target in input.targets {
            let key = (region.clone(), task_id.clone(), target.clone());
            if store.executions.contains_key(&key) {
                continue;
            }
            let execution_id = store.mint_execution_id();
            store.executions.insert(
                key,
                crate::state::Execution {
                    task_id: task_id.clone(),
                    execution_id,
                    managed_device_id: target,
                    // The command has not reached the device yet; the clock owes
                    // it `IN_PROGRESS` once the dispatch span has passed and the
                    // device is performing no other execution — "Only one task is
                    // executed on a device at a time", so the instant stored here
                    // is the EARLIEST it can be dispatched, not the instant it is.
                    state: "QUEUED".to_string(),
                    started_at: None,
                    last_updated_at: now,
                    due: Some(now + crate::state::EXECUTION_START_SPAN),
                },
            );
        }

        if let Some(token) = input.client_token {
            store.idempotency.insert((region.clone(), token), task_id.clone());
        }

        // The store's retention bound, applied where the store grows: this API
        // models no operation that deletes a task, so past the records one Region
        // keeps, the oldest TERMINAL tasks make room for this one. Nothing in flight
        // is dropped, and nothing is refused. The second call applies the same bound
        // over every Region at once, so the records the process keeps are bounded by
        // what it holds rather than by how many Regions a caller names.
        store.trim_task_history(&region, crate::state::TASK_HISTORY_LIMIT);
        store.trim_store_task_history(crate::state::STORE_TASK_HISTORY_LIMIT);
