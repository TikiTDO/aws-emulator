/// What one answered `IssueCertificate` leaves for the handler to deliver once this
/// service's store has been released.
struct Issuance {
    /// The ARN of the certificate the CA issued — or of the one it had already issued, for
    /// a repeat of a request it has already answered.
    arn: String,
    /// The CRL the CA owes object storage because of this issuance, when it owes one
    /// ([`crate::state::initial_crl_publication`]).
    publication: Option<crate::state::CrlPublication>,
    /// The CA that COMPLETED this issuance, when the CA accounts for it: `None` for the
    /// self-signed certificate a CA still waiting for its own answers, which gives that CA
    /// the certificate every issuance it serves is signed under rather than being one of
    /// them (`crate::state::issuance_metrics`).
    completed_by: Option<String>,
}

impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> IssueCertificate<Eng> {
    /// Issue the certificate this request asks the CA for, answering its ARN together with
    /// what the CA owes other services because of it: the CRL it publishes
    /// ([`crate::state::initial_crl_publication`]) and the issuance its CloudWatch series
    /// counts ([`crate::state::issuance_metrics`]).
    ///
    /// Everything that reads or writes the store happens here, so this service's lock is
    /// taken and released inside one synchronous call and no handler holds it while calling
    /// another service.
    fn issue(&self, input: IssueCertificateInput) -> Result<Issuance, IssueCertificateError> {
        let ca_arn = input.certificate_authority_arn;
        if crate::state::parse_certificate_authority_arn(&ca_arn).is_none() {
            return Err(IssueCertificateErrorModeled::InvalidArnException(
                InvalidArnException {
                    message: Some(crate::state::INVALID_ARN_MESSAGE.to_string()),
                },
            )
            .into());
        }
        if let Some(template_arn) = input.template_arn.as_deref() {
            if !template_arn.contains(":template/") {
                return Err(IssueCertificateErrorModeled::InvalidArnException(
                    InvalidArnException {
                        message: Some(crate::state::INVALID_ARN_MESSAGE.to_string()),
                    },
                )
                .into());
            }
        }

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(IssueCertificateErrorModeled::RequestFailedException(
                RequestFailedException {
                    message: Some("the private CA store is unavailable".to_string()),
                },
            )
            .into());
        };
        let mut state = state.lock();
        let now = ::std::time::SystemTime::now();

        let Some(record) = state.certificate_authority_mut(&ca_arn, now) else {
            return Err(IssueCertificateErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    message: Some(crate::state::CA_NOT_FOUND_MESSAGE.to_string()),
                },
            )
            .into());
        };

        // Only a CA that holds its own certificate can sign with it — with one exception,
        // which is the certificate that MAKES it hold one: a root CA signs its OWN
        // certification request under the root CA certificate template while it is still
        // waiting for a certificate, which is the self-signed certificate its activation
        // then imports (the documented root-CA procedure: create the CA, read its CSR,
        // issue under `template/RootCACertificate/V1`, import the result). Every other
        // issuance needs the CA active. The CA's state is judged before the body of the
        // request is read apart from what decides that exception, so the service answers
        // the state error for a CA that has not been activated whatever else the request
        // carries.
        // Whether this CA holds the certificate it signs with yet is also what says whether
        // the certificate it is about to sign is an issuance the CA SERVES or the one that
        // ACTIVATES it, which is what its issuance series accounts for.
        let serves_as_an_issuer = record.status == crate::state::STATUS_ACTIVE;
        let completing_ca = serves_as_an_issuer.then(|| ca_arn.clone());
        if !serves_as_an_issuer
            && !record.signs_its_own_root_certificate(input.template_arn.as_deref(), &input.csr)
        {
            return Err(IssueCertificateErrorModeled::InvalidStateException(
                InvalidStateException {
                    message: Some(crate::state::ISSUANCE_INVALID_STATE_MESSAGE.to_string()),
                },
            )
            .into());
        }

        // The certification request the CA is asked to answer has to be a PEM-framed
        // DER PKCS#10 certification request; anything else is malformed.
        let Some(request) = ::std::str::from_utf8(&input.csr)
            .ok()
            .and_then(|text| crate::state::parse_pem_block(text, crate::state::PEM_LABEL_CSR))
            .and_then(|der| crate::state::parse_certification_request(&der))
        else {
            return Err(IssueCertificateErrorModeled::MalformedCSRException(
                MalformedCSRException {
                    message: Some(crate::state::MALFORMED_CSR_MESSAGE.to_string()),
                },
            )
            .into());
        };

        // @idempotent: a repeat of a request this CA has already answered — inside the
        // five-minute window, under the same token or under none — answers with the
        // certificate the first call issued instead of issuing a second one.
        let identity = crate::state::IssuedCertificateRequest::new(
            input.csr.clone(),
            input.signing_algorithm.clone(),
            input.template_arn.clone(),
            &input.validity,
            input.validity_not_before.as_ref(),
            input.api_passthrough.clone(),
        );
        let idempotency_key =
            crate::state::issuance_idempotency_key(input.idempotency_token.as_ref());
        if let Some(arn) = crate::state::replay_idempotent(
            &mut record.issue_idempotency,
            Some(&idempotency_key),
            &identity,
            now,
        ) {
            return Ok(Issuance {
                arn,
                // A repeat changes nothing the CRL says, so the CA owes object storage
                // nothing for it.
                publication: None,
                // It is an issuance request the CA completed all the same, so the CA
                // accounts for it like the one it replays.
                completed_by: completing_ca.clone(),
            });
        }

        // Every issued certificate lives in memory for the life of the process, so the
        // per-CA store is capped and an issuance past the cap answers the quota error
        // the operation models.
        if record.certificates.len() >= crate::state::MAX_CERTIFICATES_PER_CA {
            return Err(IssueCertificateErrorModeled::LimitExceededException(
                LimitExceededException {
                    message: Some(format!(
                        "the quota of {} certificates issued by one certificate authority has \
                         been exceeded",
                        crate::state::MAX_CERTIFICATES_PER_CA
                    )),
                },
            )
            .into());
        }

        // "The specified signing algorithm family (RSA or ECDSA) must match the
        // algorithm family of the CA's secret key." (`IssueCertificateRequest`
        // documentation.) The CA signs with the key it was created with, so a
        // signature of another family is one it could not have produced.
        let key_algorithm = record.configuration.key_algorithm.clone();
        let key_family = crate::state::algorithm_family(&key_algorithm);
        let signature_family = crate::state::algorithm_family(&input.signing_algorithm);
        if let (Some(key_family), Some(signature_family)) = (key_family, signature_family) {
            if key_family != signature_family {
                return Err(invalid_args(format!(
                    "Signing algorithm {} cannot be used with key type {key_algorithm}. Valid \
                     signing algorithms are: {}.",
                    input.signing_algorithm,
                    crate::state::signing_algorithms_for_key(&key_algorithm).join(", ")
                )));
            }
        }

        // `ValidityNotBefore` customises the start of the window; without one the
        // window starts at issuance.
        let not_before = match input.validity_not_before.as_ref() {
            Some(validity) => {
                crate::state::resolve_validity(now, validity).map_err(invalid_args)?
            }
            None => now,
        };
        let not_after =
            crate::state::resolve_validity(not_before, &input.validity).map_err(invalid_args)?;
        let window = not_after.duration_since(not_before).map_err(|_| {
            invalid_args(
                "Validity must resolve to an instant after the start of the certificate's \
                 validity period",
            )
        })?;
        if window < ::std::time::Duration::from_secs(1) {
            return Err(invalid_args(
                "Validity must resolve to at least one second after the start of the \
                 certificate's validity period",
            ));
        }
        // "Short-lived certificate validity is limited to seven days."
        // (`CreateCertificateAuthorityRequest$UsageMode` docs.)
        if record.usage_mode == "SHORT_LIVED_CERTIFICATE"
            && window > crate::state::SHORT_LIVED_MAX_VALIDITY
        {
            return Err(invalid_args(
                "Validity may not exceed seven days for a certificate authority whose \
                 UsageMode is SHORT_LIVED_CERTIFICATE",
            ));
        }
        // "The end of the validity period configured on a certificate must not exceed the
        // limit set on its parents in the CA hierarchy."
        // (`IssueCertificateRequest$Validity` docs.) The limit a parent sets is the end of
        // its OWN certificate's validity window, so a request that would outlive the
        // issuing CA is refused here — before a serial is allocated, anything is signed or
        // anything is written. A CA still waiting for its certificate holds no window to
        // exceed, which is the root CA signing its own certificate: the one issuance that
        // SETS such a window rather than being bounded by one.
        if record
            .own_certificate_not_after()
            .is_some_and(|limit| not_after > limit)
        {
            return Err(IssueCertificateError::validation(
                crate::state::VALIDITY_EXCEEDS_CA_MESSAGE,
            ));
        }

        let serial = crate::state::mint_serial(&format!("{ca_arn}|{}", record.next_serial));
        let arn = format!("{ca_arn}/certificate/{serial}");
        // `TemplateArn` selects the certificate definition: the extensions the certificate
        // carries are the ones that template defines
        // (`crate::state::certificate_template`), and the template the caller named stays
        // readable on the resource as well.
        let template = crate::state::certificate_template(input.template_arn.as_deref());
        let Some(certificate_pem) = crate::state::derive_certificate_pem(
            record,
            &serial,
            &request.info,
            &input.signing_algorithm,
            &template,
            not_before,
            not_after,
        ) else {
            return Err(invalid_args(
                "the certificate this request asks for cannot be encoded: the certification \
                 request's subject, or the resolved validity window, is not one a certificate \
                 can carry",
            ));
        };
        let certificate = crate::state::IssuedCertificate {
            certificate_pem,
            certificate_chain_pem: record.issued_chain(),
            signing_algorithm: input.signing_algorithm,
            template_arn: input.template_arn,
            not_before,
            not_after,
            issued_at: now,
            // Issuance completes on the clock, so a caller that reads the certificate
            // straight back still sees the request in progress.
            available_at: now + crate::state::SETTLE_AFTER,
            serial,
            arn: arn.clone(),
            // Nothing is revoked at issuance; `RevokeCertificate` is what records one.
            revocation: None,
        };

        record.next_serial += 1;
        crate::state::record_idempotent(
            &mut record.issue_idempotency,
            Some(idempotency_key),
            identity,
            &arn,
            now,
        );
        record.certificates.insert(arn.clone(), certificate);

        // A CA whose CRLs are enabled publishes the CRL a relying party checks its
        // certificates against; the CRL exists from the first certificate the CA issues,
        // and a later issuance leaves what it says unchanged (a CRL lists the certificates
        // that were REVOKED).
        let publication = crate::state::initial_crl_publication(record, now);

        Ok(Issuance {
            arn,
            publication,
            completed_by: completing_ca,
        })
    }
}

