/// The request member a `MetricDataQuery` array arrives on here, as a refusal of one of its
/// entries names it (`PutMetricAlarmInput$Metrics`).
const METRICS: &str = "Metrics";

/// Why the request's `Metrics` array does not define the one time series an alarm watches, or
/// `None` when it does.
///
/// Four rules, all from `MetricDataQuery`, whose documentation is written for this operation
/// as well as for `GetMetricData`:
///
/// * "A math expression can use the `Id` of the other metrics or queries to refer to those
///   metrics" — the ids an expression refers to are the ids of the SAME request's queries, so
///   an id no query in the array defines resolves to nothing and the alarm could never be
///   evaluated.
/// * "Any expression used in a `PutMetricAlarm` operation must return a single time series." —
///   a search returns every series its query matches, which is why CloudWatch supports the
///   function in `GetMetricData` and not in an alarm at all, however the call is wrapped.
/// * The same sentence for the expression whose result the alarm watches (the one returning
///   data): it may not be a multi-series expression, while the same call wrapped in a function
///   that reduces it to one series is fine — which is why that check is for a multi-series
///   call nothing encloses.
/// * "When used in `PutMetricAlarm`, specify true for the one expression result to use as the
///   alarm. For all other metrics and expressions in the same `PutMetricAlarm` operation,
///   specify `ReturnData` as False." — an alarm grades ONE result, so the array has to
///   designate exactly one query as the one it watches ([`is_watched`]): an array designating
///   none gives the alarm nothing to grade, and one designating several gives it no single
///   result to grade.
///
/// The query the alarm's THRESHOLD comes from is not the one it watches: "If this is an alarm
/// based on an anomaly detection model, make this value match the ID of the
/// ANOMALY_DETECTION_BAND function." (`PutMetricAlarmInput$ThresholdMetricId`) — a band is the
/// PAIR of bounds the watched series is compared against, so the designated query is a
/// multi-series expression by definition and the single-series rule does not speak about it.
fn unresolvable_metrics(input: &PutMetricAlarmInput) -> Option<String> {
    let queries = input.metrics.as_deref()?;
    // The SHAPE of the array first: the ids it carries have to be ids one array may carry at
    // all — the grammar `MetricDataQuery$Id` documents, and unique within the call — before
    // anything about the series they name is resolved. The same rule the read of such an array
    // is judged by ([`crate::state::metric_query::query_id_refusal`]), naming THIS operation's
    // member for the array.
    if let Some(message) = crate::state::metric_query::query_id_refusal(queries, METRICS) {
        return Some(message);
    }
    let defined: HashSet<&str> = queries.iter().map(|query| query.id.as_str()).collect();
    for query in queries {
        let Some(expression) = query.expression.as_deref() else {
            continue;
        };
        // "This field can contain either a Metrics Insights query, or a metric math
        // expression": an Insights query is SQL-like and refers to metrics by name rather
        // than to the ids of other queries, so neither id rule below speaks about it.
        if crate::state::metric_math::is_metrics_insights_query(expression) {
            continue;
        }
        // The one reader of this language: the same parse `GetMetricData` evaluates the
        // expression through, so the two cannot disagree about which ids it refers to, which
        // functions it calls or how many series its value is. An expression the parse refuses
        // is one the metrics query service this operation calls would refuse too.
        let parsed = match crate::state::metric_math::parse(expression) {
            Ok(parsed) => parsed,
            Err(error) => {
                return Some(format!(
                    "Error in expression '{}': {}{EXPRESSION_REFUSAL_ENVELOPE}",
                    query.id, error.message
                ))
            }
        };
        if let Some(unknown) = crate::state::metric_math::references(&parsed)
            .into_iter()
            .find(|referenced| !defined.contains(referenced.as_str()))
        {
            // Built from the request: the expression that could not be resolved, and the
            // id in it that names no query of this request.
            return Some(format!(
                "Error in expression '{}': ID '{unknown}' not \
                 found{EXPRESSION_REFUSAL_ENVELOPE}",
                query.id
            ));
        }
        if crate::state::metric_math::calls_function(&parsed, SEARCH_FUNCTION) {
            return Some(SEARCH_REFUSAL.to_string());
        }
        // The single-series rule speaks about the result the alarm WATCHES ([`is_watched`]),
        // so a query feeding that result — and the pair of bounds a band the threshold comes
        // from is — may be a multi-series expression.
        if is_watched(input, query) && crate::state::metric_math::returns_many_series(&parsed) {
            return Some(format!(
                "the Expression of query {} returns more than one time series, and the \
                 expression an alarm watches must return a single time series",
                query.id
            ));
        }
    }
    // The DESIGNATION last, over the whole array: an alarm grades one result, so an array that
    // designates none designates nothing to grade and one that designates several designates no
    // single result either — neither is an alarm there is anything to create.
    if queries.iter().filter(|query| is_watched(input, query)).count() != 1 {
        return Some(NO_RETURNED_QUERY_REFUSAL.to_string());
    }
    None
}

