/// The refusal for an alarm configuration CloudWatch would not create, or `None` when this
/// request is one it would.
///
/// Everything the service checks ACROSS members, which the boundary validator cannot: the two
/// forms an alarm's series can be stated in, the cadence an alarm can be scheduled at, the span
/// its evaluation may cover, and whether its query array resolves to the single time series an
/// alarm watches. Checked before anything is written, so a refused request leaves the store
/// exactly as it was.
fn configuration_refusal(input: &PutMetricAlarmInput) -> Option<String> {
    // "If you use the `Metrics` parameter, you cannot include the `Namespace`, `MetricName`,
    // `Dimensions`, `Period`, `Unit`, `Statistic`, or `ExtendedStatistic` parameters of
    // `PutMetricAlarm` in the same operation. Instead, you retrieve the metrics you are using
    // in your math expression as part of the `Metrics` array."
    // (`smithy_query(query="doc",shape="PutMetricAlarmInput",member="Metrics")`) — the two
    // forms state the series the alarm watches two different ways, so a request carrying both
    // is one no alarm can be created from.
    //
    // The refusal names ONE member, and which one does not depend on the order this request
    // happened to carry them in: `MetricName` is the member that decides the single-metric form
    // at all ("For each PutMetricAlarm operation, you must specify either MetricName, a Metrics
    // array, or an EvaluationCriteria", `PutMetricAlarmInput$Metrics`), so a request carrying
    // it beside a `Metrics` array is told about THAT member, and the members that only describe
    // the metric it names follow it.
    if input.metrics.is_some() {
        for (member, carried) in [
            ("MetricName", input.metric_name.is_some()),
            ("Namespace", input.namespace.is_some()),
            ("Dimensions", input.dimensions.is_some()),
            ("Period", input.period.is_some()),
            ("Unit", input.unit.is_some()),
            ("Statistic", input.statistic.is_some()),
            ("ExtendedStatistic", input.extended_statistic.is_some()),
        ] {
            if carried {
                return Some(metrics_exclusive_refusal(member));
            }
        }
    }
    // "For an alarm based on a metric, you must specify either Statistic or ExtendedStatistic
    // but not both." (`smithy_query(query="doc",shape="PutMetricAlarmInput",member="Statistic")`)
    // — one statistic is what the alarm folds each of its windows by, so a request naming a basic
    // statistic AND a percentile configures no single series to grade. Stated in the one sentence
    // this service states that pair in ([`crate::state::both_statistics_message`]), closed the
    // way an alarm WRITE is recorded closing it.
    if input.statistic.is_some() && input.extended_statistic.is_some() {
        return Some(crate::state::both_statistics_message(
            ALARM_WRITE,
            crate::state::ONLY_ONE_STATISTIC,
        ));
    }
    // "Sets how this alarm is to handle missing data points." … "Valid Values: breaching |
    // notBreaching | ignore | missing"
    // (`smithy_query(query="doc",shape="PutMetricAlarmInput",member="TreatMissingData")`) — the
    // member is a plain string in the model, so the set of policies the evaluation can apply is
    // a rule only the service enforces, and a value outside it names a policy no alarm could be
    // evaluated under. Stated with the value and the whole set
    // ([`crate::state::value_not_supported_for_parameter_message`]), which is what tells a near
    // miss of a documented value from a value that was never offered.
    if let Some(policy) = input.treat_missing_data.as_deref() {
        if !crate::state::TREAT_MISSING_DATA_VALUES.contains(&policy) {
            return Some(crate::state::value_not_supported_for_parameter_message(
                policy,
                TREAT_MISSING_DATA,
                &crate::state::TREAT_MISSING_DATA_VALUES,
            ));
        }
    }
    // "If you specify ignore, the alarm state does not change during periods with too few data
    // points to be statistically significant. If you specify evaluate or omit this parameter,
    // the alarm is always evaluated" … "Valid Values: evaluate | ignore"
    // (`smithy_query(query="doc",shape="PutMetricAlarmInput",member="EvaluateLowSampleCountPercentile")`)
    // — a plain string in the model too, and the same rule: the member selects one of two
    // behaviours the evaluation implements, so a third name selects none.
    if let Some(option) = input.evaluate_low_sample_count_percentile.as_deref() {
        if !crate::state::LOW_SAMPLE_COUNT_PERCENTILE_OPTIONS.contains(&option) {
            return Some(crate::state::option_not_supported_message(
                option,
                EVALUATE_LOW_SAMPLE_COUNT_PERCENTILE,
                &crate::state::LOW_SAMPLE_COUNT_PERCENTILE_OPTIONS,
            ));
        }
    }
    // "The number of data points that must be breaching to trigger the alarm. … In that case,
    // this value is the M." (`PutMetricAlarmInput$DatapointsToAlarm`) against "The number of
    // periods over which data is compared to the specified threshold. … this value is the N."
    // (`PutMetricAlarmInput$EvaluationPeriods`) — the M of an "M out of N" cannot ask for more
    // breaching datapoints than there are periods to grade, or the alarm could never reach
    // `ALARM` at all. The relation is between the two members and nothing else, so it is
    // checked wherever BOTH are named: the series the alarm watches may be stated as one metric
    // or as a `Metrics` query array, and neither form changes what M and N mean.
    if let (Some(datapoints), Some(periods)) = (input.datapoints_to_alarm, input.evaluation_periods)
    {
        if datapoints > periods {
            return Some(crate::state::at_most_message(
                DATAPOINTS_TO_ALARM,
                EVALUATION_PERIODS,
            ));
        }
    }
    // An aligned window lays its boundaries on the CLOCK of the zone it names ("You can specify
    // an IANA time zone name […], a fixed UTC offset […], or an offset-prefixed identifier […].
    // The offset must be aligned to a multiple of 5 minutes.",
    // `smithy_query(query="shape",shape="WallClockWindow")`), so a value naming no such zone
    // names no boundary either and no alarm can be created from it. Read through the one reading
    // of that member this service has, the one the evaluation lays those boundaries by.
    if let Some(EvaluationWindow::WallClockWindow(window)) = input.evaluation_window.as_ref() {
        let timezone = window.timezone.as_deref();
        if crate::state::alarm_evaluation::AlignmentZone::of(timezone).is_none() {
            return Some(crate::state::value_is_invalid_message(
                timezone.unwrap_or_default(),
                WALL_CLOCK_TIMEZONE_PARAMETER,
            ));
        }
    }
    if let Some(period) = input.period {
        if !is_alarm_period(period) {
            return Some(period_grammar_refusal());
        }
        // An aligned window starts at a clock boundary, so only the periods a clock boundary
        // repeats at can be evaluated in one.
        if matches!(
            input.evaluation_window,
            Some(EvaluationWindow::WallClockWindow(_))
        ) && !WALL_CLOCK_PERIODS.contains(&period)
        {
            return Some(WALL_CLOCK_PERIOD_REFUSAL.to_string());
        }
        if let Some(periods) = input.evaluation_periods {
            let horizon = i64::from(period).saturating_mul(i64::from(periods));
            let ceiling = if i64::from(period) < ONE_HOUR_SECS {
                MAX_SUB_HOUR_HORIZON_SECS
            } else {
                MAX_HORIZON_SECS
            };
            if horizon > ceiling {
                return Some(horizon_refusal(period));
            }
        }
    }
    unresolvable_metrics(input)
}

