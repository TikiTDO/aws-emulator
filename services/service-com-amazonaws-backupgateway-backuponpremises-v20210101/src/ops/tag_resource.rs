impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // Every resource this service tags is REGIONAL — its region is a segment of the ARN
        // it is keyed under — so this endpoint resolves only the records of the region the
        // request itself was addressed to
        // (`crate::state::arn_is_in_request_region`): an ARN of another region names no
        // resource here, exactly as this region's listings do not report it, so it is
        // refused as the missing resource it is and NO tag is written.
        let in_request_region =
            crate::state::arn_is_in_request_region(&input.resource_arn, ctx.parts());

        // `ResourceARN`'s length and pattern and every tag's key and value constraints are
        // refused by the boundary validator before `handle` runs. What the model states
        // only in prose are the two rules of a tag PAIR — a key may not start with the
        // reserved prefix and a value may not carry spaces
        // (`crate::state::validate_tags`). Both are read off the pair and off nothing
        // else, so they are facts of the REQUEST: they are answered here, before the store
        // is consulted at all and with nothing written, exactly as `tag_map` is answered
        // for a create's `Tags` and `crate::state::validate_tag_mappings` for a put's
        // mappings. A pair this service may not persist is refused for being that pair,
        // whether or not the ARN beside it names a record this store holds.
        crate::state::validate_tags(&input.tags).map_err(|message| {
            TagResourceErrorModeled::ValidationException(ValidationException {
                error_code: None,
                message: Some(message),
            })
        })?;

        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            TagResourceErrorModeled::InternalServerException(InternalServerException {
                error_code: None,
                message: Some("Backup gateway state is unavailable on this engine.".to_string()),
            })
        })?;
        let mut state = state.lock();

        // Tagging MERGES: a key the resource already carries is overwritten, not
        // duplicated, and a key it does not carry is added.
        //
        // The ARN is resolved against the resource it NAMES — this service tags every
        // resource it holds (a gateway, a hypervisor and a virtual machine of a
        // hypervisor's inventory), so one lookup spans all three stores, resolving a
        // machine against the clock exactly as `GetVirtualMachine` does — and an ARN with
        // no record behind it takes the refusal that resource type carries: the same
        // modelled `ResourceNotFoundException` shape throughout, answered 400 with the
        // `ErrorCode` naming the resource type that was not found
        // (`crate::state::MissingResource`).
        let written = if in_request_region {
            state.merge_resource_tags(
                &input.resource_arn,
                &input.tags,
                ::std::time::SystemTime::now(),
            )
        } else {
            None
        };
        let Some(merged) = written else {
            let missing = crate::state::MissingResource::for_arn(&input.resource_arn);
            let error = TagResourceErrorModeled::ResourceNotFoundException(
                ResourceNotFoundException {
                    error_code: missing.error_code().map(str::to_string),
                    message: Some(missing.message(&input.resource_arn)),
                },
            );
            return Err(match missing.status_override() {
                Some(status) => crate::scaffolded::Scaffolded::modeled_with_status(error, status),
                None => error.into(),
            });
        };
        // The one tag rule left that is NOT a fact of the request: the per-resource tag
        // ceiling, which can only be judged against the tags the resource already carries.
        // Nothing is written when it refuses.
        let resource_arn = merged.map_err(|message| {
            TagResourceErrorModeled::ValidationException(ValidationException {
                error_code: None,
                message: Some(message),
            })
        })?;

        Ok(TagResourceOutput {
            resource_arn: Some(resource_arn),
        })
    }
}
