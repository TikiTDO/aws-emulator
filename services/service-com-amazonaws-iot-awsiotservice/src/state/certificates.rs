/// `CertificateStatus$ACTIVE` — the status of a certificate a create asked to have set
/// as active (`smithy_query(query="shape",shape="CertificateStatus")`).
pub const CERTIFICATE_STATUS_ACTIVE: &str = "ACTIVE";

/// `CertificateStatus$INACTIVE` — the status of a certificate created without
/// `setAsActive`, which "Specifies whether the certificate is active" and defaults to
/// `false`: the certificate exists but nothing may connect with it yet.
pub const CERTIFICATE_STATUS_INACTIVE: &str = "INACTIVE";

/// `CertificateStatus$REVOKED` — the status of a certificate the account has revoked: it
/// is one of the statuses `UpdateCertificate` admits
/// (`smithy_query(query="shape",shape="CertificateStatus")`).
pub const CERTIFICATE_STATUS_REVOKED: &str = "REVOKED";

/// The statuses a certificate can only reach through AWS IoT's own internal machinery:
/// `UpdateCertificate$newStatus` documents "Setting the status to PENDING_TRANSFER or
/// PENDING_ACTIVATION will result in an exception being thrown. PENDING_TRANSFER and
/// PENDING_ACTIVATION are statuses used internally by IoT. They are not intended for
/// developer use", so a request that names one of them is refused rather than recorded.
pub const INTERNAL_CERTIFICATE_STATUSES: [&str; 2] = ["PENDING_TRANSFER", "PENDING_ACTIVATION"];

/// `CertificateMode$DEFAULT`: "A certificate in `DEFAULT` mode is either generated by
/// Amazon Web Services IoT Core or registered with an issuer certificate authority (CA)
/// in `DEFAULT` mode" (`smithy_query(query="shape",shape="CertificateMode")`). A
/// certificate this service generated itself is therefore in `DEFAULT` mode.
pub const CERTIFICATE_MODE_DEFAULT: &str = "DEFAULT";

/// The `customerVersion` a freshly issued certificate carries. The member is modelled
/// `range min 1` (`smithy_query(query="shape",shape="CertificateDescription")`), so the
/// first version of a certificate is 1; a later customer-driven change moves it.
pub const FIRST_CERTIFICATE_CUSTOMER_VERSION: i32 = 1;

/// How many certificates this emulator holds for an account.
///
/// The store is one a CALLER grows — one record per `CreateKeysAndCertificate` — so it
/// is bounded: past the ceiling nothing is issued and nothing is recorded. AWS IoT
/// models no limit error on this operation, so the refusal is the emulator's own
/// capacity, reported with the error the model has for a request it cannot complete.
pub const MAX_CERTIFICATES: usize = 1_000;

/// The common name of a certificate this service issues.
///
/// `CreateKeysAndCertificate$certificateId` documents "IoT issues a default subject
/// name for the certificate (for example, IoT Certificate)", so the subject is a fixed
/// name this service chooses rather than anything a request carries.
const CERTIFICATE_COMMON_NAME: &str = "AWS IoT Certificate";

/// The organization name a certificate this service issues carries (RFC 5280 section
/// 4.1.2.4).
const CERTIFICATE_ORGANIZATION_NAME: &str = "Amazon Web Services IoT";

/// The instant an issued certificate stops being valid, as epoch seconds:
/// 2049-12-31T23:59:59Z. An AWS IoT-generated device certificate is long lived — it is
/// the device's identity for the life of the device — so the expiry is a fixed far
/// future date rather than a span measured from the call.
const CERTIFICATE_NOT_AFTER_EPOCH_SECONDS: u64 = 2_524_607_999;

/// The object identifiers an issued certificate names.
mod oid {
    use x509_cert::spki::ObjectIdentifier;

    /// `id-at-commonName` (RFC 5280 appendix A).
    pub const COMMON_NAME: ObjectIdentifier = ObjectIdentifier::new_unwrap("2.5.4.3");
    /// `id-at-organizationName` (RFC 5280 appendix A).
    pub const ORGANIZATION: ObjectIdentifier = ObjectIdentifier::new_unwrap("2.5.4.10");
    /// `sha256WithRSAEncryption` (RFC 8017 appendix C).
    pub const SHA256_WITH_RSA: ObjectIdentifier =
        ObjectIdentifier::new_unwrap("1.2.840.113549.1.1.11");
}

/// One certificate this account holds, as every reader of a certificate reports it.
///
/// It carries NO private key: the private half of the key pair is issued once, to the
/// caller of the create, and recorded nowhere.
#[derive(Debug, Clone)]
pub struct RegisteredCertificate {
    /// The certificate's identity, and its key in the store: the SHA-256 digest of its
    /// DER, hex encoded ([`certificate_id`]).
    pub certificate_id: String,
    /// `arn:aws:iot:<region>:<account>:cert/<certificateId>`, minted on the create.
    pub certificate_arn: String,
    /// "The certificate data, in PEM format" — the certificate this service issued,
    /// written by `x509-cert`.
    pub certificate_pem: String,
    /// "The status of the certificate": one of [`CERTIFICATE_STATUS_ACTIVE`] /
    /// [`CERTIFICATE_STATUS_INACTIVE`], resolved on the write from `setAsActive`.
    pub status: String,
    /// "The ID of the Amazon Web Services account that owns the certificate".
    pub owned_by: String,
    /// "The date and time the certificate was created".
    pub creation_date: SystemTime,
    /// "The date and time the certificate was last modified" — equal to
    /// [`RegisteredCertificate::creation_date`] until a later write moves it.
    pub last_modified_date: SystemTime,
    /// "The customer version of the certificate", [`FIRST_CERTIFICATE_CUSTOMER_VERSION`]
    /// on the create.
    pub customer_version: i32,
    /// "The generation ID of the certificate".
    pub generation_id: String,
    /// "The certificate is not valid before this date" — the instant it was issued.
    pub not_before: SystemTime,
    /// "The certificate is not valid after this date"
    /// ([`CERTIFICATE_NOT_AFTER_EPOCH_SECONDS`]).
    pub not_after: SystemTime,
    /// "The mode of the certificate": [`CERTIFICATE_MODE_DEFAULT`] for one this service
    /// generated.
    pub certificate_mode: String,
}

impl RegisteredCertificate {
    /// This record as the `CertificateDescription` every reader of one certificate
    /// reports: one function, so two readers cannot describe the same record
    /// differently.
    ///
    /// `caCertificateId` is absent because this certificate was generated by the
    /// service rather than signed by a registered CA, `previousOwnedBy` and
    /// `transferData` because it has never been transferred to another account.
    pub fn description(&self) -> CertificateDescription {
        CertificateDescription {
            certificate_arn: Some(self.certificate_arn.clone()),
            certificate_id: Some(self.certificate_id.clone()),
            ca_certificate_id: None,
            status: Some(self.status.clone()),
            certificate_pem: Some(self.certificate_pem.clone()),
            owned_by: Some(self.owned_by.clone()),
            previous_owned_by: None,
            creation_date: Some(::aws_smithy_types::DateTime::from(self.creation_date)),
            last_modified_date: Some(::aws_smithy_types::DateTime::from(self.last_modified_date)),
            customer_version: Some(self.customer_version),
            transfer_data: None,
            generation_id: Some(self.generation_id.clone()),
            validity: Some(CertificateValidity {
                not_before: Some(::aws_smithy_types::DateTime::from(self.not_before)),
                not_after: Some(::aws_smithy_types::DateTime::from(self.not_after)),
            }),
            certificate_mode: Some(self.certificate_mode.clone()),
        }
    }
}

/// A freshly minted key pair and the certificate issued for it: the record to persist,
/// and the key pair to hand the caller ONCE.
///
/// No `Debug`: the private key is in here, and a derived formatter is the usual way key
/// material reaches a log.
pub struct MintedKeysAndCertificate {
    /// The certificate record, which is all that is kept.
    pub certificate: RegisteredCertificate,
    /// "The generated key pair" — the public key as a PEM `SubjectPublicKeyInfo`, the
    /// private key as a PEM PKCS#1 RSA private key.
    pub key_pair: KeyPair,
}

/// The ARN of a certificate: `arn:aws:iot:<region>:<account>:cert/<certificateId>`.
///
/// `cert/` is the resource type AWS IoT certificate ARNs use — it is what
/// `CreateKeysAndCertificate$certificateArn` reports and what an `iot:AttachPolicy`
/// statement names a certificate principal by; the namespace and account segments are
/// the ones [`super::thing_arn`] documents.
pub fn certificate_arn(region: &str, certificate_id: &str) -> String {
    ::emulator_server::emulator_arn("iot", region, &format!("cert/{certificate_id}"))
}

/// The `certificateId` of the certificate whose DER is `certificate_der`: the SHA-256
/// digest of the certificate, hex encoded in lowercase.
///
/// That is a value computed from the certificate itself, so the id and the certificate
/// cannot drift, and it satisfies the modelled `length 64..64, pattern
/// ^(0x)?[a-fA-F0-9]+$` for every certificate.
pub fn certificate_id(certificate_der: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(certificate_der);
    ::hex::encode(hasher.finalize())
}

/// The message `DescribeCertificate` and every other reader or writer of one certificate
/// refuses an id the account holds no certificate under with.
///
/// AWS IoT words this one after the MEMBER the request carried — `certificateId` — rather
/// than after the resource, so a caller reads which of a request's ids named nothing.
pub fn missing_certificate_message(certificate_id: &str) -> String {
    format!("CertificateId {certificate_id} does not exist")
}

/// The message a delete refuses a certificate whose status is
/// [`CERTIFICATE_STATUS_ACTIVE`] with: AWS IoT words it after the state the certificate
/// has to be in and names the certificate by the id the request carried, because the
/// caller's next step is `UpdateCertificate` on that id.
pub fn active_certificate_deletion_message(certificate_id: &str) -> String {
    format!(
        "Certificate must be deactivated (not ACTIVE) before deletion. Id: {certificate_id}"
    )
}

/// The message a delete refuses a certificate that still holds attached policies with.
///
/// AWS IoT words a delete conflict after the relation that holds the resource back and
/// names the resource by its ARN, because what the caller has to call next —
/// `DetachPolicy` — takes the certificate as a target ARN rather than as an id.
pub fn attached_policies_deletion_message(certificate_arn: &str) -> String {
    format!("Certificate policies must be detached before deletion (arn: {certificate_arn})")
}

/// Why a certificate's status was NOT updated.
///
/// Each variant names the modelled error class the refusal answers with, so the one rule
/// `UpdateCertificate` follows is stated once, beside the record it writes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CertificateStatusUpdateRefusal {
    /// An id the account holds no certificate under: `ResourceNotFoundException`
    /// (HTTP 404).
    NotFound(String),
    /// A status only AWS IoT's own machinery sets ([`INTERNAL_CERTIFICATE_STATUSES`]):
    /// `InvalidRequestException` (HTTP 400). It is the REQUEST that is refused and not
    /// the certificate's state — the value would be refused whatever the store holds —
    /// which is why this is not the `CertificateStateException` a refusal that depends on
    /// the stored status answers with.
    InternalStatus(String),
}

impl CertificateStatusUpdateRefusal {
    /// The message the refusal states, whichever class it names.
    pub fn message(&self) -> &str {
        match self {
            Self::NotFound(message) | Self::InternalStatus(message) => message,
        }
    }
}

/// The message a status update refuses a status AWS IoT keeps to itself with, worded from
/// the rule `UpdateCertificate$newStatus` states, with the status taken from the request.
///
/// AWS publishes only that rule and not the sentence it states it in, and no recorded call
/// names one of these statuses, so the fixed text here is this emulator's rendering of the
/// documented rule rather than a reproduction of AWS's own wording; the class it is
/// reported under is chosen for the same reason
/// ([`CertificateStatusUpdateRefusal::InternalStatus`]).
pub fn internal_certificate_status_message(new_status: &str) -> String {
    format!(
        "Status {new_status} is used internally by IoT and is not intended for developer use"
    )
}

/// Why a certificate was NOT deleted.
///
/// Each variant names the modelled error class the refusal answers with, so the one rule
/// `DeleteCertificate` follows is stated once, beside the store it reads, rather than in
/// the handler.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CertificateDeletionRefusal {
    /// An id the account holds no certificate under: `ResourceNotFoundException`
    /// (HTTP 404).
    NotFound(String),
    /// A certificate whose status is [`CERTIFICATE_STATUS_ACTIVE`]:
    /// `CertificateStateException` (HTTP 406).
    Active(String),
    /// A certificate that still holds attached policies: `DeleteConflictException`
    /// (HTTP 409).
    AttachedPolicies(String),
}

impl CertificateDeletionRefusal {
    /// The message the refusal states, whichever class it names.
    pub fn message(&self) -> &str {
        match self {
            Self::NotFound(message) | Self::Active(message) | Self::AttachedPolicies(message) => {
                message
            }
        }
    }
}

impl super::ComAmazonawsIotAwsiotserviceState {
    /// Delete the certificate recorded under `certificate_id`, answering the record that
    /// was removed, or the reason the account's state held it back.
    ///
    /// "A certificate cannot be deleted if it has a policy or IoT thing attached to it or
    /// if its status is set to ACTIVE" (`DeleteCertificate`), so a certificate is deleted
    /// only when the account's state says nothing holds it: the store holds one under
    /// that id, its status is not [`CERTIFICATE_STATUS_ACTIVE`], and no policy is
    /// attached to it.
    ///
    /// `force_delete` is `DeleteCertificate$forceDelete`, which "Forces the deletion of a
    /// certificate if it is inactive and is not attached to an IoT thing": it is the
    /// attached-policy conflict it relaxes — the two conditions it names are exactly the
    /// other two, so a forced delete of an inactive certificate detaches the policies the
    /// caller would otherwise have had to detach first, and the relation stops reporting
    /// the certificate for the same reason the certificate store does. It never relaxes
    /// the status rule, which that same sentence requires to hold before the force
    /// applies.
    ///
    /// A certificate attached to an IoT THING is held back by the same rule, but nothing
    /// in this service records a thing's principals yet (`AttachThingPrincipal` is
    /// unimplemented), so no certificate can be in that relation and the refusal has
    /// nothing to read: the day a thing principal is recorded, that conflict belongs
    /// here beside this one.
    pub fn delete_certificate(
        &mut self,
        certificate_id: &str,
        force_delete: bool,
    ) -> Result<RegisteredCertificate, CertificateDeletionRefusal> {
        let Some(certificate) = self.certificates.get(certificate_id) else {
            return Err(CertificateDeletionRefusal::NotFound(
                missing_certificate_message(certificate_id),
            ));
        };
        if certificate.status == CERTIFICATE_STATUS_ACTIVE {
            return Err(CertificateDeletionRefusal::Active(
                active_certificate_deletion_message(certificate_id),
            ));
        }
        let certificate_arn = certificate.certificate_arn.clone();

        // The certificate is one target of the policy-attachment relation, under the key
        // every view of that relation records it by ([`super::PolicyTarget::key`]).
        let target_key = super::PolicyTarget::Certificate(certificate_id.to_string()).key();
        let attached_policies = self.policy_attachments.policies_of(&target_key);
        if !attached_policies.is_empty() && !force_delete {
            return Err(CertificateDeletionRefusal::AttachedPolicies(
                attached_policies_deletion_message(&certificate_arn),
            ));
        }
        for policy_name in &attached_policies {
            self.policy_attachments.detach(&target_key, policy_name);
        }

        // The id is the certificate's identity and its key in the store, so removing that
        // one record is the whole write: every later reader of the store stops reporting
        // it, and no other certificate is touched.
        self.certificates.remove(certificate_id).ok_or_else(|| {
            CertificateDeletionRefusal::NotFound(missing_certificate_message(certificate_id))
        })
    }

    /// Move the certificate recorded under `certificate_id` to `new_status`, answering the
    /// record as it stands afterwards, or the reason the request was refused.
    ///
    /// "Updates the status of the specified certificate. This operation is idempotent"
    /// (`UpdateCertificate`), so the status is the only thing a caller chooses, and a call
    /// that names the status the certificate already carries writes NOTHING: repeating it
    /// leaves the record — its `lastModifiedDate` and its `customerVersion` included —
    /// exactly as the first call left it. A call that does move the status is a
    /// customer-driven change to the certificate, so it stamps `now` as the moment the
    /// certificate was last modified and takes the certificate to its next
    /// `customerVersion`, the member whose first value is
    /// [`FIRST_CERTIFICATE_CUSTOMER_VERSION`].
    ///
    /// `new_status` has already been checked against the modelled `CertificateStatus`
    /// enum before a handler is reached, so the only value left to refuse here is one of
    /// the [`INTERNAL_CERTIFICATE_STATUSES`] — refused before the store is consulted,
    /// because the request carries a value no caller may set whatever the account holds.
    pub fn update_certificate_status(
        &mut self,
        certificate_id: &str,
        new_status: &str,
        now: SystemTime,
    ) -> Result<RegisteredCertificate, CertificateStatusUpdateRefusal> {
        if INTERNAL_CERTIFICATE_STATUSES.contains(&new_status) {
            return Err(CertificateStatusUpdateRefusal::InternalStatus(
                internal_certificate_status_message(new_status),
            ));
        }
        let Some(certificate) = self.certificates.get_mut(certificate_id) else {
            return Err(CertificateStatusUpdateRefusal::NotFound(
                missing_certificate_message(certificate_id),
            ));
        };
        if certificate.status != new_status {
            certificate.status = new_status.to_string();
            certificate.last_modified_date = now;
            certificate.customer_version = certificate.customer_version.saturating_add(1);
        }
        Ok(certificate.clone())
    }
}

/// Mint the key pair and the certificate `CreateKeysAndCertificate` issues: a 2048-bit
/// RSA key pair and an X.509 certificate over its public key, valid from `now` until
/// [`CERTIFICATE_NOT_AFTER_EPOCH_SECONDS`], owned by `owned_by` and recorded with an ARN
/// scoped to `region`.
///
/// `set_as_active` is `CreateKeysAndCertificate$setAsActive`, which "Specifies whether
/// the certificate is active": the certificate is recorded
/// [`CERTIFICATE_STATUS_ACTIVE`] when it is set, [`CERTIFICATE_STATUS_INACTIVE`]
/// otherwise.
///
/// Generating an RSA key pair is hundreds of milliseconds of CPU, so a caller runs this
/// on the blocking pool (`tokio::task::spawn_blocking`) and with no lock held: nothing
/// in here yields, so on an async worker it would starve every other request for its
/// whole duration.
///
/// `None` when the library refuses to produce or encode the key pair, or when a
/// certificate field cannot be encoded (an instant X.509 cannot represent, say).
pub fn mint_keys_and_certificate(
    region: &str,
    owned_by: &str,
    set_as_active: bool,
    now: SystemTime,
) -> Option<MintedKeysAndCertificate> {
    let key_pair = RsaKeyPairDer::generate()?;
    let not_after = UNIX_EPOCH + Duration::from_secs(CERTIFICATE_NOT_AFTER_EPOCH_SECONDS);

    let subject_public_key_info = SubjectPublicKeyInfoOwned::from_der(&key_pair.public_key_spki)
        .ok()?;
    let algorithm = AlgorithmIdentifierOwned {
        oid: oid::SHA256_WITH_RSA,
        // RSASSA-PKCS1-v1_5 takes an explicit NULL parameter (RFC 8017 appendix C).
        parameters: Some(Any::new(DerTag::Null, Vec::new()).ok()?),
    };
    let name = distinguished_name()?;
    let tbs_certificate = TbsCertificate {
        version: Version::V3,
        serial_number: certificate_serial()?,
        signature: algorithm.clone(),
        // The certificate is signed by the key it names: the issuer is the subject.
        issuer: name.clone(),
        validity: X509Validity {
            not_before: Time::try_from(now).ok()?,
            not_after: Time::try_from(not_after).ok()?,
        },
        subject: name,
        subject_public_key_info,
        issuer_unique_id: None,
        subject_unique_id: None,
        // A device certificate is an end-entity certificate: it signs nothing else
        // (RFC 5280 section 4.2.1.9, which requires the extension to be critical in a
        // CA certificate).
        extensions: Some(vec![end_entity_basic_constraints()?]),
    };
    let signature = key_pair.sign(&tbs_certificate.to_der().ok()?)?;
    let certificate = Certificate {
        tbs_certificate,
        signature_algorithm: algorithm,
        signature: BitString::from_bytes(&signature).ok()?,
    };

    let certificate_der = certificate.to_der().ok()?;
    let certificate_id = certificate_id(&certificate_der);
    let status = if set_as_active {
        CERTIFICATE_STATUS_ACTIVE
    } else {
        CERTIFICATE_STATUS_INACTIVE
    };
    Some(MintedKeysAndCertificate {
        certificate: RegisteredCertificate {
            certificate_arn: certificate_arn(region, &certificate_id),
            certificate_id,
            certificate_pem: certificate.to_pem(LineEnding::LF).ok()?,
            status: status.to_string(),
            owned_by: owned_by.to_string(),
            creation_date: now,
            last_modified_date: now,
            customer_version: FIRST_CERTIFICATE_CUSTOMER_VERSION,
            generation_id: fresh_uuid(),
            not_before: now,
            not_after,
            certificate_mode: CERTIFICATE_MODE_DEFAULT.to_string(),
        },
        key_pair: KeyPair {
            public_key: Some(key_pair.public_key_pem()?),
            private_key: Some(key_pair.private_key_pem()?),
        },
    })
}

/// An RSA key pair, as the two DER encodings a certificate and a response need.
struct RsaKeyPairDer {
    /// The public half, a DER X.509 `SubjectPublicKeyInfo`.
    public_key_spki: Vec<u8>,
    /// The private half, PKCS#8 DER.
    private_key_pkcs8: Vec<u8>,
}

impl RsaKeyPairDer {
    /// A fresh RSA-2048 key pair from `aws-lc-rs` — the "2048-bit RSA key pair"
    /// `CreateKeysAndCertificate` documents.
    fn generate() -> Option<Self> {
        let private_key =
            ::aws_lc_rs::rsa::PrivateDecryptingKey::generate(::aws_lc_rs::rsa::KeySize::Rsa2048)
                .ok()?;
        Some(Self {
            public_key_spki: private_key.public_key().as_der().ok()?.as_ref().to_vec(),
            private_key_pkcs8: private_key.as_der().ok()?.as_ref().to_vec(),
        })
    }

    /// `message` signed by this key pair's private half, RSASSA-PKCS1-v1_5 over
    /// SHA-256 — the signature `sha256WithRSAEncryption` names.
    fn sign(&self, message: &[u8]) -> Option<Vec<u8>> {
        let pair = ::aws_lc_rs::signature::RsaKeyPair::from_pkcs8(&self.private_key_pkcs8).ok()?;
        // A PKCS #1 signature is exactly as long as the key's modulus.
        let mut signature = vec![0u8; pair.public_modulus_len()];
        pair.sign(
            &::aws_lc_rs::signature::RSA_PKCS1_SHA256,
            &::aws_lc_rs::rand::SystemRandom::new(),
            message,
            &mut signature,
        )
        .ok()?;
        Some(signature)
    }

    /// The public half as the PEM `SubjectPublicKeyInfo` block (`PUBLIC KEY`) a
    /// `KeyPair$PublicKey` carries.
    fn public_key_pem(&self) -> Option<String> {
        SubjectPublicKeyInfoOwned::from_der(&self.public_key_spki)
            .ok()?
            .to_pem(LineEnding::LF)
            .ok()
    }

    /// The private half as the PEM PKCS#1 block (`RSA PRIVATE KEY`) a
    /// `KeyPair$PrivateKey` carries.
    ///
    /// `aws-lc-rs` encodes a private key as PKCS#8, whose `privateKey` octet string IS
    /// the PKCS#1 `RSAPrivateKey` for an RSA key (RFC 5958 section 2), so the PKCS#1
    /// structure is read out of it and re-encoded rather than rebuilt from parts.
    fn private_key_pem(&self) -> Option<String> {
        let pkcs8 = ::pkcs8::PrivateKeyInfo::try_from(self.private_key_pkcs8.as_slice()).ok()?;
        ::pkcs1::RsaPrivateKey::from_der(pkcs8.private_key)
            .ok()?
            .to_pem(LineEnding::LF)
            .ok()
    }
}

/// The `basicConstraints` extension of an end-entity certificate — one that is not a
/// certificate authority (RFC 5280 section 4.2.1.9).
fn end_entity_basic_constraints() -> Option<Extension> {
    let constraints = BasicConstraints {
        ca: false,
        path_len_constraint: None,
    };
    Some(Extension {
        extn_id: BasicConstraints::OID,
        critical: true,
        extn_value: OctetString::new(constraints.to_der().ok()?).ok()?,
    })
}

/// A certificate serial number: 16 bytes from the OS random source, which RFC 5280
/// section 4.1.2.2 allows up to 20 of.
///
/// `SerialNumber::new` keeps the value the positive integer that section requires by
/// prepending a zero byte when the leading bit is set, which changes no value.
fn certificate_serial() -> Option<SerialNumber> {
    let mut bytes = [0u8; 16];
    ::aws_lc_rs::rand::fill(&mut bytes).ok()?;
    SerialNumber::new(&bytes).ok()
}

/// The X.500 distinguished name an issued certificate carries: the default subject name
/// this service issues, under its organization name (RFC 5280 section 4.1.2.4).
fn distinguished_name() -> Option<Name> {
    Some(Name::from(RdnSequence(vec![
        relative_distinguished_name(oid::ORGANIZATION, CERTIFICATE_ORGANIZATION_NAME)?,
        relative_distinguished_name(oid::COMMON_NAME, CERTIFICATE_COMMON_NAME)?,
    ])))
}

/// One relative distinguished name: the `SET OF` holding the single attribute type and
/// its UTF8String value.
fn relative_distinguished_name(
    attribute: ObjectIdentifier,
    value: &str,
) -> Option<RelativeDistinguishedName> {
    let pair = AttributeTypeAndValue {
        oid: attribute,
        value: Any::new(DerTag::Utf8String, value.as_bytes()).ok()?,
    };
    Some(RelativeDistinguishedName::from(
        SetOfVec::try_from(vec![pair]).ok()?,
    ))
}
