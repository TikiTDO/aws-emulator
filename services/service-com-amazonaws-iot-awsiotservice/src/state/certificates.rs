//! The account's X.509 DEVICE CERTIFICATES: the record one holds, and the minting of
//! the key pair and the certificate `CreateKeysAndCertificate` issues.
//!
//! `CreateKeysAndCertificate` is documented "Creates a 2048-bit RSA key pair and issues
//! an X.509 certificate using the issued public key", so that is what
//! [`mint_keys_and_certificate`] does — every byte of it real. The key pair comes from
//! `aws-lc-rs` (`aws_lc_rs::rsa`), the certificate is a DER X.509 certificate written
//! by `x509-cert` that carries the `SubjectPublicKeyInfo` that library computed from
//! the key it generated, and its signature is an RSASSA-PKCS1-v1_5 SHA-256 signature
//! made by that same key over the DER of the certificate's own `TBSCertificate` — so a
//! client can parse what it is handed, check the certificate against itself, and use
//! the private key as the private half of the key the certificate names.
//!
//! The record this module keeps holds the certificate and NOT the private key: "This is
//! the only time IoT issues the private key for this certificate, so it is important to
//! keep it in a secure location" (the operation's own documentation). The private half
//! is handed to the caller that asked for it and kept nowhere.
//!
//! A certificate's identity is its `certificateId`, which is why the store is keyed by
//! it: the id is the `@httpLabel` of `/certificates/{certificateId}` on every
//! single-certificate operation, and it is modelled `length 64..64, pattern
//! ^(0x)?[a-fA-F0-9]+$` (`smithy_query(query="operation",operation="DescribeCertificate")`)
//! — the SHA-256 digest of the certificate, hex encoded, which is what
//! [`certificate_id`] computes from the certificate's own DER.

