impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for StartRemediationExecution<Eng>
{
    type Input = StartRemediationExecutionInput;
    type Output = StartRemediationExecutionOutput;
    type Error = StartRemediationExecutionError;

    const NAME: &'static str = "StartRemediationExecution";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::START_REMEDIATION_EXECUTION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::START_REMEDIATION_EXECUTION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `ctx` carries the request's Region and the in-process callback the remediation
        // acts over; the execution itself is recorded in this service's own state.
        let region = crate::state::request_region(ctx);
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            crate::scaffolded::Scaffolded::validation(crate::state::STATE_UNAVAILABLE)
        })?;

        // A resource key names ONE resource by its type and its id, so a key missing
        // either names no resource to remediate. The type is judged here rather than at
        // the boundary (`skip_validation` on `ResourceKey`, see
        // `super::types::shared_types`).
        if let Some(incomplete) = input
            .resource_keys
            .iter()
            .find(|key| key.resource_type.trim().is_empty() || key.resource_id.trim().is_empty())
        {
            return Err(
                StartRemediationExecutionErrorModeled::InvalidParameterValueException(
                    InvalidParameterValueException {
                        message: Some(format!(
                            "A ResourceKey must name both a resourceType and a resourceId; \
                             got resourceType '{}' and resourceId '{}'.",
                            incomplete.resource_type, incomplete.resource_id,
                        )),
                    },
                )
                .into(),
            );
        }

        let now = ::std::time::SystemTime::now();
        // Everything this call decides from the store is decided inside this block, so
        // its guard is released before the runs below — no lock is held across an await.
        let (failed, failure_message, actions) = {
            let mut store = state.lock();

            // The remediation configuration is what there is to run: a rule without one
            // — and a rule this account does not hold has none — is exactly the
            // precondition `NoSuchRemediationConfigurationException` documents ("You
            // specified an Config rule without a remediation configuration").
            let Some(remediation) = store.remediation_configurations.get(&input.config_rule_name)
            else {
                return Err(
                    StartRemediationExecutionErrorModeled::NoSuchRemediationConfigurationException(
                        NoSuchRemediationConfigurationException {
                            message: Some(no_remediation_configuration_message(
                                &input.config_rule_name,
                            )),
                        },
                    )
                    .into(),
                );
            };
            // The step an execution runs is the remediation target the configuration
            // names, and the inputs it runs with are that configuration's parameters — so
            // the configuration is read out before the executions are written.
            let remediation = remediation.clone();
            let target = remediation.target_id.clone();

            // What there is to remediate is what the rule's own evaluation FINDS: the
            // resources it holds a NON_COMPLIANT evaluation result for. Read before the
            // executions are written, so the decision is about the state this call
            // arrived at.
            let non_compliant: ::std::collections::BTreeSet<(String, String)> = store
                .config_rules
                .get(&input.config_rule_name)
                .map(|rule| {
                    rule.evaluation_results
                        .values()
                        .filter(|result| {
                            result.compliance_type == crate::state::COMPLIANCE_TYPE_NON_COMPLIANT
                        })
                        .map(|result| (result.resource_type.clone(), result.resource_id.clone()))
                        .collect()
                })
                .unwrap_or_default();

            let mut failed = Vec::new();
            let mut failure_message = None;
            let mut actions: Vec<crate::state::RemediationAction> = Vec::new();
            for key in input.resource_keys {
                let identity = (key.resource_type.clone(), key.resource_id.clone());
                // An execution that has not finished yet is the precondition this
                // operation states for a repeat call, so the resource is reported back
                // rather than started a second time.
                let running = store
                    .remediation_executions
                    .get(&(
                        input.config_rule_name.clone(),
                        identity.0.clone(),
                        identity.1.clone(),
                    ))
                    .is_some_and(|execution| {
                        execution.state_at(now)
                            != crate::state::REMEDIATION_EXECUTION_STATE_SUCCEEDED
                    });
                let reason = if !non_compliant.contains(&identity) {
                    Some(NO_NON_COMPLIANT_EVALUATION.to_string())
                } else if running {
                    Some(EXECUTION_IN_FLIGHT.to_string())
                } else {
                    None
                };
                if let Some(reason) = reason {
                    failure_message = failure_message.or(Some(reason));
                    failed.push(key);
                    continue;
                }
                store.record_remediation_execution(
                    &input.config_rule_name,
                    crate::state::RemediationExecutionEntry::invoked(
                        &key.resource_type,
                        &key.resource_id,
                        &target,
                        now,
                    ),
                );
                // What this execution RUNS: the action of the runbook the configuration
                // names, with that configuration's parameters resolved for this resource.
                // The run happens below, once the store's lock is released.
                actions.push(crate::state::RemediationAction {
                    config_rule_name: input.config_rule_name.clone(),
                    resource_type: key.resource_type.clone(),
                    resource_id: key.resource_id.clone(),
                    target_id: target.clone(),
                    inputs: crate::state::resolved_remediation_inputs(
                        &remediation,
                        &key.resource_id,
                    ),
                });
            }
            (failed, failure_message, actions)
        };

        // The runs happen with the store's lock RELEASED, so no action runs while this
        // call still holds it. Each one acts on its resource through the owning service's
        // own API, which is an in-process call, so the execution reports its run as
        // finished as soon as it is.
        crate::state::run_remediation_actions(ctx.callback(), &*self.engine, &region, &actions)
            .await;

        // "For resources that have failed to start execution, the API returns a resource
        // key object": the member reports the per-resource outcome of an accepted
        // request, so it is always there to be read — EMPTY when every resource the
        // request named started, which is what tells a caller "all accepted" apart from
        // a partial acceptance. `FailureMessage` stays absent while there is no failure
        // to explain.
        Ok(StartRemediationExecutionOutput {
            failed_items: Some(failed),
            failure_message,
        })
    }
}

/// How Config words `NoSuchRemediationConfigurationException` for a rule that has no
/// remediation configuration attached.
///
/// The message is BUILT FROM THE REQUEST — it quotes the rule the caller named — and
/// states the precondition the shape documents ("You specified an Config rule without a
/// remediation configuration"), so a client can tell this from a request that was
/// malformed.
fn no_remediation_configuration_message(config_rule_name: &str) -> String {
    format!(
        "There is no applicable RemediationConfiguration setup for AWS Config rule \
         {config_rule_name}"
    )
}

/// The `FailureMessage` for a resource the rule holds no `NON_COMPLIANT` evaluation
/// result for, which is the example the member documents ("Returns a failure message.
/// For example, the resource is already compliant").
///
/// FIXED, and it carries no part of the request: the sentence states the precondition
/// the resources of one request share — Config remediates a FINDING — and tells the
/// caller what to do about it, so it reads the same whichever resources the request
/// named.
const NO_NON_COMPLIANT_EVALUATION: &str =
    "There are no non-compliant EvaluationResult for the resource(s) that are trying to \
     be remediated. Please wait several minutes and try again when the resource(s) are \
     non-compliant.";

/// The `FailureMessage` for a resource whose previous remediation execution has not
