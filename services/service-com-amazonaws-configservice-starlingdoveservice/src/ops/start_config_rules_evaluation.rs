        // state already recorded and does not re-record it, so nothing but each
        // rule's invocation-and-evaluation history moves: that history is what
        // `DescribeConfigRuleEvaluationStatus` reports, and the pass completes on its
        // own a span later without any further call.
        for name in &names {
            if let Some(rule) = store.config_rules.get_mut(name) {
                rule.evaluation.invoke_on_demand(now);
                // The pass Config has just invoked carries a `ResultToken` where the
                // rule is one whose verdicts are delivered back to Config, the same way
                // the pass a write invokes does.
                rule.mint_evaluation_result_token(now);
            }
        }
        drop(store);

        // The pass this call invoked is run by the in-process pump, which is also what
        // INVOKES the evaluator of a rule whose verdicts are delivered back to Config
        // (`crate::state::custom_lambda_rule`): the work is owed from here whether or not
        // a recorder is recording.
        crate::state::drive_recorder_clock(ctx, &self.engine, &crate::state::request_region(ctx));

