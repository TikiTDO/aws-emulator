impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for CreateTransformer<Eng>
{
    type Input = CreateTransformerInput;
    type Output = CreateTransformerOutput;
    type Error = CreateTransformerError;

    const NAME: &'static str = "CreateTransformer";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_TRANSFORMER_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::CREATE_TRANSFORMER_OUTPUT_SCHEMA;
    // awsJson1_0 is an RPC protocol, so the `@http` code the model puts on this operation
    // (201) is inert on the wire and a success is 200.
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // A transformer is configured in exactly one of the two styles the model offers:
        // the deprecated members, or the ones that replace them. Checked before the store
        // is touched, so a refused request persists nothing.
        let legacy = legacy_members_present(&input);
        let current = current_members_present(&input);
        if !legacy.is_empty() && !current.is_empty() {
            return Err(mixed_configuration_styles());
        }

        // A create names no resource of its own until it mints one, so it is judged — and
        // a refusal is worded — against the account's whole transformer collection.
        if let Err(denied) = crate::state::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            &crate::state::collection_arn(
                &crate::state::request_region(ctx.parts()),
                "transformer",
            ),
        ) {
            return Err(CreateTransformerErrorModeled::AccessDeniedException(denied).into());
        }
        let Some(store) = crate::state::service_state(&*self.engine) else {
            return Err(CreateTransformerErrorModeled::InternalServerException(
                InternalServerException {
                    message: crate::state::STATE_UNAVAILABLE.to_string(),
                    retry_after_seconds: None,
                },
            )
            .into());
        };
        // `clientToken` is this operation's `@idempotencyToken`: a repeat carrying the
        // same token answers with the transformer the first call created, not a second one.
        // The model's prose calls the member "Reserved for future use", but the trait and
        // the recorded behaviour (trace
        // `b2bi.create-transformer-idempotent-token-concurrent-dedup`: concurrent creates
        // sharing one token yield exactly ONE transformer, the losing racers are refused
        // with `ConflictException`, and a replay issued after the original request
        // completed answers with the original transformerId) both say it dedupes, so the
        // trait wins.
        //
        // PHASE 1, under the lock: CLAIM the token. The claim is one atomic
        // check-and-insert ([`crate::state::ComAmazonawsB2biB2biState::claim_idempotency`]),
        // so of any number of requests sharing a token exactly one gets it and the rest
        // are answered rather than minting: the duplicate of a request that has not
        // answered yet is the racer that lost, refused with the modelled
        // `ConflictException` (409), and the duplicate of one that HAS answered replays
        // the transformer it minted. Which of the two a duplicate gets depends only on
        // whether the request it duplicates has finished — never on how long ago it did.
        //
        // A SETTLED token used again for a DIFFERENT request is the other conflict a token
        // can produce, and the digest below is what tells the two apart: the same request
        // replays, a different one is refused.
        let digest = request_digest(&input);
        let idempotency_key = input
            .client_token
            .as_deref()
            .map(|token| crate::state::idempotency_key("transformer", token));
        let mut claim = None;
        if let Some(key) = idempotency_key {
            let mut state = store.lock();
            match state.claim_idempotency(&key) {
                Some(crate::state::TokenReplay::InFlight) => {
                    return Err(CreateTransformerErrorModeled::ConflictException(
                        ConflictException {
                            message: crate::state::CLIENT_TOKEN_IN_FLIGHT.to_string(),
                        },
                    )
                    .into())
                }
                Some(crate::state::TokenReplay::Completed(minted)) => {
                    if let Some(existing) = state.transformers.get(&minted) {
                        if existing.request_digest == digest {
                            return Ok(stored_transformer_response(existing));
                        }
                        return Err(token_already_used(existing));
                    }
                    // The token settled on a transformer this store no longer holds, so
                    // there is nothing to replay: this request takes the token over.
                    state.reclaim_idempotency(&key);
                }
                None => {}
            }
            drop(state);
            // Built with the lock released: the claim's `Drop` takes it, and frees the
            // token on every exit from here that mints nothing.
            claim = Some(crate::state::IdempotencyClaim::held(store.clone(), key));
        }

        // PHASE 2, under the lock: judge the request against the store and persist it. The
        // claim taken above stands across both holds, so a duplicate that arrives while
        // this request is being answered is refused rather than minting a second
        // transformer.
        let mut state = store.lock();

        // Residency bound: this store holds at most `MAX_RECORDS_PER_STORE` transformers,
        // so repeated creates cannot grow the emulator's memory without limit. Checked
        // AFTER the idempotency replay, so a replay still answers from a full store.
        if !state.accepts_another_transformer() {
            return Err(store_full());
        }

        let mut transformer_id = crate::state::new_resource_id("t");
        while state.transformers.contains_key(&transformer_id) {
            transformer_id = crate::state::new_resource_id("t");
        }
        let region = crate::state::request_region(ctx.parts());
        let (created_at, modified_at) = crate::state::created_timestamps();
        let transformer = crate::state::Transformer {
            transformer_arn: ::engine::emulator_arn(
                "b2bi",
                &region,
                &format!("transformer/{transformer_id}"),
            ),
            transformer_id,
            name: input.name,
            status: crate::state::TRANSFORMER_STATUS_INACTIVE.to_string(),
            file_format: input.file_format,
            mapping_template: input.mapping_template,
            edi_type: input.edi_type,
            sample_document: input.sample_document,
            input_conversion: input.input_conversion,
            mapping: input.mapping,
            output_conversion: input.output_conversion,
            sample_documents: input.sample_documents,
            created_at,
            modified_at,
            tags: input.tags.unwrap_or_default(),
            request_digest: digest,
        };

        let response = stored_transformer_response(&transformer);
        let transformer_id = transformer.transformer_id.clone();
        state
            .transformers
            .insert(transformer_id.clone(), transformer);
        state.transformer_order.push(transformer_id.clone());
        // The claim becomes the transformer it minted, under this same hold: the record
        // and the token a later repeat replays it through become visible together.
        if let Some(claim) = claim.as_mut() {
            claim.settle(&mut state, &transformer_id);
        }
        // `state` is dropped before `claim` (it is declared after it), so the claim's
        // `Drop` does not take a lock this scope still holds.
        Ok(response)
    }
}
