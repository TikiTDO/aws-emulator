/// Every transformer id a capability's `configuration` names.
///
/// The modelled `CapabilityConfiguration` is a union whose only member today is `edi`,
/// and an `EdiConfiguration` carries exactly one required `transformerId`. Walking the
/// union (rather than reaching straight into `edi`) means the day the model adds another
/// configuration variant, its references are resolved too — the match stops compiling
/// until they are.
///
/// Shared with `DeleteTransformer`, which asks the opposite question (is this transformer
/// still referenced?) of the same member, so both see one definition of "a capability
/// references a transformer".
pub(crate) fn referenced_transformers(configuration: &CapabilityConfiguration) -> Vec<&str> {
    match configuration {
        CapabilityConfiguration::Edi(edi) => vec![edi.transformer_id.as_str()],
    }
}

/// Every Amazon S3 bucket a capability's `configuration` will read from and write to — its
/// input location's bucket and its output location's bucket.
///
/// Walked over the union rather than reaching into `edi`, for the same reason
/// [`referenced_transformers`] is: a configuration variant the model adds stops this
/// matching until its own locations are listed here. A location naming no bucket yields
/// the empty name, which no account owns.
///
/// Shared with `UpdateCapability`, which writes a configuration onto an existing record
/// and so has to resolve the very same locations the create does.
pub(crate) fn configured_buckets(configuration: &CapabilityConfiguration) -> Vec<&str> {
    match configuration {
        CapabilityConfiguration::Edi(edi) => vec![
            edi.input_location.bucket_name.as_deref().unwrap_or_default(),
            edi.output_location
                .bucket_name
                .as_deref()
                .unwrap_or_default(),
        ],
    }
}

