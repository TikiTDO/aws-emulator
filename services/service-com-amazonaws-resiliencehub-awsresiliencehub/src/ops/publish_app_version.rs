impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for PublishAppVersion<Eng>
{
    type Input = PublishAppVersionInput;
    type Output = PublishAppVersionOutput;
    type Error = PublishAppVersionError;

    const NAME: &'static str = "PublishAppVersion";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PUBLISH_APP_VERSION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PUBLISH_APP_VERSION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(internal_failure());
        };

        // Every modeled constraint on this input — `appArn`'s pattern and
        // `versionName`'s — is already refused by the boundary validator before this
        // handler runs, so there is nothing left here to re-check.
        let mut store = state.lock();

        // A version is published FROM an application, so the application has to
        // exist: minting a version under an unknown `appArn` would make a later read
        // report a version of an application that was never created.
        if !store.apps.contains_key(&input.app_arn) {
            return Err(app_not_found(&input.app_arn));
        }

        // Publishing freezes what the draft's app template maps, and an app
        // template is publishable only once it maps at least one RESOURCE: the
        // Application Components a draft holds only group resources, so a draft
        // with none describes no application to address or assess. `app_version`
        // answers `None` for a draft nobody has written to yet, which maps no
        // resource just as a draft whose resources were all removed again does.
        let draft = store
            .app_version(&input.app_arn, crate::state::DRAFT_APP_VERSION)
            .filter(|draft| draft.maps_a_resource())
            .cloned();
        let Some(draft) = draft else {
            return Err(empty_draft_conflict());
        };

        // The store is bounded: past the ceiling no further version is published.
        if store.published_app_version_count(&input.app_arn)
            >= crate::state::MAX_PUBLISHED_APP_VERSIONS_PER_APP
        {
            return Err(too_many_published_versions(&input.app_arn));
        }

        // The two output members for the published snapshot are DIFFERENT values:
        // `identifier` is the publish sequence number this snapshot was minted
        // with, while `appVersion` is the label a later read addresses it by — and
        // the newest published snapshot is always labelled by the release alias, so
        // a client reads its current release without knowing how many times it has
        // published.
        let identifier = store.next_published_app_version(&input.app_arn);

        // A frozen COPY of the draft: the draft stays as it is, editable, so a later
        // change to it cannot alter what was published.
        let published = crate::state::AppVersionContents {
            app_components: draft.app_components,
            resources: draft.resources,
            version_name: input.version_name.clone(),
            identifier: Some(identifier),
            creation_time: Some(crate::state::now()),
        };
        // Storing under the alias is what moves it: the snapshot it supersedes
        // stays readable under its own sequence number.
        let app_version = store.publish_app_version(&input.app_arn, published);

        Ok(PublishAppVersionOutput {
            app_arn: input.app_arn,
            app_version: Some(app_version.to_string()),
            identifier: Some(identifier),
            version_name: input.version_name,
        })
    }
}

