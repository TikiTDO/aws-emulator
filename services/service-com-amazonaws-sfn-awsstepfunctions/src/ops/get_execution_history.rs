/// One stored event as this API reports it: the event's own identity, and the detail
/// member its type names where the execution's record carries what that detail holds.
///
/// Every value that MOVES — the output, the error, the cause and the redrive count —
/// is read off the EVENT, because the execution's own are those of its latest attempt
/// and the event an earlier attempt ended on stays in the history. Only what an
/// execution carries for its whole life (the input it was started with, and the alias
/// or version it was started through) is read off the record.
///
/// A detail this emulator does not record is left unset rather than filled with a
/// stand-in: `stateEnteredEventDetails`/`stateExitedEventDetails` carry the state's
/// name and the data it was entered with or emitted, and the four execution-level
/// details carry the input, the output, the error and the cause the record holds.
fn projected(
    stored: &crate::state::HistoryEvent,
    execution: &crate::state::Execution,
    with_data: bool,
) -> HistoryEvent {
    // "Indicates whether input or output was included in the response" — it is,
    // whenever the request asked for execution data, because the stored record carries
    // it whole and nothing here is truncated.
    let included = Some(HistoryEventExecutionDataDetails { truncated: false });
    let data = |value: Option<String>| if with_data { value } else { None };
    let mut event = HistoryEvent {
        timestamp: crate::state::to_date_time(stored.timestamp),
        r#type: stored.event_type.clone(),
        id: stored.id,
        previous_event_id: stored.previous_event_id,
        activity_failed_event_details: None,
        activity_schedule_failed_event_details: None,
        activity_scheduled_event_details: None,
        activity_started_event_details: None,
        activity_succeeded_event_details: None,
        activity_timed_out_event_details: None,
        task_failed_event_details: None,
        task_scheduled_event_details: None,
        task_start_failed_event_details: None,
        task_started_event_details: None,
        task_submit_failed_event_details: None,
        task_submitted_event_details: None,
        task_succeeded_event_details: None,
        task_timed_out_event_details: None,
        execution_failed_event_details: None,
        execution_started_event_details: None,
        execution_succeeded_event_details: None,
        execution_aborted_event_details: None,
        execution_timed_out_event_details: None,
        execution_redriven_event_details: None,
        map_state_started_event_details: None,
        map_iteration_started_event_details: None,
        map_iteration_succeeded_event_details: None,
        map_iteration_failed_event_details: None,
        map_iteration_aborted_event_details: None,
        lambda_function_failed_event_details: None,
        lambda_function_schedule_failed_event_details: None,
        lambda_function_scheduled_event_details: None,
        lambda_function_start_failed_event_details: None,
        lambda_function_succeeded_event_details: None,
        lambda_function_timed_out_event_details: None,
        state_entered_event_details: None,
        state_exited_event_details: None,
        map_run_started_event_details: None,
        map_run_failed_event_details: None,
        map_run_redriven_event_details: None,
        evaluation_failed_event_details: None,
    };
    let event_type = stored.event_type.as_str();
    if let Some(name) = stored.state_name.clone() {
        if event_type.ends_with(STATE_ENTERED_SUFFIX) {
            event.state_entered_event_details = Some(StateEnteredEventDetails {
                name,
                // "The string that contains the JSON input data for the state": the
                // data the state was entered WITH, which the walk recorded on the
                // event. `inputDetails` says whether that data is included, so it is
                // reported beside the data rather than instead of it.
                input: data(stored.details.input.clone()),
                input_details: included
                    .clone()
                    .filter(|_| with_data && stored.details.input.is_some()),
            });
            return event;
        }
        if event_type.ends_with(STATE_EXITED_SUFFIX) {
            // "Map of variable name and value as a serialized JSON representation":
            // the variables in scope as the state left, which a JSONata state's
            // `Assign` writes. A state that left none assigned reports neither
            // member, since there is nothing to report under them.
            let assigned: std::collections::HashMap<String, String> = stored
                .details
                .assigned_variables
                .iter()
                .map(|(name, value)| (name.clone(), value.clone()))
                .collect();
            event.state_exited_event_details = Some(StateExitedEventDetails {
                name,
                // "The JSON output data of the state": what the state EMITTED, which
                // is its post-processing result — `ResultSelector`, `ResultPath` and
                // `OutputPath`, or a JSONata state's `Output`, already applied — as
                // the walk recorded it.
                output: data(stored.details.output.clone()),
                output_details: included
                    .clone()
                    .filter(|_| with_data && stored.details.output.is_some()),
                assigned_variables: (!assigned.is_empty()).then(|| assigned.clone()),
                // "Indicates whether assigned variables were truncated in the
                // response. Always false for API calls."
                assigned_variables_details: (!assigned.is_empty())
                    .then_some(AssignedVariablesDetails { truncated: false }),
            });
            return event;
        }
    }
    match event_type {
        crate::state::EVENT_ACTIVITY_SCHEDULED => {
            // `resource` is the activity the task was scheduled for, which the event
            // only reports when the record carries it: the member is required, so a
            // detail with nothing to name it is not reported at all.
            if let Some(resource) = stored.details.resource.clone() {
                event.activity_scheduled_event_details = Some(ActivityScheduledEventDetails {
                    resource,
                    input: data(stored.details.input.clone()),
                    input_details: included.clone().filter(|_| with_data),
                    timeout_in_seconds: seconds(stored.details.timeout_seconds),
                    heartbeat_in_seconds: seconds(stored.details.heartbeat_seconds),
                });
            }
        }
        crate::state::EVENT_ACTIVITY_STARTED => {
            event.activity_started_event_details = Some(ActivityStartedEventDetails {
                worker_name: stored.details.worker_name.clone(),
            });
        }
        crate::state::EVENT_ACTIVITY_SUCCEEDED => {
            event.activity_succeeded_event_details = Some(ActivitySucceededEventDetails {
                output: data(stored.details.output.clone()),
                output_details: included
                    .clone()
                    .filter(|_| with_data && stored.details.output.is_some()),
            });
        }
        crate::state::EVENT_ACTIVITY_TIMED_OUT => {
            event.activity_timed_out_event_details = Some(ActivityTimedOutEventDetails {
                error: stored.details.error.clone(),
                cause: stored.details.cause.clone(),
            });
        }
        crate::state::EVENT_ACTIVITY_FAILED => {
            event.activity_failed_event_details = Some(ActivityFailedEventDetails {
                error: stored.details.error.clone(),
                cause: stored.details.cause.clone(),
            });
        }
        crate::state::EVENT_EXECUTION_STARTED => {
            event.execution_started_event_details = Some(ExecutionStartedEventDetails {
                input: data(Some(execution.input.clone())),
                input_details: included.filter(|_| with_data),
                // "The Amazon Resource Name (ARN) of the IAM role used for executing
                // Lambda tasks": the execution role this execution RUNS under, which
                // the start pinned on the record ("all currently running executions
                // will continue to use the previous definition and roleArn"), so the
                // history reports the role the run really assumed however the state
                // machine has moved since. The member is `@length 1..256`, so a
                // record carrying no role names none.
                role_arn: Some(execution.ran.role_arn.clone())
                    .filter(|role_arn| !role_arn.is_empty()),
                state_machine_alias_arn: execution.state_machine_alias_arn.clone(),
                state_machine_version_arn: execution.state_machine_version_arn.clone(),
            });
        }
        EVENT_EXECUTION_SUCCEEDED => {
            event.execution_succeeded_event_details = Some(ExecutionSucceededEventDetails {
                output: data(stored.details.output.clone()),
                output_details: included
                    .filter(|_| with_data && stored.details.output.is_some()),
            });
        }
        crate::state::EVENT_EXECUTION_FAILED => {
            event.execution_failed_event_details = Some(ExecutionFailedEventDetails {
                error: stored.details.error.clone(),
                cause: stored.details.cause.clone(),
            });
        }
        EVENT_EXECUTION_ABORTED => {
            event.execution_aborted_event_details = Some(ExecutionAbortedEventDetails {
                error: stored.details.error.clone(),
                cause: stored.details.cause.clone(),
            });
        }
        EVENT_EXECUTION_TIMED_OUT => {
            event.execution_timed_out_event_details = Some(ExecutionTimedOutEventDetails {
                error: stored.details.error.clone(),
                cause: stored.details.cause.clone(),
            });
        }
        crate::state::EVENT_EXECUTION_REDRIVEN => {
            event.execution_redriven_event_details = Some(ExecutionRedrivenEventDetails {
                redrive_count: stored.details.redrive_count,
            });
        }
        // A `Task` state's own work: every one of its events names the work, so a
        // record that does not carry what names it reports no detail at all — the two
        // members are required.
        crate::state::EVENT_TASK_SCHEDULED => {
            if let Some((resource_type, resource)) = named_work(stored) {
                event.task_scheduled_event_details = Some(TaskScheduledEventDetails {
                    resource_type,
                    resource,
                    region: crate::state::arn_region(&execution.arn),
                    // "You can select whether execution data (input or output of a
                    // history event) is returned": `parameters` is neither. It is a
                    // REQUIRED member of this detail with no `inputDetails` companion to
                    // say a document was withheld — unlike every `input` and `output`
                    // member, which is optional and paired with one — so it is reported
                    // whatever the request asked for, since a read that withheld it
                    // would answer a document the task was never handed.
                    parameters: stored.details.input.clone().unwrap_or_default(),
                    timeout_in_seconds: seconds(stored.details.timeout_seconds),
                    heartbeat_in_seconds: seconds(stored.details.heartbeat_seconds),
                    task_credentials: None,
                });
            }
        }
        crate::state::EVENT_TASK_STARTED => {
            if let Some((resource_type, resource)) = named_work(stored) {
                event.task_started_event_details = Some(TaskStartedEventDetails {
                    resource_type,
                    resource,
                });
            }
        }
        crate::state::EVENT_TASK_SUCCEEDED => {
            if let Some((resource_type, resource)) = named_work(stored) {
                event.task_succeeded_event_details = Some(TaskSucceededEventDetails {
                    resource_type,
                    resource,
                    output: data(stored.details.output.clone()),
                    output_details: included
                        .filter(|_| with_data && stored.details.output.is_some()),
                });
            }
        }
        // A run-a-job task's own submission: "the response from a resource when a task
        // has started", which is the document the call that started the job answered.
        crate::state::EVENT_TASK_SUBMITTED => {
            if let Some((resource_type, resource)) = named_work(stored) {
                event.task_submitted_event_details = Some(TaskSubmittedEventDetails {
                    resource_type,
                    resource,
                    output: data(stored.details.output.clone()),
                    output_details: included
                        .filter(|_| with_data && stored.details.output.is_some()),
                });
            }
        }
        crate::state::EVENT_TASK_SUBMIT_FAILED => {
            if let Some((resource_type, resource)) = named_work(stored) {
                event.task_submit_failed_event_details = Some(TaskSubmitFailedEventDetails {
                    resource_type,
                    resource,
                    error: stored.details.error.clone(),
                    cause: stored.details.cause.clone(),
                });
            }
        }
        crate::state::EVENT_TASK_FAILED => {
            if let Some((resource_type, resource)) = named_work(stored) {
                event.task_failed_event_details = Some(TaskFailedEventDetails {
                    resource_type,
                    resource,
                    error: stored.details.error.clone(),
                    cause: stored.details.cause.clone(),
                });
            }
        }
        crate::state::EVENT_TASK_TIMED_OUT => {
            if let Some((resource_type, resource)) = named_work(stored) {
                event.task_timed_out_event_details = Some(TaskTimedOutEventDetails {
                    resource_type,
                    resource,
                    error: stored.details.error.clone(),
                    cause: stored.details.cause.clone(),
                });
            }
        }
        // The same lifecycle for a `Task` state whose `Resource` is the ARN of a Lambda
        // FUNCTION, which the model records under its own family: the invocation is
        // named by that function's ARN alone — `resource` is required, so an event whose
        // record does not carry it reports no detail — and `LambdaFunctionStarted` is
        // the one event of either family the model gives no detail structure at all.
        crate::state::EVENT_LAMBDA_FUNCTION_SCHEDULED => {
            if let Some(resource) = stored.details.resource.clone() {
                event.lambda_function_scheduled_event_details =
                    Some(LambdaFunctionScheduledEventDetails {
                        resource,
                        input: data(stored.details.input.clone()),
                        input_details: included
                            .clone()
                            .filter(|_| with_data && stored.details.input.is_some()),
                        timeout_in_seconds: seconds(stored.details.timeout_seconds),
                        task_credentials: None,
                    });
            }
        }
        crate::state::EVENT_LAMBDA_FUNCTION_SUCCEEDED => {
            event.lambda_function_succeeded_event_details =
                Some(LambdaFunctionSucceededEventDetails {
                    output: data(stored.details.output.clone()),
                    output_details: included
                        .filter(|_| with_data && stored.details.output.is_some()),
                });
        }
        crate::state::EVENT_LAMBDA_FUNCTION_FAILED => {
            event.lambda_function_failed_event_details = Some(LambdaFunctionFailedEventDetails {
                error: stored.details.error.clone(),
                cause: stored.details.cause.clone(),
            });
        }
        crate::state::EVENT_LAMBDA_FUNCTION_TIMED_OUT => {
            event.lambda_function_timed_out_event_details =
                Some(LambdaFunctionTimedOutEventDetails {
                    error: stored.details.error.clone(),
                    cause: stored.details.cause.clone(),
                });
        }
        // "The size of the array for Map state iterations", which the state knew when
        // it started iterating.
        crate::state::EVENT_MAP_STATE_STARTED => {
            event.map_state_started_event_details = Some(MapStateStartedEventDetails {
                length: stored.details.length.unwrap_or_default(),
            });
        }
        // One iteration of a `Map` state, which reports "the name of the iteration's
        // parent Map state" and "the index of the array" it was handed.
        crate::state::EVENT_MAP_ITERATION_STARTED => {
            event.map_iteration_started_event_details = Some(iteration(stored));
        }
        crate::state::EVENT_MAP_ITERATION_SUCCEEDED => {
            event.map_iteration_succeeded_event_details = Some(iteration(stored));
        }
        crate::state::EVENT_MAP_ITERATION_FAILED => {
            event.map_iteration_failed_event_details = Some(iteration(stored));
        }
        crate::state::EVENT_MAP_ITERATION_ABORTED => {
            event.map_iteration_aborted_event_details = Some(iteration(stored));
        }
        // An expression of a state that could not be evaluated: "the name of the
        // state in which the evaluation error occurred" is required, so an event
        // whose record names no state reports no detail at all, and the location is
        // the field of the definition the diagnosis named.
        crate::state::EVENT_EVALUATION_FAILED => {
            if let Some(state) = stored.state_name.clone() {
                event.evaluation_failed_event_details = Some(EvaluationFailedEventDetails {
                    error: stored.details.error.clone(),
                    cause: stored.details.cause.clone(),
                    location: stored.details.location.clone(),
                    state,
                });
            }
        }
        _ => {}
    }
    event
}

/// The work a `Task` state's event names: "the service name of the resource in a task
/// state" and "the action of the resource called by a task state", both of which the
/// model makes required — so an event whose record names neither reports no detail
/// rather than an empty one.
fn named_work(stored: &crate::state::HistoryEvent) -> Option<(String, String)> {
    let resource_type = stored.details.resource_type.clone()?;
    let resource = stored.details.resource.clone()?;
    Some((resource_type, resource))
}

/// One `Map` iteration's own detail: the state the iteration belongs to and the index
/// of the item it was handed.
fn iteration(stored: &crate::state::HistoryEvent) -> MapIterationEventDetails {
    MapIterationEventDetails {
        name: stored.state_name.clone(),
        index: stored.details.index.unwrap_or_default(),
    }
}

/// A bound the scheduling state declared, as the modelled `timeoutInSeconds` and
/// `heartbeatInSeconds` carry it.
fn seconds(bound: Option<u64>) -> Option<i64> {
    bound.map(|seconds| i64::try_from(seconds).unwrap_or(i64::MAX))
}
