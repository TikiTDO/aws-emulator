    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_JOBS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // An unreachable store is an internal mounting fault, reported through this
            // operation's own server error, the same way `GetJob` reports it.
            return Err(GetJobsErrorModeled::InternalServiceException(
                InternalServiceException {
                    message: Some("the Glue job store is unavailable".into()),
                },
            )
            .into());
        };

        // "The maximum size of the response" (`MaxResults`, range 1..1000). Absent, the
        // page is the largest the model accepts for it; the clamp re-states that range
        // here so the page size is never 0 even if the boundary validator ever stops
        // enforcing it.
        let page_size = usize::try_from(input.max_results.unwrap_or(MAX_PAGE_SIZE))
            .unwrap_or(MAX_PAGE_SIZE as usize)
            .clamp(1, MAX_PAGE_SIZE as usize);

        let region = crate::state::request_region(ctx.parts());
        let store = state.lock();
        // Only THIS Region's jobs are reported: a Glue job exists only in the Region it
        // was created in. `jobs_in` hands them back in name order, so one page follows
        // another deterministically however the store happens to hash its keys — the same
        // order `ListJobs` walks, so the two listings agree name for name.
        let stored: Vec<&crate::state::JobEntry> = store.jobs_in(&region);

        // The token is the name of the last definition of the previous page, so the page
        // resumes at the first stored name strictly after it — which stays correct across
        // jobs created or deleted between two calls, exactly as the name listing's token
        // does. A token this service never issued is DELIBERATELY a position in that order
        // rather than a refusal, for the same reason: the cursor is a key in the listing's
        // own order, so every string names one.
        let start = match input.next_token.as_deref() {
            Some(cursor) => stored.partition_point(|job| job.name.as_str() <= cursor),
            None => 0,
        };
        // Taken with `skip`/`take` rather than by slicing, so a cursor the request chose
        // can never index outside the set.
        let page: Vec<&crate::state::JobEntry> =
            stored.iter().skip(start).take(page_size).copied().collect();
        let end = start.saturating_add(page.len());
        // The token names the last entry of the page, taken from the page itself so there
        // is no index arithmetic to underflow on an empty page, and is absent once the page
        // reaches the end of the listing.
        let next_token = if end < stored.len() {
            page.last().map(|job| job.name.clone())
        } else {
            None
        };
        // The whole definition per entry, through the projection the single-job read
        // serves.
        let jobs: Vec<Job> = page.iter().map(|job| job.to_job()).collect();

        Ok(GetJobsOutput {
            jobs: Some(jobs),
            next_token,
        })
    }
