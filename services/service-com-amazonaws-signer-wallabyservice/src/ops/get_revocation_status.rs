    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_REVOCATION_STATUS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // Signer is regional: the profile version and the signing job a request
        // names are the ones held by the region whose endpoint it was signed for,
        // and no other region's.
        let region = crate::state::request_region(ctx.parts());

        // Every value this route's published contract CONSTRAINS is refused for
        // the constraint it violated before anything it might name is resolved,
        // in the order the model declares the members — so `platformId`, whose
        // published character class this service checks itself, comes before
        // `certificateHashes`. A value outside that class is not a platform id
        // at all: it names no platform, so it is refused for the syntax it
        // violated rather than reported as a platform that does not exist, which
        // would say the id was well formed but unknown.
        if let Some(message) =
            crate::state::platform_id_pattern_refusal(PLATFORM_ID_QUERY, &input.platform_id)
        {
            return Err(validation(message));
        }

        // `certificateHashes` is `@required`, and what it requires is a
        // certificate to check — so a request that supplies the parameter but no
        // element in it is refused for what it actually did (supplied nothing),
        // not for the absence of a member it did supply. The absent-parameter
        // form of the same request is worded identically by
        // `crate::service::missing_list_member_constraint`: on the query string
        // an empty list and an absent one are the same request.
        if input.certificate_hashes.is_empty() {
            return Err(validation(crate::service::missing_list_member_constraint(
                CERTIFICATE_HASHES_QUERY,
            )));
        }

        // `platformId` names the signing platform the signature was produced on,
        // and this service publishes the WHOLE set of platforms a signature can
        // be produced on, so an id inside the published character class but
        // outside that catalog names no platform at all.
        if crate::state::signing_platform(&input.platform_id).is_none() {
            return Err(validation(crate::state::platform_not_found_message(
                &input.platform_id,
            )));
        }

        // Both members name a resource of THIS service, and each names a resource
        // of ONE kind: `profileVersionArn` "The version of a signing profile" and
        // `jobArn` "The ARN of a signing job". So a value that is not an ARN of
        // the SHAPE its member names — the fields an ARN of this service carries
        // plus that kind's resource form — resolves to no resource this endpoint
        // could hold and is refused for the value it carried, named by the member
        // that carried it. Shape is all that is judged: the identifiers inside an
        // ARN the caller was handed are not held to the bounds the model places
        // on the members that carry a profile name or a version directly, so an
        // ARN-shaped value is answered rather than refused. The operation models
        // no not-found, so one naming a resource this endpoint holds none of —
        // another account's, another region's, a name or id nothing was created
        // under — is answered as a resource that is simply not revoked.
        let Some((_, profile_name, profile_version)) =
            crate::state::profile_version_in_arn(&input.profile_version_arn)
        else {
            return Err(validation(crate::state::invalid_arn_message(
                PROFILE_VERSION_ARN_QUERY,
                &input.profile_version_arn,
            )));
        };
        let Some((_, job_id_named)) = crate::state::job_region_and_id_in_arn(&input.job_arn) else {
            return Err(validation(crate::state::invalid_arn_message(
                JOB_ARN_QUERY,
                &input.job_arn,
            )));
        };

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(
                GetRevocationStatusErrorModeled::InternalServiceErrorException(
                    InternalServiceErrorException {
                        message: Some("the signer revocation store is unavailable".to_string()),
                        code: Some(crate::state::ERROR_CODE_INTERNAL_SERVICE_ERROR.to_string()),
                    },
                )
                .into(),
            );
        };
        // A REPORT of what the store holds: the guard is taken for reading only
        // and nothing is written, so repeating the call answers the same list and
        // a later caller sees exactly what this one saw.
        let store = state.lock();

        // "A list of revoked entities … supplied as input to the API": each one is
        // reported by the identifier the REQUEST carried for it, in the order the
        // input names them — the profile version, then the job, then the
        // certificate hashes.
        let mut revoked_entities: Vec<String> = Vec::new();

        // The ARN has to be the one the stored profile's version carries, so a
        // version ARN naming another account's or another partition's profile of
        // the same name names no version this endpoint can report on.
        if store.profile(&region, profile_name).is_some_and(|profile| {
            profile.version_arn(profile_version) == input.profile_version_arn
                && profile.version_revoked_at(profile_version, &input.signature_timestamp)
        }) {
            revoked_entities.push(input.profile_version_arn.clone());
        }

        // A revoked signature is revoked outright: `SigningJobRevocationRecord`
        // carries when the signature was revoked and by whom, and no instant from
        // which the revocation takes effect, so the one signature that job
        // produced is untrusted whenever it was made.
        if store
            .job(&region, job_id_named)
            .is_some_and(|job| job.arn() == input.job_arn && job.is_revoked())
        {
            revoked_entities.push(input.job_arn.clone());
        }

        // No certificate hash is ever reported: this service revokes signing
        // profiles and signing jobs' signatures and models no revocation of a
        // certificate, so there is no record one of these hashes could resolve
        // to. A request carrying them is answered on the entities that do have
        // records rather than refused for asking (see this module's header).

        // Always present, and empty when nothing the request named is revoked:
        // the member reports "zero or more" of the input entities, so a caller
        // reads the answer off the list itself.
        Ok(GetRevocationStatusOutput {
            revoked_entities: Some(revoked_entities),
        })
    }
