//! A CloudFormation-deployed bucket notification really runs its Lambda target, and the
//! object the handler writes from the event lands back in the same bucket — the
//! `ObjectCreated` pipeline an infrastructure-as-code client deploys, observed only through
//! the API surface.
//!
//! The rule under test: **once a stack that declares an `AWS::S3::Bucket` with a
//! `NotificationConfiguration` naming a function for an event class is `CREATE_COMPLETE`,
//! every object write into that bucket whose key the configuration admits is published to the
//! function as one asynchronous invocation carrying the `Records` envelope, whatever shape the
//! key has and whether the bucket's name was declared or generated — so the writes the handler
//! makes off the event are readable through `HeadObject` and `GetObject`, and a bucket the
//! stack declares no configuration on publishes nothing.**
//!
//! Four crates have to agree for that to hold (CloudFormation installs the declared
//! configuration on the bucket it created, S3 evaluates it and makes the invocation, Lambda
//! holds the grant and runs the handler, IAM answers for the execution role the handler's own
//! SDK calls are signed as), so the suite lives here: no crate-local suite can see more than
//! one side of it. The sibling suite `s3_notification_invokes_its_lambda_target` pins what the
//! key-name `Filter` admits; what this one adds is the deployed pipeline a client actually
//! ships — a generated bucket name read out of a stack output, and a handler that writes back
//! into the bucket the event came from, read back the way the client reads it. The declared
//! configuration carries a prefix filter for one reason only: the copy the handler writes lands
//! outside it, so each row is ONE invocation rather than a chain of them.
//!
//! The rows differ along what the rule generalises over: where the bucket's name came from
//! (declared in the template, or generated by CloudFormation), the shape of the written key
//! (one prefix deep, several prefixes deep, and one carrying a character the published record
//! percent-encodes), and the size of the body carried through. The last case asserts the other
//! half of the rule: a bucket of the same stack carrying no notification configuration at all
//! leaves no copy behind.

use std::sync::Arc;
use std::time::Duration;

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

// The awsQuery form encoder and the stack readers this test crate writes ONCE, rather than a
// second copy of either: `form_encode` is also what percent-encodes one path segment of an
// object key here, and `wait_for_stack_status` is the poll every suite deploying a stack whose
// resources their owning services report as still coming up needs.
use crate::cloudformation_firehose_stream_stabilisation::wait_for_stack_status;
use crate::query_wire::{form_encode, outputs_of};
use crate::rds_docdb_neptune_signing_name_routing::authorization;

/// The Region every request here is signed for, which is the Region the shared
/// [`authorization`] builder signs for and so the Region the stack's resources belong to.
const REGION: &str = "us-east-1";

/// The `StackStatus` a deployed stack must reach before the pipeline it declares is wired.
const CREATE_COMPLETE: &str = "CREATE_COMPLETE";

/// The service principal Amazon S3 publishes notifications under, and the action it performs
/// on a function destination.
const S3_PRINCIPAL: &str = "s3.amazonaws.com";
const INVOKE_ACTION: &str = "lambda:InvokeFunction";

/// The event class the declared configuration names: "you can enable notifications for every
/// event of a type by using the wildcard", so this is every object-created event.
const OBJECT_CREATED: &str = "s3:ObjectCreated:*";

/// The prefix the handler writes its copy of an object under. It skips a key already carrying
/// it, so the handler stays idempotent however often it is handed the same object.
const PROCESSED_PREFIX: &str = "processed/";

/// The prefix the declared configuration's key-name `Filter` admits, and so the prefix every
/// row writes under. It is what keeps one write to one invocation: the copy the handler makes
/// lands outside this prefix, so the configuration does not publish the copy's own event.
const WATCHED_PREFIX: &str = "incoming/";

/// How long this suite waits for work the clock owes — a stack's resources coming up, and the
/// asynchronous delivery of an object event — and how often it looks while waiting.
const WAIT: Duration = Duration::from_secs(60);
const LOOK_INTERVAL: Duration = Duration::from_millis(100);

/// How long the row that must see NOTHING keeps looking before concluding nothing came: well
/// past the span every delivered row above it took to leave its copy.
const QUIET_WINDOW: Duration = Duration::from_secs(3);

/// The handler the stack deploys: for every record it is handed it reads the object the event
/// named and writes that object's bytes back into the same bucket under
/// [`PROCESSED_PREFIX`], through the AWS SDK the runtime supplies. A record's key "is URL
/// encoded" (Amazon S3 User Guide, *Event message structure*), so it is decoded the way that
/// guide's own handler decodes it before being used as a key again.
const COPYING_HANDLER: &str = r#"
import urllib.parse

import boto3

PROCESSED_PREFIX = "processed/"


def handler(event, context):
    s3 = boto3.client("s3")
    copied = []
    for record in event["Records"]:
        bucket = record["s3"]["bucket"]["name"]
        key = urllib.parse.unquote_plus(record["s3"]["object"]["key"])
        if key.startswith(PROCESSED_PREFIX):
            continue
        body = s3.get_object(Bucket=bucket, Key=key)["Body"].read()
        s3.put_object(Bucket=bucket, Key=PROCESSED_PREFIX + key, Body=body)
        copied.append(key)
    return {"copied": copied}
"#;

/// The emulator as it is ASSEMBLED, on one engine: the handler's own SDK calls are dispatched
/// back into this same router, so the bucket it writes is the bucket this suite reads.
fn build_router() -> MultiServiceRouter {
    let engine: Arc<engine::InMemoryEngine> = Arc::new(engine::InMemoryEngine::new());
    let mut router = aws_emulator_router::build_router(engine);
    router.set_request_authentication(false);
    router
}

/// One CloudFormation call over its awsQuery wire, answered with the HTTP status and the XML.
async fn cloudformation(
    router: &MultiServiceRouter,
    action: &str,
    members: &[(&str, &str)],
) -> (u16, String) {
    let mut body = format!("Action={action}&Version=2010-05-15");
    for (key, value) in members {
        body.push('&');
        body.push_str(&form_encode(key));
        body.push('=');
        body.push_str(&form_encode(value));
    }
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("cloudformation.{REGION}.amazonaws.com"))
        .header("content-type", "application/x-www-form-urlencoded")
        .header("authorization", authorization("cloudformation"))
        .body(Bytes::from(body))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    (status, String::from_utf8_lossy(response.body()).to_string())
}

/// One response of S3's REST surface: the status, the body, and the length S3 reported.
struct Answer {
    status: u16,
    body: String,
    content_length: Option<String>,
}

/// Dispatch one request against S3's REST surface, path-style.
async fn s3(router: &MultiServiceRouter, method: &str, path: &str, body: &str) -> Answer {
    let host = format!("s3.{REGION}.amazonaws.com");
    let request = http::Request::builder()
        .method(method)
        .uri(format!("https://{host}{path}"))
        .header("host", host)
        .header("authorization", authorization("s3"))
        .header("content-type", "application/octet-stream")
        .body(Bytes::from(body.to_owned()))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let content_length = response
        .headers()
        .get("content-length")
        .and_then(|value| value.to_str().ok())
        .map(str::to_owned);
    Answer {
        status: response.status().as_u16(),
        body: String::from_utf8_lossy(response.body()).into_owned(),
        content_length,
    }
}

/// The request path of one object: every segment of the key percent-encoded over the unreserved
/// set, with the key's own separators kept as the path separators they are.
fn object_path(bucket: &str, key: &str) -> String {
    let encoded: Vec<String> = key.split('/').map(form_encode).collect();
    format!("/{bucket}/{}", encoded.join("/"))
}

/// `PUT /<bucket>/<key>` — `PutObject`.
async fn put_object(router: &MultiServiceRouter, case: &str, bucket: &str, key: &str, body: &str) {
    let answer = s3(router, "PUT", &object_path(bucket, key), body).await;
    assert_eq!(
        answer.status, 200,
        "case {case:?}: PutObject({bucket:?}, {key:?}) must succeed, got {} with {}",
        answer.status, answer.body
    );
}

/// `HEAD /<bucket>/<key>` — `HeadObject`, answered as it came so a caller can poll on a key
/// that is not there yet.
async fn head_object(router: &MultiServiceRouter, bucket: &str, key: &str) -> Answer {
    s3(router, "HEAD", &object_path(bucket, key), "").await
}

/// Poll `HeadObject` until it reports the key, and answer the last response it gave — the probe
/// a client polling for the handler's write makes. `expected` says only how long to keep
/// looking: a key that must appear is waited for, and a key that must NOT appear is looked for
/// over the quiet window and then answered as it last came.
async fn awaited_object(
    router: &MultiServiceRouter,
    bucket: &str,
    key: &str,
    expected: bool,
) -> Answer {
    let wait = if expected { WAIT } else { QUIET_WINDOW };
    let looks = wait.as_millis() / LOOK_INTERVAL.as_millis();
    let mut answer = head_object(router, bucket, key).await;
    for _ in 0..looks {
        if answer.status == 200 {
            return answer;
        }
        tokio::time::sleep(LOOK_INTERVAL).await;
        answer = head_object(router, bucket, key).await;
    }
    answer
}

/// The trust policy a Lambda execution role needs, and the grant the handler's own calls need:
/// it reads the object the event named and writes the copy back, and it logs.
fn role_resource() -> Value {
    json!({
        "Type": "AWS::IAM::Role",
        "Properties": {
            "AssumeRolePolicyDocument": {
                "Version": "2012-10-17",
                "Statement": [{
                    "Effect": "Allow",
                    "Principal": { "Service": "lambda.amazonaws.com" },
                    "Action": "sts:AssumeRole",
                }],
            },
            "Policies": [{
                "PolicyName": "copy-the-object",
                "PolicyDocument": {
                    "Version": "2012-10-17",
                    "Statement": [{
                        "Effect": "Allow",
                        "Action": ["s3:GetObject", "s3:PutObject", "logs:*"],
                        "Resource": "*",
                    }],
                },
            }],
        },
    })
}

/// One bucket the template declares with the notification configuration under test, ordered
/// after the grant: the configuration S3 records is validated against the function's own
/// policy, so the grant has to be in place before the bucket is created with it.
fn notifying_bucket(name: Option<&str>) -> Value {
    let mut bucket = json!({
        "Type": "AWS::S3::Bucket",
        "DependsOn": "InvokePermission",
        "Properties": {
            "NotificationConfiguration": {
                "LambdaConfigurations": [{
                    "Event": OBJECT_CREATED,
                    "Function": { "Fn::GetAtt": ["Handler", "Arn"] },
                    "Filter": {
                        "S3Key": { "Rules": [{ "Name": "prefix", "Value": WATCHED_PREFIX }] },
                    },
                }],
            },
        },
    });
    if let Some(name) = name {
        bucket["Properties"]["BucketName"] = json!(name);
    }
    bucket
}

/// The whole stack this suite deploys: the role, the function with its inline code, the grant
/// Amazon S3 needs on it, the two buckets the configuration is declared on — one NAMED by the
/// template and one left for CloudFormation to name — and a bucket declaring no configuration
/// at all. Every bucket's name travels back as an output, which is how a client learns the
/// generated one.
fn pipeline_stack(named_bucket: &str) -> Value {
    json!({
        "AWSTemplateFormatVersion": "2010-09-09",
        "Resources": {
            "HandlerRole": role_resource(),
            "Handler": {
                "Type": "AWS::Lambda::Function",
                "Properties": {
                    "Runtime": "python3.12",
                    "Handler": "index.handler",
                    "Role": { "Fn::GetAtt": ["HandlerRole", "Arn"] },
                    "Timeout": 30,
                    "Code": { "ZipFile": COPYING_HANDLER },
                },
            },
            "InvokePermission": {
                "Type": "AWS::Lambda::Permission",
                "Properties": {
                    "FunctionName": { "Fn::GetAtt": ["Handler", "Arn"] },
                    "Action": INVOKE_ACTION,
                    "Principal": S3_PRINCIPAL,
                },
            },
            "NamedBucket": notifying_bucket(Some(named_bucket)),
            "GeneratedBucket": notifying_bucket(None),
            "QuietBucket": { "Type": "AWS::S3::Bucket" },
        },
        "Outputs": {
            "NamedBucketName": { "Value": { "Ref": "NamedBucket" } },
            "GeneratedBucketName": { "Value": { "Ref": "GeneratedBucket" } },
            "QuietBucketName": { "Value": { "Ref": "QuietBucket" } },
        },
    })
}

/// Which declared bucket a row writes into.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Declared {
    /// The bucket whose name the template states.
    Named,
    /// The bucket whose name CloudFormation generated, read out of the stack's outputs.
    Generated,
}

/// One row: the bucket written into, the key written, and the body — repeated `repeats` times,
/// so one row carries a body far longer than a single line.
struct Row {
    case: &'static str,
    bucket: Declared,
    key: &'static str,
    body_unit: &'static str,
    repeats: usize,
}

const ROWS: &[Row] = &[
    Row {
        case: "a key one prefix deep in the bucket the template names",
        bucket: Declared::Named,
        key: "incoming/report.txt",
        body_unit: "quarterly data",
        repeats: 1,
    },
    Row {
        case: "a key in the bucket CloudFormation named, carrying a long body",
        bucket: Declared::Generated,
        key: "incoming/bulk.csv",
        body_unit: "quarterly,data\n",
        repeats: 500,
    },
    Row {
        case: "a key several prefixes deep, carrying a character the record encodes",
        bucket: Declared::Named,
        key: "incoming/2026/01/weekly report.json",
        body_unit: "{\"rows\":3}",
        repeats: 1,
    },
];

/// Every row: the write into the deployed bucket runs the deployed function, whose handler
/// copies the object the event named back into the same bucket, where a client reads it — and
/// the stack's bucket carrying no configuration publishes nothing at all.
#[tokio::test]
async fn a_deployed_bucket_notification_copies_the_object_it_was_handed() {
    let router = build_router();
    let stack = "cfn-notify-copy-stack";
    let named = format!("{stack}-incoming");
    let template = pipeline_stack(&named).to_string();

    let (status, body) = cloudformation(
        &router,
        "CreateStack",
        &[
            ("StackName", stack),
            ("TemplateBody", &template),
            ("Capabilities.member.1", "CAPABILITY_IAM"),
        ],
    )
    .await;
    assert_eq!(
        status, 200,
        "CreateStack({stack:?}) must be accepted, got {status} with {body}"
    );
    let (reported, answer) = wait_for_stack_status(&router, stack, CREATE_COMPLETE).await;
    assert_eq!(
        reported, CREATE_COMPLETE,
        "the pipeline stack must reach {CREATE_COMPLETE}, got {reported:?} with {answer}"
    );
    let outputs = outputs_of(&answer);
    let bucket_of = |which: Declared| {
        let output = match which {
            Declared::Named => "NamedBucketName",
            Declared::Generated => "GeneratedBucketName",
        };
        outputs.get(output).cloned().unwrap_or_else(|| {
            panic!("the stack must output {output:?} for a client to address, got {outputs:?}")
        })
    };
    assert_eq!(
        bucket_of(Declared::Named),
        named,
        "the named bucket's output must be the name the template declared, got {outputs:?}"
    );
    let generated = bucket_of(Declared::Generated);
    assert!(
        !generated.is_empty() && generated != named,
        "CloudFormation must name the unnamed bucket itself, got {generated:?}"
    );

    for row in ROWS {
        let case = row.case;
        let bucket = bucket_of(row.bucket);
        let body = row.body_unit.repeat(row.repeats);
        put_object(&router, case, &bucket, row.key, &body).await;

        let copied = format!("{PROCESSED_PREFIX}{}", row.key);
        let head = awaited_object(&router, &bucket, &copied, true).await;
        assert_eq!(
            head.status, 200,
            "case {case:?}: the write of {:?} must run the function, which copies it to \
             {copied:?} — HeadObject answered {} with {}",
            row.key, head.status, head.body
        );
        assert_eq!(
            head.content_length.as_deref(),
            Some(body.len().to_string().as_str()),
            "case {case:?}: the copy of {copied:?} must be as long as the object written, got \
             {:?}",
            head.content_length
        );
        let read = s3(&router, "GET", &object_path(&bucket, &copied), "").await;
        assert_eq!(
            read.status, 200,
            "case {case:?}: GetObject({copied:?}) must succeed, got {} with {}",
            read.status, read.body
        );
        assert_eq!(
            read.body, body,
            "case {case:?}: the copy must carry the bytes written to {:?}, got {} byte(s)",
            row.key,
            read.body.len()
        );
    }

    // The other half of the rule: the bucket the same stack declares with no notification
    // configuration publishes nothing, so a write into it leaves no copy behind.
    let case = "a bucket the stack declares no configuration on";
    let quiet = outputs
        .get("QuietBucketName")
        .cloned()
        .unwrap_or_else(|| panic!("case {case:?}: the stack must output the quiet bucket's name"));
    let key = "incoming/unwatched.txt";
    assert!(
        key.starts_with(WATCHED_PREFIX),
        "case {case:?}: the key must be one the declared filter would admit, so what is under \
         test is the absent configuration and not the filter, got {key:?}"
    );
    put_object(&router, case, &quiet, key, "nothing watches this").await;
    let copied = format!("{PROCESSED_PREFIX}{key}");
    let head = awaited_object(&router, &quiet, &copied, false).await;
    assert_eq!(
        head.status, 404,
        "case {case:?}: no configuration names a function for {quiet:?}, so {copied:?} must \
         never come into existence, got {} with {}",
        head.status, head.body
    );
}
