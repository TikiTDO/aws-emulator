//! An execution's status changes reach an EventBridge rule's SQS target on a router that
//! VERIFIES request signatures — the configuration the emulator serves traffic in.
//!
//! The RULE under test: **every status an execution of a STANDARD state machine MOVES
//! INTO is published onto the account's DEFAULT EventBridge bus as `source` `aws.states` /
//! `detail-type` `Step Functions Execution Status Change`, in an envelope naming the
//! execution's ARN in `resources`, whose `detail` reports the same execution
//! `DescribeExecution` serves** — including the TERMINAL status, which falls due after the
//! call that started the execution has already answered and so is owed by this service
//! itself rather than by a later client call.
//!
//! What this suite adds to the owning crate's own table
//! (`services/service-com-amazonaws-sfn-awsstepfunctions/tests/all/execution_status_change_events.rs`)
//! is the axis that table cannot cover: it turns request authentication OFF, so it cannot
//! see whether the publication Step Functions makes THROUGH THE EMULATOR'S OWN CALLBACK is
//! accepted by a router that authenticates every request, which is how the emulator is
//! served — and in particular whether the publication the CLOCK makes, with no request in
//! flight, is accepted too. Every call below is signed with the keys this process
//! publishes, and the envelopes that must arrive are published by Step Functions itself, in
//! process, against that same authenticating router.
//!
//! The rows span what the rule generalises over: the terminal status the execution reaches
//! (`SUCCEEDED` from a `Pass`-only definition, `FAILED` from a `Fail` state) and the rule
//! pattern the client watches it through (the `source` alone, and the `source` with the
//! `detail-type`), with a rule on another service's source asserted to receive nothing.
//!
//! Assembling the whole router costs stack (see `boot_serve.rs`), so it is built — and the
//! requests driven — on an explicitly sized thread.

use std::sync::Arc;
use std::time::{Duration, Instant, SystemTime};

use aws_credential_types::Credentials;
use aws_emulator_router::{build_router, InMemoryEngine};
use aws_sigv4::http_request::{sign, SignableBody, SignableRequest, SigningSettings};
use aws_sigv4::sign::v4::SigningParams;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

/// Keep this at or above the size `boot_serve.rs` uses: the same assembly runs here.
const BOOT_STACK_SIZE: usize = 64 * 1024 * 1024;

/// The Region every call is signed for and addressed in.
const REGION: &str = "us-east-1";

/// The `source` and `detail-type` Step Functions publishes an execution's status changes
/// under, spelled out here rather than imported, so a wrong constant in the implementation
/// cannot make this suite pass.
const SFN_SOURCE: &str = "aws.states";
const EXECUTION_STATUS_CHANGE: &str = "Step Functions Execution Status Change";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon
/// Web Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what the
/// queue's resource policy admits ("for Amazon SQS queues, EventBridge relies on
/// resource-based policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// The namespace the wiring-check event is published under: the client's own, not the
/// `aws.` one AWS reserves for its services.
const WARM_UP_SOURCE: &str = "com.example.authenticated-wiring-check";

/// The role every state machine below declares. Nothing here grants or denies anything
/// about it: the account's own published credential, which every call is signed with, is
/// the caller no identity policy governs.
const ROLE_ARN: &str = "arn:aws:iam::000000000000:role/StatesExecutionRole";

/// The status an execution rests in while it runs, which is the first one published.
const RUNNING: &str = "RUNNING";

/// How long this suite waits for something the clock owes — an execution reaching its
/// terminal status, an envelope reaching a queue — before giving up.
const DEADLINE: Duration = Duration::from_secs(30);

/// One poll inside [`DEADLINE`].
const POLL_INTERVAL: Duration = Duration::from_millis(25);

/// The credential every call below signs with: the pair this process publishes once
/// request authentication is on.
struct Signer {
    key_id: String,
    secret: String,
}

impl Signer {
    /// Sign `request` for `signing_name` in `REGION`, in the `Authorization` header an SDK
    /// request carries.
    fn sign(
        &self,
        mut request: http::Request<Vec<u8>>,
        signing_name: &str,
    ) -> http::Request<Vec<u8>> {
        let identity = Credentials::new(&self.key_id, &self.secret, None, None, "test").into();
        let params = SigningParams::builder()
            .identity(&identity)
            .region(REGION)
            .name(signing_name)
            .time(SystemTime::now())
            .settings(SigningSettings::default())
            .build()
            .expect("the signing parameters are complete")
            .into();
        let (method, uri) = (request.method().to_string(), request.uri().to_string());
        let headers: Vec<(String, String)> = request
            .headers()
            .iter()
            .map(|(name, value)| {
                (
                    name.as_str().to_string(),
                    value.to_str().expect("a text header").to_string(),
                )
            })
            .collect();
        let signable = SignableRequest::new(
            &method,
            &uri,
            headers
                .iter()
                .map(|(name, value)| (name.as_str(), value.as_str())),
            SignableBody::Bytes(request.body()),
        )
        .expect("the request is signable");
        let (instructions, _) = sign(signable, &params)
            .expect("the request signs")
            .into_parts();
        instructions.apply_to_request_http1x(&mut request);
        request
    }
}

/// One signed RPC call on the regional endpoint of `signing_name`. Answers the status and
/// the parsed body.
async fn call(
    router: &MultiServiceRouter,
    signer: &Signer,
    signing_name: &str,
    content_type: &str,
    target: &str,
    body: &Value,
) -> (u16, Value) {
    let host = format!("{signing_name}.{REGION}.amazonaws.com");
    let built = http::Request::builder()
        .method("POST")
        .uri(format!("https://{host}/"))
        .header("host", &host)
        .header("content-type", content_type)
        .header("x-amz-target", target)
        .body(body.to_string().into_bytes())
        .expect("the test request is well formed");
    let signed = signer.sign(built, signing_name);
    let (parts, payload) = signed.into_parts();
    let request = http::Request::from_parts(parts, bytes::Bytes::from(payload));
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let parsed = if response.body().is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(response.body()).unwrap_or(Value::Null)
    };
    (status, parsed)
}

/// One Step Functions call (`awsJson1_0`, `AWSStepFunctions.<Operation>`), which must
/// answer 200.
async fn sfn(
    router: &MultiServiceRouter,
    signer: &Signer,
    case: &str,
    operation: &str,
    body: &Value,
) -> Value {
    let (status, parsed) = call(
        router,
        signer,
        "states",
        "application/x-amz-json-1.0",
        &format!("AWSStepFunctions.{operation}"),
        body,
    )
    .await;
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from Step Functions {operation}, got {status} with \
         {parsed}"
    );
    parsed
}

