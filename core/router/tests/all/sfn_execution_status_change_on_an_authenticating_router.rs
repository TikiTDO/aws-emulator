/// A string member of a response, or a panic naming the case and what came back.
fn member(case: &str, body: &Value, pointer: &str) -> String {
    body.pointer(pointer)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: expected {pointer} in {body}"))
        .to_string()
}

/// An SQS queue called `name` whose resource policy admits EventBridge; answers its url and
/// the ARN a rule names it by.
async fn queue(
    router: &MultiServiceRouter,
    signer: &Signer,
    case: &str,
    name: &str,
) -> (String, String) {
    let created = sqs(router, signer, case, "CreateQueue", &json!({"QueueName": name})).await;
    let url = member(case, &created, "/QueueUrl");
    let attributes = sqs(
        router,
        signer,
        case,
        "GetQueueAttributes",
        &json!({"QueueUrl": &url, "AttributeNames": ["QueueArn"]}),
    )
    .await;
    let arn = member(case, &attributes, "/Attributes/QueueArn");
    let policy = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowEventBridge",
            "Effect": "Allow",
            "Principal": {"Service": EVENTS_PRINCIPAL},
            "Action": "sqs:SendMessage",
            "Resource": &arn,
        }],
    })
    .to_string();
    sqs(
        router,
        signer,
        case,
        "SetQueueAttributes",
        &json!({"QueueUrl": &url, "Attributes": {"Policy": policy}}),
    )
    .await;
    (url, arn)
}

/// An ENABLED rule called `name` on the default bus carrying `pattern`, with the queue
/// `queue_arn` as its one target.
async fn rule(
    router: &MultiServiceRouter,
    signer: &Signer,
    case: &str,
    name: &str,
    pattern: &Value,
    queue_arn: &str,
) {
    events(
        router,
        signer,
        case,
        "PutRule",
        &json!({
            "Name": name,
            "EventBusName": DEFAULT_BUS,
            "EventPattern": pattern.to_string(),
            "State": "ENABLED",
        }),
    )
    .await;
    let targeted = events(
        router,
        signer,
        case,
        "PutTargets",
        &json!({
            "Rule": name,
            "EventBusName": DEFAULT_BUS,
            "Targets": [{"Id": "t1", "Arn": queue_arn}],
        }),
    )
    .await;
    assert_eq!(
        targeted["FailedEntryCount"],
        json!(0),
        "case {case:?}: every target must be accepted, got {targeted}"
    );
}

/// Receive everything waiting on the queue at `url` and DELETE it; answers the parsed
/// envelopes its message bodies carried.
async fn drain(router: &MultiServiceRouter, signer: &Signer, case: &str, url: &str) -> Vec<Value> {
    let received = sqs(
        router,
        signer,
        case,
        "ReceiveMessage",
        // Long polling, as a client watching a queue for an event it cannot predict the
        // arrival of reads it: "the call waits for a message to arrive".
        &json!({"QueueUrl": url, "MaxNumberOfMessages": 10, "WaitTimeSeconds": 1}),
    )
    .await;
    let messages = received["Messages"].as_array().cloned().unwrap_or_default();
    let mut envelopes = Vec::new();
    for message in &messages {
        if let Some(handle) = message["ReceiptHandle"].as_str() {
            sqs(
                router,
                signer,
                case,
                "DeleteMessage",
                &json!({"QueueUrl": url, "ReceiptHandle": handle}),
            )
            .await;
        }
        let raw = message["Body"].as_str().unwrap_or_default();
        envelopes.push(serde_json::from_str::<Value>(raw).unwrap_or(Value::Null));
    }
    envelopes
}

/// Collect envelopes off the queue at `url` until `wanted` have arrived or [`DEADLINE`]
/// passes; answers everything that did arrive.
async fn collect(
    router: &MultiServiceRouter,
    signer: &Signer,
    case: &str,
    url: &str,
    wanted: usize,
) -> Vec<Value> {
    let started = Instant::now();
    let mut arrived: Vec<Value> = Vec::new();
    while arrived.len() < wanted && started.elapsed() < DEADLINE {
        arrived.extend(drain(router, signer, case, url).await);
        if arrived.len() < wanted {
            tokio::time::sleep(POLL_INTERVAL).await;
        }
    }
    arrived
}

/// Prove the wiring from EventBridge to the queue at `url` delivers at all on this
/// authenticating router, the way a client proves it: a rule on a source of the client's
/// OWN, one event published under it, and the envelope read back off the queue. Leaves the
/// queue empty again, so what arrives later is only what Step Functions published.
async fn prove_wiring(
    router: &MultiServiceRouter,
    signer: &Signer,
    case: &str,
    name: &str,
    url: &str,
    arn: &str,
) {
    rule(
        router,
        signer,
        case,
        name,
        &json!({"source": [WARM_UP_SOURCE]}),
        arn,
    )
    .await;
    let published = events(
        router,
        signer,
        case,
        "PutEvents",
        &json!({
            "Entries": [{
                "EventBusName": DEFAULT_BUS,
                "Source": WARM_UP_SOURCE,
                "DetailType": "wiring check",
                "Detail": json!({"check": name}).to_string(),
            }],
        }),
    )
    .await;
    assert_eq!(
        published["FailedEntryCount"],
        json!(0),
        "case {case:?}: the wiring publication must be accepted, got {published}"
    );
    let arrived = collect(router, signer, case, url, 1).await;
    let sources: Vec<&str> = arrived
        .iter()
        .map(|envelope| envelope["source"].as_str().unwrap_or_default())
        .collect();
    assert_eq!(
        sources,
        vec![WARM_UP_SOURCE],
        "case {case:?}: the wiring to {url} must deliver the client's own event before any \
         Step Functions event is expected on it, got {arrived:?}"
    );
}

/// Poll `DescribeExecution` until the execution reports `wanted`, or [`DEADLINE`] passes;
/// answers the status it last reported.
async fn await_status(
    router: &MultiServiceRouter,
    signer: &Signer,
    case: &str,
    execution_arn: &str,
    wanted: &str,
) -> String {
    let started = Instant::now();
    let mut last = String::new();
    while started.elapsed() < DEADLINE {
        let described = sfn(
            router,
            signer,
            case,
            "DescribeExecution",
            &json!({"executionArn": execution_arn}),
        )
        .await;
        last = described["status"].as_str().unwrap_or_default().to_string();
        if last == wanted {
            return last;
        }
        tokio::time::sleep(POLL_INTERVAL).await;
    }
    last
}

/// The `detail.status` of each envelope, sorted: an SQS standard queue makes "a best-effort
/// to preserve order", so what is asserted is WHICH transitions arrived.
fn statuses(envelopes: &[Value]) -> Vec<String> {
    let mut found: Vec<String> = envelopes
        .iter()
        .map(|envelope| {
            envelope["detail"]["status"]
                .as_str()
                .unwrap_or_default()
                .to_string()
        })
        .collect();
    found.sort();
    found
}

/// One row: the definition an execution runs, the terminal status it must reach, and the
/// rule pattern the client watches it through.
struct Row {
    case: &'static str,
    definition: &'static str,
    terminal: &'static str,
    /// The rule pattern the client watches the execution through, as a thunk so a row
    /// states it in the same words a client writes it in.
    pattern: fn() -> Value,
}

/// RULE: on a router that verifies request signatures, each status an execution moves into
/// reaches the SQS target of a rule matching it — the `RUNNING` the start writes and the
/// terminal status this service owes once the start has answered — and a rule on another
/// service's source receives nothing.
#[test]
fn an_execution_status_change_reaches_its_rule_s_queue_on_an_authenticating_router() {
    std::thread::Builder::new()
        .name("sfn-execution-status-change-authenticated".to_string())
        .stack_size(BOOT_STACK_SIZE)
        .spawn(|| {
            let runtime = tokio::runtime::Builder::new_current_thread()
                .enable_time()
                .build()
                .expect("build a current-thread runtime");
            runtime.block_on(drive());
        })
        .expect("spawn the sized thread")
        .join()
        .expect("the suite thread runs to completion");
}

/// Every row, against ONE assembled router per row.
async fn drive() {
    let rows = [
        Row {
            case: "a Pass-only definition succeeds, watched by a rule on the source alone",
            definition: r#"{"StartAt":"Hello","States":{"Hello":{"Type":"Pass","Result":{"msg":"hi"},"End":true}}}"#,
            terminal: "SUCCEEDED",
            pattern: || json!({"source": [SFN_SOURCE]}),
        },
        Row {
            case: "a Fail state fails, watched by a rule on the source and the detail-type",
            definition: r#"{"StartAt":"Bang","States":{"Bang":{"Type":"Fail","Error":"Boom","Cause":"on purpose"}}}"#,
            terminal: "FAILED",
            pattern: || json!({"source": [SFN_SOURCE], "detail-type": [EXECUTION_STATUS_CHANGE]}),
        },
    ];

    // ONE assembled router for every row, as one emulator serves every call a client
    // makes: a later row's execution is started on a store that already carries the
    // earlier rows' finished ones, which is what a second status change has to be
    // published from.
    let engine: Arc<InMemoryEngine> = Arc::new(InMemoryEngine::new());
    let mut router = build_router(engine);
    // Every row runs with request authentication ON, as the emulator serves traffic:
    // every call below carries the signature this process's keys produce.
    router.set_request_authentication(true);
    let published = ::emulator_server::SigV4Authenticator::minted_credentials()
        .expect("turning authentication on publishes this process's keys");
    let signer = Signer {
        key_id: published.access_key_id.clone(),
        secret: published.secret_access_key.clone(),
    };

    for (index, row) in rows.iter().enumerate() {
        let case = row.case;

        // The consumer: one SQS queue admitting EventBridge, proven reachable from the bus
        // before any Step Functions event is expected on it.
        let (url, queue_arn) = queue(&router, &signer, case, &format!("states-{index}")).await;
        prove_wiring(
            &router,
            &signer,
            case,
            &format!("wiring-{index}"),
            &url,
            &queue_arn,
        )
        .await;

        // The rule under test, and one on ANOTHER service's source that must stay empty.
        rule(
            &router,
            &signer,
            case,
            &format!("states-{index}"),
            &(row.pattern)(),
            &queue_arn,
        )
        .await;
        let (other_url, other_arn) = queue(&router, &signer, case, &format!("other-{index}")).await;
        rule(
            &router,
            &signer,
            case,
            &format!("other-{index}"),
            &json!({"source": ["aws.ecs"]}),
            &other_arn,
        )
        .await;

        let machine = sfn(
            &router,
            &signer,
            case,
            "CreateStateMachine",
            &json!({
                "name": format!("machine-{index}"),
                "definition": row.definition,
                "roleArn": ROLE_ARN,
                "type": "STANDARD",
            }),
        )
        .await;
        let machine_arn = member(case, &machine, "/stateMachineArn");
        let started = sfn(
            &router,
            &signer,
            case,
            "StartExecution",
            &json!({
                "stateMachineArn": &machine_arn,
                "name": format!("run-{index}"),
                "input": r#"{"who":"world"}"#,
            }),
        )
        .await;
        let execution_arn = member(case, &started, "/executionArn");

        // The execution reaches its terminal status on its own: the start has already
        // answered, so the transition is owed by this service rather than by a client.
        let reached = await_status(&router, &signer, case, &execution_arn, row.terminal).await;
        assert_eq!(
            reached, row.terminal,
            "case {case:?}: the execution must reach {}, got {reached:?}",
            row.terminal
        );

        // BOTH statuses the execution moved through arrive on the rule's queue.
        let arrived = collect(&router, &signer, case, &url, 2).await;
        assert_eq!(
            statuses(&arrived),
            {
                let mut wanted = vec![RUNNING.to_string(), row.terminal.to_string()];
                wanted.sort();
                wanted
            },
            "case {case:?}: expected the rule's queue to receive {RUNNING} and {}, got \
             {arrived:?}",
            row.terminal
        );
        for envelope in &arrived {
            assert_eq!(
                envelope["source"],
                json!(SFN_SOURCE),
                "case {case:?}: expected the source {SFN_SOURCE}, got {envelope}"
            );
            assert_eq!(
                envelope["detail-type"],
                json!(EXECUTION_STATUS_CHANGE),
                "case {case:?}: expected the detail-type {EXECUTION_STATUS_CHANGE}, got \
                 {envelope}"
            );
            assert_eq!(
                envelope["resources"],
                json!([&execution_arn]),
                "case {case:?}: expected the execution's ARN in resources, got {envelope}"
            );
            assert_eq!(
                envelope["detail"]["executionArn"],
                json!(&execution_arn),
                "case {case:?}: expected the execution's ARN in the detail, got {envelope}"
            );
            assert_eq!(
                envelope["detail"]["stateMachineArn"],
                json!(&machine_arn),
                "case {case:?}: expected the state machine's ARN in the detail, got {envelope}"
            );
        }

        // The terminal envelope's detail is the execution DescribeExecution serves.
        let described = sfn(
            &router,
            &signer,
            case,
            "DescribeExecution",
            &json!({"executionArn": &execution_arn}),
        )
        .await;
        let terminal = arrived
            .iter()
            .find(|envelope| envelope["detail"]["status"] == json!(row.terminal))
            .unwrap_or_else(|| panic!("case {case:?}: no terminal envelope in {arrived:?}"));
        for member_name in ["name", "status", "error", "cause"] {
            assert_eq!(
                terminal["detail"][member_name],
                described
                    .get(member_name)
                    .cloned()
                    .unwrap_or(Value::Null),
                "case {case:?}: the envelope and the describe must agree on {member_name}, got \
                 {terminal} and {described}"
            );
        }

        // A rule on another service's source received nothing from this execution.
        let elsewhere = drain(&router, &signer, case, &other_url).await;
        assert!(
            elsewhere.is_empty(),
            "case {case:?}: a rule on another service's source receives nothing, got \
             {elsewhere:?}"
        );
    }
}
